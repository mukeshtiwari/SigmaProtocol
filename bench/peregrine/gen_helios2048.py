#!/usr/bin/env python3
"""Write Helios2048Defs.v: the 7-candidate approval ballot of
Examples/WasmBenchDefs.v (same group, key and fixed inputs) in the form of
the modules of Examples/WasmBenchSmallDefs.v, so that it compiles without
the Coqprime certificates of Examples/HeliosTallyIns.v.

usage (from the repository root): python3 bench/peregrine/gen_helios2048.py
"""
import re, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[2]
EX = ROOT / 'src' / 'Examples'
helios = (EX / 'HeliosTallyIns.v').read_text()
wb = (EX / 'WasmBenchDefs.v').read_text()
small = re.search(r'Module Small64\.(.*?)End Small64\.',
                  (EX / 'WasmBenchSmallDefs.v').read_text(), re.S).group(1)


def val(name):
    return re.search(r'Definition %s : Z :=\s*([0-9]+)%%Z\.' % name, helios).group(1)


inputs = re.search(r'  \(\*\* The fixed encryption randomness of the seven answers\. \*\).*?'
                   r'Definition bench_cs : Vector\.t \(@Zp q\) 7 :=.*?\]\.', wb, re.S).group(0)
funcs = re.search(r'  \(\*\* Encryption of an approval ballot.*?Defined\.\n.*?Defined\.\n',
                  small, re.S).group(0)

out = '''(** * The Helios ballot of [Examples/WasmBenchDefs.v] for Peregrine's C backend

    Generated by [bench/peregrine/gen_helios2048.py]; do not edit.

    The group, the IACR 2024 election key and the fixed inputs are those of
    [Examples/HeliosTallyIns.v] and [Examples/WasmBenchDefs.v]; the functions
    are those of [Small64] in [Examples/WasmBenchSmallDefs.v]. [prime_q],
    [prime_p] and the subgroup membership of [g] and [h] are [Admitted], so
    that the file needs neither the Coqprime certificates nor the in-kernel
    exponentiations (several minutes each); compilation erases them, and
    [HeliosTallyIns.v] proves all four. Nothing in this file is evidence of
    correctness; it exists for performance measurement only. *)
From Stdlib Require Import Utf8 ZArith Vector.
From Crypto Require Import Sigma EncProof Elgamal.
From Frontend Require Import Approval.
From Utility Require Import Zpstar Util.
Import Vspace Schnorr Zpfield Zpgroup VectorNotations.

Module Helios2048.

  (** The 256-bit prime order [q] ([HeliosTallyIns.q]). Primality is
      admitted here; [Examples/primeQ.v] certifies it. *)
  Definition q : Z := %(q)s%%Z.
  Lemma prime_q : Znumtheory.prime q. Admitted.

  (** The 2048-bit modulus [p] ([HeliosTallyIns.p]). Primality is admitted
      here; [Examples/primeP.v] certifies it. *)
  Definition p : Z := %(p)s%%Z.
  Lemma prime_p : Znumtheory.prime p. Admitted.

  (** The cofactor [k = p / q] and the Schnorr-group equation [p = k q + 1]. *)
  Definition k : Z := Z.div p q.
  Theorem safe_prime : p = (k * q + 1)%%Z.
  Proof. vm_cast_no_check (eq_refl p). Qed.

  (** The generator [g] and the IACR 2024 election key [h]. Their subgroup
      membership is admitted here and checked in [HeliosTallyIns.v]. *)
  Definition gval : Z := %(g)s%%Z.
  Lemma gval_mem : Zpow_facts.Zpow_mod gval q p = 1%%Z.
  Admitted.
  Definition g : @Schnorr_group p q :=
    {| Schnorr.v := gval; Ha := conj eq_refl eq_refl : (0 < gval < p)%%Z;
       Hb := gval_mem |}.

  Definition hval : Z := %(h)s%%Z.
  Lemma hval_mem : Zpow_facts.Zpow_mod hval q p = 1%%Z.
  Admitted.
  Definition h : @Schnorr_group p q :=
    {| Schnorr.v := hval; Ha := conj eq_refl eq_refl : (0 < hval < p)%%Z;
       Hb := hval_mem |}.

  Lemma q_neq_zero : q <> 0%%Z.
  Proof. discriminate. Qed.

  Definition mkzp (z : Z) : @Zp q :=
    mk_zp (Z.modulo z q) (Z.mod_mod z q q_neq_zero).

''' % dict(q=val('q'), p=val('p'), g=val('gval'), h=val('hval2024'))

out += funcs + '\n' + inputs + '''

  (** Encryption and proofs of the full 7-candidate ballot. *)
  Definition ballot_bench :=
    small_encrypt_ballot_and_generate_enc_proof bench_rs bench_ms bench_uscs bench_cs.

  (** Verification of [ballot_bench] (expected [true]). *)
  Definition ballot_verify_bench : bool :=
    small_verify_encryption_ballot_proof ballot_bench.

End Helios2048.
'''
(pathlib.Path(__file__).resolve().parent / 'Helios2048Defs.v').write_text(out)
