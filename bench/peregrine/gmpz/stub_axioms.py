#!/usr/bin/env python3
"""Realize the remaining axioms of a Peregrine λ□ program by C stubs that fail
when used, and optionally replace named constants by a trap value.

usage: stub_axioms.py PROG.ast PROG.attrs OUT.ast OUT.attrs STUBS [TRAP,...]

Writes OUT.ast, OUT.attrs, STUBS.c and STUBS.h (STUBS is a path without
extension; the attribute file names the header by its base name).

* Axioms.  After splice_gmp_z.py the program can still contain axioms that
  are not remapped: mathcomp's HB.lock bodies (X.body) and the constants of
  sealed modules (BLS12_381_Primes.r, FpNat.N).  Each becomes a nullary
  remapped constant whose C function prints the name of the axiom and aborts.

* Traps.  Each constant of the comma-separated TRAP list
  loses its body and becomes a nullary remapped constant whose value is a
  pointer into a page mapped without access rights.  A name is File.name:
  the constant name of the Rocq file File (not inside a module).  Such a value can be
  passed around and stored in blocks (the garbage collector only follows
  pointers into its own heap), but a case analysis on it, an application of
  it or a GMP operation on it reads the page and stops the program with
  SIGSEGV.  This is for arguments that the extracted functions carry but never
  inspect, such as the section variables [r : nat] (a unary nat of about
  2^255) and the mathcomp group structures of ExecKZG.

A run that prints a result therefore used neither the stubbed axioms nor the
trapped values, so the printed result does not depend on them.  The script
prints what it stubs and traps.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from splice_locked import parse, dump, kn_str, env_of

def main(prog_f, attrs_f, out_f, out_attrs_f, base, traps=''):
    prog = parse(open(prog_f).read())
    attrs = open(attrs_f).read()
    hdr = os.path.basename(base) + '.h'
    trap_names = set(filter(None, traps.split(',')))
    trapped, found = [], set()
    env = env_of(prog)
    for i, d in enumerate(env):
        k = kn_str(d[0])
        for t in trap_names:
            f, _, name = t.rpartition('.')
            if (d[1][0] == 'ConstantDecl' and d[0][-1] == '"%s"' % name
                    and k.startswith('((MPfile ("%s"' % f)):
                env[i] = [d[0], ['ConstantDecl', ['constant_body', 'None']]]
                trapped.append(k)
                found.add(t)
    missing = trap_names - found
    if missing:
        sys.exit('stub_axioms: no constant named %s' % ', '.join(sorted(missing)))
    stubs = []
    for d in env:
        if d[1][0] == 'ConstantDecl' and d[1][1][1] == 'None':
            k = kn_str(d[0])
            if k in trapped or k in attrs:  # trapped, or already remapped (GmpZ)
                continue
            stubs.append(k)
    out = []
    dump(prog, out)
    open(out_f, 'w').write(''.join(out))
    remaps = ['(%s (remapped_constant (Some "%s") 0 false false "ax_stub_%d"))' % (k, hdr, i)
              for i, k in enumerate(stubs)]
    remaps += ['(%s (remapped_constant (Some "%s") 0 false false "ax_trap"))' % (k, hdr)
               for k in trapped]
    head = '(attributes_config () ('
    assert attrs.startswith(head), attrs[:40]
    open(out_attrs_f, 'w').write(head + ' '.join(remaps) + ' ' + attrs[len(head):])
    with open(base + '.h', 'w') as h:
        h.write('/* Generated by stub_axioms.py. */\n#include "values.h"\n')
        h.write('value ax_trap(void);\n')
        for i in range(len(stubs)):
            h.write('value ax_stub_%d(void);\n' % i)
    with open(base + '.c', 'w') as c:
        c.write('/* Generated by stub_axioms.py: axioms that must not be evaluated\n'
                '   and a trap value that must not be inspected. */\n')
        c.write('#include <stdio.h>\n#include <stdlib.h>\n#include <sys/mman.h>\n'
                '#include "%s"\n' % hdr)
        c.write('value ax_trap(void) {\n'
                '  static value trap = 0;\n'
                '  if (!trap) {\n'
                '    void *page = mmap(NULL, 1 << 16, PROT_NONE, MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);\n'
                '    if (page == MAP_FAILED) { perror("mmap"); abort(); }\n'
                '    trap = (value) ((char *) page + (1 << 15));\n'
                '  }\n'
                '  return trap;\n}\n')
        for i, k in enumerate(stubs):
            name = k.replace('\\', '\\\\').replace('"', '\\"')
            c.write('value ax_stub_%d(void) {\n  fprintf(stderr, "axiom evaluated: %%s\\n", "%s");\n'
                    '  abort();\n}\n' % (i, name))
    print('stubbed %d axioms (abort when evaluated):' % len(stubs))
    for k in stubs:
        print('  ' + k)
    print('trapped %d constants (fault when inspected):' % len(trapped))
    for k in trapped:
        print('  ' + k)

if __name__ == '__main__':
    # run with run_deep.py: the terms are deeper than the default recursion limit
    main(*sys.argv[1:])
