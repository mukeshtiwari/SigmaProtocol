/* Zl.add, Zl.sub, Zl.mul and Zl.opp by the verified bedrock2 arithmetic
   modulo l = 2^252 + 27742317777372353535851937790883648493.

   remap_const.py remaps the Rocq constants
       Curve.Ed25519.Ed25519.Zl.{add,sub,mul} : Zl.F -> Zl.F -> Zl.F
       Curve.Ed25519.Ed25519.Zl.opp           : Zl.F -> Zl.F
   (Zl.F = Zmod l, a record of one integer in [0, l)) to the functions
   below, which

     1. read the integer of each argument as 32 little-endian bytes and
        check that it is below l;
     2. call zl_add_bytes, zl_sub_bytes, zl_mul_bytes or zl_opp_bytes, which
        write the 32 little-endian bytes of the result;
     3. build the result, a record of one integer, in the CertiRocq heap.

   Step 2 is the bedrock2 code of fieldl_bedrock.c: the functions of
   ZlBytes.v over the arithmetic modulo l generated by fiat-crypto's
   word-by-word Montgomery pipeline (FieldL.v).  The theorems
   zl_exec_add_bytes, zl_exec_sub_bytes, zl_exec_mul_bytes and
   zl_exec_opp_bytes of ZlBytes.v state that a call on the bytes of the
   canonical representatives of a and b writes the bytes of Zl.add a b,
   Zl.sub a b, Zl.mul a b and Zl.opp a; the input buffers and the output
   buffer must be disjoint, as they are below.  Trusted here: the byte
   conversions and heap layout of steps 1 and 3.  Outside this file:
   bedrock2's printer ToCString, which produced fieldl_bedrock.c.

   Layout of a value of Zl.F after erasure (checked at run time; a mismatch
   aborts): a block of tag 0 [z] (the record Zmod, its proof field erased),
   z an integer in the representation of z_gmp.c. */
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <gmp.h>
#include "gc_stack.h"
#include "zl_glue.h"

#include "fieldl_bedrock.c"

#define ZSIZE(v) ((mp_size_t) Field(v, 0))
#define ZLIMBS(v) ((mp_limb_t *) &Field(v, 1))

/* l, little-endian */
static const uint8_t l_bytes[32] = {
  0xed, 0xd3, 0xf5, 0x5c, 0x1a, 0x63, 0x12, 0x58, 0xd6, 0x9c, 0xf7, 0xa2, 0xde, 0xf9, 0xde, 0x14,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x10};

static void fail(const char *what) {
  fprintf(stderr, "zl_glue: %s\n", what);
  abort();
}

/* The integer of a value of Zl.F as 32 little-endian bytes, checked < l. */
static void zl_to_bytes(value v, uint8_t out[32]) {
  if (!Is_block(v) || Tag_val(v) != 0 || Wosize_val(v) != 1) fail("unexpected representation");
  value z = Field(v, 0);
  memset(out, 0, 32);
  if (Is_long(z)) {
    intnat n = Long_val(z);
    if (n < 0) fail("negative integer");
    for (int i = 0; i < 8; i++) out[i] = (uint8_t) ((uintnat) n >> (8 * i));
    return;
  }
  if (Tag_val(z) != No_scan_tag) fail("integer expected");
  mp_size_t s = ZSIZE(z);
  if (s < 0) fail("negative integer");
  if ((size_t) s * sizeof(mp_limb_t) > 32) fail("integer of more than 256 bits");
  for (mp_size_t i = 0; i < s; i++) {
    mp_limb_t limb = ZLIMBS(z)[i];
    for (size_t j = 0; j < sizeof(mp_limb_t); j++)
      out[i * sizeof(mp_limb_t) + j] = (uint8_t) (limb >> (8 * j));
  }
  for (int i = 31; i >= 0; i--) {
    if (out[i] < l_bytes[i]) return;
    if (out[i] > l_bytes[i]) break;
  }
  fail("integer not below l");
}

/* A value of Zl.F with the integer of 32 little-endian bytes, in the heap. */
static value zl_of_bytes(struct thread_info *tinfo, const uint8_t b[32]) {
  mp_limb_t limbs[4];
  mp_size_t s = 0;
  for (int i = 0; i < 4; i++) {
    mp_limb_t l = 0;
    for (int j = 0; j < 8; j++) l |= (mp_limb_t) b[8 * i + j] << (8 * j);
    limbs[i] = l;
    if (l) s = i + 1;
  }
  int boxed = !(s == 0 || (s == 1 && limbs[0] <= (mp_limb_t) Max_long));
  uintnat words = 2 + (boxed ? (uintnat) s + 2 : 0);
  /* The arguments are dead, so a collection here needs no roots. */
  if ((uintnat) (tinfo->limit - tinfo->alloc) < words) {
    tinfo->nalloc = words;
    garbage_collect(tinfo);
  }
  value z;
  if (!boxed) {
    z = Val_long(s == 0 ? 0 : (intnat) limbs[0]);
  } else {
    value *p = tinfo->alloc;
    tinfo->alloc = p + s + 2;
    p[0] = (value) (((header_t) (s + 1) << 10) | No_scan_tag);
    p[1] = (value) s;
    memcpy(p + 2, limbs, (size_t) s * sizeof(mp_limb_t));
    z = (value) (p + 1);
  }
  value *q = tinfo->alloc;
  tinfo->alloc = q + 2;
  q[0] = (value) ((header_t) 1 << 10);  /* size 1, tag 0 */
  q[1] = z;
  return (value) (q + 1);
}

value zl_add(struct thread_info *tinfo, value a, value b) {
  uint8_t x[32], y[32], o[32];
  zl_to_bytes(a, x); zl_to_bytes(b, y);
  zl_add_bytes((br_word_t) o, (br_word_t) x, (br_word_t) y);
  return zl_of_bytes(tinfo, o);
}

value zl_sub(struct thread_info *tinfo, value a, value b) {
  uint8_t x[32], y[32], o[32];
  zl_to_bytes(a, x); zl_to_bytes(b, y);
  zl_sub_bytes((br_word_t) o, (br_word_t) x, (br_word_t) y);
  return zl_of_bytes(tinfo, o);
}

value zl_mul(struct thread_info *tinfo, value a, value b) {
  uint8_t x[32], y[32], o[32];
  zl_to_bytes(a, x); zl_to_bytes(b, y);
  zl_mul_bytes((br_word_t) o, (br_word_t) x, (br_word_t) y);
  return zl_of_bytes(tinfo, o);
}

value zl_opp(struct thread_info *tinfo, value a) {
  uint8_t x[32], o[32];
  zl_to_bytes(a, x);
  zl_opp_bytes((br_word_t) o, (br_word_t) x);
  return zl_of_bytes(tinfo, o);
}
