#!/usr/bin/env python3
"""Write the secret input of the constant-time build.

usage: gen_secrets.py BALLOT.v OUT.h

Reads the list [Definition secrets : list F := (s n0 :: s n1 :: ... :: nil)%list]
of BALLOT.v
(Ed25519Ballot_LamBox.v) and writes OUT.h (ct_secrets.h, included by
zl_ct_glue.c) with ZLC_NSECRETS and the array zlc_secret_bytes of the
32 little-endian bytes of each n_i mod l, the value of [s n_i] = [of_Z n_i].
"""
import re, sys

L = 2**252 + 27742317777372353535851937790883648493


def main(src, out):
    text = open(src).read()
    m = re.search(r'Definition secrets : list F :=\s*\((.*?) :: nil\)%list\.', text, re.S)
    if not m:
        sys.exit('gen_secrets: no list secrets in %s' % src)
    items = [x.strip() for x in m.group(1).split('::')]
    nums = []
    for it in items:
        mm = re.fullmatch(r's (\d+)', it)
        if not mm:
            sys.exit('gen_secrets: unexpected entry %r' % it)
        nums.append(int(mm.group(1)) % L)
    rows = ',\n  '.join('{' + ', '.join('0x%02x' % b for b in n.to_bytes(32, 'little')) + '}'
                        for n in nums)
    open(out, 'w').write(
        '/* Generated by gen_secrets.py from %s: the secret scalars, mod l. */\n'
        '#define ZLC_NSECRETS %d\n'
        'uint8_t zlc_secret_bytes[ZLC_NSECRETS][32] = {\n  %s};\n'
        % (src.split('/')[-1], len(nums), rows))
    print('gen_secrets: %d secrets' % len(nums))


if __name__ == '__main__':
    main(*sys.argv[1:])
