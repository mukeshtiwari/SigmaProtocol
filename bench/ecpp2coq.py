#!/usr/bin/env python3
"""Turn a PARI/GP ECPP certificate into a Coqprime certificate.

usage: ecpp2coq.py PARI_CERT_FILE LEMMA_NAME > file.v

PARI_CERT_FILE holds the output of `write(file, primecert(N))`: a vector of
steps [N_i, t_i, s_i, a_i, [x_i, y_i]] with N_1 = N, m_i = N_i + 1 - t_i the
order of the curve y^2 = x^3 + a_i x + b_i over Z/N_i, q_i = m_i / s_i the
next number of the chain, and q_last < 2^64 prime. Each step becomes
Coqprime's `Ell_certif N_i s_i ((q_i, 1) :: nil) a_i b_i x_i y_i`, whose
checker (Coqprime.num.NEll, Pock) verifies that (x_i, y_i) is on the curve,
that 4 N_i < (q_i - 1)^2, that [m_i] P = O and [s_i] P <> O; the last prime
is certified by the Pocklington certificate of pocklington.py. The checker
computes with Bignums, so the resulting lemma depends on the
primitive-integer axioms Uint63Axioms.*, as the other PocklingtonRefl
certificates of this repository do."""
import sys, os, importlib.util
here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("pocklington", os.path.join(here, "pocklington.py"))
pock = importlib.util.module_from_spec(spec); spec.loader.exec_module(pock)

def zlit(v):
    return "(%d)%%Z" % v if v < 0 else "%d%%Z" % v

def main():
    cert = eval(open(sys.argv[1]).read().strip()); name = sys.argv[2]
    N0 = cert[0][0]
    lines = []
    for (N, t, s, a, P) in cert:
        m = N + 1 - t
        assert m % s == 0, "s does not divide m"
        q = m // s
        x, y = P
        b = (y * y - x * x * x - a * x) % N
        assert 4 * N < (q - 1) ** 2, "Coqprime's bound 4N < (q-1)^2 fails at N of %d bits" % N.bit_length()
        lines.append("Ell_certif %d %d ((%d, 1)::nil) %s %s %s %s" % (N, s, q, zlit(a % N), zlit(b), zlit(x % N), zlit(y % N)))
    # the tail: q_last and every prime its Pocklington certificate uses
    Nl, tl, sl, _, _ = cert[-1]
    qlast = (Nl + 1 - tl) // sl
    certs = {}; order = []
    pock.certificate(qlast, certs, order)
    for n in sorted(order, reverse=True):
        c = certs[n]
        if c[0] == 'proof': lines.append("Proof_certif %d prime%d" % (n, n))
        else:
            _, n, a, dec, sqrt = c
            dec2 = sorted(dec, key=lambda pe: -pe[0])
            lines.append("Pock_certif %d %d (%s nil) %d" % (n, a, "".join("(%d, %d)::" % pe for pe in dec2), sqrt))
    body = " ::\n   ".join(lines[1:])
    print("(* Elliptic-curve (ECPP) primality certificate for the %d-bit prime %s,\n   generated by PARI/GP's primecert and converted with bench/ecpp2coq.py;\n   %d elliptic steps, then a Pocklington certificate for the final %d-bit prime. *)"
          % (N0.bit_length(), name, len(cert), qlast.bit_length()))
    print("From Coqprime Require Import PocklingtonRefl.\nLocal Open Scope positive_scope.\n")
    print("Lemma %s : prime %d.\nProof.\n apply (Pocklington_refl\n  (%s)\n  (%s ::\n   nil)).\n vm_cast_no_check (refl_equal true).\nQed." % (name, N0, lines[0], body))

if __name__ == '__main__':
    main()
