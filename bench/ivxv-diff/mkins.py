#!/usr/bin/env python3
"""Generates the certified instances at the safe-prime group of the IVXV
campaign (group.txt: Verificatum's `vog -gen ModPGroup -fixed 2048`, the
kind of group IVXV's auditor accepts, p = 2q + 1):

  src/Examples/IvxvGroupIns.v         p, q, k = 2, the generator g of the group
                                      description; the primality of p and q is
                                      ASSUMED (axioms prime_p, prime_q)
  src/Examples/VerificatumIvxvIns.v   VerificatumIns.v at that group
  src/Examples/BayerGrothIvxvIns.v    BayerGrothIns.v at that group (for its
                                      group and vector-space instance; q assumed
                                      prime, p proved prime from it)
  src/Examples/SwissPostZkpIvxvIns.v  SwissPostZkpIns.v (the Maurer verifier
                                      verify_rows) over BayerGrothIvxvIns.v
  src/Examples/BayerGrothIvxvGoIns.v, SwissPostZkpIvxvGoIns.v
                                      the same at RFC 3526 group 14, the group of
                                      the Go core library's proofs (q assumed prime)

Do not edit the generated files; edit the originals and regenerate.

usage: mkins.py [group.txt]"""
import os, re, struct, sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, "..", ".."))
ex = os.path.join(root, "src", "Examples")
desc = open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "group.txt")).read().strip()

def bt(b, pos=0):
    tag, n = b[pos], struct.unpack(">I", b[pos + 1:pos + 5])[0]; pos += 5
    if tag == 1: return b[pos:pos + n], pos + n
    cs = []
    for _ in range(n):
        c, pos = bt(b, pos); cs.append(c)
    return cs, pos
t, _ = bt(bytes.fromhex(desc.split("::")[-1]))
assert t[0] == b"com.verificatum.arithm.ModPGroup"
p, q, g = (int.from_bytes(x, "big") for x in t[1][:3])
assert p == 2 * q + 1 and pow(g, q, p) == 1 and g != 1 and pow(2, q, p) == 1

header = """(* GENERATED by bench/ivxv-diff/mkins.py from {src}, at the safe-prime
   group of the IVXV campaign (bench/ivxv-diff/group.txt, Verificatum's
   `vog -gen ModPGroup -fixed 2048`). The primality of {what} is ASSUMED
   (axioms, listed by Print Assumptions), not certified. Do not edit. *)

"""

open(os.path.join(ex, "IvxvGroupIns.v"), "w").write(header.format(src="HeliosTallyIns.v (the group part)", what="p and q") + f"""From Stdlib Require Import Utf8 ZArith Znumtheory Zpow_facts.
From Utility Require Import Zpstar Util.
From Examples Require Import BigNPow.
Import Vspace Schnorr Zpfield Zpgroup.

Section IvxvGroup.

  Definition q : Z := {q}%Z.
  Definition p : Z := {p}%Z.

  (* ASSUMED, not certified *)
  Axiom prime_q : Znumtheory.prime q.
  Axiom prime_p : Znumtheory.prime p.

  Definition k : Z := Z.div p q.
  Theorem safe_prime : p = (k * q + 1)%Z.
  Proof. vm_cast_no_check (eq_refl p). Qed.

  (* the generator of the group description *)
  Definition gval : Z := {g}%Z.
  (* g is in the subgroup of order q, by computation (as in BayerGrothIns.v) *)
  Theorem g_order : Zpow_mod gval q p = 1%Z.
  Proof.
    unfold q; rewrite BigNPow.bpow_mod_spec by (vm_compute; discriminate).
    vm_cast_no_check (eq_refl 1%Z).
  Qed.
  Definition g : @Schnorr_group p q.
  Proof.
    refine {{| Schnorr.v := gval; Ha := conj eq_refl eq_refl : (0 < gval < p)%Z; Hb := g_order |}}.
  Defined.

End IvxvGroup.
""")

vi = open(os.path.join(ex, "VerificatumIns.v")).read()
vi = vi.replace("From Examples Require Import HeliosTallyIns.", "From Examples Require Import IvxvGroupIns.")
vi = vi.replace("HeliosTallyIns.", "IvxvGroupIns.")
vi = vi.replace("Section VerificatumIns.", "Section VerificatumIvxvIns.").replace("End VerificatumIns.", "End VerificatumIvxvIns.")
assert "Import HeliosTallyIns" not in vi
open(os.path.join(ex, "VerificatumIvxvIns.v"), "w").write(header.format(src="VerificatumIns.v", what="p and q") + vi)

bg = open(os.path.join(ex, "BayerGrothIns.v")).read()
bg = bg.replace("From Examples Require Import BigNPow primeQSP.", "From Examples Require Import BigNPow.")
bg = re.sub(r"Definition p : Z := 0x[0-9a-f]+\.", f"Definition p : Z := {hex(p)}.", bg)
bg = re.sub(r"Definition q : Z := 0x[0-9a-f]+\.", f"Definition q : Z := {hex(q)}.", bg)
old = "  Theorem prime_q : prime q.\n  Proof. exact primeQSP.prime_q_sp. Qed."
assert old in bg
bg = bg.replace(old, "  (* ASSUMED, not certified *)\n  Axiom prime_q : prime q.")
bg = bg.replace("Section BayerGrothIns.", "Section BayerGrothIvxvIns.").replace("End BayerGrothIns.", "End BayerGrothIvxvIns.")
assert "primeQSP.prime" not in bg
open(os.path.join(ex, "BayerGrothIvxvIns.v"), "w").write(header.format(src="BayerGrothIns.v", what="q") + bg)

zk = open(os.path.join(ex, "SwissPostZkpIns.v")).read()
zk = zk.replace("From Examples Require Import BayerGrothIns.", "From Examples Require Import BayerGrothIvxvIns.")
zk = zk.replace("Section SwissPostZkpIns.", "Section SwissPostZkpIvxvIns.").replace("End SwissPostZkpIns.", "End SwissPostZkpIvxvIns.")
open(os.path.join(ex, "SwissPostZkpIvxvIns.v"), "w").write(header.format(src="SwissPostZkpIns.v (over BayerGrothIvxvIns.v)", what="q") + zk)

# The Go core library (tivi.io/core) only knows named groups; its proofs are tested
# at RFC3526ModPGroup2048 (RFC 3526 group 14, g = 2), checked by run.sh against the
# library's own table (math/group/modqp/wellknown.go).
P14 = int("FFFFFFFFFFFFFFFFC90FDAA22168C234C4C6628B80DC1CD129024E088A67CC74020BBEA63B139B22514A08798E3404DD"
          "EF9519B3CD3A431B302B0A6DF25F14374FE1356D6D51C245E485B576625E7EC6F44C42E9A637ED6B0BFF5CB6F406B7ED"
          "EE386BFB5A899FA5AE9F24117C4B1FE649286651ECE45B3DC2007CB8A163BF0598DA48361C55D39A69163FA8FD24CF5F"
          "83655D23DCA3AD961C62F356208552BB9ED529077096966D670C354E4ABC9804F1746C08CA18217C32905E462E36CE3B"
          "E39E772C180E86039B2783A2EC07A28FB5C55DF06F4C52C9DE2BCBF6955817183995497CEA956AE515D2261898FA0510"
          "15728E5A8AACAA68FFFFFFFFFFFFFFFF", 16)
Q14 = (P14 - 1) // 2
assert pow(2, Q14, P14) == 1
bg2 = open(os.path.join(ex, "BayerGrothIns.v")).read()
bg2 = bg2.replace("From Examples Require Import BigNPow primeQSP.", "From Examples Require Import BigNPow.")
bg2 = re.sub(r"Definition p : Z := 0x[0-9a-f]+\.", f"Definition p : Z := {hex(P14)}.", bg2)
bg2 = re.sub(r"Definition q : Z := 0x[0-9a-f]+\.", f"Definition q : Z := {hex(Q14)}.", bg2)
bg2 = bg2.replace(old, "  (* ASSUMED, not certified *)\n  Axiom prime_q : prime q.")
bg2 = bg2.replace("Section BayerGrothIns.", "Section BayerGrothIvxvGoIns.").replace("End BayerGrothIns.", "End BayerGrothIvxvGoIns.")
assert "primeQSP.prime" not in bg2 and hex(P14) in bg2
gohdr = header.replace("the safe-prime\n   group of the IVXV campaign (bench/ivxv-diff/group.txt, Verificatum's\n   `vog -gen ModPGroup -fixed 2048`)", "RFC 3526 group 14\n   (RFC3526ModPGroup2048 of the IVXV Go core library)")
open(os.path.join(ex, "BayerGrothIvxvGoIns.v"), "w").write(gohdr.format(src="BayerGrothIns.v", what="q") + bg2)
zk2 = open(os.path.join(ex, "SwissPostZkpIns.v")).read()
zk2 = zk2.replace("From Examples Require Import BayerGrothIns.", "From Examples Require Import BayerGrothIvxvGoIns.")
zk2 = zk2.replace("Section SwissPostZkpIns.", "Section SwissPostZkpIvxvGoIns.").replace("End SwissPostZkpIns.", "End SwissPostZkpIvxvGoIns.")
open(os.path.join(ex, "SwissPostZkpIvxvGoIns.v"), "w").write(gohdr.format(src="SwissPostZkpIns.v (over BayerGrothIvxvGoIns.v)", what="q") + zk2)
print("wrote IvxvGroupIns.v, VerificatumIvxvIns.v, BayerGrothIvxvIns.v, SwissPostZkpIvxvIns.v (p =", hex(p)[:18] + "...) and BayerGrothIvxvGoIns.v, SwissPostZkpIvxvGoIns.v (RFC 3526 group 14)")
