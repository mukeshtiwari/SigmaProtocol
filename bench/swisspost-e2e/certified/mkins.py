#!/usr/bin/env python3
"""Generates src/Examples/BayerGrothE2EIns.v and SwissPostZkpE2EIns.v: the
instances of BayerGrothIns.v and SwissPostZkpIns.v at the encryption group of
a Swiss Post election event (the group of the payloads of the synthetic
election Post_E2E_DEV of the e-voting testdata repository), with the
primality of q ASSUMED (an axiom, listed by Print Assumptions) instead of
certified; p = 2q + 1 is still proved prime from it by Pocklington's
criterion, and the order of g = 2 is checked by computation.

usage: mkins.py PAYLOAD.json   (any payload with an encryptionGroup)"""
import base64, json, os, re, sys

root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
ex = os.path.join(root, "src", "Examples")
g = json.load(open(sys.argv[1]))["encryptionGroup"]
z = lambda s: int.from_bytes(base64.b64decode(s), "big")
p, q, gen = z(g["p"]), z(g["q"]), z(g["g"])
assert p == 2 * q + 1 and gen == 2 and pow(gen, q, p) == 1

header = """(* GENERATED by bench/swisspost-e2e/certified/mkins.py from BayerGrothIns.v:
   the same instance at the encryption group of the Swiss Post synthetic
   election Post_E2E_DEV (e-voting testdata 1.6.1.0), whose payloads all
   carry this 3072-bit p = 2q + 1 with generator g = 2. The primality of q
   is ASSUMED (the axiom prime_q, listed by Print Assumptions), not
   certified; p is proved prime from it by Pocklington's criterion as in
   BayerGrothIns.v, and the order of g is checked by computation. Do not
   edit; edit BayerGrothIns.v and regenerate. *)

"""
bg = open(os.path.join(ex, "BayerGrothIns.v")).read()
bg = bg.replace("From Examples Require Import BigNPow primeQSP.", "From Examples Require Import BigNPow.")
bg = re.sub(r"Definition p : Z := 0x[0-9a-f]+\.", f"Definition p : Z := {hex(p)}.", bg)
bg = re.sub(r"Definition q : Z := 0x[0-9a-f]+\.", f"Definition q : Z := {hex(q)}.", bg)
old = "  Theorem prime_q : prime q.\n  Proof. exact primeQSP.prime_q_sp. Qed."
assert old in bg
bg = bg.replace(old, "  (* ASSUMED, not certified *)\n  Axiom prime_q : prime q.")
bg = bg.replace("  (* the 3072-bit group of the test vectors *)", "  (* the 3072-bit group of the election event Post_E2E_DEV *)")
bg = bg.replace("Section BayerGrothIns.", "Section BayerGrothE2EIns.").replace("End BayerGrothIns.", "End BayerGrothE2EIns.")
assert "primeQSP.prime" not in bg and "Import BigNPow primeQSP" not in bg
open(os.path.join(ex, "BayerGrothE2EIns.v"), "w").write(header + bg)

zk = open(os.path.join(ex, "SwissPostZkpIns.v")).read()
zk = zk.replace("From Examples Require Import BayerGrothIns.", "From Examples Require Import BayerGrothE2EIns.")
zk = zk.replace("Section SwissPostZkpIns.", "Section SwissPostZkpE2EIns.").replace("End SwissPostZkpIns.", "End SwissPostZkpE2EIns.")
assert "BayerGrothIns" not in zk.split("*)", 1)[1]
open(os.path.join(ex, "SwissPostZkpE2EIns.v"), "w").write(header.replace("BayerGrothIns.v:", "SwissPostZkpIns.v (over BayerGrothE2EIns.v):") + zk)
print("wrote BayerGrothE2EIns.v and SwissPostZkpE2EIns.v for p =", hex(p)[:18] + "…")
