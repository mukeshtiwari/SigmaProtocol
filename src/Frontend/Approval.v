      (** Converse of [vote_proof_invalid_reject]: a prover who knows the
          challenge in advance can cheat. If the simulated challenge [c₁]
          equals the verifier challenge [c], the proof for any [m] (even
          [m ∉ {0, 1}]) is accepted, because the branch for [g ^ 1] is
          then a simulated conversation and the real branch gets challenge
          [0]. With challenges drawn uniformly from [F] this happens with
          probability [1/|F|]. *)
      Theorem vote_proof_invalid_accept :
        ∀ (r : F) (g h : G) (m : F)  (u₁ u₂ c₁ : F) (c : F),
          (m <> zero ∧ m <> one) → c₁ = c ->
          verify_encryption_vote_proof g h
            (encrypt_vote_and_generate_enc_proof g h r m [u₁; u₂; c₁] c) = true.
      Proof.
        intros * [hal har] hb.
        unfold encrypt_vote_and_generate_enc_proof,
        verify_encryption_vote_proof,
        generate_enc_proof.
        eapply generalised_accepting_elgamal_conversations_correctness_gen.
        destruct (Fdec m zero) as [fa | fa]; try congruence.
        subst.
        unfold generalised_accepting_encryption_proof_elgamal,
        enc, generalised_construct_encryption_proof_elgamal_real.
        simpl.
        (* Split the prover randomness; the real branch now receives
           challenge c - c = 0. *)
        destruct (vector_fin_app_pred 1 (FS F1) [u₁; u₂] [c]) as
          (m₁ & m₂ & v₁ & v₃ & vm & v₂ & v₄ & pfaa & pfbb & haa).
        destruct pfaa as [pfa].
        destruct pfbb as [pfb].
        destruct haa as [ha].
        destruct ha as (ha & hb & hc & hd).
        subst; cbn in * |- *.
        assert (m₂ = 0).
        {
          destruct m₂ as [|m₂].
          reflexivity. nia.
        }
        subst. cbn.
        assert (pfa = eq_refl).
        eapply Eqdep_dec.UIP_refl_nat.
        assert (pfb = eq_refl).
        eapply Eqdep_dec.UIP_refl_nat.
        subst. cbn in * |- *.
        pose proof (vector_inv_0 v₂) as hd.
        pose proof (vector_inv_0 v₄) as he.
        rewrite hd, he in * |- *. cbn.
        subst; cbn.
        destruct (vector_inv_S v₁) as (ma & msr & hmm).
        rewrite hmm in * |- *.
        subst; cbn.
        pose proof (vector_inv_0 msr) as hd.
        subst; cbn.
        destruct (vector_inv_S v₃) as (mb & msr & hmm).
        subst; cbn.
        pose proof (vector_inv_0 msr) as hd.
        subst; cbn.
        assert (hd : c = (c + (sub c (c + zero) + zero))). field.
        rewrite <-hd; clear hd.
        split. reflexivity.
        intros f. rewrite !dec_true.
        (* Branch 0 is a simulated Schnorr-style conversation; branch 1
           has challenge 0 and is trivially accepting. *)
        destruct (fin_inv_S _ f) as [f' | (f' & hf)].
        +
          subst; cbn.
          split.
          ++
            pose proof @simulator_completeness F zero one add mul sub div opp inv
              G gid ginv gop gpow Gdec Hvec g (g ^ r) u₁ c as hb.
            unfold accepting_conversation, schnorr_simulator in hb.
            rewrite dec_true in hb; cbn in hb.
            exact hb.
          ++
            assert(hb :  (ginv (g ^ zero)) = gid).
            rewrite field_zero, group_inv_id;
            reflexivity.
            rewrite !hb; clear hb.
            remember (gop (g ^ m) (h ^ r)) as gm.
            rewrite <-associative.
            assert (hb : gop (gop gm gid ^ opp c) (gop gm gid ^ c) = gid).
            destruct Hvec.
            rewrite <-vector_space_smul_distributive_fadd.
            assert (hb : (opp c + c) = zero).
            field. rewrite hb; clear hb.
            rewrite field_zero; reflexivity.
            rewrite hb; clear hb.
            rewrite right_identity.
            reflexivity.
        +
          subst; cbn.
          destruct (fin_inv_S _ f') as [f'' | (f'' & hf)];
          subst; cbn; (try refine match f'' with end).
          split.
          ++
            assert (hb : sub c (c + zero) * r = zero). field.
            rewrite !hb; clear hb.
            assert(hb : sub c (c + zero) = zero). field.
            rewrite hb; clear hb.
            rewrite field_zero, right_identity.
            rewrite right_identity; reflexivity.
          ++
            assert (hb : sub c (c + zero) * r = zero). field.
            rewrite !hb; clear hb.
            assert(hb : sub c (c + zero) = zero). field.
            rewrite hb; clear hb.
            rewrite field_one, field_zero,
            right_identity, right_identity.
            reflexivity.
      Qed.

      (** Completeness for a whole ballot: if every [m_i] is [0] or [1], the
          honestly generated ballot passes [verify_encryption_ballot_proof].
          By induction on the number of candidates using [vote_proof_valid]. *)
      Theorem ballot_proof_valid :
        ∀ (n : nat) (rs : Vector.t F n) (g h : G)
          (ms : Vector.t F n) (uscs : Vector.t (Vector.t F 3) n) (chs : Vector.t F n),
          (∀ (i : Fin.t n), Vector.nth ms i = zero ∨ Vector.nth ms i = one) ->
          verify_encryption_ballot_proof g h
            (encrypt_ballot_and_generate_enc_proof g h rs ms uscs chs) = true.
      Proof.
        induction n as [|n ihn].
        +
          intros * ha.
          pose proof (vector_inv_0 rs) as hb.
          pose proof (vector_inv_0 ms) as hc.
          pose proof (vector_inv_0 uscs) as hd.
          pose proof (vector_inv_0 chs) as he.
          subst; cbn. reflexivity.
        +
          intros * ha.
          destruct (vector_inv_S rs) as (rsh & rst & hb).
          destruct (vector_inv_S ms) as (msh & mst & hc).
          destruct (vector_inv_S uscs) as (uscsh & uscst & hd).
          destruct (vector_inv_S chs) as (chsh & chst & he).
          subst. simpl. eapply Bool.andb_true_iff.
          split.
          ++
            eapply vote_proof_valid.
            exact (ha Fin.F1).
          ++
            eapply ihn.
            intro f.
            exact (ha (Fin.FS f)).
      Qed.

      (** *** Completeness of the overall proof *)

      (** The [i]-th entry of [powers g k] is [g ^ (of_nat i)]. *)
      Lemma powers_nth : forall (g : G) (k : nat) (i : Fin.t (S k)),
        (powers g k)[@i] = g ^ of_nat (proj1_sig (Fin.to_nat i)).
      Proof.
        intros g; induction k as [| k ih]; intros i.
        + destruct (fin_inv_S _ i) as [hi | (j & hi)]; subst;
          [reflexivity | inversion j].
        + destruct (fin_inv_S _ i) as [hi | (j & hi)]; subst; cbn; [reflexivity |].
          rewrite map_fin, ih.
          destruct (Fin.to_nat j) as (a & ha); cbn.
          rewrite (@vector_space_smul_distributive_fadd F (@eq F)
            zero one add mul sub div opp inv G (@eq G) gid ginv gop gpow).
          rewrite field_one; reflexivity.
          typeclasses eauto.
      Qed.

      (** Rearrangement in the commutative group:
          [(a · b) · (c · d) = (a · c) · (b · d)]. *)
      Lemma gop_rearrange : forall (a b c d : G),
        gop (gop a b) (gop c d) = gop (gop a c) (gop b d).
      Proof.
        intros a b c d.
        rewrite <- associative, (associative b c d), (commutative b c),
          <- (associative c b d), associative.
        reflexivity.
      Qed.

      (** Homomorphism: the product of the encryptions of [ms] with
          randomness [rs] is the encryption of [Σ ms] with randomness
          [Σ rs]. *)
      Lemma ballot_product_enc : forall (k : nat) (g h : G) (rs ms : Vector.t F k),
        ballot_product (encrypt_ballot g h rs ms) =
        (g ^ Vector.fold_right add rs zero,
         gop (g ^ Vector.fold_right add ms zero) (h ^ Vector.fold_right add rs zero)).
      Proof.
        induction k as [| k ih]; intros g h rs ms.
        + rewrite (vector_inv_0 rs), (vector_inv_0 ms); cbn.
          rewrite !vector_space_field_zero, left_identity; reflexivity.
        + destruct (vector_inv_S rs) as (r & rs' & hr).
          destruct (vector_inv_S ms) as (m & ms' & hm).
          subst; cbn.
          change (fold_right (λ '(a, b) '(c, d), (gop a c, gop b d))
            (encrypt_ballot g h rs' ms') (gid, gid))
            with (ballot_product (encrypt_ballot g h rs' ms')).
          rewrite ih; cbn.
          rewrite gop_rearrange.
          rewrite <- !(@vector_space_smul_distributive_fadd F (@eq F)
            zero one add mul sub div opp inv G (@eq G) gid ginv gop gpow).
          reflexivity.
          all: typeclasses eauto.
      Qed.

      (** On a 0/1 ballot the field sum of the votes is [of_nat] of the
          number of approvals. *)
      Lemma sum_ballot_count : forall (k : nat) (ms : Vector.t F k),
        (forall i : Fin.t k, ms[@i] = zero ∨ ms[@i] = one) ->
        Vector.fold_right add ms zero = of_nat (count_ones ms).
      Proof.
        induction k as [| k ih]; intros ms hm.
        + rewrite (vector_inv_0 ms); reflexivity.
        + destruct (vector_inv_S ms) as (m & ms' & hms); subst.
          unfold count_ones in *; cbn.
          rewrite (ih ms' (fun i => hm (Fin.FS i))).
          destruct (Fdec m one) as [hone | hnone].
          * subst; cbn; reflexivity.
          * destruct (hm Fin.F1) as [hz | ho];
            [cbn in hz; subst; field | cbn in ho; contradiction].
      Qed.

      (** Completeness of the overall proof: for a 0/1 ballot with at least
          one candidate, the overall proof generated on the product of its
          ciphertexts is accepted. Uses [ballot_product_enc],
          [sum_ballot_count] and [powers_nth] to identify the real branch
          message with [g ^ (Σ ms)]. *)
      Theorem overall_proof_valid : forall (n : nat) (g h : G)
        (rs ms : Vector.t F (S n)) (uscs : Vector.t F ((2 + n) + (1 + n))) (c : F),
        (forall i : Fin.t (S n), ms[@i] = zero ∨ ms[@i] = one) ->
        verify_overall_proof g h (encrypt_ballot g h rs ms)
          (generate_overall_proof g h rs ms uscs c) = true.
      Proof.
        intros * hm.
        unfold verify_overall_proof, generate_overall_proof.
        rewrite ballot_product_enc.
        apply generalised_construct_encryption_proof_elgamal_real_completeness.
        split; [reflexivity |].
        rewrite (powers_nth g (S n)).
        unfold overall_index; rewrite Fin.to_nat_of_nat; cbn.
        rewrite <- (sum_ballot_count _ ms hm).
        rewrite (commutative (g ^ Vector.fold_right add ms zero)), <- associative,
          group_is_right_inverse, right_identity.
        reflexivity.
      Qed.

      (** Completeness of the full ballot: an honest 0/1 ballot together
          with its overall proof is accepted by [verify_ballot]. *)
      Theorem ballot_with_overall_proof_valid : forall (n : nat) (g h : G)
        (rs ms : Vector.t F (S n)) (uscs : Vector.t (Vector.t F 3) (S n))
        (cs : Vector.t F (S n)) (uscs' : Vector.t F ((2 + n) + (1 + n))) (c : F),
        (forall i : Fin.t (S n), ms[@i] = zero ∨ ms[@i] = one) ->
        verify_ballot g h (encrypt_ballot_with_overall_proof g h rs ms uscs cs uscs' c) = true.
      Proof.
        intros * hm.
        unfold verify_ballot, encrypt_ballot_with_overall_proof; cbn [fst snd].
        rewrite ballot_proof_valid, first_project_ballot_encryption, overall_proof_valid;
        [reflexivity | exact hm | exact hm].
      Qed.

      (** *** Commitments for Fiat–Shamir *)

      (** The announcement of [generate_enc_proof] equals the output of
          [generate_enc_proof_commitment]; the challenge does not influence
          the announcement. The proof unfolds the vector splitting performed
          inside [generalised_construct_encryption_proof_elgamal_real] and
          eliminates the length equality proofs by [UIP_refl_nat]. *)
      Lemma generate_enc_proof_commitment_announcement :
        forall (g h : G) (r m : F) (uscs : Vector.t F 3) (cp : G * G) (c : F),
        Sigma.announcement (generate_enc_proof g h r m uscs cp c) =
        generate_enc_proof_commitment g h m uscs cp.
      Proof.
        intros *.
        destruct (vector_inv_S uscs) as (u₁ & ust & ha).
        destruct (vector_inv_S ust) as (u₂ & ust' & hb).
        destruct (vector_inv_S ust') as (c₁ & ust'' & hc).
        pose proof (vector_inv_0 ust'') as hd.
        subst.
        unfold generate_enc_proof, generate_enc_proof_commitment.
        destruct (Fdec m zero) as [fa | fa].
        - unfold generalised_construct_encryption_proof_elgamal_real; simpl.
          destruct (vector_fin_app_pred 1 F1 [u₁; u₂] [c₁]) as
            (m₁ & m₂ & v₁ & v₃ & vm & v₂ & v₄ & pfaa & pfbb & haa).
          destruct pfaa as [pfa]; destruct pfbb as [pfb];
          destruct haa as [ha]; destruct ha as (ha & hb & hc & hd).
          subst. cbn in * |- *.
          assert (m₂ = 1) by (destruct m₂ as [|[|m₂]]; try nia; reflexivity).
          subst.
          assert (hp : pfa = eq_refl) by apply Stdlib.Logic.Eqdep_dec.UIP_refl_nat.
          subst pfa. cbn in ha, hc. subst.
          rewrite !eq_rew_r_dep_refl_nat.
          destruct cp; cbn; reflexivity.
        - unfold generalised_construct_encryption_proof_elgamal_real; simpl.
          destruct (vector_fin_app_pred 1 (FS F1) [u₁; u₂] [c₁]) as
            (m₁ & m₂ & v₁ & v₃ & vm & v₂ & v₄ & pfaa & pfbb & haa).
          destruct pfaa as [pfa]; destruct pfbb as [pfb];
          destruct haa as [ha]; destruct ha as (ha & hb & hc & hd).
          subst. cbn in * |- *.
          assert (m₂ = 0) by (destruct m₂ as [|m₂]; try nia; reflexivity).
          subst.
          assert (hp : pfa = eq_refl) by apply Stdlib.Logic.Eqdep_dec.UIP_refl_nat.
          subst pfa. cbn in ha, hc. subst.
          rewrite !eq_rew_r_dep_refl_nat.
          destruct cp; cbn.
          assert (hq : pfb = eq_refl) by apply Stdlib.Logic.Eqdep_dec.UIP_refl_nat.
          subst pfb. cbn in hc. subst.
          rewrite !eq_rew_r_dep_refl_nat.
          cbn. reflexivity.
      Qed.

      (** Ballot-level version: the announcements of the proofs of an
          encrypted ballot are [generate_ballot_commitment g h r m uscs].
          Hence the challenges of a non-interactive ballot may be derived
          by hashing these commitments before the proofs are completed. *)
      Theorem ballot_commitment_announcement :
        ∀ (n : nat) (r : Vector.t F n) (g h : G) (m : Vector.t F n)
          (uscs : Vector.t (Vector.t F 3) n) (c : Vector.t F n),
        Vector.map (fun '(_, pf) => Sigma.announcement pf)
          (encrypt_ballot_and_generate_enc_proof g h r m uscs c) =
        generate_ballot_commitment g h r m uscs.
      Proof.
        induction n as [|n ihn].
        + intros *. reflexivity.
        + intros *.
          destruct (vector_inv_S r) as (rh & rt & ha).
          destruct (vector_inv_S m) as (mh & mt & hb).
          destruct (vector_inv_S uscs) as (uscsh & uscst & hc).
          destruct (vector_inv_S c) as (ch & ct & hd).
          subst. cbn.
          rewrite ihn, generate_enc_proof_commitment_announcement.
          reflexivity.
      Qed.

      (** *** Special soundness *)

      (** Special soundness of the vote proof: from two accepting
          transcripts for the ciphertext [cp] with the same announcement [a]
          and different main challenges [c₁ ≠ c₂], one extracts [r] such that
          [cp] encrypts [0] or [1] with randomness [r]. Instance of
          [generalised_accepting_elgamal_soundness_main] with two branches;
          the extracted equation [c₂ · (g ^ m)⁻¹ = h ^ r] is rearranged to the
          ciphertext form. *)
      Theorem vote_proof_sound : forall (g h : G) (cp : G * G)
        (a : Vector.t (G * G) 2) (c₁ c₂ : F) (cs₁ cs₂ rs₁ rs₂ : Vector.t F 2),
        verify_encryption_vote_proof g h (cp, (a; c₁ :: cs₁; rs₁)) = true ->
        verify_encryption_vote_proof g h (cp, (a; c₂ :: cs₂; rs₂)) = true ->
        c₁ <> c₂ ->
        ∃ (r : F), cp = (g ^ r, gop (g ^ zero) (h ^ r)) ∨
          cp = (g ^ r, gop (g ^ one) (h ^ r)).
      Proof.
        intros * ha hb hc.
        unfold verify_encryption_vote_proof in ha, hb.
        destruct cp as (p₁, p₂).
        destruct (generalised_accepting_elgamal_soundness_main (n := 0) g h
          [g ^ zero; g ^ one] p₁ p₂ a c₁ cs₁ rs₁ c₂ cs₂ rs₂ ha hb hc) as
          (y & hy & f & hf).
        assert (hg : forall (p w v : G), v = gop p (ginv w) -> p = gop w v).
        { intros * hv; rewrite hv, commutative, <-associative,
            group_is_left_inverse, monoid_is_right_identity; reflexivity. }
        exists y.
        destruct (fin_inv_S _ f) as [hf0 | (f' & hf1)]; subst.
        + left. cbn in hf. f_equal; eapply hg; exact hf.
        + destruct (fin_inv_S _ f') as [hf0 | (f'' & hf1)]; subst;
          [| refine match f'' with end].
          right. cbn in hf. f_equal; eapply hg; exact hf.
      Qed.

      (** Special soundness of the overall proof: two accepting overall
          proofs for the same ciphertexts [cps] (of [k + 1] candidates) with
          equal announcement and different challenges yield [r] and a count
          [m ≤ k + 1] such that the product of [cps] equals
          [(g ^ r, g ^ (of_nat m) · h ^ r)], that is, the ballot carries at
          most [k + 1] approvals. *)
      Theorem overall_proof_sound : forall (k : nat) (g h : G)
        (cps : Vector.t (G * G) (S k))
        (a : Vector.t (G * G) (S (S k))) (c₁ c₂ : F)
        (cs₁ cs₂ rs₁ rs₂ : Vector.t F (S (S k))),
        verify_overall_proof g h cps (a; c₁ :: cs₁; rs₁) = true ->
        verify_overall_proof g h cps (a; c₂ :: cs₂; rs₂) = true ->
        c₁ <> c₂ ->
        ∃ (r : F) (m : nat), m <= S k ∧
          ballot_product cps = (g ^ r, gop (g ^ of_nat m) (h ^ r)).
      Proof.
        intros * ha hb hc.
        unfold verify_overall_proof in ha, hb.
        destruct (ballot_product cps) as (p₁, p₂) eqn:hp.
        destruct (generalised_accepting_elgamal_soundness_main (n := k) g h
          (powers g (S k)) p₁ p₂ a c₁ cs₁ rs₁ c₂ cs₂ rs₂ ha hb hc) as
          (y & hy & f & hf).
        exists y, (proj1_sig (Fin.to_nat f)).
        split.
        + destruct (Fin.to_nat f) as (m & hm); cbn; lia.
        + rewrite (powers_nth g (S k)) in hf.
          f_equal; [symmetry; exact hy |].
          assert (hg : forall (p w v : G), v = gop p (ginv w) -> p = gop w v).
          { intros * hv; rewrite hv, commutative, <-associative,
              group_is_left_inverse, monoid_is_right_identity; reflexivity. }
          eapply hg; exact hf.
      Qed.

      (** *** The prover without a branch on the vote

          [generate_enc_proof_ct] computes [generate_enc_proof] on the votes
          [0] and [1]. The proof unfolds the vector splitting of
          [generalised_construct_encryption_proof_elgamal_real] as in
          [generate_enc_proof_commitment_announcement] and then uses
          [g ^ 0 = 1], [x · 1 = x] and the field laws. *)
      Theorem generate_enc_proof_ct_eq :
        forall (g h : G) (r m : F) (uscs : Vector.t F 3) (cp : G * G) (c : F),
        (m = zero ∨ m = one) ->
        generate_enc_proof_ct g h r m uscs cp c = generate_enc_proof g h r m uscs cp c.
      Proof.
        intros * hm.
        destruct (vector_inv_S uscs) as (u₁ & ust & ha).
        destruct (vector_inv_S ust) as (u₂ & ust' & hb).
        destruct (vector_inv_S ust') as (c₁ & ust'' & hc).
        pose proof (vector_inv_0 ust'') as hd.
        subst.
        assert (hz : forall x : G, x ^ (opp (zero * c₁)) = gid).
        { intro x. assert (e : opp (zero * c₁) = zero) by field.
          rewrite e; apply field_zero. }
        assert (hr : forall x : G, gop x gid = x).
        { intro x; apply monoid_is_right_identity. }
        unfold generate_enc_proof, generate_enc_proof_ct.
        destruct (Fdec m zero) as [fa | fa].
        - subst m.
          unfold generalised_construct_encryption_proof_elgamal_real; simpl.
          destruct (vector_fin_app_pred 1 F1 [u₁; u₂] [c₁]) as
            (m₁ & m₂ & v₁ & v₃ & vm & v₂ & v₄ & pfaa & pfbb & haa).
          destruct pfaa as [pfa]; destruct pfbb as [pfb];
          destruct haa as [ha]; destruct ha as (ha & hb & hc & hd).
          subst. cbn in * |- *.
          assert (m₂ = 1) by (destruct m₂ as [|[|m₂]]; try nia; reflexivity).
          subst.
          assert (hp : pfa = eq_refl) by apply Stdlib.Logic.Eqdep_dec.UIP_refl_nat.
          subst pfa. cbn in ha, hc. subst.
          rewrite !eq_rew_r_dep_refl_nat.
          destruct cp as (p₁, p₂); cbn.
          rewrite !hz, !hr.
          assert (e1 : sub one zero * c₁ = c₁) by field.
          assert (e2 : zero * c₁ + sub one zero * sub c (c₁ + zero) =
            sub c (c₁ + zero)) by field.
          assert (e3 : sub one zero * c₁ + zero * sub c (c₁ + zero) = c₁) by field.
          assert (e4 : u₁ + sub one zero * (sub c (c₁ + zero) * r) =
            u₁ + sub c (c₁ + zero) * r) by field.
          assert (e5 : u₂ + zero * (sub c (c₁ + zero) * r) = u₂) by field.
          rewrite e2, e3, e4, e5, e1; reflexivity.
        - destruct hm as [hm | hm]; [congruence | subst m].
          unfold generalised_construct_encryption_proof_elgamal_real; simpl.
          destruct (vector_fin_app_pred 1 (FS F1) [u₁; u₂] [c₁]) as
            (m₁ & m₂ & v₁ & v₃ & vm & v₂ & v₄ & pfaa & pfbb & haa).
          destruct pfaa as [pfa]; destruct pfbb as [pfb];
          destruct haa as [ha]; destruct ha as (ha & hb & hc & hd).
          subst. cbn in * |- *.
          assert (m₂ = 0) by (destruct m₂ as [|m₂]; try nia; reflexivity).
          subst.
          assert (hp : pfa = eq_refl) by apply Stdlib.Logic.Eqdep_dec.UIP_refl_nat.
          subst pfa. cbn in ha, hc. subst.
          rewrite !eq_rew_r_dep_refl_nat.
          assert (hq : pfb = eq_refl) by apply Stdlib.Logic.Eqdep_dec.UIP_refl_nat.
          subst pfb. cbn in hc. subst.
          rewrite !eq_rew_r_dep_refl_nat.
          destruct cp as (p₁, p₂); cbn.
          assert (e0 : sub one one * c₁ = zero * c₁) by field.
          assert (e2 : one * c₁ + sub one one * sub c (c₁ + zero) = c₁) by field.
          assert (e3 : sub one one * c₁ + one * sub c (c₁ + zero) =
            sub c (c₁ + zero)) by field.
          assert (e4 : u₁ + sub one one * (sub c (c₁ + zero) * r) = u₁) by field.
          assert (e5 : u₂ + one * (sub c (c₁ + zero) * r) =
            u₂ + sub c (c₁ + zero) * r) by field.
          assert (e1 : one * c₁ = c₁) by field.
          rewrite e2, e3, e4, e5, e0, e1, !hz, !hr; reflexivity.
      Qed.

      (** Ballot-level version: [encrypt_ballot_and_generate_enc_proof_ct]
          computes [encrypt_ballot_and_generate_enc_proof] when every vote
          is [0] or [1]. *)
      Theorem encrypt_ballot_and_generate_enc_proof_ct_eq :
        ∀ (n : nat) (rs : Vector.t F n) (g h : G)
          (ms : Vector.t F n) (uscs : Vector.t (Vector.t F 3) n) (chs : Vector.t F n),
          (∀ (i : Fin.t n), Vector.nth ms i = zero ∨ Vector.nth ms i = one) ->
          encrypt_ballot_and_generate_enc_proof_ct g h rs ms uscs chs =
          encrypt_ballot_and_generate_enc_proof g h rs ms uscs chs.
      Proof.
        induction n as [|n ihn].
        + intros. reflexivity.
        + intros * ha.
          destruct (vector_inv_S rs) as (rsh & rst & hb).
          destruct (vector_inv_S ms) as (msh & mst & hc).
          destruct (vector_inv_S uscs) as (uscsh & uscst & hd).
          destruct (vector_inv_S chs) as (chsh & chst & he).
          subst. cbn.
          unfold encrypt_vote_and_generate_enc_proof_ct,
            encrypt_vote_and_generate_enc_proof.
          rewrite generate_enc_proof_ct_eq by exact (ha Fin.F1).
          f_equal. apply ihn. intro f. exact (ha (Fin.FS f)).
      Qed.

    End Proofs.
