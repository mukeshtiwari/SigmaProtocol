(** * Approval voting ballots: per-candidate 0/1 proofs and an overall proof

    This file formalises the voter side (the _front end_) of encrypted
    approval voting in the style of Helios. A ballot for [k] candidates is a
    vector of [k] votes [m_i], each of which must be [0] (not approved) or
    [1] (approved). Every vote is encrypted separately under exponential
    ElGamal with public key [h = g ^ x]:
[[
      enc g h m r = (g ^ r, g ^ m · h ^ r)
]]
    and is accompanied by a non-interactive-ready Sigma proof that the
    ciphertext encrypts either [g ^ 0] or [g ^ 1]. The tally (see
    [Backend/Tally.v] and [Examples/ApprovalIns.v]) multiplies the
    ciphertexts candidate-wise across ballots and decrypts the sums.

    _The per-vote proof._ The relation proved for a ciphertext [(c₁, c₂)] is
    the disjunction
[[
      ∃ r, (c₁, c₂) = (g ^ r, g ^ 0 · h ^ r)  ∨  (c₁, c₂) = (g ^ r, g ^ 1 · h ^ r)
]]
    It is an instance of the generalised disjunctive (OR) encryption proof of
    [Crypto/EncProof.v] with two branches, which is itself the
    Cramer–Damgård–Schoenmakers (CRYPTO 1994) OR-composition of
    Chaum–Pedersen equality-of-discrete-log proofs: for the true branch [i]
    the prover runs a real Chaum–Pedersen proof that
    [log_g c₁ = log_h (c₂ · (g ^ m_i)⁻¹)], for the other branch it runs the
    Chaum–Pedersen simulator with a self-chosen challenge, and the real
    branch challenge is fixed so that the branch challenges sum to the
    verifier challenge [c]. A proof therefore has type
    [sigma_proto F (G * G) 2 3 2]: two announcements (pairs of group
    elements), the challenge vector [c :: [c₀; c₁] ], and two responses. The
    prover randomness [uscs] consists of two commitment
    exponents [u₁], [u₂] and one simulated challenge [c₁].

    _The overall proof._ In addition, [generate_overall_proof] proves, on the
    homomorphic product [∏ (c₁ᵢ, c₂ᵢ)] of all ciphertexts of a ballot with
    [n + 1] candidates, that it encrypts [g ^ j] for some [0 ≤ j ≤ n + 1],
    using the same disjunctive proof with [n + 2] branches over the messages
    [ [g ^ 0; g ^ 1; …; g ^ (n + 1)] ], proved at the index equal to the real
    number of approvals. This mirrors the proof Helios attaches when a
    question has a maximum number of approvals; here the maximum is the
    number of candidates.

    _What is proved._

    - Correctness of the encryption and projection lemmas
      ([encryption_correct], [first_project_ballot_encryption],
      [second_project_ballot_sigma_proof]).
    - Completeness: honest 0/1 votes produce accepting proofs
      ([vote_proof_valid], [ballot_proof_valid], [overall_proof_valid],
      [ballot_with_overall_proof_valid]).
    - Rejection of dishonest votes generated by the honest prover algorithm
      on a value outside [{0, 1}] unless the simulated challenge equals the
      verifier challenge or [g] is the identity ([vote_proof_invalid_reject],
      [vote_proof_invalid_reject_]), and the converse fact that a prover who
      guesses the challenge can cheat ([vote_proof_invalid_accept]).
    - Special soundness at the ballot level: two accepting transcripts with
      equal announcements and different challenges yield a witness that the
      ciphertext encrypts [0] or [1] ([vote_proof_sound]) and that the
      product encrypts at most the number of candidates
      ([overall_proof_sound]). Both are instances of
      [EncProof.generalised_accepting_elgamal_soundness_main].
    - The announcements computed before the challenge is known
      ([generate_enc_proof_commitment], [generate_ballot_commitment]) are
      exactly the announcements of the final proofs
      ([generate_enc_proof_commitment_announcement],
      [ballot_commitment_announcement]); this justifies the Fiat–Shamir
      instantiation in [Examples/ApprovalIns.v], which hashes these
      commitments to derive the challenges.

    Honest-verifier zero knowledge is not re-proved in this file; it is
    inherited from the special HVZK of the generalised encryption proof,
    [generalised_encryption_proof_elgamal_special_honest_verifier_zkp] in
    [Crypto/EncProof.v]. Everything is parametric in an abstract field [F]
    and a vector space (group) [G] over it, so the development can be
    instantiated with Schnorr groups modulo a prime or with elliptic curves. *)
