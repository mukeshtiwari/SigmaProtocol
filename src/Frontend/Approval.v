(** ** Parameters

    The section is parametric in a field [F] of exponents (with decidable
    equality [Fdec]) and a group [G] of ciphertext components (with decidable
    equality [Gdec]), written multiplicatively with [gop], identity [gid],
    inverse [ginv] and exponentiation [gpow], written [^] below. The vector
    space laws connecting them are only assumed in the [Proofs] section. *)
Section Approval.

  (** The field of exponents (scalars) and its operations. *)
  Context
    {F : Type}
    {zero one : F}
    {add mul sub div : F -> F -> F}
    {opp inv : F -> F}
    {Fdec: forall x y : F, {x = y} + {x <> y}}.

  (** The group of ciphertext components (vectors) and its operations. *)
  Context
    {G : Type}
    {gid : G}
    {ginv : G -> G}
    {gop : G -> G -> G}
    {gpow : G -> F -> G}
    {Gdec : forall x y : G, {x = y} + {x <> y}}.

  Local Infix "^" := gpow.
  Local Infix "*" := mul.
  Local Infix "+" := add.

  (** [(a; c; r)] builds a Sigma transcript with announcement [a],
      challenge vector [c] and response vector [r]. *)
  #[local] Notation "( a ; c ; r )" := (mk_sigma _ _ _ a c r).

  (** ** Ballot construction and verification

      The prover and verifier algorithms. Throughout, [g] is the group
      generator, [h = g ^ x] the election public key, [r] the encryption
      randomness, [m] the vote (a field element meant to be [0] or [1]),
      [uscs] the prover randomness of the Sigma proof and [c] the verifier
      challenge (in deployment obtained by Fiat–Shamir hashing). *)
  Section Definitions.

      (** *** Single votes *)

      (** [encrypt_vote g h r m] is the exponential ElGamal encryption
          [(g ^ r, g ^ m · h ^ r)] of the vote [m] with randomness [r]. *)
      Definition encrypt_vote (g h : G) (r : F) (m : F) : G * G :=
        @enc F G gop gpow g h m r.

      (** [generate_enc_proof g h r m uscs cp c] is the prover side of the
          two-branch disjunctive encryption proof for the ciphertext [cp]
          with challenge [c]. If [m = 0] it proves branch [F1] (the real
          Chaum–Pedersen proof is run against the message list
          [ [g ^ m; g ^ 1] ]); otherwise it proves branch [FS F1] against
          [ [g ^ 0; g ^ m] ]. Putting [m] itself into the list makes the real
          branch consistent with the ciphertext even when [m] is neither
          [0] nor [1]; such a proof is then rejected by
          [verify_encryption_vote_proof], which checks against
          [ [g ^ 0; g ^ 1] ] (see [vote_proof_invalid_reject]). *)
      Definition generate_enc_proof
        (g h : G) (r : F)  (m : F)
        (uscs : Vector.t F 3) (cp : G * G) (c : F) : @Sigma.sigma_proto F (G * G) 2 3 2 :=
          match Fdec m zero with
          | left _ =>
            @generalised_construct_encryption_proof_elgamal_real F zero add mul sub
              opp G ginv gop gpow 0 Fin.F1 r uscs [g^m; g^one] g h cp c
          | right _ =>
            @generalised_construct_encryption_proof_elgamal_real F zero add mul sub
              opp G ginv gop gpow 0 (Fin.FS Fin.F1) r uscs [g^zero; g^m] g h cp c
          end.

      (** [generate_enc_proof_commitment g h m uscs cp] computes the two
          announcements of [generate_enc_proof] without the challenge: the
          real Chaum–Pedersen commitment on the proved branch and a simulated
          announcement on the other. A non-interactive ballot hashes these to
          derive the challenge ([nizk_encrypt_ballot_and_generate_enc_proof_ins]
          in [Examples/ApprovalIns.v]); [generate_enc_proof_commitment_announcement]
          shows they coincide with the announcements of the final proof. *)
      Definition generate_enc_proof_commitment
        (g h : G) (m : F) (uscs : Vector.t F 3) (cp : G * G) :
        Vector.t (G * G) 2 :=
          match Fdec m zero with
          | left _ =>
            @construct_encryption_proof_elgamal_commitment F opp G ginv gop gpow
              0 1 uscs [g^m; g^one] g h cp
          | right _ =>
            @construct_encryption_proof_elgamal_commitment F opp G ginv gop gpow
              1 0 uscs [g^zero; g^m] g h cp
          end.

      (** [encrypt_vote_and_generate_enc_proof g h r m uscs c] encrypts [m]
          and attaches the disjunctive proof for the resulting ciphertext.
          The function is total: on a value [m] outside [{0, 1}] it still
          produces a proof, which the verifier rejects except with the
          negligible probability of a correctly guessed challenge
          ([vote_proof_invalid_reject], [vote_proof_invalid_accept]). *)
      Definition encrypt_vote_and_generate_enc_proof
        (g h : G) (r : F)  (m : F)
        (uscs : Vector.t F 3) (c : F) : G * G * @Sigma.sigma_proto F (G * G) 2 3 2 :=
        let cp := @enc F G gop gpow g h m r in
        let sig_proof := generate_enc_proof g h r m uscs cp c
        in (cp, sig_proof).

      (** [verify_encryption_vote_proof g h (cp, pf)] accepts iff [pf] is an
          accepting two-branch disjunctive encryption proof that [cp]
          encrypts [g ^ 0] or [g ^ 1]: every branch is an accepting
          Chaum–Pedersen conversation and the branch challenges add up to
          the main challenge. *)
      Definition verify_encryption_vote_proof (g h : G)
        (cppf : G * G * @Sigma.sigma_proto F (G * G) 2 3 2) : bool :=
        match cppf with
        | (cp, pf) => @generalised_accepting_encryption_proof_elgamal F zero add
          Fdec G ginv gop gpow Gdec _ [g^zero; g^one] g h cp pf
        end.

      (** *** Whole ballots

          The following functions lift the single-vote functions pointwise to
          vectors of length [n], one entry per candidate. They are defined by
          recursion on [n] in proof mode so that they reduce by [cbn]. *)

      (** [encrypt_ballot g h r m] encrypts each vote [m_i] with its own
          randomness [r_i]. *)
      Fixpoint encrypt_ballot {n : nat}
        (g h : G) (r : Vector.t F n) (m : Vector.t F n) : Vector.t (G * G) n.
      Proof.
        destruct n as [| n].
        +
          exact [].
        +
          destruct (vector_inv_S r) as (rh & rt & _).
          destruct (vector_inv_S m) as (mh & mt & _).
          exact (encrypt_vote g h rh mh :: encrypt_ballot _ g h rt mt).
      Defined.

      (** [generate_enc_proof_ballot g h r m uscs cp c] produces the vote
          proof for each candidate, given the ciphertexts [cp], the prover
          randomness [uscs] and one challenge [c_i] per candidate. *)
      Fixpoint generate_enc_proof_ballot {n : nat}
        (g h : G) (r : Vector.t F n) (m : Vector.t F n)
        (uscs : Vector.t (Vector.t F 3) n)
        (cp : Vector.t (G * G) n) (c : Vector.t F n) :
        Vector.t (@Sigma.sigma_proto F (G * G) 2 3 2) n.
      Proof.
        destruct n as [| n].
        +
          exact [].
        +
          destruct (vector_inv_S r) as (rh & rt & _).
          destruct (vector_inv_S m) as (mh & mt & _).
          destruct (vector_inv_S uscs) as (uscsh & uscst & _).
          destruct (vector_inv_S cp) as (cph & cpt & _).
          destruct (vector_inv_S c) as (ch & ct & _).
          exact(generate_enc_proof g h rh mh uscsh cph ch ::
            generate_enc_proof_ballot _ g h rt mt uscst cpt ct).
      Defined.

      (** [generate_ballot_commitment g h r m uscs] computes the
          announcements of all the vote proofs of a ballot before any
          challenge is known (pointwise [generate_enc_proof_commitment] on the
          freshly computed ciphertexts). *)
      Fixpoint generate_ballot_commitment {n : nat}
        (g h : G) (r : Vector.t F n) (m : Vector.t F n)
        (uscs : Vector.t (Vector.t F 3) n) :
        Vector.t (Vector.t (G * G) 2) n.
      Proof.
        destruct n as [| n].
        +
          exact [].
        +
          destruct (vector_inv_S r) as (rh & rt & _).
          destruct (vector_inv_S m) as (mh & mt & _).
          destruct (vector_inv_S uscs) as (uscsh & uscst & _).
          exact (generate_enc_proof_commitment g h mh uscsh (encrypt_vote g h rh mh) ::
            generate_ballot_commitment _ g h rt mt uscst).
      Defined.

      (** [encrypt_ballot_and_generate_enc_proof g h r m uscs c] produces the
          list of pairs (ciphertext, vote proof) for all candidates. *)
      Fixpoint encrypt_ballot_and_generate_enc_proof {n : nat}
        (g h : G) (r : Vector.t F n) (m : Vector.t F n)
        (uscs : Vector.t (Vector.t F 3) n) (c : Vector.t F n) :
        Vector.t (G * G * @Sigma.sigma_proto F (G * G) 2 3 2) n.
      Proof.
        destruct n as [| n].
        +
          exact [].
        +
          destruct (vector_inv_S r) as (rh & rt & _).
          destruct (vector_inv_S m) as (mh & mt & _).
          destruct (vector_inv_S uscs) as (uscsh & uscst & _).
          destruct (vector_inv_S c) as (ch & ct & _).
          exact ((encrypt_vote_and_generate_enc_proof g h rh mh uscsh ch) ::
            (encrypt_ballot_and_generate_enc_proof n
            g h rt mt uscst ct)).
      Defined.

      (** [verify_encryption_ballot_proof g h cppf] is the conjunction of
          [verify_encryption_vote_proof] over all entries of the ballot. *)
      Fixpoint verify_encryption_ballot_proof {n : nat} (g h : G)
        (cppf : Vector.t (G * G * @Sigma.sigma_proto F (G * G) 2 3 2) n) : bool.
      Proof.
        destruct n as [| n].
        +
          exact true.
        +
          destruct (vector_inv_S cppf) as (cppfh & cppft & _).
          exact ((verify_encryption_vote_proof g h cppfh) &&
            (verify_encryption_ballot_proof _ g h cppft))%bool.
      Defined.

      (** *** The overall proof

          The vote proofs show that every entry encrypts 0 or 1. The overall
          proof additionally shows, on the homomorphic product of the
          ballot's ciphertexts, that the number of approvals lies between 0
          and the number of candidates. It is the disjunctive encryption
          proof over the messages [g ^ 0, …, g ^ (n + 1)], proved at the
          index equal to the actual count. Since the per-vote proofs already
          bound the sum by the number of candidates, this proof is useful
          mainly as a template for questions with a smaller maximum. *)

      (** [of_nat k] is the field element [1 + 1 + … + 1] ([k] ones). *)
      Fixpoint of_nat (k : nat) : F :=
        match k with
        | 0 => zero
        | S k' => one + of_nat k'
        end.

      (** [powers g k] is the vector [ [g ^ 0; g ^ 1; …; g ^ k] ] of length
          [k + 1], with [g ^ (j + 1)] computed as [g · g ^ j]. *)
      Fixpoint powers (g : G) (k : nat) : Vector.t G (S k) :=
        match k with
        | 0 => [g ^ zero]
        | S k' => g ^ zero :: Vector.map (fun m => gop g m) (powers g k')
        end.

      (** [ballot_product cps] is the component-wise product of the
          ciphertexts in [cps], the homomorphic encryption of the sum of the
          votes under the sum of the randomness ([ballot_product_enc]). *)
      Definition ballot_product {k : nat} (cps : Vector.t (G * G) k) : G * G :=
        Vector.fold_right (fun '(a, b) '(c, d) => (gop a c, gop b d)) cps (gid, gid).

      (** [count_ones ms] is the number of entries of [ms] equal to [one],
          that is, the number of approvals on the ballot. *)
      Definition count_ones {k : nat} (ms : Vector.t F k) : nat :=
        Vector.fold_right (fun m acc => if Fdec m one then S acc else acc) ms 0.

      (** The number of approvals is bounded by the number of candidates. *)
      Lemma count_ones_le : forall (k : nat) (ms : Vector.t F k), count_ones ms <= k.
      Proof.
        induction k as [| k ih]; intros ms.
        + rewrite (vector_inv_0 ms); cbn; lia.
        + destruct (vector_inv_S ms) as (m & ms' & hm); subst.
          unfold count_ones in *; cbn.
          destruct (Fdec m one); specialize (ih ms'); lia.
      Qed.

      (** [overall_index ms] is the branch index [count_ones ms] of the
          overall proof, as an element of [Fin.t (2 + n)] (the bound comes
          from [count_ones_le]). *)
      Definition overall_index {n : nat} (ms : Vector.t F (S n)) : Fin.t (2 + n) :=
        Fin.of_nat_lt (le_n_S _ _ (count_ones_le _ ms)).

      (** [generate_overall_proof g h rs ms uscs c] proves that the product
          of the ciphertexts of the ballot [ms] (with randomness [rs])
          encrypts [g ^ (count_ones ms)], using the [(n + 2)]-branch
          disjunctive proof over [powers g (S n)] with real branch
          [overall_index ms] and witness [Σ rs]. The prover randomness
          [uscs] holds [n + 2] commitment exponents and [n + 1] simulated
          challenges. *)
      Definition generate_overall_proof {n : nat} (g h : G)
        (rs ms : Vector.t F (S n)) (uscs : Vector.t F ((2 + n) + (1 + n))) (c : F) :
        @Sigma.sigma_proto F (G * G) (2 + n) (1 + (2 + n)) (2 + n) :=
        @generalised_construct_encryption_proof_elgamal_real F zero add mul sub opp
          G ginv gop gpow n (overall_index ms) (Vector.fold_right add rs zero)
          uscs (powers g (S n)) g h (ballot_product (encrypt_ballot g h rs ms)) c.

      (** [verify_overall_proof g h cps pf] checks the overall proof against
          the product of [cps] and the message list [powers g k]. A ballot
          with no candidates ([k = 0]) has nothing to prove and is accepted;
          the dependent match is needed because the proof type depends on
          [k]. *)
      Definition verify_overall_proof {k : nat} (g h : G) (cps : Vector.t (G * G) k)
        (pf : @Sigma.sigma_proto F (G * G) (S k) (S (S k)) (S k)) : bool :=
        match k as k' return Vector.t (G * G) k' ->
          @Sigma.sigma_proto F (G * G) (S k') (S (S k')) (S k') -> bool
        with
        | 0 => fun _ _ => true
        | S k' => fun cps pf =>
          @generalised_accepting_encryption_proof_elgamal F zero add Fdec
            G ginv gop gpow Gdec (S (S k')) (powers g (S k')) g h (ballot_product cps) pf
        end cps pf.

      (** [encrypt_ballot_with_overall_proof] produces the full ballot: one
          ciphertext and vote proof per candidate, together with the overall
          proof on their product. *)
      Definition encrypt_ballot_with_overall_proof {n : nat} (g h : G)
        (rs ms : Vector.t F (S n)) (uscs : Vector.t (Vector.t F 3) (S n))
        (cs : Vector.t F (S n)) (uscs' : Vector.t F ((2 + n) + (1 + n))) (c : F) :
        Vector.t (G * G * @Sigma.sigma_proto F (G * G) 2 3 2) (S n) *
        @Sigma.sigma_proto F (G * G) (2 + n) (1 + (2 + n)) (2 + n) :=
        (encrypt_ballot_and_generate_enc_proof g h rs ms uscs cs,
         generate_overall_proof g h rs ms uscs' c).

      (** [verify_ballot g h b] accepts a full ballot iff all vote proofs and
          the overall proof (computed on the ciphertexts contained in [b])
          are accepting. *)
      Definition verify_ballot {k : nat} (g h : G)
        (b : Vector.t (G * G * @Sigma.sigma_proto F (G * G) 2 3 2) k *
             @Sigma.sigma_proto F (G * G) (S k) (S (S k)) (S k)) : bool :=
        (verify_encryption_ballot_proof g h (fst b) &&
         verify_overall_proof g h (Vector.map fst (fst b)) (snd b))%bool.

      (** *** A prover without a branch on the vote

          [generate_enc_proof] selects the real branch by a case analysis on
          the vote [m], so a compiled prover branches on a secret. The prover
          [generate_enc_proof_ct] computes both announcements as simulated
          ones, with sub-challenge [m · c₁] on the first branch and
          [(1 - m) · c₁] on the second ([c₁] the simulated challenge of
          [uscs]); on the real branch the sub-challenge is [0], and the
          simulated announcement [(g ^ u · c₁' ^ 0, h ^ u · X ^ 0)] is the
          real one [(g ^ u, h ^ u)]. Challenges and responses are combined
          in the same way by multiplications with [m] and [1 - m]. Its
          sequence of field and group operations does not depend on [m]; it
          agrees with [generate_enc_proof] for [m ∈ {0, 1}]
          ([generate_enc_proof_ct_eq]) and is meant for those votes only. *)
      Definition generate_enc_proof_ct
        (g h : G) (r : F) (m : F)
        (uscs : Vector.t F 3) (cp : G * G) (c : F) : @Sigma.sigma_proto F (G * G) 2 3 2 :=
        let u₀ := Vector.hd uscs in
        let u₁ := Vector.hd (Vector.tl uscs) in
        let cs := Vector.hd (Vector.tl (Vector.tl uscs)) in
        let nm := sub one m in
        let cb := sub c (add cs zero) in
        let w := cb * r in
        let sim (u s : F) (mi : G) :=
          match cp with
          | (c₁, c₂) =>
            (gop (g^u) (c₁^(opp s)), gop (h^u) ((gop c₂ (ginv mi))^(opp s)))
          end in
        ([sim u₀ (m * cs) (g^zero); sim u₁ (nm * cs) (g^one)];
         [c; m * cs + nm * cb; nm * cs + m * cb];
         [u₀ + nm * w; u₁ + m * w]).

      (** [encrypt_vote_and_generate_enc_proof] with [generate_enc_proof_ct]. *)
      Definition encrypt_vote_and_generate_enc_proof_ct
        (g h : G) (r : F)  (m : F)
        (uscs : Vector.t F 3) (c : F) : G * G * @Sigma.sigma_proto F (G * G) 2 3 2 :=
        let cp := @enc F G gop gpow g h m r in
        (cp, generate_enc_proof_ct g h r m uscs cp c).

      (** [encrypt_ballot_and_generate_enc_proof] with
          [generate_enc_proof_ct]. *)
      Fixpoint encrypt_ballot_and_generate_enc_proof_ct {n : nat}
        (g h : G) (r : Vector.t F n) (m : Vector.t F n)
        (uscs : Vector.t (Vector.t F 3) n) (c : Vector.t F n) :
        Vector.t (G * G * @Sigma.sigma_proto F (G * G) 2 3 2) n.
      Proof.
        destruct n as [| n].
        +
          exact [].
        +
          destruct (vector_inv_S r) as (rh & rt & _).
          destruct (vector_inv_S m) as (mh & mt & _).
          destruct (vector_inv_S uscs) as (uscsh & uscst & _).
          destruct (vector_inv_S c) as (ch & ct & _).
          exact ((encrypt_vote_and_generate_enc_proof_ct g h rh mh uscsh ch) ::
            (encrypt_ballot_and_generate_enc_proof_ct n
            g h rt mt uscst ct)).
      Defined.

    End Definitions.

    (** ** Correctness, completeness and soundness

        From here on [G] is assumed to be a vector space over [F]
        ([Hvec]), which provides the group, field and exponentiation laws
        used in the algebraic reasoning, and the [field] tactic is enabled
        for [F]. *)
    Section Proofs.

        Context
          {Hvec: @vector_space F (@eq F) zero one add mul sub
