    Lemma zPhi_zPsi : forall l, length l = zR -> zPhi (zPsi l) = l.
    Proof.
      intros l hl. pose proof zR_ge as hR.
      set (at_ := slice l 0 n). set (bt := slice l n n). set (rt := nth (2 * n) l zero). set (st := nth (2 * n + 1) l zero).
