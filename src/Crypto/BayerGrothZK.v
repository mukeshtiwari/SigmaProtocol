  Definition c0 (v : CT) : G := Vector.hd v.
  Definition c1 (v : CT) : G := Vector.hd (Vector.tl v).
  Definition mkct (u v : G) : CT := Vector.cons G u 1 (Vector.cons G v 0 (Vector.nil G)).

  Lemma ct_eta : forall v : CT, v = mkct (c0 v) (c1 v).
  Proof.
    intros v. unfold mkct, c0, c1.
    transitivity (Vector.cons G (Vector.hd v) 1 (Vector.tl v)); [apply Vector.eta |].
    f_equal. transitivity (Vector.cons G (Vector.hd (Vector.tl v)) 0 (Vector.tl (Vector.tl v))); [apply Vector.eta |].
    f_equal. apply Vector.nil_spec.
  Qed.

  Lemma cmul_solve : forall X Y W : CT, cmul X Y = W -> X = cmul W (cpow Y (opp one)).
  Proof. intros X Y W e. rewrite <-e. symmetry. apply (cmul_cancel (Hvec := Hvec) (l := 1)). Qed.

