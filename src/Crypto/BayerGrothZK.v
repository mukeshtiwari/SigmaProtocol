    Variables (A : list (list F)) (r : list F) (s : F) (x y xz : F) (m : nat).
    Local Notation n := (length gs).
    Local Notation cA := (com_list h gs A r).
    Local Notation cb := (com h gs (hprefix A (length A - 1)) s).

    Hypothesis hAm : length A = m.
    Hypothesis hm : (2 <= m)%nat.
    Hypothesis hn : (1 <= n)%nat.
    Hypothesis hr : length r = m.
    Hypothesis hAn : Forall (fun v => length v = n) A.
    Hypothesis hγl : length γ = n.
    Hypothesis hγ : forall j, (j < n)%nat -> nth j gs gid = h ^ (nth j γ zero).

    (* the inner zero argument's witness, as the honest prover forms it *)
    Definition hBs : list (list F) := map (hprefix A) (seq 0 (length A)).
    Definition hss (smid : list F) : list F := nth 0 r zero :: smid ++ [s].
    Definition hA' : list (list F) := tl A ++ [repeat (opp one) n].
    Definition hB' : list (list F) :=
      map (fun i => lscale (fpow x (S i)) (hprefix A i)) (seq 0 (length A - 1)) ++ [lscale x (lveval (tl hBs) x)].
    Definition hr' : list F := tl r ++ [zero].
    Definition hs' (smid : list F) : list F :=
      map (fun i => fpow x (S i) * nth i (hss smid) zero) (seq 0 (length A - 1)) ++ [x * feval (tl (hss smid)) x].

    (* the prover's randomness: s_1..s_{m-2}, then the zero argument's *)
    Definition hR : nat := (m - 2 + zR gs m)%nat.

    Definition hreal (l : list F) : hadamard_argument :=
      let l' := skipn (m - 2) l in
      hadamard_prove h gs n A r s (slice l 0 (m - 2)) x y (slice l' 0 n) (slice l' n n) (nth (2 * n) l' zero)
        (nth (2 * n + 1) l' zero) (slice l' (2 * n + 2) (S m)) (slice l' (2 * n + 3 + m) (m - 1)) xz.

    (* the simulator: c_{B0} = c_{A0} and c_{B(m-1)} = c_b are forced by the verifier,
       the other c_{Bi} are random group elements, and the zero argument is simulated *)
    Definition hsim (cA' : list G) (cb' : G) (l : list F) : hadamard_argument :=
      let cB := nth 0 cA' gid :: map (fun u => h ^ u) (slice l 0 (m - 2)) ++ [cb'] in
      let st := hadamard_zero_stmt h gs n cA' cB x in
      mk_had cB (zsim h gs y xz m (fst st) (snd st) (skipn (m - 2) l)).

    Definition hadamard_real_distribution (lf : list F) (Hlfn : lf <> []) : dist hadamard_argument :=
      Bind (rand lf Hlfn hR) (fun l => Ret (hreal l)).
    Definition hadamard_sim_distribution (lf : list F) (Hlfn : lf <> []) (cA' : list G) (cb' : G) : dist hadamard_argument :=
      Bind (rand lf Hlfn hR) (fun l => Ret (hsim cA' cb' l)).

    Definition hsmid_to_u (smid : list F) : list F := map (fun i => nth i smid zero + dot γ (hprefix A (S i))) (seq 0 (m - 2)).
    Definition hu_to_smid (us : list F) : list F := map (fun i => nth i us zero - dot γ (hprefix A (S i))) (seq 0 (m - 2)).

    Definition hPhi (l : list F) : list F :=
      let smid := slice l 0 (m - 2) in
      hsmid_to_u smid ++ zPhi gs γ hA' hB' hr' (hs' smid) y xz m (skipn (m - 2) l).
    Definition hPsi (l : list F) : list F :=
      let smid := hu_to_smid (slice l 0 (m - 2)) in
      smid ++ zPsi gs γ hA' hB' hr' (hs' smid) y xz m (skipn (m - 2) l).

    Lemma hBs_length : length hBs = m.
    Proof. unfold hBs; rewrite length_map, length_seq; exact hAm. Qed.
    Lemma hss_length : forall smid, length smid = (m - 2)%nat -> length (hss smid) = m.
    Proof. intros smid hsm; unfold hss; cbn [length]; rewrite length_app, hsm; cbn [length]; lia. Qed.
    Lemma hA'_length : length hA' = m.
    Proof. unfold hA'; rewrite length_app, tl_len, hAm; cbn [length]; lia. Qed.
    Lemma hB'_length : length hB' = m.
    Proof. unfold hB'; rewrite length_app, length_map, length_seq, hAm; cbn [length]; lia. Qed.
    Lemma hr'_length : length hr' = m.
    Proof. unfold hr'; rewrite length_app, tl_len, hr; cbn [length]; lia. Qed.
    Lemma hs'_length : forall smid, length (hs' smid) = m.
    Proof. intros smid; unfold hs'; rewrite length_app, length_map, length_seq, hAm; cbn [length]; lia. Qed.
    Lemma hA'_rows : Forall (fun v => length v = n) hA'.
    Proof.
      unfold hA'; apply Forall_app; split.
      + destruct A as [| a0 A0]; [constructor | inversion hAn; assumption].
      + constructor; [apply repeat_length | constructor].
    Qed.
    Lemma hBs_rows : forall v, In v hBs -> length v = n.
    Proof.
      intros v hv; unfold hBs in hv; apply in_map_iff in hv; destruct hv as (i & <- & hi); apply in_seq in hi.
      apply (hprefix_length n A i hAn); lia.
    Qed.
    Lemma tl_hBs_ne : tl hBs <> [].
    Proof. intro e; apply (f_equal (@length (list F))) in e; rewrite tl_len, hBs_length in e; cbn in e; lia. Qed.
    Lemma hB'_rows : Forall (fun v => length v = n) hB'.
    Proof.
      unfold hB'; apply Forall_app; split.
      + rewrite Forall_forall; intros v hv; apply in_map_iff in hv; destruct hv as (i & <- & hi); apply in_seq in hi.
        unfold SigmaK.lscale; rewrite length_map. apply (hprefix_length n A i hAn); lia.
      + constructor; [| constructor]. unfold SigmaK.lscale; rewrite length_map.
        apply lveval_length; [exact tl_hBs_ne |]. intros v hv; apply hBs_rows, in_tl; exact hv.
    Qed.
    Lemma hsmid_to_u_length : forall smid, length (hsmid_to_u smid) = (m - 2)%nat.
    Proof. intros; unfold hsmid_to_u; rewrite length_map, length_seq; reflexivity. Qed.
    Lemma hu_to_smid_length : forall us, length (hu_to_smid us) = (m - 2)%nat.
    Proof. intros; unfold hu_to_smid; rewrite length_map, length_seq; reflexivity. Qed.
    Lemma hu_smid : forall smid, length smid = (m - 2)%nat -> hu_to_smid (hsmid_to_u smid) = smid.
    Proof.
      intros smid hsm. unfold hu_to_smid.
      transitivity (map (fun i => nth i smid zero) (seq 0 (m - 2))); [| apply map_nth_seq_id; exact hsm].
      apply map_ext_in; intros i hi; apply in_seq in hi. unfold hsmid_to_u; rewrite nth_map_seq_gen by lia; cbn [Nat.add]; field.
    Qed.
    Lemma hsmid_u : forall us, length us = (m - 2)%nat -> hsmid_to_u (hu_to_smid us) = us.
    Proof.
      intros us hus. unfold hsmid_to_u.
      transitivity (map (fun i => nth i us zero) (seq 0 (m - 2))); [| apply map_nth_seq_id; exact hus].
      apply map_ext_in; intros i hi; apply in_seq in hi. unfold hu_to_smid; rewrite nth_map_seq_gen by lia; cbn [Nat.add]; field.
    Qed.

    (* the honest transcript is the commitment list c_B with the honest zero argument *)
    Lemma hreal_unfold : forall l, hreal l = mk_had (com_list h gs hBs (hss (slice l 0 (m - 2))))
      (zreal h gs hA' hB' hr' (hs' (slice l 0 (m - 2))) y xz m (skipn (m - 2) l)).
    Proof. intros l; reflexivity. Qed.

    Lemma hreal_eq_hsim : forall l (cA' : list G) (cb' : G), length l = hR ->
      hadamard_verify h gs n cA' cb' x y xz (hreal l) = true -> hreal l = hsim cA' cb' (hPhi l).
    Proof.
      intros l cA' cb' hl hv. unfold hR in hl.
      rewrite hreal_unfold in hv |- *.
      set (smid := slice l 0 (m - 2)) in *. set (l' := skipn (m - 2) l) in *.
      assert (hsm : length smid = (m - 2)%nat) by (apply length_slice; lia).
      assert (hl' : length l' = zR gs m) by (unfold l'; rewrite length_skipn; lia).
      set (cB := com_list h gs hBs (hss smid)) in *.
      assert (hcBl : length cB = m) by (unfold cB; rewrite com_list_length, hBs_length, (hss_length smid hsm), Nat.min_id; reflexivity).
      apply hadamard_verify_true in hv. destruct hv as (hcA2 & hcBA & E0 & Em & hz).
      assert (hcAl : length cA' = m) by lia.
      set (us := hsmid_to_u smid).
      assert (hus : length us = (m - 2)%nat) by apply hsmid_to_u_length.
      assert (hcB : cB = nth 0 cA' gid :: map (fun u => h ^ u) us ++ [cb']).
      { apply (nth_ext _ _ gid gid).
        + rewrite hcBl; cbn [length]; rewrite length_app, length_map, hus; cbn [length]; lia.
        + intros i hi. rewrite hcBl in hi. destruct i as [| i]; [cbn [nth]; exact E0 |].
          cbn [nth]. destruct (Nat.eq_dec (S i) (m - 1)) as [e | e].
          - rewrite app_nth2 by (rewrite length_map, hus; lia). rewrite length_map, hus.
            replace (i - (m - 2))%nat with 0%nat by lia. cbn [nth].
            rewrite <-Em, hcAl, <-e. reflexivity.
          - rewrite app_nth1 by (rewrite length_map, hus; lia).
            rewrite (nth_indep (map (fun u => h ^ u) us) gid (h ^ zero)) by (rewrite length_map, hus; lia).
            rewrite (map_nth (fun u => h ^ u)). unfold us, hsmid_to_u. rewrite nth_map_seq_gen by lia. cbn [Nat.add].
            unfold cB. rewrite (nth_com_list (zero := zero)) by (rewrite ?hBs_length, ?(hss_length smid hsm); lia).
            unfold hBs; rewrite nth_map_seq_gen by lia. cbn [Nat.add].
            unfold hss; cbn [nth]. rewrite app_nth1 by lia.
            apply (com_dlog h gs γ (hprefix A (S i)) (nth i smid zero) hγl hγ). }
      unfold hsim, hPhi; cbv zeta. fold smid l' us.
      set (Z := zPhi gs γ hA' hB' hr' (hs' smid) y xz m l').
      rewrite (slice_app0 us Z (m - 2) hus), (skipn_app_exact us Z (m - 2) hus).
      rewrite <-hcB. f_equal.
      apply (zreal_eq_zsim h gs γ hA' hB' hr' (hs' smid) y xz m hA'_length hn (ltac:(lia)) hB'_length hr'_length
        (hs'_length smid) hA'_rows hB'_rows hγl hγ l' _ _ hl').
      unfold hadamard_zero_stmt; cbv zeta; cbn [fst snd]. exact hz.
    Qed.

    Lemma hPhi_length : forall l, length l = hR -> length (hPhi l) = hR.
    Proof.
      intros l hl. unfold hR in *. unfold hPhi; cbv zeta. rewrite length_app, hsmid_to_u_length. f_equal.
      apply (zPhi_length gs γ hA' hB' hr' _ y xz m hA'_length hn (ltac:(lia)) hB'_length hr'_length (hs'_length _) hA'_rows hB'_rows hγl).
      rewrite length_skipn; lia.
    Qed.

    Lemma hPsi_length : forall l, length l = hR -> length (hPsi l) = hR.
    Proof.
      intros l hl. unfold hR in *. unfold hPsi; cbv zeta. rewrite length_app, hu_to_smid_length. f_equal.
      apply (zPsi_length gs γ hA' hB' hr' _ y xz m hA'_length hn (ltac:(lia)) hB'_length hr'_length (hs'_length _) hA'_rows hB'_rows hγl).
      rewrite length_skipn; lia.
    Qed.

    Lemma hPsi_hPhi : forall l, length l = hR -> hPsi (hPhi l) = l.
    Proof.
      intros l hl. unfold hR in hl.
      unfold hPhi; cbv zeta. set (smid := slice l 0 (m - 2)). set (l' := skipn (m - 2) l).
      assert (hsm : length smid = (m - 2)%nat) by (apply length_slice; lia).
      assert (hl' : length l' = zR gs m) by (unfold l'; rewrite length_skipn; lia).
      set (us := hsmid_to_u smid). set (Z := zPhi gs γ hA' hB' hr' (hs' smid) y xz m l').
      assert (hus : length us = (m - 2)%nat) by apply hsmid_to_u_length.
      unfold hPsi; cbv zeta. rewrite (slice_app0 us Z (m - 2) hus), (skipn_app_exact us Z (m - 2) hus).
      unfold us; rewrite (hu_smid smid hsm). unfold Z.
      rewrite (zPsi_zPhi gs γ hA' hB' hr' (hs' smid) y xz m hA'_length hn (ltac:(lia)) hB'_length hr'_length
        (hs'_length smid) hA'_rows hB'_rows hγl l' hl').
      unfold smid, l', slice; cbn [skipn]. apply firstn_skipn.
    Qed.

    Lemma hPhi_hPsi : forall l, length l = hR -> hPhi (hPsi l) = l.
    Proof.
      intros l hl. unfold hR in hl.
      unfold hPsi; cbv zeta. set (us := slice l 0 (m - 2)). set (l' := skipn (m - 2) l).
      assert (hus : length us = (m - 2)%nat) by (apply length_slice; lia).
      assert (hl' : length l' = zR gs m) by (unfold l'; rewrite length_skipn; lia).
      set (smid := hu_to_smid us). set (Z := zPsi gs γ hA' hB' hr' (hs' smid) y xz m l').
      assert (hsm : length smid = (m - 2)%nat) by apply hu_to_smid_length.
      unfold hPhi; cbv zeta. rewrite (slice_app0 smid Z (m - 2) hsm), (skipn_app_exact smid Z (m - 2) hsm).
      unfold Z. rewrite (zPhi_zPsi gs γ hA' hB' hr' (hs' smid) y xz m hA'_length hn (ltac:(lia)) hB'_length hr'_length
        (hs'_length smid) hA'_rows hB'_rows hγl l' hl').
      unfold smid; rewrite (hsmid_u us hus).
      unfold us, l', slice; cbn [skipn]. apply firstn_skipn.
    Qed.

    (* the verifier rejects the challenges 0 *)
    Hypothesis hx0 : x <> zero.
    Hypothesis hy0 : y <> zero.

    Lemma hreal_eq_hsim_honest : forall l, length l = hR -> hreal l = hsim cA cb (hPhi l).
    Proof.
      intros l hl. apply hreal_eq_hsim; [exact hl |]. unfold hR, zR in hl. unfold hreal; cbv zeta.
      apply hadamard_completeness; rewrite ?hAm; try assumption; try reflexivity; apply length_slice; rewrite ?length_skipn; lia.
    Qed.

    Theorem hadamard_shvzk : forall (lf : list F) (Hlfn : lf <> []),
      NoDup lf -> (forall v : F, In v lf) ->
      Permutation (hadamard_real_distribution lf Hlfn) (hadamard_sim_distribution lf Hlfn cA cb).
    Proof.
      intros lf Hlfn hnd hall. unfold hadamard_real_distribution, hadamard_sim_distribution.
      apply (zk_of_bijection lf Hlfn hR hreal (hsim cA cb) hPhi hPsi hnd hall hPhi_length hPsi_length hPsi_hPhi hPhi_hPsi).
      intros l hl. apply hreal_eq_hsim_honest. exact hl.
    Qed.

  End HadamardZK.


