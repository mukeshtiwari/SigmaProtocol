  Lemma slice_app_gen : forall (a rest : list F) k off len, length a = k -> slice (a ++ rest) (k + off) len = slice rest off len.
  Proof. intros a rest k off len hl; unfold slice; rewrite skipn_app, skipn_all2, hl by lia; replace (k + off - k)%nat with off by lia; reflexivity. Qed.

  Lemma nth_map_seq_gen : forall {X : Type} (f : nat -> X) (st len i : nat) (d : X), (i < len)%nat ->
    nth i (map f (seq st len)) d = f (st + i)%nat.
  Proof.
    intros X f st len i d hi. rewrite (nth_indep _ d (f 0%nat)) by (rewrite length_map, length_seq; exact hi).
    rewrite map_nth, seq_nth by exact hi. reflexivity.
  Qed.

  Lemma list_hd_tl : forall (l : list G) (d : G), l <> [] -> l = nth 0 l d :: tl l.
  Proof. intros l d hl; destruct l; [contradiction | reflexivity]. Qed.

  Lemma gop_solve_r : forall u v w : G, gop u v = w -> v = gop w (ginv u).
  Proof. intros u v w e. apply gop_solve. rewrite gcomm. exact e. Qed.

  (* splitting a list into consecutive slices *)
  Lemma firstn_add_skipn : forall (l : list F) k k', firstn (Nat.add k k') l = firstn k l ++ firstn k' (skipn k l).
  Proof.
    intros l k; revert l; induction k as [| k ih]; intros l k'; [reflexivity |].
    destruct l as [| a l]; [cbn [firstn skipn app]; rewrite !firstn_nil; reflexivity |].
    cbn [Nat.add firstn skipn app]. rewrite ih. reflexivity.
  Qed.

  Lemma slice_split : forall (l : list F) off len len', slice l off (len + len')%nat = slice l off len ++ slice l (off + len)%nat len'.
  Proof. intros; unfold slice. rewrite firstn_add_skipn, skipn_skipn, (Nat.add_comm len off). reflexivity. Qed.

  Lemma slice_one : forall (l : list F) off, (off < length l)%nat -> slice l off 1 = [nth off l zero].
  Proof.
    intros l off hoff. unfold slice.
    assert (hne : skipn off l <> []) by (intro e; apply (f_equal (@length F)) in e; rewrite length_skipn in e; cbn in e; lia).
    destruct (skipn off l) as [| a t] eqn:e; [contradiction |]. cbn [firstn]. f_equal.
    transitivity (nth 0 (skipn off l) zero); [rewrite e; reflexivity | rewrite nth_skipn_add, Nat.add_0_r; reflexivity].
  Qed.

  Lemma slice_all : forall (l : list F) k, length l = k -> slice l 0 k = l.
  Proof. intros l k hk; unfold slice; cbn [skipn]; apply firstn_all2; lia. Qed.

  Lemma map_nth_seq_id : forall (l : list F) k, length l = k -> map (fun i => nth i l zero) (seq 0 k) = l.
  Proof.
    intros l k hk. apply (nth_ext _ _ zero zero).
    + rewrite length_map, length_seq; symmetry; exact hk.
    + intros i hi; rewrite length_map, length_seq in hi. rewrite nth_map_seq_gen by exact hi. reflexivity.
  Qed.

  Section ZeroZK.

    Variables (h : G) (gs : list G) (γ : list F).
    Variables (A B : list (list F)) (r s : list F) (y x : F) (m : nat).
    Local Notation n := (length gs).
    Hypothesis hAm : length A = m.
    Local Notation cA := (com_list h gs A r).
    Local Notation cB := (com_list h gs B s).

    (* the prover's randomness: a_0, b_m ∈ F^n, r_0, s_m, t_0..t_m, t_{m+2}..t_{2m} *)
    Definition zR : nat := (2 * n + 2 * m + 2)%nat.

    Definition zreal (l : list F) : zero_argument :=
      zero_prove h gs A B r s y (slice l 0 n) (slice l n n) (nth (2 * n) l zero) (nth (2 * n + 1) l zero)
        (slice l (2 * n + 2) (S m)) (slice l (2 * n + 3 + m) (m - 1)) x.

    (* the simulator: responses ã, b̃, r̃, s̃, t̃ and the discrete logarithms of
      c_{d_1}, …, c_{d_m}, c_{d_{m+2}}, …, c_{d_{2m}} at random; c_{d_{m+1}} = 1 and
      c_{A0}, c_{Bm}, c_{d_0} from the verification equations *)
    Definition zsim (cA' cB' : list G) (l : list F) : zero_argument :=
      let at_ := slice l 0 n in
      let bt := slice l n n in
      let rt := nth (2 * n) l zero in
      let st := nth (2 * n + 1) l zero in
      let tt := nth (2 * n + 2) l zero in
      let us := slice l (2 * n + 3) (2 * m - 1) in
      let cdt := map (fun k => if Nat.eqb k (S m) then gid else h ^ (nth (if Nat.leb k m then k - 1 else k - 2) us zero)) (seq 1 (2 * m)) in
      mk_zero (gop (com h gs at_ rt) (ginv ((geval cA' x) ^ x))) (gop (com h gs bt st) (ginv ((geval (rev cB') x) ^ x)))
        (gop (com h gs [star y at_ bt] tt) (ginv ((geval cdt x) ^ x)) :: cdt) at_ bt rt st tt.

    Definition zero_real_distribution (lf : list F) (Hlfn : lf <> []) : dist zero_argument :=
      Bind (rand lf Hlfn zR) (fun l => Ret (zreal l)).
    Definition zero_sim_distribution (lf : list F) (Hlfn : lf <> []) (cA' cB' : list G) : dist zero_argument :=
      Bind (rand lf Hlfn zR) (fun l => Ret (zsim cA' cB' l)).

    (* the bijection: the real randomness to the simulator's randomness *)
    Definition zPhi (l : list F) : list F :=
      let a0 := slice l 0 n in
      let bm := slice l n n in
      let r0 := nth (2 * n) l zero in
      let sm := nth (2 * n + 1) l zero in
      let t1 := slice l (2 * n + 2) (S m) in
      let t2 := slice l (2 * n + 3 + m) (m - 1) in
      let tz := t1 ++ zero :: t2 in
      let d := fpmul (star y) (a0 :: A) (bm :: rev B) in
      lveval (a0 :: A) x ++ lveval (bm :: rev B) x ++
      [feval (r0 :: r) x; feval (sm :: rev s) x; feval tz x] ++
      map (fun k => nth k tz zero + nth 0 γ zero * nth k d zero) (seq 1 m ++ seq (m + 2) (m - 1)).

    Definition zPsi (l : list F) : list F :=
      let at_ := slice l 0 n in
      let bt := slice l n n in
      let rt := nth (2 * n) l zero in
      let st := nth (2 * n + 1) l zero in
      let tt := nth (2 * n + 2) l zero in
      let us := slice l (2 * n + 3) (2 * m - 1) in
      let a0 := psub at_ (lscale x (lveval A x)) in
      let bm := psub bt (lscale x (lveval (rev B) x)) in
      let r0 := rt - x * feval r x in
      let sm := st - x * feval (rev s) x in
      let d := fpmul (star y) (a0 :: A) (bm :: rev B) in
      let ttl := map (fun k => nth (k - 1) us zero - nth 0 γ zero * nth k d zero) (seq 1 m) ++
                 zero :: map (fun k => nth (k - 2) us zero - nth 0 γ zero * nth k d zero) (seq (m + 2) (m - 1)) in
      let t0 := tt - x * feval ttl x in
      a0 ++ bm ++ [r0; sm] ++ (t0 :: firstn m ttl) ++ skipn (m + 1) ttl.


    Hypothesis hn : (1 <= n)%nat.
    Hypothesis hm : (1 <= m)%nat.
    Hypothesis hB : length B = m.
    Hypothesis hr : length r = m.
    Hypothesis hs : length s = m.
    Hypothesis hAn : Forall (fun v => length v = n) A.
    Hypothesis hBn : Forall (fun v => length v = n) B.
    Hypothesis hγl : length γ = n.
    Hypothesis hγ : forall j, (j < n)%nat -> nth j gs gid = h ^ (nth j γ zero).

    (* the pieces of the real randomness *)
    Lemma zR_ge : (2 * n + 3 + m + (m - 1) <= zR)%nat.
