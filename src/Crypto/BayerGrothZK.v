    Lemma svp_prove_eq_ssim : forall (d dmid : list F) (rd s0 sx : F) (ca' : G) (b' : F),
      length d = n -> length dmid = (n - 2)%nat ->
      svp_verify h gs ca' b' x (svp_prove h gs a r d rd dmid s0 sx x) = true ->
      svp_prove h gs a r d rd dmid s0 sx x =
      ssim ca' b' (map (fun k => x * nth k a zero + nth k d zero) (seq 0 n) ++ [x * r + rd; x * sx + s0]
        ++ map (fun k => x * prefix_prod a (S k) + nth k dmid zero) (seq 0 (n - 2)) ++ [sx + dot γ (DeltaOf d dmid)]).
    Proof.
      intros d dmid rd s0 sx ca' b' hd hdmid hv.
      set (ta := map (fun k => x * nth k a zero + nth k d zero) (seq 0 n)).
      set (bmid := map (fun k => x * prefix_prod a (S k) + nth k dmid zero) (seq 0 (n - 2))).
      set (u := sx + dot γ (DeltaOf d dmid)).
      assert (hta : length ta = n) by (unfold ta; rewrite length_map, length_seq; reflexivity).
      assert (hbmid : length bmid = (n - 2)%nat) by (unfold bmid; rewrite length_map, length_seq; reflexivity).
      destruct (ssim_slices ta bmid (x * r + rd) (x * sx + s0) u hta hbmid) as (S1 & S2 & S3 & S4 & S5).
      unfold ssim; cbv zeta. rewrite S1, S2, S3, S4, S5.
      unfold BayerGroth.svp_prove in hv |- *; cbv beta zeta in hv |- *. rewrite ha in hv |- *. fold ta in hv |- *.
      apply svp_verify_true in hv. destruct hv as (_ & htb & E1 & E2 & E3 & E4).
      rewrite hta in htb, E2, E4.
      set (tb := map (fun k => x * prefix_prod a k + nth k (nth 0 d zero :: dmid ++ [zero]) zero) (seq 0 n)) in *.
      assert (hb : tb = nth 0 ta zero :: bmid ++ [x * b']).
      { apply (nth_ext _ _ zero zero).
        + rewrite htb; cbn [length]; rewrite length_app, hbmid; cbn [length]; lia.
        + intros i hi. rewrite htb in hi. destruct i as [| i].
          - cbn [nth]. exact E3.
          - cbn [nth]. destruct (Nat.eq_dec (S i) (n - 1)) as [e | e].
            * replace i with (n - 2)%nat by lia. rewrite (nth_app_len bmid _ _ zero hbmid). cbn [nth].
              replace (S (n - 2)) with (n - 1)%nat by lia. exact E4.
            * rewrite app_nth1 by (rewrite hbmid; lia).
              unfold tb, bmid; rewrite !nth_map_seq_gen by lia. cbn [Nat.add nth].
              rewrite app_nth1 by (rewrite hdmid; lia). reflexivity. }
      rewrite <-hb. unfold u. rewrite <-(com_dlog h gs γ (DeltaOf d dmid) sx hγl hγ). unfold DeltaOf; cbv beta zeta.
      f_equal; solve [exact (gop_solve_r _ _ _ E1) | exact (gop_solve_r _ _ _ E2) | reflexivity].
    Qed.

