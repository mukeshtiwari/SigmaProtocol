    Hypothesis hγl : length γ = n.
    Hypothesis hγ : forall j, (j < n)%nat -> nth j gs gid = h ^ (nth j γ zero).
    Hypothesis hdl : forall v : G, g ^ dl v = v.
    Hypothesis hdl' : forall u : F, dl (g ^ u) = u.

    (* the prover's randomness: r, s, then the product argument's, then the multi-exponentiation argument's *)
    Definition shR : nat := (2 * m + pR gs m + mR gs m)%nat.

    Definition shreal (l : list F) : shuffle_argument :=
      let r := slice l 0 m in let s := slice l m m in
      let lp := slice l (2 * m) (pR gs m) in let lm := skipn (2 * m + pR gs m) l in
      let lh := slice lp 1 (hR gs m) in let lz := skipn (m - 2) lh in let ls := skipn (1 + hR gs m) lp in
      shuffle_prove h gs g pk m n Cs' perm ρs r s (nth 0 lp zero) (slice lh 0 (m - 2))
        (slice lz 0 n) (slice lz n n) (nth (2 * n) lz zero) (nth (2 * n + 1) lz zero)
        (slice lz (2 * n + 2) (S m)) (slice lz (2 * n + 3 + m) (m - 1))
        (slice ls 0 n) (nth n ls zero) (slice ls (n + 1) (n - 2)) (nth (2 * n - 1) ls zero) (nth (2 * n) ls zero)
        (slice lm 0 n) (nth n lm zero) (slice lm (n + 1) (2 * m)) (slice lm (n + 1 + 2 * m) (2 * m)) (slice lm (n + 1 + 4 * m) (2 * m))
        x y z xh yh xz xs xm.

    (* the simulator: random commitments c_A, c_B and the two simulated sub-arguments *)
    Definition shsim (Cs0 Cs0' : list CT) (l : list F) : shuffle_argument :=
      let cA := map (fun u => h ^ u) (slice l 0 m) in let cB := map (fun u => h ^ u) (slice l m m) in
      let lp := slice l (2 * m) (pR gs m) in let lm := skipn (2 * m + pR gs m) l in
      let st := shuffle_product_stmt h gs n Nn cA cB x y z in
      mk_shuffle cA cB (psim h gs xh yh xz xs m (fst st) (snd st) lp)
        (msim h gs g sk xm m (chunk n m Cs0') (shuffle_mexp_C Cs0 x Nn) cB lm).

    Definition shuffle_real_distribution (lf : list F) (Hlfn : lf <> []) : dist shuffle_argument :=
      Bind (rand lf Hlfn shR) (fun l => Ret (shreal l)).
    Definition shuffle_sim_distribution (lf : list F) (Hlfn : lf <> []) (Cs0 Cs0' : list CT) : dist shuffle_argument :=
      Bind (rand lf Hlfn shR) (fun l => Ret (shsim Cs0 Cs0' l)).

    Definition shPhi (l : list F) : list F :=
      let r := slice l 0 m in let s := slice l m m in
      let lp := slice l (2 * m) (pR gs m) in let lm := skipn (2 * m + pR gs m) l in
      map (fun i => nth i r zero + dot γ (nth i A [])) (seq 0 m) ++ map (fun i => nth i s zero + dot γ (nth i B [])) (seq 0 m)
      ++ pPhi gs γ (chunk n m dz) (ladd (lscale y r) s) xh yh xz xs m lp ++ mPhi gs γ sk dl (chunk n m Cs') B s ρ xm m lm.
    Definition shPsi (l : list F) : list F :=
      let r := map (fun i => nth i (slice l 0 m) zero - dot γ (nth i A [])) (seq 0 m) in
      let s := map (fun i => nth i (slice l m m) zero - dot γ (nth i B [])) (seq 0 m) in
      let lp := slice l (2 * m) (pR gs m) in let lm := skipn (2 * m + pR gs m) l in
      r ++ s ++ pPsi gs γ (chunk n m dz) (ladd (lscale y r) s) xh yh xz xs m lp ++ mPsi gs γ sk dl (chunk n m Cs') B s ρ xm m lm.

