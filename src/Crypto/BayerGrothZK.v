    (* the 2m entries of a block, with distinguished 0-th and m-th entries *)
    Definition pblk (f0 : F) (fm f : nat -> F) : list F :=
      map (fun k => if Nat.eqb k 0 then f0 else if Nat.eqb k m then fm k else f k) (seq 0 (2 * m)).
    (* the entries 1..2m-1 of a block *)
    Definition blk (f fm : nat -> F) : list F := map (fun k => if Nat.eqb k m then fm k else f k) (seq 1 (2 * m - 1)).

    (* the simulator: random responses; c_{Bk} = h^{u_k} and E_k = (g^{u'_k}, g^{v_k}) random for
       k ∉ {0, m}, c_{Bm} = 1 and E_m = C as the verifier demands, and c_{A0}, c_{B0}, E_0 forced
       by the verifier's three equations *)
    Definition msim (Cs' : list (list CT)) (C' : CT) (cA' : list G) (l : list F) : multiexp_argument :=
      let a := slice l 0 n in let rt := nth n l zero in
      let Bb := slice l (n + 1) (2 * m) in let Sb := slice l (n + 1 + 2 * m) (2 * m) in let Tb := slice l (n + 1 + 4 * m) (2 * m) in
      let b := nth 0 Bb zero in let s := nth 0 Sb zero in let τ := nth 0 Tb zero in
      let cBt := map (fun k => if Nat.eqb k m then gid else h ^ nth k Sb zero) (seq 1 (2 * m - 1)) in
      let Et := map (fun k => if Nat.eqb k m then C' else mkct (g ^ nth k Tb zero) (g ^ nth k Bb zero)) (seq 1 (2 * m - 1)) in
      let prodC := cprod (map (fun p => cmexp (snd p) (lscale (fpow x (m - fst p - 1)) a)) (combine (seq 0 m) Cs')) in
      mk_mexp (gop (com h gs a rt) (ginv ((geval cA' x) ^ x)))
        (gop (com h gs [b] s) (ginv ((geval cBt x) ^ x)) :: cBt)
        (cmul (cmul (encg g pk b τ) prodC) (cpow (cpow (ceval Et x) x) (opp one)) :: Et)
        a rt b s τ.

