    Lemma tlen : forall (r s : list F), length r = m -> length s = m -> length (ladd (lscale y r) s) = m.
    Proof. intros r s hr hs. rewrite ladd_length; unfold SigmaK.lscale; rewrite length_map; [exact hr | rewrite hr, hs; reflexivity]. Qed.

    (* ---- slices ---- *)

    Lemma shslices : forall (X Y P M : list F), length X = m -> length Y = m -> length P = pR gs m ->
      let l := X ++ Y ++ P ++ M in
      slice l 0 m = X /\ slice l m m = Y /\ slice l (2 * m) (pR gs m) = P /\ skipn (2 * m + pR gs m) l = M.
    Proof.
      intros X Y P M hX hY hP. cbv zeta. repeat split.
      + apply slice_app0; exact hX.
      + rewrite (slice_app X _ m m hX). apply slice_app0; exact hY.
      + replace (2 * m)%nat with (m + m)%nat by lia.
        rewrite (slice_app_gen X _ m m _ hX), (slice_app Y _ m _ hY). apply slice_app0; exact hP.
      + replace (2 * m + pR gs m)%nat with (m + (m + pR gs m))%nat by lia.
        rewrite (skipn_app_gen X _ m _ hX), (skipn_app_gen Y _ m _ hY). exact (skipn_app_exact P M _ hP).
    Qed.

    Lemma shrecompose : forall l, length l = shR ->
      l = slice l 0 m ++ slice l m m ++ slice l (2 * m) (pR gs m) ++ skipn (2 * m + pR gs m) l.
    Proof.
      intros l hl. unfold shR in hl.
      transitivity (firstn (2 * m + pR gs m) l ++ skipn (2 * m + pR gs m) l); [symmetry; apply firstn_skipn |].
      rewrite !app_assoc. f_equal. rewrite <-app_assoc.
      transitivity (slice l 0 (m + (m + pR gs m))); [unfold slice; cbn [skipn]; f_equal; lia |].
      rewrite !slice_split. replace (0 + m)%nat with m by lia. replace (m + m)%nat with (2 * m)%nat by lia. reflexivity.
    Qed.

    Lemma shreal_unfold : forall l,
      shreal l = mk_shuffle (com_list h gs A (slice l 0 m)) (com_list h gs B (slice l m m))
        (preal h gs (chunk n m dz) (ladd (lscale y (slice l 0 m)) (slice l m m)) xh yh xz xs m (slice l (2 * m) (pR gs m)))
        (mreal h gs g sk (chunk n m Cs') B (slice l m m) ρ xm m (skipn (2 * m + pR gs m) l)).
    Proof. intros l; reflexivity. Qed.

    Lemma com_list_dlog : forall (As : list (list F)) (rs : list F), length As = m -> length rs = m ->
      com_list h gs As rs = map (fun u => h ^ u) (map (fun i => nth i rs zero + dot γ (nth i As [])) (seq 0 m)).
    Proof.
      intros As rs hAs hrs. apply (nth_ext _ _ gid gid).
      + rewrite com_list_length, hAs, hrs, Nat.min_id, !length_map, length_seq; reflexivity.
      + intros i hi. rewrite com_list_length, hAs, hrs, Nat.min_id in hi.
        rewrite (nth_com_list (zero := zero)) by (rewrite ?hAs, ?hrs; lia).
        rewrite (nth_indep _ gid (h ^ zero)) by (rewrite !length_map, length_seq; lia).
        rewrite (map_nth (fun u => h ^ u)). rewrite nth_map_seq_gen by lia; cbn [Nat.add].
        apply (com_dlog h gs γ _ _ hγl hγ).
    Qed.

    (* ---- the honest transcript is the simulator's output ---- *)

    Lemma shreal_eq_shsim : forall l (Cs0 Cs0' : list CT), length l = shR ->
      shuffle_verify h gs g pk m n Cs0 Cs0' x y z xh yh xz xs xm (shreal l) = true -> shreal l = shsim Cs0 Cs0' (shPhi l).
    Proof.
      intros l Cs0 Cs0' hl hv. unfold shR in hl.
      rewrite shreal_unfold in hv |- *.
      set (r := slice l 0 m) in *. set (s := slice l m m) in *.
      set (lp := slice l (2 * m) (pR gs m)) in *. set (lm := skipn (2 * m + pR gs m) l) in *.
      assert (hr : length r = m) by (apply length_slice; lia).
      assert (hs : length s = m) by (apply length_slice; lia).
      assert (hlp : length lp = pR gs m) by (apply length_slice; lia).
      assert (hlm : length lm = mR gs m) by (unfold lm; rewrite length_skipn; lia).
      set (t := ladd (lscale y r) s) in *.
      assert (htl : length t = m) by (apply tlen; assumption).
      apply shuffle_verify_true in hv. destruct hv as (_ & _ & hC0 & hC0' & hcAl & hcBl & hvp & hvm).
      set (us := map (fun i => nth i r zero + dot γ (nth i A [])) (seq 0 m)).
      set (vs := map (fun i => nth i s zero + dot γ (nth i B [])) (seq 0 m)).
      assert (hus : length us = m) by (unfold us; rewrite length_map, length_seq; reflexivity).
      assert (hvs : length vs = m) by (unfold vs; rewrite length_map, length_seq; reflexivity).
      pose proof (com_list_dlog A r shAm hr) as hcA. pose proof (com_list_dlog B s shBm hs) as hcB.
      fold us in hcA. fold vs in hcB.
      rewrite hcA, hcB in hvp. rewrite hcB in hvm. rewrite hcA, hcB.
      unfold shsim, shPhi; cbv zeta. fold r s lp lm t us vs.
      set (P := pPhi gs γ (chunk n m dz) t xh yh xz xs m lp). set (M := mPhi gs γ sk dl (chunk n m Cs') B s ρ xm m lm).
      assert (hP : length P = pR gs m) by apply (pPhi_length gs γ (chunk n m dz) t xh yh xz xs m shDm hm hn htl shDn hγl lp hlp).
      destruct (shslices us vs P M hus hvs hP) as (S1 & S2 & S3 & S4). rewrite S1, S2, S3, S4.
      f_equal.
      - unfold shuffle_product_stmt; cbv zeta; cbn [fst snd].
        apply (preal_eq_psim h gs γ (chunk n m dz) t xh yh xz xs m shDm hm hn htl shDn hγl hγ lp _ _ hlp).
        + rewrite !length_map, combine_length, !length_map, hus, hvs; lia.
        + exact hvp.
      - apply (mreal_eq_msim h gs γ g sk dl (chunk n m Cs') B s ρ xm m shBm hm (ltac:(lia)) shCm hs shBn hγl hγ hdl lm _ _ _ hlm).
        exact hvm.
    Qed.

    (* ---- the bijection ---- *)

    Lemma rs_undo : forall (As : list (list F)) (rs : list F), length rs = m ->
      map (fun i => nth i (map (fun i => nth i rs zero + dot γ (nth i As [])) (seq 0 m)) zero - dot γ (nth i As [])) (seq 0 m) = rs.
    Proof.
      intros As rs hrs. transitivity (map (fun i => nth i rs zero) (seq 0 m)); [| apply map_nth_seq_id; exact hrs].
      apply map_ext_in; intros i hi; apply in_seq in hi. rewrite nth_map_seq_gen by lia; cbn [Nat.add]; field.
    Qed.
    Lemma us_undo : forall (As : list (list F)) (us : list F), length us = m ->
      map (fun i => nth i (map (fun i => nth i us zero - dot γ (nth i As [])) (seq 0 m)) zero + dot γ (nth i As [])) (seq 0 m) = us.
    Proof.
      intros As us hus. transitivity (map (fun i => nth i us zero) (seq 0 m)); [| apply map_nth_seq_id; exact hus].
      apply map_ext_in; intros i hi; apply in_seq in hi. rewrite nth_map_seq_gen by lia; cbn [Nat.add]; field.
    Qed.

    Lemma shPhi_length : forall l, length l = shR -> length (shPhi l) = shR.
    Proof.
      intros l hl. unfold shR in *. unfold shPhi; cbv zeta.
      assert (hr : length (slice l 0 m) = m) by (apply length_slice; lia).
      assert (hs : length (slice l m m) = m) by (apply length_slice; lia).
      assert (hlp : length (slice l (2 * m) (pR gs m)) = pR gs m) by (apply length_slice; lia).
      assert (hlm : length (skipn (2 * m + pR gs m) l) = mR gs m) by (rewrite length_skipn; lia).
      rewrite !length_app, !length_map, !length_seq.
      rewrite (pPhi_length gs γ (chunk n m dz) _ xh yh xz xs m shDm hm hn (tlen _ _ hr hs) shDn hγl _ hlp).
      rewrite (mPhi_length gs γ sk dl (chunk n m Cs') B _ ρ xm m shBm hm (ltac:(lia)) shCm hs shBn hγl _ hlm). lia.
    Qed.

    Lemma shPsi_length : forall l, length l = shR -> length (shPsi l) = shR.
    Proof.
      intros l hl. unfold shR in *. unfold shPsi; cbv zeta.
      assert (hlp : length (slice l (2 * m) (pR gs m)) = pR gs m) by (apply length_slice; lia).
      assert (hlm : length (skipn (2 * m + pR gs m) l) = mR gs m) by (rewrite length_skipn; lia).
      assert (hr : length (map (fun i => nth i (slice l 0 m) zero - dot γ (nth i A [])) (seq 0 m)) = m) by (rewrite length_map, length_seq; reflexivity).
      assert (hs : length (map (fun i => nth i (slice l m m) zero - dot γ (nth i B [])) (seq 0 m)) = m) by (rewrite length_map, length_seq; reflexivity).
      rewrite !length_app, hr, hs.
      rewrite (pPsi_length gs γ (chunk n m dz) _ xh yh xz xs m shDm hm hn (tlen _ _ hr hs) shDn hγl _ hlp).
      rewrite (mPsi_length gs γ sk dl (chunk n m Cs') B _ ρ xm m shBm hm (ltac:(lia)) shCm hs shBn hγl _ hlm). lia.
    Qed.

    Lemma shPsi_shPhi : forall l, length l = shR -> shPsi (shPhi l) = l.
    Proof.
      intros l hl. pose proof (shrecompose l hl) as hdec. unfold shR in hl.
      unfold shPhi; cbv zeta.
      set (r := slice l 0 m) in *. set (s := slice l m m) in *.
      set (lp := slice l (2 * m) (pR gs m)) in *. set (lm := skipn (2 * m + pR gs m) l) in *.
      assert (hr : length r = m) by (apply length_slice; lia).
      assert (hs : length s = m) by (apply length_slice; lia).
      assert (hlp : length lp = pR gs m) by (apply length_slice; lia).
      assert (hlm : length lm = mR gs m) by (unfold lm; rewrite length_skipn; lia).
      set (us := map (fun i => nth i r zero + dot γ (nth i A [])) (seq 0 m)).
      set (vs := map (fun i => nth i s zero + dot γ (nth i B [])) (seq 0 m)).
      assert (hus : length us = m) by (unfold us; rewrite length_map, length_seq; reflexivity).
      assert (hvs : length vs = m) by (unfold vs; rewrite length_map, length_seq; reflexivity).
      set (t := ladd (lscale y r) s). assert (htl : length t = m) by (apply tlen; assumption).
      set (P := pPhi gs γ (chunk n m dz) t xh yh xz xs m lp). set (M := mPhi gs γ sk dl (chunk n m Cs') B s ρ xm m lm).
      assert (hP : length P = pR gs m) by apply (pPhi_length gs γ (chunk n m dz) t xh yh xz xs m shDm hm hn htl shDn hγl lp hlp).
      unfold shPsi; cbv zeta.
      destruct (shslices us vs P M hus hvs hP) as (S1 & S2 & S3 & S4). rewrite S1, S2, S3, S4.
      unfold us, vs. rewrite (rs_undo A r hr), (rs_undo B s hs). fold t.
      unfold P, M.
      rewrite (pPsi_pPhi gs γ (chunk n m dz) t xh yh xz xs m shDm hm hn htl shDn hγl lp hlp).
      rewrite (mPsi_mPhi gs γ sk dl (chunk n m Cs') B s ρ xm m shBm hm (ltac:(lia)) shCm hs shBn hγl lm hlm).
      exact (eq_sym hdec).
    Qed.

    Lemma shPhi_shPsi : forall l, length l = shR -> shPhi (shPsi l) = l.
    Proof.
      intros l hl. pose proof (shrecompose l hl) as hdec. unfold shR in hl.
      unfold shPsi; cbv zeta.
      set (us := slice l 0 m) in *. set (vs := slice l m m) in *.
      set (lp := slice l (2 * m) (pR gs m)) in *. set (lm := skipn (2 * m + pR gs m) l) in *.
      assert (hus : length us = m) by (apply length_slice; lia).
      assert (hvs : length vs = m) by (apply length_slice; lia).
      assert (hlp : length lp = pR gs m) by (apply length_slice; lia).
      assert (hlm : length lm = mR gs m) by (unfold lm; rewrite length_skipn; lia).
      set (r := map (fun i => nth i us zero - dot γ (nth i A [])) (seq 0 m)).
      set (s := map (fun i => nth i vs zero - dot γ (nth i B [])) (seq 0 m)).
      assert (hr : length r = m) by (unfold r; rewrite length_map, length_seq; reflexivity).
      assert (hs : length s = m) by (unfold s; rewrite length_map, length_seq; reflexivity).
      set (t := ladd (lscale y r) s). assert (htl : length t = m) by (apply tlen; assumption).
      set (P := pPsi gs γ (chunk n m dz) t xh yh xz xs m lp). set (M := mPsi gs γ sk dl (chunk n m Cs') B s ρ xm m lm).
      assert (hP : length P = pR gs m) by apply (pPsi_length gs γ (chunk n m dz) t xh yh xz xs m shDm hm hn htl shDn hγl lp hlp).
      unfold shPhi; cbv zeta.
      destruct (shslices r s P M hr hs hP) as (S1 & S2 & S3 & S4). rewrite S1, S2, S3, S4. fold t.
      unfold P, M.
      rewrite (pPhi_pPsi gs γ (chunk n m dz) t xh yh xz xs m shDm hm hn htl shDn hγl lp hlp).
      rewrite (mPhi_mPsi gs γ sk dl (chunk n m Cs') B s ρ xm m shBm hm (ltac:(lia)) shCm hs shBn hγl lm hlm).
      unfold r, s. rewrite (us_undo A us hus), (us_undo B vs hvs).
      exact (eq_sym hdec).
    Qed.

    (* the verifier rejects the Hadamard challenges 0 (for m > 1) *)
    Hypothesis hxh0 : (1 < m)%nat -> xh <> zero.
    Hypothesis hyh0 : (1 < m)%nat -> yh <> zero.

    Lemma shreal_eq_shsim_honest : forall l, length l = shR -> shreal l = shsim Cs Cs' (shPhi l).
    Proof.
      intros l hl. apply shreal_eq_shsim; [exact hl |]. unfold shR in hl. unfold shreal; cbv zeta.
      assert (hlp : length (slice l (2 * m) (pR gs m)) = pR gs m) by (apply length_slice; lia).
      assert (hlh : length (slice (slice l (2 * m) (pR gs m)) 1 (hR gs m)) = hR gs m) by (apply length_slice; rewrite hlp; unfold pR; lia).
      assert (hlm : length (skipn (2 * m + pR gs m) l) = mR gs m) by (rewrite length_skipn; lia).
      apply shuffle_completeness; try assumption; try reflexivity;
        apply length_slice; rewrite ?length_skipn, ?hlh, ?hlp, ?hlm; try unfold pR, hR, zR, sR, mR in *; lia.
    Qed.

    Theorem shuffle_shvzk : forall (lf : list F) (Hlfn : lf <> []),
      NoDup lf -> (forall v : F, In v lf) ->
      Permutation (shuffle_real_distribution lf Hlfn) (shuffle_sim_distribution lf Hlfn Cs Cs').
    Proof.
      intros lf Hlfn hnd hall. unfold shuffle_real_distribution, shuffle_sim_distribution.
      apply (zk_of_bijection lf Hlfn shR shreal (shsim Cs Cs') shPhi shPsi hnd hall shPhi_length shPsi_length shPsi_shPhi shPhi_shPsi).
      intros l hl. apply shreal_eq_shsim_honest. exact hl.
    Qed.

