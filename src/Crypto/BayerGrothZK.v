  Definition slice (l : list F) (off len : nat) : list F := firstn len (skipn off l).

  Lemma length_slice : forall l off len, (off + len <= length l)%nat -> length (slice l off len) = len.
  Proof. intros; unfold slice; rewrite length_firstn, length_skipn; lia. Qed.

  Lemma slice_app0 : forall (a r : list F) len, length a = len -> slice (a ++ r) 0 len = a.
  Proof. intros a r len hl; unfold slice; cbn [skipn]; rewrite firstn_app, firstn_all2, hl, Nat.sub_diag by lia; cbn; apply app_nil_r. Qed.

  Lemma skipn_app_exact : forall (a r : list F) off, length a = off -> skipn off (a ++ r) = r.
  Proof. intros a r off hl; rewrite skipn_app, skipn_all2, hl, Nat.sub_diag by lia; reflexivity. Qed.

  Lemma slice_app : forall (a r : list F) off len, length a = off -> slice (a ++ r) off len = slice r 0 len.
  Proof. intros; unfold slice; rewrite skipn_app_exact by assumption; reflexivity. Qed.

  Lemma slice_skip : forall (l : list F) off1 off2 len, slice l (off1 + off2) len = slice (skipn off1 l) off2 len.
  Proof. intros; unfold slice; rewrite skipn_skipn, Nat.add_comm; reflexivity. Qed.

  Lemma nth_app_exact : forall (a r : list F) off i d, length a = off -> nth (off + i) (a ++ r) d = nth i r d.
  Proof. intros a r off i d hl; rewrite app_nth2 by lia; rewrite hl; replace (off + i - off)%nat with i by lia; reflexivity. Qed.

  Lemma nth_app_len : forall (a rest : list F) k d, length a = k -> nth k (a ++ rest) d = nth 0 rest d.
  Proof. intros a rest k d hl; rewrite app_nth2 by lia; rewrite hl, Nat.sub_diag; reflexivity. Qed.

  (* a list of length ≥ 2 as its first two elements *)
  Lemma firstn2 : forall (l : list F), (2 <= length l)%nat -> firstn 2 l = [nth 0 l zero; nth 1 l zero].
  Proof. intros l hl; destruct l as [| a [| b l]]; cbn in hl; try lia; reflexivity. Qed.

  (* pointwise difference of two lists *)
  Definition psub (a b : list F) : list F := map (fun p => fst p - snd p) (combine a b).

  Lemma psub_padd : forall a b, length a = length b -> padd (psub a b) b = a.
  Proof.
    induction a as [| a0 a ih]; intros b hl; destruct b as [| b0 b]; try discriminate; [reflexivity |].
    unfold psub in *; cbn [combine map fst snd SigmaK.padd]. rewrite ih by (cbn in hl; lia). f_equal; field.
  Qed.

  Lemma padd_psub : forall a b, length a = length b -> psub (padd a b) b = a.
  Proof.
    induction a as [| a0 a ih]; intros b hl; destruct b as [| b0 b]; try discriminate; [reflexivity |].
    unfold psub in *; cbn [combine map fst snd SigmaK.padd]. rewrite ih by (cbn in hl; lia). f_equal; field.
  Qed.

  Lemma psub_length : forall a b, length a = length b -> length (psub a b) = length a.
  Proof. intros; unfold psub; rewrite length_map, length_combine; lia. Qed.

