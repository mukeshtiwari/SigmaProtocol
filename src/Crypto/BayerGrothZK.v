  Lemma nth_cons_S : forall (c : F) (t : list F) (k : nat), (0 < k)%nat -> nth k (c :: t) zero = nth (k - 1) t zero.
  Proof. intros c t k hk; destruct k as [| k]; [lia | cbn [nth]; f_equal; lia]. Qed.

  (** Section for the multi-exponentiation argument. *)
  Section MultiExpZK.

    (** The commitment key [h], [gs] with discrete logarithms [γ]; the
        ElGamal generator [g], secret key [sk] (only [pk = g ^ sk] is used
        by the prover and the simulator; [sk] appears in the bijection) and
        a discrete-logarithm function [dl] to base [g]. The witness: the
        exponent columns [A] with randomness [r] and the re-encryption
        randomness [ρ]; the ciphertext rows [Cs]; the challenge [x]. *)
    Variables (h : G) (gs : list G) (γ : list F) (g : G) (sk : F) (dl : G -> F).
    Variables (Cs : list (list CT)) (A : list (list F)) (r : list F) (ρ : F) (x : F) (m : nat).
    (** [pk] is the public key, [cA] the commitment to [A] and [C] the
        target ciphertext [Enc(1; ρ) · Π_i Cs_i ^ A_i]. *)
    Local Notation n := (length gs).
    Local Notation pk := (Vector.cons G (g ^ sk) 0 (Vector.nil G)).
    Local Notation cA := (com_list h gs A r).
    Local Notation C := (cmul (enc g pk (Vector.const gid 1) ρ)
      (cprod (map (fun p => cmexp (snd p) (nth (fst p) A [])) (combine (seq 0 (length A)) Cs)))).

    (** Side conditions: [m ≥ 1], [n ≥ 1], the lengths of [A], [Cs], [r],
        columns of length [n], and [gs_j = h ^ γ_j]. Moreover [hdl]:
        [g ^ dl v = v] for every [v : G], so [g] generates [G]. The converse
        [hdl'] is declared but not used by any proof, so it does not appear
        in the exported theorems. *)
    Hypothesis hAm : length A = m.
    Hypothesis hm : (1 <= m)%nat.
    Hypothesis hn : (1 <= n)%nat.
    Hypothesis hCs : length Cs = m.
    Hypothesis hr : length r = m.
    Hypothesis hAn : Forall (fun v => length v = n) A.
    Hypothesis hγl : length γ = n.
    Hypothesis hγ : forall j, (j < n)%nat -> nth j gs gid = h ^ (nth j γ zero).
    Hypothesis hdl : forall v : G, g ^ dl v = v.
    Hypothesis hdl' : forall u : F, dl (g ^ u) = u.

    (** Number of coins: [a_0 ∈ F^n], [r_0], and three blocks of [2m]
        scalars [b_k], [s_k], [τ_k] (whose [m]-th entries are overwritten
        by the prover). *)
    Definition mR : nat := (n + 1 + 6 * m)%nat.

    (** The honest transcript: [multiexp_prove] with its coins read from
        [l]. *)
    Definition mreal (l : list F) : multiexp_argument :=
      multiexp_prove h gs g pk Cs A r ρ (slice l 0 n) (nth n l zero) (slice l (n + 1) (2 * m))
        (slice l (n + 1 + 2 * m) (2 * m)) (slice l (n + 1 + 4 * m) (2 * m)) x.

    (** [pblk f0 fm f] is the block [k ↦ f0] at [k = 0], [fm m] at
        [k = m] and [f k] elsewhere, for [k < 2m]. *)
    Definition pblk (f0 : F) (fm f : nat -> F) : list F :=
      map (fun k => if Nat.eqb k 0 then f0 else if Nat.eqb k m then fm k else f k) (seq 0 (2 * m)).
    (** [blk f fm] is the block of entries [1 .. 2m-1], with [fm m] at
        [k = m] and [f k] elsewhere. *)
    Definition blk (f fm : nat -> F) : list F := map (fun k => if Nat.eqb k m then fm k else f k) (seq 1 (2 * m - 1)).

    (** The simulator on statement [Cs'], [C'], [cA']. From [l] it reads
        responses [a], [r̃], [b̃ = Bb_0], [s̃ = Sb_0], [τ̃ = Tb_0] and, for
        [k ∈ 1..2m-1], sets [c_{Bk} = h ^ Sb_k] and
        [E_k = (g ^ Tb_k, g ^ Bb_k)], except [c_{Bm} = 1] and [E_m = C'].
        It solves the three verification equations for [c_{A0}], [c_{B0}]
        and [E_0]. Only the public key [pk = g ^ sk] is used. *)
    Definition msim (Cs' : list (list CT)) (C' : CT) (cA' : list G) (l : list F) : multiexp_argument :=
      let a := slice l 0 n in let rt := nth n l zero in
      let Bb := slice l (n + 1) (2 * m) in let Sb := slice l (n + 1 + 2 * m) (2 * m) in let Tb := slice l (n + 1 + 4 * m) (2 * m) in
      let b := nth 0 Bb zero in let s := nth 0 Sb zero in let τ := nth 0 Tb zero in
      let cBt := map (fun k => if Nat.eqb k m then gid else h ^ nth k Sb zero) (seq 1 (2 * m - 1)) in
      let Et := map (fun k => if Nat.eqb k m then C' else mkct (g ^ nth k Tb zero) (g ^ nth k Bb zero)) (seq 1 (2 * m - 1)) in
      let prodC := cprod (map (fun p => cmexp (snd p) (lscale (fpow x (m - fst p - 1)) a)) (combine (seq 0 m) Cs')) in
      mk_mexp (gop (com h gs a rt) (ginv ((geval cA' x) ^ x)))
        (gop (com h gs [b] s) (ginv ((geval cBt x) ^ x)) :: cBt)
        (cmul (cmul (encg g pk b τ) prodC) (cpow (cpow (ceval Et x) x) (opp one)) :: Et)
        a rt b s τ.

    (** The real and simulated distributions over uniform coins. *)
    Definition multiexp_real_distribution (lf : list F) (Hlfn : lf <> []) : dist multiexp_argument :=
      Bind (rand lf Hlfn mR) (fun l => Ret (mreal l)).
    Definition multiexp_sim_distribution (lf : list F) (Hlfn : lf <> []) (Cs' : list (list CT)) (C' : CT) (cA' : list G)
      : dist multiexp_argument := Bind (rand lf Hlfn mR) (fun l => Ret (msim Cs' C' cA' l)).

    (** The diagonal products [D_k] for the extended witness [a_0 :: A]. *)
    Definition mD (a0 : list F) : list CT := diagonals m Cs (a0 :: A).

    (** The bijection from prover coins to simulator coins: the responses
        [a = Σ x^i a_i], [r], [b], [s], [τ] (evaluations of the blocks with
        the forced [m]-th entries); for [k ≠ 0, m], the discrete logarithms
        of [E_k = Enc(g ^ b_k; τ_k) · D_k], namely
        [τ_k + dl (c0 D_k)] and [sk τ_k + b_k + dl (c1 D_k)], and the
        discrete logarithm [s_k + γ_0 b_k] of [c_{Bk}]; at [k = m] the
        prover's unused coin is passed through unchanged. *)
    Definition mPhi (l : list F) : list F :=
      let a0 := slice l 0 n in let r0 := nth n l zero in
      let bs := slice l (n + 1) (2 * m) in let ss := slice l (n + 1 + 2 * m) (2 * m) in let τs := slice l (n + 1 + 4 * m) (2 * m) in
      let D := mD a0 in
      lveval (a0 :: A) x ++ [feval (r0 :: r) x]
      ++ pblk (feval (set_nth m zero bs) x) (fun k => nth k bs zero) (fun k => sk * nth k τs zero + nth k bs zero + dl (c1 (nth k D cone)))
      ++ pblk (feval (set_nth m zero ss) x) (fun k => nth k ss zero) (fun k => nth k ss zero + nth 0 γ zero * nth k bs zero)
      ++ pblk (feval (set_nth m ρ τs) x) (fun k => nth k τs zero) (fun k => nth k τs zero + dl (c0 (nth k D cone))).

    (** Components of the inverse map: recover [τ_k], then [b_k], then
        [s_k] from the simulator's exponents. *)
    Definition mtau (Tb : list F) (D : list CT) (k : nat) : F := nth k Tb zero - dl (c0 (nth k D cone)).
    Definition mb (Bb Tb : list F) (D : list CT) (k : nat) : F := nth k Bb zero - sk * mtau Tb D k - dl (c1 (nth k D cone)).
    Definition ms (Sb Bb Tb : list F) (D : list CT) (k : nat) : F := nth k Sb zero - nth 0 γ zero * mb Bb Tb D k.

    (** The inverse of [mPhi]: recover [a_0], [r_0], then [b_k], [s_k],
        [τ_k] for [k ≠ 0] (with [D] recomputed from the recovered [a_0])
        and finally [b_0], [s_0], [τ_0] from the responses. *)
    Definition mPsi (l : list F) : list F :=
      let a := slice l 0 n in let rt := nth n l zero in
      let Bb := slice l (n + 1) (2 * m) in let Sb := slice l (n + 1 + 2 * m) (2 * m) in let Tb := slice l (n + 1 + 4 * m) (2 * m) in
      let a0 := psub a (lscale x (lveval A x)) in
      let D := mD a0 in
      a0 ++ [rt - x * feval r x]
      ++ ((nth 0 Bb zero - x * feval (blk (mb Bb Tb D) (fun _ => zero)) x) :: blk (mb Bb Tb D) (fun k => nth k Bb zero))
      ++ ((nth 0 Sb zero - x * feval (blk (ms Sb Bb Tb D) (fun _ => zero)) x) :: blk (ms Sb Bb Tb D) (fun k => nth k Sb zero))
      ++ ((nth 0 Tb zero - x * feval (blk (mtau Tb D) (fun _ => ρ)) x) :: blk (mtau Tb D) (fun k => nth k Tb zero)).

    (** Lengths and entries of [pblk] and [blk] ([pblk_length],
        [blk_length], [nth_pblk_0], [nth_pblk_m], [nth_pblk], [nth_blk]). *)
    Lemma pblk_length : forall f0 fm f, length (pblk f0 fm f) = (2 * m)%nat.
    Proof. intros; unfold pblk; rewrite length_map, length_seq; reflexivity. Qed.
    Lemma blk_length : forall f fm, length (blk f fm) = (2 * m - 1)%nat.
    Proof. intros; unfold blk; rewrite length_map, length_seq; reflexivity. Qed.
    Lemma nth_pblk_0 : forall f0 fm f, nth 0 (pblk f0 fm f) zero = f0.
    Proof. intros; unfold pblk; rewrite nth_map_seq_gen by lia; reflexivity. Qed.
    Lemma nth_pblk_m : forall f0 fm f, nth m (pblk f0 fm f) zero = fm m.
    Proof.
      intros; unfold pblk; rewrite nth_map_seq_gen by lia; cbn [Nat.add].
      replace (m =? 0) with false by (symmetry; apply Nat.eqb_neq; lia). rewrite Nat.eqb_refl. reflexivity.
    Qed.
    Lemma nth_pblk : forall f0 fm f k, (k < 2 * m)%nat -> k <> 0 -> k <> m -> nth k (pblk f0 fm f) zero = f k.
    Proof.
      intros; unfold pblk; rewrite nth_map_seq_gen by lia; cbn [Nat.add].
      replace (k =? 0) with false by (symmetry; apply Nat.eqb_neq; lia).
      replace (k =? m) with false by (symmetry; apply Nat.eqb_neq; lia). reflexivity.
    Qed.
    Lemma nth_blk : forall f fm i, (i < 2 * m - 1)%nat -> nth i (blk f fm) zero = if Nat.eqb (S i) m then fm (S i) else f (S i).
    Proof. intros; unfold blk; rewrite nth_map_seq_gen by lia; cbn [Nat.add]; reflexivity. Qed.

    (** A [blk] that agrees with [xs] on entries [1 .. 2m-1] is [tl xs]. *)
    Lemma blk_eq_tl : forall (xs : list F) f fm, length xs = (2 * m)%nat ->
      (forall k, (0 < k < 2 * m)%nat -> (if Nat.eqb k m then fm k else f k) = nth k xs zero) -> blk f fm = tl xs.
    Proof.
      intros xs f fm hxs hk. apply (nth_ext _ _ zero zero); [rewrite blk_length, tl_len; lia |].
      intros i hi; rewrite blk_length in hi. rewrite nth_blk by exact hi.
      rewrite nth_tl by (destruct xs; [cbn in hxs; lia | discriminate]). apply hk; lia.
    Qed.

    (** Overwriting entry [m] of [c :: blk f fm] replaces [fm]. *)
    Lemma set_nth_cons_blk : forall (c v : F) f fm, set_nth m v (c :: blk f fm) = c :: blk f (fun _ => v).
    Proof.
      intros. apply (nth_ext _ _ zero zero); [rewrite set_nth_length; cbn [length]; rewrite !blk_length; reflexivity |].
      intros i hi. rewrite set_nth_length in hi. cbn [length] in hi; rewrite blk_length in hi.
      rewrite (nth_set_nth (zero := zero)) by (cbn [length]; rewrite blk_length; lia).
      destruct i as [| i]; [replace (0 =? m) with false by (symmetry; apply Nat.eqb_neq; lia); reflexivity |].
      cbn [nth]. rewrite !nth_blk by lia. destruct (Nat.eqb (S i) m); reflexivity.
    Qed.

    (** Reading back the five fields of a coin list of length [mR]. *)
    Lemma mslices : forall (X B S_ T : list F) (y : F), length X = n -> length B = (2 * m)%nat ->
      length S_ = (2 * m)%nat -> length T = (2 * m)%nat ->
      let l := X ++ [y] ++ B ++ S_ ++ T in
      slice l 0 n = X /\ nth n l zero = y /\ slice l (n + 1) (2 * m) = B /\
      slice l (n + 1 + 2 * m) (2 * m) = S_ /\ slice l (n + 1 + 4 * m) (2 * m) = T.
    Proof.
      intros X B S_ T y hX hB hS hT. cbv zeta. repeat split.
      + apply slice_app0; exact hX.
      + rewrite (nth_app_len X _ n zero hX); reflexivity.
      + rewrite (slice_app_gen X _ n 1 (2 * m) hX), (slice_app [y] _ 1 (2 * m) eq_refl). apply slice_app0; exact hB.
      + replace (n + 1 + 2 * m)%nat with (n + (1 + 2 * m))%nat by lia.
        rewrite (slice_app_gen X _ n _ _ hX), (slice_app_gen [y] _ 1 (2 * m) (2 * m) eq_refl), (slice_app B _ (2 * m) (2 * m) hB).
        apply slice_app0; exact hS.
      + replace (n + 1 + 4 * m)%nat with (n + (1 + (2 * m + 2 * m)))%nat by lia.
        rewrite (slice_app_gen X _ n _ _ hX), (slice_app_gen [y] _ 1 _ _ eq_refl), (slice_app_gen B _ (2 * m) (2 * m) (2 * m) hB),
          (slice_app S_ _ (2 * m) (2 * m) hS). apply slice_all; exact hT.
    Qed.

    (** Every list of length [mR] is the assembly of its five fields. *)
    Lemma mrecompose : forall l, length l = mR ->
      l = slice l 0 n ++ [nth n l zero] ++ slice l (n + 1) (2 * m) ++ slice l (n + 1 + 2 * m) (2 * m) ++ slice l (n + 1 + 4 * m) (2 * m).
    Proof.
      intros l hl. unfold mR in hl.
      transitivity (slice l 0 (n + (1 + (2 * m + (2 * m + 2 * m))))); [symmetry; apply slice_all; lia |].
      rewrite !slice_split, slice_one by lia.
      replace (0 + n)%nat with n by lia. replace (n + 1 + 2 * m + 2 * m)%nat with (n + 1 + 4 * m)%nat by lia. reflexivity.
    Qed.

    (** Length facts: [A] is non-empty and the evaluations
        [Σ x^i A_i] (scaled or extended by [a_0]) have length [n]. *)
    Lemma mAne : A <> [].
    Proof. destruct A; [cbn in hAm; lia | discriminate]. Qed.
    Lemma mlA : length (lveval A x) = n.
    Proof. apply lveval_length; [exact mAne | rewrite Forall_forall in hAn; exact hAn]. Qed.
    Lemma mlsc : length (lscale x (lveval A x)) = n.
    Proof. unfold SigmaK.lscale; rewrite length_map; exact mlA. Qed.
    Lemma lveval_cons_length : forall a0, length a0 = n -> length (lveval (a0 :: A) x) = n.
    Proof.
      intros a0 ha0. apply lveval_length; [discriminate |].
      intros v [<- | hv]; [exact ha0 | rewrite Forall_forall in hAn; apply hAn; exact hv].
    Qed.

    (** Under [hdl], [Enc(g ^ b; τ) · d] is the pair
        [(g ^ (τ + dl d_0), g ^ (sk τ + b + dl d_1))]: an encryption
        multiplied by any ciphertext is a pair of powers of [g] whose
        exponents are translates of [τ] and [b]. *)
    Lemma encg_mul_ct : forall (b τ : F) (d : CT),
      cmul (encg g pk b τ) d = mkct (g ^ (τ + dl (c0 d))) (g ^ (sk * τ + b + dl (c1 d))).
    Proof.
      intros b τ d. transitivity (cmul (encg g pk b τ) (mkct (c0 d) (c1 d))); [rewrite <-ct_eta; reflexivity |].
      unfold BayerGroth.encg, BayerGroth.enc, mkct, vec_add. cbn [Vector.map2 Vector.const].
      rewrite !gpow_add, gpow_mul, !hdl. reflexivity.
    Qed.

    (** Key equation: if the multi-exponentiation verifier accepts
        [mreal l] on statement [Cs'], [C'], [cA'], then
        [mreal l = msim Cs' C' cA' (mPhi l)]. *)
    Lemma mreal_eq_msim : forall l (Cs' : list (list CT)) (C' : CT) (cA' : list G), length l = mR ->
      multiexp_verify h gs g pk Cs' C' cA' x (mreal l) = true -> mreal l = msim Cs' C' cA' (mPhi l).
    Proof.
      intros l Cs' C' cA' hl hv. unfold mR in hl.
      unfold mreal, BayerGroth.multiexp_prove in hv |- *; cbv zeta in hv |- *. rewrite hAm in hv |- *.
      set (a0 := slice l 0 n) in *. set (r0 := nth n l zero) in *.
      set (bs := slice l (n + 1) (2 * m)) in *. set (ss := slice l (n + 1 + 2 * m) (2 * m)) in *.
      set (τs := slice l (n + 1 + 4 * m) (2 * m)) in *.
      set (bz := set_nth m zero bs) in *. set (sz := set_nth m zero ss) in *. set (τz := set_nth m ρ τs) in *.
      set (D := diagonals m Cs (a0 :: A)) in *.
      set (E := cpadd (map (fun p => encg g pk (fst p) (snd p)) (combine bz τz)) D) in *.
      set (cB := com_list h gs (map (fun bk => [bk]) bz) sz) in *.
      assert (ha0 : length a0 = n) by (apply length_slice; lia).
      assert (hbs : length bs = (2 * m)%nat) by (apply length_slice; lia).
      assert (hss : length ss = (2 * m)%nat) by (apply length_slice; lia).
      assert (hτs : length τs = (2 * m)%nat) by (apply length_slice; lia).
      assert (hbz : length bz = (2 * m)%nat) by (unfold bz; rewrite set_nth_length; exact hbs).
      assert (hsz : length sz = (2 * m)%nat) by (unfold sz; rewrite set_nth_length; exact hss).
      assert (hτz : length τz = (2 * m)%nat) by (unfold τz; rewrite set_nth_length; exact hτs).
      assert (hcB : length cB = (2 * m)%nat) by (unfold cB; rewrite com_list_length, length_map, hbz, hsz, Nat.min_id; reflexivity).
      (* The verifier's checks: lengths, c_{Bm} = 1, E_m = C' and the three
         verification equations. *)
      apply multiexp_verify_true in hv. destruct hv as (hm' & hCs' & hcBl & hEl & EBm & EEm & E1 & E2 & E3).
      assert (hcAl : length cA' = m) by lia.
      rewrite hcAl in hEl, EEm, E3.
      pose proof (lveval_cons_length a0 ha0) as hla.
      set (Bb := pblk (feval bz x) (fun k => nth k bs zero) (fun k => sk * nth k τs zero + nth k bs zero + dl (c1 (nth k D cone)))).
      set (Sb := pblk (feval sz x) (fun k => nth k ss zero) (fun k => nth k ss zero + nth 0 γ zero * nth k bs zero)).
      set (Tb := pblk (feval τz x) (fun k => nth k τs zero) (fun k => nth k τs zero + dl (c0 (nth k D cone)))).
      unfold msim, mPhi; cbv zeta. fold a0 r0 bs ss τs bz sz τz. unfold mD; fold D. fold Bb Sb Tb.
      destruct (mslices (lveval (a0 :: A) x) Bb Sb Tb (feval (r0 :: r) x) hla (pblk_length _ _ _) (pblk_length _ _ _) (pblk_length _ _ _))
        as (S1 & S2 & S3 & S4 & S5).
      rewrite S1, S2, S3, S4, S5.
      assert (hB0 : nth 0 Bb zero = feval bz x) by apply nth_pblk_0.
      assert (hS0 : nth 0 Sb zero = feval sz x) by apply nth_pblk_0.
      assert (hT0 : nth 0 Tb zero = feval τz x) by apply nth_pblk_0.
      rewrite hB0, hS0, hT0.
      set (cBt := map (fun k => if Nat.eqb k m then gid else h ^ nth k Sb zero) (seq 1 (2 * m - 1))).
      set (Et := map (fun k => if Nat.eqb k m then C' else mkct (g ^ nth k Tb zero) (g ^ nth k Bb zero)) (seq 1 (2 * m - 1))).
      assert (hcBne : cB <> []) by (intro e; rewrite e in hcB; cbn in hcB; lia).
      assert (hEne : E <> []) by (intro e; rewrite e in hEl; cbn in hEl; lia).
      (* The free commitments c_{Bk} are powers of h (com_single_dlog). *)
      assert (hcBt : tl cB = cBt).
      { apply (nth_ext _ _ gid gid).
        + unfold cBt; rewrite tl_len, length_map, length_seq, hcB; reflexivity.
        + intros i hi. rewrite tl_len, hcB in hi. rewrite nth_tl by exact hcBne.
          unfold cBt; rewrite nth_map_seq_gen by lia; cbn [Nat.add].
          unfold cB. rewrite (nth_com_list (zero := zero)) by (rewrite ?length_map, ?hbz, ?hsz; lia).
          rewrite (nth_indep (map (fun bk => [bk]) bz) [] ((fun bk => [bk]) zero)) by (rewrite length_map, hbz; lia).
          rewrite (map_nth (fun bk => [bk])).
          unfold bz, sz; rewrite !(nth_set_nth (zero := zero)) by lia.
          destruct (Nat.eqb (S i) m) eqn:e.
          - apply com_zero_single.
          - unfold Sb; rewrite nth_pblk by (try lia; apply Nat.eqb_neq; exact e).
            apply (com_single_dlog h gs γ _ _ hγl hn hγ). }
      (* The free ciphertexts E_k are pairs of powers of g (encg_mul_ct). *)
      assert (hEt : tl E = Et).
      { apply (nth_ext _ _ cone cone).
        + unfold Et; rewrite tl_len, length_map, length_seq, hEl; reflexivity.
        + intros i hi. rewrite tl_len, hEl in hi. rewrite nth_tl by exact hEne.
          unfold Et; rewrite nth_map_seq_gen by lia; cbn [Nat.add].
          destruct (Nat.eqb (S i) m) eqn:e.
          - apply Nat.eqb_eq in e. rewrite e. exact EEm.
          - unfold E. rewrite (nth_vpadd (HV := CTvs)).
            rewrite (nth_indep (map (fun p => encg g pk (fst p) (snd p)) (combine bz τz)) cone
              ((fun p => encg g pk (fst p) (snd p)) (zero, zero))) by (rewrite length_map, combine_length, hbz, hτz; lia).
            rewrite (map_nth (fun p => encg g pk (fst p) (snd p))). rewrite combine_nth by (rewrite hbz, hτz; reflexivity). cbn [fst snd].
            unfold bz, τz; rewrite !(nth_set_nth (zero := zero)) by lia. rewrite e.
            unfold Bb, Tb; rewrite !nth_pblk by (try lia; apply Nat.eqb_neq; exact e).
            apply encg_mul_ct. }
      (* The solved announcements c_{A0}, c_{B0}, E_0. *)
      rewrite <-hcBt, <-hEt. f_equal.
      - rewrite (veval_cons (HV := Hvec)) in E1. exact (gop_solve _ _ _ E1).
      - transitivity (nth 0 cB gid :: tl cB); [apply list_hd_tl_gen; exact hcBne |]. f_equal.
        rewrite (list_hd_tl_gen cB gid hcBne) in E2. rewrite (veval_cons (HV := Hvec)) in E2. exact (gop_solve _ _ _ E2).
      - transitivity (nth 0 E cone :: tl E); [apply list_hd_tl_gen; exact hEne |]. f_equal.
        rewrite (list_hd_tl_gen E cone hEne) in E3. rewrite (veval_cons (HV := CTvs)) in E3. exact (cmul_solve _ _ _ E3).
    Qed.

    (** On the honest statement, acceptance follows from
        [multiexp_completeness]. *)
    Lemma mreal_eq_msim_honest : forall l, length l = mR -> mreal l = msim Cs C cA (mPhi l).
    Proof.
      intros l hl. apply mreal_eq_msim; [exact hl |]. unfold mR in hl. unfold mreal.
      apply multiexp_completeness; rewrite ?hAm; try assumption; try (apply length_slice; lia);
        (constructor; [apply length_slice; lia | assumption]).
    Qed.

    (** [mPhi] preserves length [mR]. *)
    Lemma mPhi_length : forall l, length l = mR -> length (mPhi l) = mR.
    Proof.
      intros l hl. unfold mR in *. unfold mPhi; cbv zeta.
      rewrite !length_app, !pblk_length. cbn [length].
      rewrite (lveval_cons_length _ (length_slice l 0 n (ltac:(lia)))). lia.
    Qed.

    (** [mPsi] preserves length [mR]. *)
    Lemma mPsi_length : forall l, length l = mR -> length (mPsi l) = mR.
    Proof.
      intros l hl. unfold mR in *. unfold mPsi; cbv zeta.
      rewrite !length_app. cbn [length]. rewrite !blk_length, psub_length by (rewrite mlsc; apply length_slice; lia).
      rewrite length_slice by lia. lia.
    Qed.

    (** [mPsi] is a left inverse of [mPhi] on lists of length [mR]. *)
    Lemma mPsi_mPhi : forall l, length l = mR -> mPsi (mPhi l) = l.
    Proof.
      intros l hl. pose proof (mrecompose l hl) as hdec. unfold mR in hl.
      unfold mPhi; cbv zeta.
      set (a0 := slice l 0 n) in *. set (r0 := nth n l zero) in *.
      set (bs := slice l (n + 1) (2 * m)) in *. set (ss := slice l (n + 1 + 2 * m) (2 * m)) in *.
      set (τs := slice l (n + 1 + 4 * m) (2 * m)) in *.
      set (D := mD a0).
      assert (ha0 : length a0 = n) by (apply length_slice; lia).
      assert (hbs : length bs = (2 * m)%nat) by (apply length_slice; lia).
      assert (hss : length ss = (2 * m)%nat) by (apply length_slice; lia).
      assert (hτs : length τs = (2 * m)%nat) by (apply length_slice; lia).
      pose proof (lveval_cons_length a0 ha0) as hla.
      set (Bb := pblk (feval (set_nth m zero bs) x) (fun k => nth k bs zero) (fun k => sk * nth k τs zero + nth k bs zero + dl (c1 (nth k D cone)))).
      set (Sb := pblk (feval (set_nth m zero ss) x) (fun k => nth k ss zero) (fun k => nth k ss zero + nth 0 γ zero * nth k bs zero)).
      set (Tb := pblk (feval (set_nth m ρ τs) x) (fun k => nth k τs zero) (fun k => nth k τs zero + dl (c0 (nth k D cone)))).
      unfold mPsi; cbv zeta.
      destruct (mslices (lveval (a0 :: A) x) Bb Sb Tb (feval (r0 :: r) x) hla (pblk_length _ _ _) (pblk_length _ _ _) (pblk_length _ _ _))
        as (S1 & S2 & S3 & S4 & S5).
      rewrite S1, S2, S3, S4, S5.
      assert (ha0' : psub (lveval (a0 :: A) x) (lscale x (lveval A x)) = a0).
      { change (lveval (a0 :: A) x) with (padd a0 (lscale x (lveval A x))). apply padd_psub. rewrite ha0, mlsc; reflexivity. }
      rewrite ha0'. fold D.
      assert (hB0 : nth 0 Bb zero = feval (set_nth m zero bs) x) by apply nth_pblk_0.
      assert (hS0 : nth 0 Sb zero = feval (set_nth m zero ss) x) by apply nth_pblk_0.
      assert (hT0 : nth 0 Tb zero = feval (set_nth m ρ τs) x) by apply nth_pblk_0.
      assert (hBm : nth m Bb zero = nth m bs zero) by apply nth_pblk_m.
      assert (hSm : nth m Sb zero = nth m ss zero) by apply nth_pblk_m.
      assert (hTm : nth m Tb zero = nth m τs zero) by apply nth_pblk_m.
      assert (hBk : forall k, (0 < k < 2 * m)%nat -> k <> m ->
        nth k Bb zero = sk * nth k τs zero + nth k bs zero + dl (c1 (nth k D cone))) by (intros; apply nth_pblk; lia).
      assert (hSk : forall k, (0 < k < 2 * m)%nat -> k <> m ->
        nth k Sb zero = nth k ss zero + nth 0 γ zero * nth k bs zero) by (intros; apply nth_pblk; lia).
      assert (hTk : forall k, (0 < k < 2 * m)%nat -> k <> m ->
        nth k Tb zero = nth k τs zero + dl (c0 (nth k D cone))) by (intros; apply nth_pblk; lia).
      (* Undo the translates: τ_k, then b_k, then s_k. *)
      assert (hτk : forall k, (0 < k < 2 * m)%nat -> k <> m -> mtau Tb D k = nth k τs zero)
        by (intros k hk hkm; unfold mtau; rewrite hTk by assumption; field).
      assert (hbk : forall k, (0 < k < 2 * m)%nat -> k <> m -> mb Bb Tb D k = nth k bs zero)
        by (intros k hk hkm; unfold mb; rewrite hτk, hBk by assumption; field).
      assert (hsk : forall k, (0 < k < 2 * m)%nat -> k <> m -> ms Sb Bb Tb D k = nth k ss zero)
        by (intros k hk hkm; unfold ms; rewrite hbk, hSk by assumption; field).
      rewrite (blk_eq_tl bs (mb Bb Tb D) (fun k => nth k Bb zero) hbs)
        by (intros k hk; destruct (Nat.eqb k m) eqn:e; [apply Nat.eqb_eq in e; subst k; exact hBm | apply hbk; [exact hk | apply Nat.eqb_neq; exact e]]).
      rewrite (blk_eq_tl ss (ms Sb Bb Tb D) (fun k => nth k Sb zero) hss)
        by (intros k hk; destruct (Nat.eqb k m) eqn:e; [apply Nat.eqb_eq in e; subst k; exact hSm | apply hsk; [exact hk | apply Nat.eqb_neq; exact e]]).
      rewrite (blk_eq_tl τs (mtau Tb D) (fun k => nth k Tb zero) hτs)
        by (intros k hk; destruct (Nat.eqb k m) eqn:e; [apply Nat.eqb_eq in e; subst k; exact hTm | apply hτk; [exact hk | apply Nat.eqb_neq; exact e]]).
      rewrite (blk_eq_tl (set_nth m zero bs) (mb Bb Tb D) (fun _ => zero) (ltac:(rewrite set_nth_length; exact hbs)))
        by (intros k hk; rewrite (nth_set_nth (zero := zero)) by lia; destruct (Nat.eqb k m) eqn:e; [reflexivity | apply hbk; [exact hk | apply Nat.eqb_neq; exact e]]).
      rewrite (blk_eq_tl (set_nth m zero ss) (ms Sb Bb Tb D) (fun _ => zero) (ltac:(rewrite set_nth_length; exact hss)))
        by (intros k hk; rewrite (nth_set_nth (zero := zero)) by lia; destruct (Nat.eqb k m) eqn:e; [reflexivity | apply hsk; [exact hk | apply Nat.eqb_neq; exact e]]).
      rewrite (blk_eq_tl (set_nth m ρ τs) (mtau Tb D) (fun _ => ρ) (ltac:(rewrite set_nth_length; exact hτs)))
        by (intros k hk; rewrite (nth_set_nth (zero := zero)) by lia; destruct (Nat.eqb k m) eqn:e; [reflexivity | apply hτk; [exact hk | apply Nat.eqb_neq; exact e]]).
      (* The first entries are recovered from the responses (Horner). *)
      rewrite hB0, hS0, hT0.
      assert (hbzne : set_nth m zero bs <> []) by (intro e; apply (f_equal (@length F)) in e; rewrite set_nth_length, hbs in e; cbn in e; lia).
      assert (hszne : set_nth m zero ss <> []) by (intro e; apply (f_equal (@length F)) in e; rewrite set_nth_length, hss in e; cbn in e; lia).
      assert (hτzne : set_nth m ρ τs <> []) by (intro e; apply (f_equal (@length F)) in e; rewrite set_nth_length, hτs in e; cbn in e; lia).
      rewrite (feval_hd_tl _ x hbzne), (feval_hd_tl _ x hszne), (feval_hd_tl _ x hτzne).
      rewrite !(nth_set_nth (zero := zero)) by lia.
      replace (0 =? m) with false by (symmetry; apply Nat.eqb_neq; lia).
      replace (nth 0 bs zero + x * feval (tl (set_nth m zero bs)) x - x * feval (tl (set_nth m zero bs)) x) with (nth 0 bs zero) by field.
      replace (nth 0 ss zero + x * feval (tl (set_nth m zero ss)) x - x * feval (tl (set_nth m zero ss)) x) with (nth 0 ss zero) by field.
      replace (nth 0 τs zero + x * feval (tl (set_nth m ρ τs)) x - x * feval (tl (set_nth m ρ τs)) x) with (nth 0 τs zero) by field.
      replace (feval (r0 :: r) x - x * feval r x) with r0 by (rewrite feval_cons; field).
      assert (hbsne : bs <> []) by (intro e; rewrite e in hbs; cbn in hbs; lia).
      assert (hssne : ss <> []) by (intro e; rewrite e in hss; cbn in hss; lia).
      assert (hτsne : τs <> []) by (intro e; rewrite e in hτs; cbn in hτs; lia).
      transitivity (a0 ++ [r0] ++ (nth 0 bs zero :: tl bs) ++ (nth 0 ss zero :: tl ss) ++ (nth 0 τs zero :: tl τs)); [reflexivity |].
      rewrite <-(list_hd_tl_gen bs zero hbsne), <-(list_hd_tl_gen ss zero hssne), <-(list_hd_tl_gen τs zero hτsne).
      exact (eq_sym hdec).
    Qed.

    (** [mPsi] is a right inverse of [mPhi] on lists of length [mR]. *)
    Lemma mPhi_mPsi : forall l, length l = mR -> mPhi (mPsi l) = l.
    Proof.
      intros l hl. pose proof (mrecompose l hl) as hdec. unfold mR in hl.
      unfold mPsi; cbv zeta.
      set (a := slice l 0 n) in *. set (rt := nth n l zero) in *.
      set (Bb := slice l (n + 1) (2 * m)) in *. set (Sb := slice l (n + 1 + 2 * m) (2 * m)) in *.
      set (Tb := slice l (n + 1 + 4 * m) (2 * m)) in *.
      set (a0 := psub a (lscale x (lveval A x))). set (D := mD a0).
      set (bs := (nth 0 Bb zero - x * feval (blk (mb Bb Tb D) (fun _ => zero)) x) :: blk (mb Bb Tb D) (fun k => nth k Bb zero)).
      set (ss := (nth 0 Sb zero - x * feval (blk (ms Sb Bb Tb D) (fun _ => zero)) x) :: blk (ms Sb Bb Tb D) (fun k => nth k Sb zero)).
      set (τs := (nth 0 Tb zero - x * feval (blk (mtau Tb D) (fun _ => ρ)) x) :: blk (mtau Tb D) (fun k => nth k Tb zero)).
      assert (ha : length a = n) by (apply length_slice; lia).
      assert (hBb : length Bb = (2 * m)%nat) by (apply length_slice; lia).
      assert (hSb : length Sb = (2 * m)%nat) by (apply length_slice; lia).
      assert (hTb : length Tb = (2 * m)%nat) by (apply length_slice; lia).
      assert (ha0 : length a0 = n) by (unfold a0; rewrite psub_length; [exact ha | rewrite ha, mlsc; reflexivity]).
      assert (hbs : length bs = (2 * m)%nat) by (unfold bs; cbn [length]; rewrite blk_length; lia).
      assert (hss : length ss = (2 * m)%nat) by (unfold ss; cbn [length]; rewrite blk_length; lia).
      assert (hτs : length τs = (2 * m)%nat) by (unfold τs; cbn [length]; rewrite blk_length; lia).
      unfold mPhi; cbv zeta.
      destruct (mslices a0 bs ss τs (rt - x * feval r x) ha0 hbs hss hτs) as (S1 & S2 & S3 & S4 & S5).
      rewrite S1, S2, S3, S4, S5. fold D.
      assert (hlv : lveval (a0 :: A) x = a).
      { change (lveval (a0 :: A) x) with (padd a0 (lscale x (lveval A x))). unfold a0. apply psub_padd. rewrite ha, mlsc; reflexivity. }
      rewrite hlv.
      replace (feval ((rt - x * feval r x) :: r) x) with rt by (rewrite feval_cons; field).
      assert (hbz : set_nth m zero bs = (nth 0 Bb zero - x * feval (blk (mb Bb Tb D) (fun _ => zero)) x) :: blk (mb Bb Tb D) (fun _ => zero))
        by apply set_nth_cons_blk.
      assert (hsz : set_nth m zero ss = (nth 0 Sb zero - x * feval (blk (ms Sb Bb Tb D) (fun _ => zero)) x) :: blk (ms Sb Bb Tb D) (fun _ => zero))
        by apply set_nth_cons_blk.
      assert (hτz : set_nth m ρ τs = (nth 0 Tb zero - x * feval (blk (mtau Tb D) (fun _ => ρ)) x) :: blk (mtau Tb D) (fun _ => ρ))
        by apply set_nth_cons_blk.
      assert (hB : pblk (feval (set_nth m zero bs) x) (fun k => nth k bs zero)
        (fun k => sk * nth k τs zero + nth k bs zero + dl (c1 (nth k D cone))) = Bb).
      { apply (nth_ext _ _ zero zero); [rewrite pblk_length, hBb; reflexivity |].
        intros k hk. rewrite pblk_length in hk. destruct k as [| k'].
        + rewrite nth_pblk_0, hbz, feval_cons. field.
        + destruct (Nat.eq_dec (S k') m) as [e | e].
          - rewrite e, nth_pblk_m. unfold bs. rewrite nth_cons_S by lia. rewrite nth_blk by lia.
            replace (S (m - 1)) with m by lia. rewrite Nat.eqb_refl. reflexivity.
          - rewrite nth_pblk by lia. unfold bs, τs; cbn [nth]; rewrite !nth_blk by lia.
            replace (S k' =? m) with false by (symmetry; apply Nat.eqb_neq; exact e). unfold mb, mtau. field. }
      assert (hS : pblk (feval (set_nth m zero ss) x) (fun k => nth k ss zero)
        (fun k => nth k ss zero + nth 0 γ zero * nth k bs zero) = Sb).
      { apply (nth_ext _ _ zero zero); [rewrite pblk_length, hSb; reflexivity |].
        intros k hk. rewrite pblk_length in hk. destruct k as [| k'].
        + rewrite nth_pblk_0, hsz, feval_cons. field.
        + destruct (Nat.eq_dec (S k') m) as [e | e].
          - rewrite e, nth_pblk_m. unfold ss. rewrite nth_cons_S by lia. rewrite nth_blk by lia.
            replace (S (m - 1)) with m by lia. rewrite Nat.eqb_refl. reflexivity.
          - rewrite nth_pblk by lia. unfold ss, bs; cbn [nth]; rewrite !nth_blk by lia.
            replace (S k' =? m) with false by (symmetry; apply Nat.eqb_neq; exact e). unfold ms. field. }
      assert (hT : pblk (feval (set_nth m ρ τs) x) (fun k => nth k τs zero)
        (fun k => nth k τs zero + dl (c0 (nth k D cone))) = Tb).
      { apply (nth_ext _ _ zero zero); [rewrite pblk_length, hTb; reflexivity |].
        intros k hk. rewrite pblk_length in hk. destruct k as [| k'].
        + rewrite nth_pblk_0, hτz, feval_cons. field.
        + destruct (Nat.eq_dec (S k') m) as [e | e].
          - rewrite e, nth_pblk_m. unfold τs. rewrite nth_cons_S by lia. rewrite nth_blk by lia.
            replace (S (m - 1)) with m by lia. rewrite Nat.eqb_refl. reflexivity.
          - rewrite nth_pblk by lia. unfold τs; cbn [nth]; rewrite !nth_blk by lia.
            replace (S k' =? m) with false by (symmetry; apply Nat.eqb_neq; exact e). unfold mtau. field. }
      rewrite hB, hS, hT. exact (eq_sym hdec).
    Qed.

    (** Perfect special HVZK of the multi-exponentiation argument for
        [l = 1]: for every challenge [x], the honest transcript
        distribution on [A], [r], [ρ] equals the simulator's distribution
        on [Cs], [C], [cA]. Hypotheses: [lf] enumerates [F], [m ≥ 1],
        [n ≥ 1], the length conditions, [gs_j = h ^ γ_j] and [hdl]
        ([g] generates [G] with discrete logarithm [dl]). The relation
        holds by definition of [C]. *)
    Theorem multiexp_shvzk : forall (lf : list F) (Hlfn : lf <> []),
      NoDup lf -> (forall v : F, In v lf) ->
      Permutation (multiexp_real_distribution lf Hlfn) (multiexp_sim_distribution lf Hlfn Cs C cA).
    Proof.
      intros lf Hlfn hnd hall. unfold multiexp_real_distribution, multiexp_sim_distribution.
      apply (zk_of_bijection lf Hlfn mR mreal (msim Cs C cA) mPhi mPsi hnd hall mPhi_length mPsi_length mPsi_mPhi mPhi_mPsi).
      intros l hl. apply mreal_eq_msim_honest. exact hl.
    Qed.

  End MultiExpZK.

  (** ** The shuffle argument (Alg. 9.11 / 9.12) for single-message ElGamal

      Statement: input ciphertexts [Cs] and output ciphertexts [Cs'] of
      length [N = m n] with [Cs'_i = Enc(1; ρ_i) · Cs_{π(i)}]. The prover
      commits to [a = π] (as field elements, arranged as an [n × m] matrix)
      and, after challenge [x], to [b = (x ^ π(i))_i]; after [y], [z] it
      runs the product argument on [y a + b - z] and the
      multi-exponentiation argument on [B], [Cs'] and the target
      [Π Cs_i ^ (x ^ i)].

      The simulator [shsim] draws random commitments [c_A = h ^ u] and
      [c_B = h ^ v], derives the product statement and the
      multi-exponentiation target from the public data, and composes
      [psim] and [msim]. Theorem: [shuffle_shvzk]. *)
  Local Notation shuffle_verify := (shuffle_verify (zero := zero) (one := one) (add := add)
    (mul := mul) (sub := sub) (opp := opp) (Fdec := Fdec) (gid := gid) (gop := gop) (gpow := gpow)
    (Gdec := Gdec) (l := 1)).
  Local Notation shuffle_prove := (shuffle_prove (zero := zero) (one := one) (add := add)
    (mul := mul) (sub := sub) (opp := opp) (gid := gid) (gop := gop) (gpow := gpow) (l := 1)).
  Local Notation shuffle_argument := (@shuffle_argument F G 1).
  Local Notation mk_shuffle := (@mk_shuffle F G 1).
  Local Notation shuffle_product_stmt := (shuffle_product_stmt (zero := zero) (one := one)
    (add := add) (mul := mul) (sub := sub) (opp := opp) (gid := gid) (gop := gop) (gpow := gpow)).
  Local Notation shuffle_mexp_C := (shuffle_mexp_C (one := one) (mul := mul) (gid := gid)
    (gop := gop) (gpow := gpow) (l := 1)).
  Local Notation ladd := (ladd (add := add)).
  Local Notation lpows := (lpows (one := one) (mul := mul)).
  Local Notation fnat := (fnat (zero := zero) (one := one) (add := add)).

  (** Dropping [length a + off] elements of [a ++ rest] is dropping [off]
      elements of [rest]. *)
  Lemma skipn_app_gen : forall (a rest : list F) k off, length a = k -> skipn (k + off) (a ++ rest) = skipn off rest.
  Proof. intros a rest k off hk. rewrite Nat.add_comm, <-skipn_skipn, (skipn_app_exact a rest k hk). reflexivity. Qed.

  (** Section for the shuffle argument. *)
  Section ShuffleZK.

    (** The commitment and ElGamal parameters as in the
        multi-exponentiation section; the input and output ciphertexts
        [Cs], [Cs']; the witness permutation [perm] and re-encryption
        randomness [ρs]; the challenges [x], [y], [z] of the shuffle,
        [xh], [yh], [xz], [xs] of the product argument and [xm] of the
        multi-exponentiation argument; [m] is the number of columns. *)
    Variables (h : G) (gs : list G) (γ : list F) (g : G) (sk : F) (dl : G -> F).
    Variables (Cs Cs' : list CT) (perm : list nat) (ρs : list F).
    Variables (x y z xh yh xz xs xm : F) (m : nat).
    (** Derived witness data as in [shuffle_prove]: [a] is the permutation
        as field elements, [b] the vector [x ^ π(i)], [A] and [B] their
        [n × m] matrices, [dz] the vector [y a + b - z] and [ρ] the
        combined re-encryption randomness [-Σ ρ_i b_i]. *)
    Local Notation n := (length gs).
    Local Notation Nn := (m * n)%nat.
    Local Notation pk := (Vector.cons G (g ^ sk) 0 (Vector.nil G)).
    Local Notation a := (map fnat perm).
    Local Notation A := (chunk n m a).
    Local Notation b := (map (fun i => fpow x i) perm).
    Local Notation B := (chunk n m b).
    Local Notation dz := (map (fun p => y * fst p + snd p - z) (combine a b)).
    Local Notation ρ := (opp (fold_right add zero (map (fun p => fst p * snd p) (combine ρs b)))).

    (** Side conditions and the witness relation: [m ≥ 1], [n ≥ 2],
        [|Cs| = |Cs'| = |ρs| = N], [perm] is a permutation of [0..N-1],
        [Cs'_i = Enc(1; ρ_i) · Cs_{perm i}] ([hre]), [gs_j = h ^ γ_j], and
        [hdl] as in the multi-exponentiation section ([hdl'] is again
        unused). *)
    Hypothesis hm : (1 <= m)%nat.
    Hypothesis hn : (2 <= n)%nat.
    Hypothesis hCs : length Cs = Nn.
    Hypothesis hCs' : length Cs' = Nn.
    Hypothesis hperm : Permutation perm (seq 0 Nn).
    Hypothesis hρs : length ρs = Nn.
    Hypothesis hre : forall i, (i < Nn)%nat ->
      nth i Cs' cone = cmul (encg g pk zero (nth i ρs zero)) (nth (nth i perm 0%nat) Cs cone).
    Hypothesis hγl : length γ = n.
    Hypothesis hγ : forall j, (j < n)%nat -> nth j gs gid = h ^ (nth j γ zero).
    Hypothesis hdl : forall v : G, g ^ dl v = v.
    Hypothesis hdl' : forall u : F, dl (g ^ u) = u.

    (** Number of coins: the commitment randomness [r], [s] of [c_A],
        [c_B], then the product-argument coins and the
        multi-exponentiation coins. *)
    Definition shR : nat := (2 * m + pR gs m + mR gs m)%nat.

    (** The honest transcript: [shuffle_prove] with its coins read from
        [l]. *)
    Definition shreal (l : list F) : shuffle_argument :=
      let r := slice l 0 m in let s := slice l m m in
      let lp := slice l (2 * m) (pR gs m) in let lm := skipn (2 * m + pR gs m) l in
      let lh := slice lp 1 (hR gs m) in let lz := skipn (m - 2) lh in let ls := skipn (1 + hR gs m) lp in
      shuffle_prove h gs g pk m n Cs' perm ρs r s (nth 0 lp zero) (slice lh 0 (m - 2))
        (slice lz 0 n) (slice lz n n) (nth (2 * n) lz zero) (nth (2 * n + 1) lz zero)
        (slice lz (2 * n + 2) (S m)) (slice lz (2 * n + 3 + m) (m - 1))
        (slice ls 0 n) (nth n ls zero) (slice ls (n + 1) (n - 2)) (nth (2 * n - 1) ls zero) (nth (2 * n) ls zero)
        (slice lm 0 n) (nth n lm zero) (slice lm (n + 1) (2 * m)) (slice lm (n + 1 + 2 * m) (2 * m)) (slice lm (n + 1 + 4 * m) (2 * m))
        x y z xh yh xz xs xm.

    (** The simulator on statement [Cs0], [Cs0']: [c_A = h ^ u] and
        [c_B = h ^ v] from the first [2m] coins, then [psim] on the
        statement [shuffle_product_stmt] computed from [c_A], [c_B] and
        the challenges, and [msim] on the rows of [Cs0'], the target
        [shuffle_mexp_C Cs0 x N] and [c_B]. The simulator receives [sk]
        as an argument only because [msim] is parameterised by it; it uses
        nothing but [pk = g ^ sk]. *)
    Definition shsim (Cs0 Cs0' : list CT) (l : list F) : shuffle_argument :=
      let cA := map (fun u => h ^ u) (slice l 0 m) in let cB := map (fun u => h ^ u) (slice l m m) in
      let lp := slice l (2 * m) (pR gs m) in let lm := skipn (2 * m + pR gs m) l in
      let st := shuffle_product_stmt h gs n Nn cA cB x y z in
      mk_shuffle cA cB (psim h gs xh yh xz xs m (fst st) (snd st) lp)
        (msim h gs g sk xm m (chunk n m Cs0') (shuffle_mexp_C Cs0 x Nn) cB lm).

    (** The real and simulated distributions over uniform coins. *)
    Definition shuffle_real_distribution (lf : list F) (Hlfn : lf <> []) : dist shuffle_argument :=
      Bind (rand lf Hlfn shR) (fun l => Ret (shreal l)).
    Definition shuffle_sim_distribution (lf : list F) (Hlfn : lf <> []) (Cs0 Cs0' : list CT) : dist shuffle_argument :=
      Bind (rand lf Hlfn shR) (fun l => Ret (shsim Cs0 Cs0' l)).

    (** The bijection: [u_i = r_i + ⟨γ, A_i⟩] and [v_i = s_i + ⟨γ, B_i⟩]
        (discrete logarithms of the commitments), then [pPhi] and [mPhi]
        for the derived witnesses. *)
    Definition shPhi (l : list F) : list F :=
      let r := slice l 0 m in let s := slice l m m in
      let lp := slice l (2 * m) (pR gs m) in let lm := skipn (2 * m + pR gs m) l in
      map (fun i => nth i r zero + dot γ (nth i A [])) (seq 0 m) ++ map (fun i => nth i s zero + dot γ (nth i B [])) (seq 0 m)
      ++ pPhi gs γ (chunk n m dz) (ladd (lscale y r) s) xh yh xz xs m lp ++ mPhi gs γ sk dl (chunk n m Cs') B s ρ xm m lm.
    (** The inverse of [shPhi]. *)
    Definition shPsi (l : list F) : list F :=
      let r := map (fun i => nth i (slice l 0 m) zero - dot γ (nth i A [])) (seq 0 m) in
      let s := map (fun i => nth i (slice l m m) zero - dot γ (nth i B [])) (seq 0 m) in
      let lp := slice l (2 * m) (pR gs m) in let lm := skipn (2 * m + pR gs m) l in
      r ++ s ++ pPsi gs γ (chunk n m dz) (ladd (lscale y r) s) xh yh xz xs m lp ++ mPsi gs γ sk dl (chunk n m Cs') B s ρ xm m lm.

    (** Length and shape facts for the derived witness: [perm], [a], [b],
        [dz] have length [N]; [A], [B], the matrix of [dz] and the rows of
        [Cs'] have [m] columns of length [n]. *)
    Lemma shpl : length perm = Nn.
    Proof. rewrite (Permutation_length hperm), length_seq; reflexivity. Qed.
    Lemma shal : length a = Nn.
    Proof. rewrite length_map; exact shpl. Qed.
    Lemma shbl : length b = Nn.
    Proof. rewrite length_map; exact shpl. Qed.
    Lemma shdz : length dz = Nn.
    Proof. rewrite length_map, combine_length, shal, shbl; lia. Qed.
    Lemma shAm : length A = m.
    Proof. apply chunk_length. Qed.
    Lemma shBm : length B = m.
    Proof. apply chunk_length. Qed.
    Lemma shDm : length (chunk n m dz) = m.
    Proof. apply chunk_length. Qed.
    Lemma shCm : length (chunk n m Cs') = m.
    Proof. apply chunk_length. Qed.
    Lemma shAn : Forall (fun v => length v = n) A.
    Proof. apply chunk_forall_length; exact shal. Qed.
    Lemma shBn : Forall (fun v => length v = n) B.
    Proof. apply chunk_forall_length; exact shbl. Qed.
    Lemma shDn : Forall (fun v => length v = n) (chunk n m dz).
    Proof. apply chunk_forall_length; exact shdz. Qed.
    (** The combined randomness [y r + s] has length [m]. *)
    Lemma tlen : forall (r s : list F), length r = m -> length s = m -> length (ladd (lscale y r) s) = m.
    Proof. intros r s hr hs. rewrite ladd_length; unfold SigmaK.lscale; rewrite length_map; [exact hr | rewrite hr, hs; reflexivity]. Qed.

    (** Reading back the four fields of a coin list. *)
    Lemma shslices : forall (X Y P M : list F), length X = m -> length Y = m -> length P = pR gs m ->
      let l := X ++ Y ++ P ++ M in
      slice l 0 m = X /\ slice l m m = Y /\ slice l (2 * m) (pR gs m) = P /\ skipn (2 * m + pR gs m) l = M.
    Proof.
      intros X Y P M hX hY hP. cbv zeta. repeat split.
      + apply slice_app0; exact hX.
      + rewrite (slice_app X _ m m hX). apply slice_app0; exact hY.
      + replace (2 * m)%nat with (m + m)%nat by lia.
        rewrite (slice_app_gen X _ m m _ hX), (slice_app Y _ m _ hY). apply slice_app0; exact hP.
      + replace (2 * m + pR gs m)%nat with (m + (m + pR gs m))%nat by lia.
        rewrite (skipn_app_gen X _ m _ hX), (skipn_app_gen Y _ m _ hY). exact (skipn_app_exact P M _ hP).
    Qed.

    (** Every list of length [shR] is the assembly of its four fields. *)
    Lemma shrecompose : forall l, length l = shR ->
      l = slice l 0 m ++ slice l m m ++ slice l (2 * m) (pR gs m) ++ skipn (2 * m + pR gs m) l.
    Proof.
      intros l hl. unfold shR in hl.
      transitivity (firstn (2 * m + pR gs m) l ++ skipn (2 * m + pR gs m) l); [symmetry; apply firstn_skipn |].
      rewrite !app_assoc. f_equal. rewrite <-app_assoc.
      transitivity (slice l 0 (m + (m + pR gs m))); [unfold slice; cbn [skipn]; f_equal; lia |].
      rewrite !slice_split. replace (0 + m)%nat with m by lia. replace (m + m)%nat with (2 * m)%nat by lia. reflexivity.
    Qed.

    (** Unfolding of [shreal] into the two commitments and the sub-argument
        transcripts [preal] and [mreal]. *)
    Lemma shreal_unfold : forall l,
      shreal l = mk_shuffle (com_list h gs A (slice l 0 m)) (com_list h gs B (slice l m m))
        (preal h gs (chunk n m dz) (ladd (lscale y (slice l 0 m)) (slice l m m)) xh yh xz xs m (slice l (2 * m) (pR gs m)))
        (mreal h gs g sk (chunk n m Cs') B (slice l m m) ρ xm m (skipn (2 * m + pR gs m) l)).
    Proof. intros l; reflexivity. Qed.

    (** Under [gs_j = h ^ γ_j], the commitments to the columns of a matrix
        are the powers [h ^ (r_i + ⟨γ, As_i⟩)]. *)
    Lemma com_list_dlog : forall (As : list (list F)) (rs : list F), length As = m -> length rs = m ->
      com_list h gs As rs = map (fun u => h ^ u) (map (fun i => nth i rs zero + dot γ (nth i As [])) (seq 0 m)).
    Proof.
      intros As rs hAs hrs. apply (nth_ext _ _ gid gid).
      + rewrite com_list_length, hAs, hrs, Nat.min_id, !length_map, length_seq; reflexivity.
      + intros i hi. rewrite com_list_length, hAs, hrs, Nat.min_id in hi.
        rewrite (nth_com_list (zero := zero)) by (rewrite ?hAs, ?hrs; lia).
        rewrite (nth_indep _ gid (h ^ zero)) by (rewrite !length_map, length_seq; lia).
        rewrite (map_nth (fun u => h ^ u)). rewrite nth_map_seq_gen by lia; cbn [Nat.add].
        apply (com_dlog h gs γ _ _ hγl hγ).
    Qed.

    (** Key equation: if the shuffle verifier accepts [shreal l] on
        statement [Cs0], [Cs0'], then
        [shreal l = shsim Cs0 Cs0' (shPhi l)]. The commitments are powers
        of [h] by [com_list_dlog]; the sub-arguments follow from
        [preal_eq_psim] and [mreal_eq_msim] on the statements the shuffle
        verifier derives. *)
    Lemma shreal_eq_shsim : forall l (Cs0 Cs0' : list CT), length l = shR ->
      shuffle_verify h gs g pk m n Cs0 Cs0' x y z xh yh xz xs xm (shreal l) = true -> shreal l = shsim Cs0 Cs0' (shPhi l).
    Proof.
      intros l Cs0 Cs0' hl hv. unfold shR in hl.
      rewrite shreal_unfold in hv |- *.
      set (r := slice l 0 m) in *. set (s := slice l m m) in *.
      set (lp := slice l (2 * m) (pR gs m)) in *. set (lm := skipn (2 * m + pR gs m) l) in *.
      assert (hr : length r = m) by (apply length_slice; lia).
      assert (hs : length s = m) by (apply length_slice; lia).
      assert (hlp : length lp = pR gs m) by (apply length_slice; lia).
      assert (hlm : length lm = mR gs m) by (unfold lm; rewrite length_skipn; lia).
      set (t := ladd (lscale y r) s) in *.
      assert (htl : length t = m) by (apply tlen; assumption).
      (* Acceptance of the product and multi-exponentiation arguments on
         the derived statements. *)
      apply shuffle_verify_true in hv. destruct hv as (_ & _ & hC0 & hC0' & hcAl & hcBl & hvp & hvm).
      set (us := map (fun i => nth i r zero + dot γ (nth i A [])) (seq 0 m)).
      set (vs := map (fun i => nth i s zero + dot γ (nth i B [])) (seq 0 m)).
      assert (hus : length us = m) by (unfold us; rewrite length_map, length_seq; reflexivity).
      assert (hvs : length vs = m) by (unfold vs; rewrite length_map, length_seq; reflexivity).
      pose proof (com_list_dlog A r shAm hr) as hcA. pose proof (com_list_dlog B s shBm hs) as hcB.
      fold us in hcA. fold vs in hcB.
      rewrite hcA, hcB in hvp. rewrite hcB in hvm. rewrite hcA, hcB.
      unfold shsim, shPhi; cbv zeta. fold r s lp lm t us vs.
      set (P := pPhi gs γ (chunk n m dz) t xh yh xz xs m lp). set (M := mPhi gs γ sk dl (chunk n m Cs') B s ρ xm m lm).
      assert (hP : length P = pR gs m) by apply (pPhi_length gs γ (chunk n m dz) t xh yh xz xs m shDm hm hn htl shDn hγl lp hlp).
      destruct (shslices us vs P M hus hvs hP) as (S1 & S2 & S3 & S4). rewrite S1, S2, S3, S4.
      f_equal.
      (* The product sub-argument. *)
      - unfold shuffle_product_stmt; cbv zeta; cbn [fst snd].
        apply (preal_eq_psim h gs γ (chunk n m dz) t xh yh xz xs m shDm hm hn htl shDn hγl hγ lp _ _ hlp).
        + rewrite !length_map, combine_length, !length_map, hus, hvs; lia.
        + exact hvp.
      (* The multi-exponentiation sub-argument. *)
      - apply (mreal_eq_msim h gs γ g sk dl (chunk n m Cs') B s ρ xm m shBm hm (ltac:(lia)) shCm hs shBn hγl hγ hdl lm _ _ _ hlm).
        exact hvm.
    Qed.

    (** The shift by [⟨γ, As_i⟩] and its inverse cancel
        ([rs_undo], [us_undo]). *)
    Lemma rs_undo : forall (As : list (list F)) (rs : list F), length rs = m ->
      map (fun i => nth i (map (fun i => nth i rs zero + dot γ (nth i As [])) (seq 0 m)) zero - dot γ (nth i As [])) (seq 0 m) = rs.
    Proof.
      intros As rs hrs. transitivity (map (fun i => nth i rs zero) (seq 0 m)); [| apply map_nth_seq_id; exact hrs].
      apply map_ext_in; intros i hi; apply in_seq in hi. rewrite nth_map_seq_gen by lia; cbn [Nat.add]; field.
    Qed.
    Lemma us_undo : forall (As : list (list F)) (us : list F), length us = m ->
      map (fun i => nth i (map (fun i => nth i us zero - dot γ (nth i As [])) (seq 0 m)) zero + dot γ (nth i As [])) (seq 0 m) = us.
    Proof.
      intros As us hus. transitivity (map (fun i => nth i us zero) (seq 0 m)); [| apply map_nth_seq_id; exact hus].
      apply map_ext_in; intros i hi; apply in_seq in hi. rewrite nth_map_seq_gen by lia; cbn [Nat.add]; field.
    Qed.

    (** [shPhi] preserves length [shR]. *)
    Lemma shPhi_length : forall l, length l = shR -> length (shPhi l) = shR.
    Proof.
      intros l hl. unfold shR in *. unfold shPhi; cbv zeta.
      assert (hr : length (slice l 0 m) = m) by (apply length_slice; lia).
      assert (hs : length (slice l m m) = m) by (apply length_slice; lia).
      assert (hlp : length (slice l (2 * m) (pR gs m)) = pR gs m) by (apply length_slice; lia).
      assert (hlm : length (skipn (2 * m + pR gs m) l) = mR gs m) by (rewrite length_skipn; lia).
      rewrite !length_app, !length_map, !length_seq.
      rewrite (pPhi_length gs γ (chunk n m dz) _ xh yh xz xs m shDm hm hn (tlen _ _ hr hs) shDn hγl _ hlp).
      rewrite (mPhi_length gs γ sk dl (chunk n m Cs') B _ ρ xm m shBm hm (ltac:(lia)) shCm hs shBn hγl _ hlm). lia.
    Qed.

    (** [shPsi] preserves length [shR]. *)
    Lemma shPsi_length : forall l, length l = shR -> length (shPsi l) = shR.
    Proof.
      intros l hl. unfold shR in *. unfold shPsi; cbv zeta.
      assert (hlp : length (slice l (2 * m) (pR gs m)) = pR gs m) by (apply length_slice; lia).
      assert (hlm : length (skipn (2 * m + pR gs m) l) = mR gs m) by (rewrite length_skipn; lia).
      assert (hr : length (map (fun i => nth i (slice l 0 m) zero - dot γ (nth i A [])) (seq 0 m)) = m) by (rewrite length_map, length_seq; reflexivity).
      assert (hs : length (map (fun i => nth i (slice l m m) zero - dot γ (nth i B [])) (seq 0 m)) = m) by (rewrite length_map, length_seq; reflexivity).
      rewrite !length_app, hr, hs.
      rewrite (pPsi_length gs γ (chunk n m dz) _ xh yh xz xs m shDm hm hn (tlen _ _ hr hs) shDn hγl _ hlp).
      rewrite (mPsi_length gs γ sk dl (chunk n m Cs') B _ ρ xm m shBm hm (ltac:(lia)) shCm hs shBn hγl _ hlm). lia.
    Qed.

    (** [shPsi] is a left inverse of [shPhi] on lists of length [shR]. *)
    Lemma shPsi_shPhi : forall l, length l = shR -> shPsi (shPhi l) = l.
    Proof.
      intros l hl. pose proof (shrecompose l hl) as hdec. unfold shR in hl.
      unfold shPhi; cbv zeta.
      set (r := slice l 0 m) in *. set (s := slice l m m) in *.
      set (lp := slice l (2 * m) (pR gs m)) in *. set (lm := skipn (2 * m + pR gs m) l) in *.
      assert (hr : length r = m) by (apply length_slice; lia).
      assert (hs : length s = m) by (apply length_slice; lia).
      assert (hlp : length lp = pR gs m) by (apply length_slice; lia).
      assert (hlm : length lm = mR gs m) by (unfold lm; rewrite length_skipn; lia).
      set (us := map (fun i => nth i r zero + dot γ (nth i A [])) (seq 0 m)).
      set (vs := map (fun i => nth i s zero + dot γ (nth i B [])) (seq 0 m)).
      assert (hus : length us = m) by (unfold us; rewrite length_map, length_seq; reflexivity).
      assert (hvs : length vs = m) by (unfold vs; rewrite length_map, length_seq; reflexivity).
      set (t := ladd (lscale y r) s). assert (htl : length t = m) by (apply tlen; assumption).
      set (P := pPhi gs γ (chunk n m dz) t xh yh xz xs m lp). set (M := mPhi gs γ sk dl (chunk n m Cs') B s ρ xm m lm).
      assert (hP : length P = pR gs m) by apply (pPhi_length gs γ (chunk n m dz) t xh yh xz xs m shDm hm hn htl shDn hγl lp hlp).
      unfold shPsi; cbv zeta.
      destruct (shslices us vs P M hus hvs hP) as (S1 & S2 & S3 & S4). rewrite S1, S2, S3, S4.
      unfold us, vs. rewrite (rs_undo A r hr), (rs_undo B s hs). fold t.
      unfold P, M.
      rewrite (pPsi_pPhi gs γ (chunk n m dz) t xh yh xz xs m shDm hm hn htl shDn hγl lp hlp).
      rewrite (mPsi_mPhi gs γ sk dl (chunk n m Cs') B s ρ xm m shBm hm (ltac:(lia)) shCm hs shBn hγl lm hlm).
      exact (eq_sym hdec).
    Qed.

    (** [shPsi] is a right inverse of [shPhi] on lists of length [shR]. *)
    Lemma shPhi_shPsi : forall l, length l = shR -> shPhi (shPsi l) = l.
    Proof.
      intros l hl. pose proof (shrecompose l hl) as hdec. unfold shR in hl.
      unfold shPsi; cbv zeta.
      set (us := slice l 0 m) in *. set (vs := slice l m m) in *.
      set (lp := slice l (2 * m) (pR gs m)) in *. set (lm := skipn (2 * m + pR gs m) l) in *.
      assert (hus : length us = m) by (apply length_slice; lia).
      assert (hvs : length vs = m) by (apply length_slice; lia).
      assert (hlp : length lp = pR gs m) by (apply length_slice; lia).
      assert (hlm : length lm = mR gs m) by (unfold lm; rewrite length_skipn; lia).
      set (r := map (fun i => nth i us zero - dot γ (nth i A [])) (seq 0 m)).
      set (s := map (fun i => nth i vs zero - dot γ (nth i B [])) (seq 0 m)).
      assert (hr : length r = m) by (unfold r; rewrite length_map, length_seq; reflexivity).
      assert (hs : length s = m) by (unfold s; rewrite length_map, length_seq; reflexivity).
      set (t := ladd (lscale y r) s). assert (htl : length t = m) by (apply tlen; assumption).
      set (P := pPsi gs γ (chunk n m dz) t xh yh xz xs m lp). set (M := mPsi gs γ sk dl (chunk n m Cs') B s ρ xm m lm).
      assert (hP : length P = pR gs m) by apply (pPsi_length gs γ (chunk n m dz) t xh yh xz xs m shDm hm hn htl shDn hγl lp hlp).
      unfold shPhi; cbv zeta.
      destruct (shslices r s P M hr hs hP) as (S1 & S2 & S3 & S4). rewrite S1, S2, S3, S4. fold t.
      unfold P, M.
      rewrite (pPhi_pPsi gs γ (chunk n m dz) t xh yh xz xs m shDm hm hn htl shDn hγl lp hlp).
      rewrite (mPhi_mPsi gs γ sk dl (chunk n m Cs') B s ρ xm m shBm hm (ltac:(lia)) shCm hs shBn hγl lm hlm).
      unfold r, s. rewrite (us_undo A us hus), (us_undo B vs hvs).
      exact (eq_sym hdec).
    Qed.

    (** The Hadamard challenges of the inner product argument are non-zero
        when [m > 1]. *)
    Hypothesis hxh0 : (1 < m)%nat -> xh <> zero.
    Hypothesis hyh0 : (1 < m)%nat -> yh <> zero.

    (** On the honest statement [Cs], [Cs'], acceptance follows from
        [shuffle_completeness]. *)
    Lemma shreal_eq_shsim_honest : forall l, length l = shR -> shreal l = shsim Cs Cs' (shPhi l).
    Proof.
      intros l hl. apply shreal_eq_shsim; [exact hl |]. unfold shR in hl. unfold shreal; cbv zeta.
      assert (hlp : length (slice l (2 * m) (pR gs m)) = pR gs m) by (apply length_slice; lia).
      assert (hlh : length (slice (slice l (2 * m) (pR gs m)) 1 (hR gs m)) = hR gs m) by (apply length_slice; rewrite hlp; unfold pR; lia).
      assert (hlm : length (skipn (2 * m + pR gs m) l) = mR gs m) by (rewrite length_skipn; lia).
      apply shuffle_completeness; try assumption; try reflexivity;
        apply length_slice; rewrite ?length_skipn, ?hlh, ?hlp, ?hlm; try unfold pR, hR, zR, sR, mR in *; lia.
    Qed.

    (** Perfect special HVZK of the Bayer–Groth shuffle argument for
        single-message ElGamal: for all challenges [x], [y], [z], [xh],
        [yh], [xz], [xs], [xm] (with [xh], [yh] non-zero when [m > 1]), the
        honest transcript distribution on the witness [perm], [ρs] equals
        the simulator's distribution on the public ciphertexts [Cs], [Cs'].
        Hypotheses: [lf] enumerates [F], [m ≥ 1], [n ≥ 2], the length
        conditions, the shuffle relation [hre], [gs_j = h ^ γ_j] and
        [hdl]. *)
    Theorem shuffle_shvzk : forall (lf : list F) (Hlfn : lf <> []),
      NoDup lf -> (forall v : F, In v lf) ->
      Permutation (shuffle_real_distribution lf Hlfn) (shuffle_sim_distribution lf Hlfn Cs Cs').
    Proof.
      intros lf Hlfn hnd hall. unfold shuffle_real_distribution, shuffle_sim_distribution.
      apply (zk_of_bijection lf Hlfn shR shreal (shsim Cs Cs') shPhi shPsi hnd hall shPhi_length shPsi_length shPsi_shPhi shPhi_shPsi).
      intros l hl. apply shreal_eq_shsim_honest. exact hl.
    Qed.

  End ShuffleZK.

