    (* the prover's randomness: d ∈ F^n, r_d, δ_1..δ_{n-2}, s_0, s_x *)
    Definition sR : nat := (2 * n + 1)%nat.

    Definition sreal (l : list F) : svp_argument :=
      svp_prove h gs a r (slice l 0 n) (nth n l zero) (slice l (n + 1) (n - 2)) (nth (2 * n - 1) l zero) (nth (2 * n) l zero) x.

    (* the simulator: random ã, r̃, s̃, b̃_1..b̃_{n-2} and a random commitment c_Δ = h^u;
       b̃_0 = ã_0 and b̃_{n-1} = x b are forced by the verifier, c_d and c_δ by its two group equations *)
    Definition ssim (ca' : G) (b' : F) (l : list F) : svp_argument :=
      let ta := slice l 0 n in let rt := nth n l zero in let st := nth (n + 1) l zero in
      let bmid := slice l (n + 2) (n - 2) in let u := nth (2 * n) l zero in
      let tb := nth 0 ta zero :: bmid ++ [x * b'] in
      let e := map (fun i => x * nth (S i) tb zero - nth i tb zero * nth (S i) ta zero) (seq 0 (n - 1)) in
      mk_svp (gop (com h gs ta rt) (ginv (ca' ^ x))) (gop (com h gs e st) (ginv ((h ^ u) ^ x))) (h ^ u) ta tb rt st.

    Definition svp_real_distribution (lf : list F) (Hlfn : lf <> []) : dist svp_argument :=
      Bind (rand lf Hlfn sR) (fun l => Ret (sreal l)).
    Definition svp_sim_distribution (lf : list F) (Hlfn : lf <> []) (ca' : G) (b' : F) : dist svp_argument :=
      Bind (rand lf Hlfn sR) (fun l => Ret (ssim ca' b' l)).

    (* the vector Δ of the honest prover, as a function of its randomness *)
    Definition DeltaOf (d dmid : list F) : list F :=
      let bf := prefix_prod a in
      let af := fun i => nth i a zero in
      let df := fun i => nth i d zero in
      let delta := fun i => nth i (df 0 :: dmid ++ [zero]) zero in
      map (fun k => delta (S k) - af (S k) * delta k - bf k * df (S k)) (seq 0 (n - 1)).

    Definition sPhi (l : list F) : list F :=
      let d := slice l 0 n in let rd := nth n l zero in let dmid := slice l (n + 1) (n - 2) in
      let s0 := nth (2 * n - 1) l zero in let sx := nth (2 * n) l zero in
      map (fun k => x * nth k a zero + nth k d zero) (seq 0 n) ++ [x * r + rd; x * sx + s0]
        ++ map (fun k => x * prefix_prod a (S k) + nth k dmid zero) (seq 0 (n - 2)) ++ [sx + dot γ (DeltaOf d dmid)].

    Definition sPsi (l : list F) : list F :=
      let ta := slice l 0 n in let rt := nth n l zero in let st := nth (n + 1) l zero in
      let bmid := slice l (n + 2) (n - 2) in let u := nth (2 * n) l zero in
      let d := map (fun k => nth k ta zero - x * nth k a zero) (seq 0 n) in
      let dmid := map (fun k => nth k bmid zero - x * prefix_prod a (S k)) (seq 0 (n - 2)) in
      let sx := u - dot γ (DeltaOf d dmid) in
      d ++ [rt - x * r] ++ dmid ++ [st - x * sx; sx].

    Lemma ssim_slices : forall (ta bmid : list F) (rt st u : F), length ta = n -> length bmid = (n - 2)%nat ->
      let l := ta ++ [rt; st] ++ bmid ++ [u] in
      slice l 0 n = ta /\ nth n l zero = rt /\ nth (n + 1) l zero = st /\ slice l (n + 2) (n - 2) = bmid /\ nth (2 * n) l zero = u.
    Proof.
      intros ta bmid rt st u hta hb. cbv zeta. repeat split.
      + apply slice_app0; exact hta.
      + rewrite (nth_app_len ta _ n zero hta); reflexivity.
      + rewrite (nth_app_exact ta _ n 1 zero hta); reflexivity.
      + rewrite (slice_app_gen ta _ n 2 (n - 2) hta), (slice_app [rt; st] _ 2 (n - 2) eq_refl). apply slice_app0; exact hb.
      + replace (2 * n)%nat with (n + (2 + (n - 2)))%nat by lia.
        rewrite (nth_app_exact ta _ n _ zero hta), (nth_app_exact [rt; st] _ 2 _ zero eq_refl), (nth_app_len bmid _ _ zero hb). reflexivity.
    Qed.

    Lemma sreal_slices : forall (d dmid : list F) (rd s0 sx : F), length d = n -> length dmid = (n - 2)%nat ->
      let l := d ++ [rd] ++ dmid ++ [s0; sx] in
      slice l 0 n = d /\ nth n l zero = rd /\ slice l (n + 1) (n - 2) = dmid /\ nth (2 * n - 1) l zero = s0 /\ nth (2 * n) l zero = sx.
    Proof.
      intros d dmid rd s0 sx hd hm. cbv zeta. repeat split.
      + apply slice_app0; exact hd.
      + rewrite (nth_app_len d _ n zero hd); reflexivity.
      + rewrite (slice_app_gen d _ n 1 (n - 2) hd), (slice_app [rd] _ 1 (n - 2) eq_refl). apply slice_app0; exact hm.
      + replace (2 * n - 1)%nat with (n + (1 + (n - 2)))%nat by lia.
        rewrite (nth_app_exact d _ n _ zero hd), (nth_app_exact [rd] _ 1 _ zero eq_refl), (nth_app_len dmid _ _ zero hm). reflexivity.
      + replace (2 * n)%nat with (n + (1 + ((n - 2) + 1)))%nat by lia.
