(* Special honest-verifier zero knowledge of the Bayer–Groth arguments
   (Step 4.2 of plans/ZK_APPLICATIONS_PLAN.md).

   For every argument the honest transcript (announcements and responses,
   the challenges fixed) is the image of the prover's uniformly random
   scalars under the prover's function (the *_prove functions of
   Crypto/BayerGroth.v with their randomness as parameters), and the
   simulated transcript is the image of uniformly random scalars under a
   simulator that knows only the statement and the challenges: it draws the
   responses and the free announcements at random and computes the remaining
   announcements from the verification equations. The two distributions are
   permutations of each other because the two maps differ by a bijection of
   the randomness (Distr.repeat_uniform_bijection_perm, lifted to lists of
   scalars by rand_bijection_perm): responses are affine bijections of the
   prover's fresh scalars, and a free announcement com(v; t) = h^{t + ⟨γ, v⟩}
   is the translate of the uniform h^t once the commitment key lies in the
   group generated by h (g_j = h^{γ_j}). The challenges are in F, the
   randomness is drawn from a list lf that enumerates F.

   Contents: zk_of_bijection (the reduction to a bijection of the coin
   lists), then one section per argument (zero, single value product,
   Hadamard, product, multi-exponentiation, shuffle) with the honest
   transcript *real, the simulator *sim, the bijection *Phi/*Psi, the
   equation lemma *real_eq_*sim (taking the verifier's acceptance of the
   honest transcript on an arbitrary statement as hypothesis, so that the
   compositions reuse it on the statements the outer verifier derives) and
   the theorem *_shvzk. The multi-exponentiation and shuffle simulators are
   for single-message ElGamal (l = 1, ciphertexts in G²) under the
   hypothesis that g generates the group with a discrete-logarithm
   function dl (g ^ dl v = v): a random ciphertext is then a pair of random
   group elements, so the E_k of the simulated argument are identically
   distributed. For l > 1 the argument is only computationally
   zero-knowledge, which this finite-distribution framework does not
   express. *)

