      assert (hat : length at_ = n) by (unfold at_; apply length_slice; lia).
      assert (hbt : length bt = n) by (unfold bt; apply length_slice; lia).
      assert (hus : length us = (2 * m - 1)%nat) by (unfold us; apply length_slice; lia).
      set (a0 := psub at_ (lscale x (lveval A x))). set (bm := psub bt (lscale x (lveval (rev B) x))).
