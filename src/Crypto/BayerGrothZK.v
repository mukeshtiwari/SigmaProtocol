    Qed.

    Lemma srecompose_real : forall l, length l = sR ->
      l = slice l 0 n ++ [nth n l zero] ++ slice l (n + 1) (n - 2) ++ [nth (2 * n - 1) l zero; nth (2 * n) l zero].
