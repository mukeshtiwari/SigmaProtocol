    (* the slices of a list assembled from pieces *)
    Lemma sim_slices : forall (x1 x2 x4 : list F) (a b c : F), length x1 = n -> length x2 = n -> length x4 = (2 * m - 1)%nat ->
      slice (x1 ++ x2 ++ [a; b; c] ++ x4) 0 n = x1 /\ slice (x1 ++ x2 ++ [a; b; c] ++ x4) n n = x2 /\
      nth (2 * n) (x1 ++ x2 ++ [a; b; c] ++ x4) zero = a /\ nth (2 * n + 1) (x1 ++ x2 ++ [a; b; c] ++ x4) zero = b /\
      nth (2 * n + 2) (x1 ++ x2 ++ [a; b; c] ++ x4) zero = c /\ slice (x1 ++ x2 ++ [a; b; c] ++ x4) (2 * n + 3) (2 * m - 1) = x4.
    Proof.
      intros * h1 h2 h4.
      rewrite (slice_app0 x1) by exact h1. rewrite (slice_app x1 _ n n h1), (slice_app0 x2) by exact h2.
      replace (2 * n)%nat with (n + n)%nat by lia. rewrite (nth_app_exact x1 _ n n zero h1).
      replace (n + n + 1)%nat with (n + (n + 1))%nat by lia. rewrite (nth_app_exact x1 _ n (n + 1) zero h1).
      replace (n + n + 2)%nat with (n + (n + 2))%nat by lia. rewrite (nth_app_exact x1 _ n (n + 2) zero h1).
      rewrite (nth_app_len x2 _ n zero h2), (nth_app_exact x2 _ n 1 zero h2), (nth_app_exact x2 _ n 2 zero h2).
      replace (n + n + 3)%nat with (n + (n + (3 + 0)))%nat by lia.
      rewrite (slice_app_gen x1 _ n _ _ h1), (slice_app_gen x2 _ n _ _ h2), (slice_app_gen [a; b; c] _ 3 0 _ eq_refl).
      unfold slice; cbn [skipn]; rewrite firstn_all2 by (rewrite h4; lia). cbn [app nth].
      repeat split; reflexivity.
    Qed.

    Lemma real_slices : forall (x1 x2 x4 x5 : list F) (a b : F), length x1 = n -> length x2 = n -> length x4 = S m -> length x5 = (m - 1)%nat ->
      slice (x1 ++ x2 ++ [a; b] ++ x4 ++ x5) 0 n = x1 /\ slice (x1 ++ x2 ++ [a; b] ++ x4 ++ x5) n n = x2 /\
      nth (2 * n) (x1 ++ x2 ++ [a; b] ++ x4 ++ x5) zero = a /\ nth (2 * n + 1) (x1 ++ x2 ++ [a; b] ++ x4 ++ x5) zero = b /\
      slice (x1 ++ x2 ++ [a; b] ++ x4 ++ x5) (2 * n + 2) (S m) = x4 /\ slice (x1 ++ x2 ++ [a; b] ++ x4 ++ x5) (2 * n + 3 + m) (m - 1) = x5.
    Proof.
      intros * h1 h2 h4 h5.
      rewrite (slice_app0 x1) by exact h1. rewrite (slice_app x1 _ n n h1), (slice_app0 x2) by exact h2.
      replace (2 * n)%nat with (n + n)%nat by lia. rewrite (nth_app_exact x1 _ n n zero h1).
      replace (n + n + 1)%nat with (n + (n + 1))%nat by lia. rewrite (nth_app_exact x1 _ n (n + 1) zero h1).
      rewrite (nth_app_len x2 _ n zero h2), (nth_app_exact x2 _ n 1 zero h2).
      replace (n + n + 2)%nat with (n + (n + (2 + 0)))%nat by lia.
      rewrite (slice_app_gen x1 _ n _ _ h1), (slice_app_gen x2 _ n _ _ h2), (slice_app_gen [a; b] _ 2 0 _ eq_refl).
      replace (n + n + 3 + m)%nat with (n + (n + (2 + (S m + 0))))%nat by lia.
      rewrite (slice_app_gen x1 _ n _ _ h1), (slice_app_gen x2 _ n _ _ h2), (slice_app_gen [a; b] _ 2 _ _ eq_refl),
        (slice_app_gen x4 _ (S m) 0 _ h4).
      rewrite (slice_app0 x4 x5 (S m) h4).
      unfold slice; cbn [skipn]; rewrite (firstn_all2 x5) by (rewrite h5; lia).
      cbn [app nth]. repeat split; reflexivity.
    Qed.

    (* a list of the right length is the assembly of its pieces *)
    Lemma recompose_sim : forall l, length l = zR ->
      l = slice l 0 n ++ slice l n n ++ [nth (2 * n) l zero; nth (2 * n + 1) l zero; nth (2 * n + 2) l zero] ++ slice l (2 * n + 3) (2 * m - 1).
    Proof.
      intros l hl. unfold slice, zR in *. cbn [skipn].
      rewrite <-(firstn_skipn n l) at 1. f_equal.
      rewrite <-(firstn_skipn n (skipn n l)) at 1. f_equal.
      rewrite skipn_skipn. replace (n + n)%nat with (2 * n)%nat by lia.
      rewrite <-(firstn_skipn 3 (skipn (2 * n) l)) at 1. f_equal.
      + assert (h3 : (3 <= length (skipn (2 * n) l))%nat) by (rewrite length_skipn; lia).
        assert (h0 : nth (2 * n) l zero = nth 0 (skipn (2 * n) l) zero) by (rewrite nth_skipn_add, Nat.add_0_r; reflexivity).
        assert (h1 : nth (2 * n + 1) l zero = nth 1 (skipn (2 * n) l) zero) by (rewrite nth_skipn_add; reflexivity).
        assert (h2 : nth (2 * n + 2) l zero = nth 2 (skipn (2 * n) l) zero) by (rewrite nth_skipn_add; reflexivity).
        rewrite h0, h1, h2. destruct (skipn (2 * n) l) as [| a [| b [| c l']]]; cbn in h3; try lia. reflexivity.
      + rewrite skipn_skipn. replace (3 + 2 * n)%nat with (2 * n + 3)%nat by lia. rewrite firstn_all2; [reflexivity | rewrite length_skipn; lia].
    Qed.

    Lemma recompose_real : forall l, length l = zR ->
      l = slice l 0 n ++ slice l n n ++ [nth (2 * n) l zero; nth (2 * n + 1) l zero] ++ slice l (2 * n + 2) (S m) ++ slice l (2 * n + 3 + m) (m - 1).
    Proof.
      intros l hl. unfold slice, zR in *. cbn [skipn].
      rewrite <-(firstn_skipn n l) at 1. f_equal.
      rewrite <-(firstn_skipn n (skipn n l)) at 1. f_equal.
      rewrite skipn_skipn. replace (n + n)%nat with (2 * n)%nat by lia.
      rewrite <-(firstn_skipn 2 (skipn (2 * n) l)) at 1. f_equal.
      + assert (h2 : (2 <= length (skipn (2 * n) l))%nat) by (rewrite length_skipn; lia).
        assert (h0 : nth (2 * n) l zero = nth 0 (skipn (2 * n) l) zero) by (rewrite nth_skipn_add, Nat.add_0_r; reflexivity).
        assert (h1 : nth (2 * n + 1) l zero = nth 1 (skipn (2 * n) l) zero) by (rewrite nth_skipn_add; reflexivity).
        rewrite h0, h1. destruct (skipn (2 * n) l) as [| a [| b l']]; cbn in h2; try lia. reflexivity.
      + rewrite skipn_skipn. replace (2 + 2 * n)%nat with (2 * n + 2)%nat by lia.
        rewrite <-(firstn_skipn (S m) (skipn (2 * n + 2) l)) at 1. f_equal.
        rewrite skipn_skipn. replace (S m + (2 * n + 2))%nat with (2 * n + 3 + m)%nat by lia.
        rewrite firstn_all2; [reflexivity | rewrite length_skipn; lia].
    Qed.

