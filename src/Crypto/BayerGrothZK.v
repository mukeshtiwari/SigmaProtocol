  (** ** The multi-exponentiation argument for single-message ElGamal
      (Alg. 9.15 / 9.16 with [l = 1])

      Ciphertexts are pairs [(c0, c1)] in [G × G], with componentwise
      product [cmul] and power [cpow]; [encg g pk b τ] is the ElGamal
      encryption [(g ^ τ, pk ^ τ · g ^ b)] of [g ^ b] under [pk = g ^ sk].
      Statement: ciphertext rows [Cs], a target ciphertext [C] and
      commitments [cA] to the exponent columns [A]; relation
      [C = Enc(1; ρ) · Π_i Cs_i ^ A_i]. The prover commits to [2m] scalars
      [b_k] and sends [2m] ciphertexts [E_k = Enc(g ^ b_k; τ_k) · D_k],
      where [D_k] are the diagonal products ([diagonals]); entries at
      index [m] are forced ([b_m = 0], [s_m = 0], [τ_m = ρ]), so that
      [c_{Bm} = 1] and [E_m = C].

      The simulator [msim] draws random responses, random commitments
      [c_{Bk} = h ^ u_k] and random ciphertexts [E_k = (g ^ v_k, g ^ w_k)]
      for [k ≠ 0, m], and solves the verification equations for [c_{A0}],
      [c_{B0}] and [E_0]. Random pairs are distributed like
      [Enc(g ^ b_k; τ_k) · D_k] only because [g] generates [G]: this is the
      hypothesis [hdl]. Theorem: [multiexp_shvzk]. *)
  Local Notation CT := (Vector.t G 2).
  Local Notation cone := (vec_id (V := G) (vid := gid) 2).
  Local Notation cmul := (vec_add (vadd := gop) (n := 2)).
  Local Notation cpow := (vec_smul (smul := gpow) (n := 2)).
  Local Notation CTvs := (vec_vspace (HV := Hvec) 2).
  Local Notation cmexp := (lmexp (vid := cone) (vadd := cmul) (smul := cpow)).
  Local Notation ceval := (veval (one := one) (mul := mul) (vid := cone) (vadd := cmul) (smul := cpow)).
  Local Notation cpadd := (vpadd (vadd := cmul)).
  Local Notation cprod := (fold_right cmul cone).
  Local Notation enc := (enc (gop := gop) (gpow := gpow) (l := 1)).
  Local Notation encg := (encg (gop := gop) (gpow := gpow) (l := 1)).
  Local Notation diagonals := (diagonals (gid := gid) (gop := gop) (gpow := gpow) (l := 1)).
  Local Notation multiexp_verify := (multiexp_verify (one := one) (mul := mul) (gid := gid) (gop := gop)
    (gpow := gpow) (Gdec := Gdec) (l := 1)).
  Local Notation multiexp_prove := (multiexp_prove (zero := zero) (one := one) (add := add) (mul := mul)
    (gid := gid) (gop := gop) (gpow := gpow) (l := 1)).
  Local Notation multiexp_argument := (@multiexp_argument F G 1).
  Local Notation mk_mexp := (@mk_mexp F G 1).
  Local Notation set_nth := (@set_nth F).

  (** The two components of a single-message ciphertext, and the pair
      constructor [mkct]. *)
  Definition c0 (v : CT) : G := Vector.hd v.
  Definition c1 (v : CT) : G := Vector.hd (Vector.tl v).
  Definition mkct (u v : G) : CT := Vector.cons G u 1 (Vector.cons G v 0 (Vector.nil G)).

  (** Every ciphertext is the pair of its components. *)
  Lemma ct_eta : forall v : CT, v = mkct (c0 v) (c1 v).
  Proof.
    intros v. unfold mkct, c0, c1.
    transitivity (Vector.cons G (Vector.hd v) 1 (Vector.tl v)); [apply Vector.eta |].
    f_equal. transitivity (Vector.cons G (Vector.hd (Vector.tl v)) 0 (Vector.tl (Vector.tl v))); [apply Vector.eta |].
    f_equal. apply Vector.nil_spec.
  Qed.

  (** Solving a ciphertext equation: [X · Y = W] implies
      [X = W · Y ^ (-1)]. *)
  Lemma cmul_solve : forall X Y W : CT, cmul X Y = W -> X = cmul W (cpow Y (opp one)).
  Proof. intros X Y W e. rewrite <-e. symmetry. apply (cmul_cancel (Hvec := Hvec) (l := 1)). Qed.

  (** A non-empty list is its head consed onto its tail (any type). *)
  Lemma list_hd_tl_gen : forall {X : Type} (l : list X) (d : X), l <> [] -> l = nth 0 l d :: tl l.
  Proof. intros X l d hne; destruct l; [contradiction | reflexivity]. Qed.

