  Definition dot (γ v : list F) : F := fold_right add zero (map (fun p => fst p * snd p) (combine γ v)).

  Lemma com_dlog : forall (h : G) (gs : list G) (γ v : list F) (t : F), length γ = length gs ->
    (forall j, (j < length gs)%nat -> nth j gs gid = h ^ (nth j γ zero)) ->
    com h gs v t = h ^ (t + dot γ v).
  Proof.
    intros h gs; induction gs as [| g gs ih]; intros γ v t hl hγ.
    + unfold BayerGroth.com. rewrite lmexp_nil_l. destruct γ; [| discriminate]. unfold dot; cbn.
      rewrite gid_r. f_equal; field.
    + destruct γ as [| γ0 γ]; [discriminate |]. destruct v as [| v0 v].
      - unfold BayerGroth.com. rewrite lmexp_nil_r, gid_r. unfold dot; cbn. f_equal; field.
      - unfold BayerGroth.com. rewrite lmexp_cons. pose proof (hγ 0%nat ltac:(cbn; lia)) as h0; cbn [nth] in h0. rewrite h0.
        rewrite <-gpow_mul, gassoc, <-gpow_add.
        assert (hrec : gop (h ^ (t + γ0 * v0)) (gmexp gs v) = com h gs v (t + γ0 * v0)) by reflexivity.
        rewrite hrec, (ih γ v) by (cbn in hl; lia || (intros j hj; exact (hγ (S j) ltac:(cbn; lia)))).
        unfold dot; cbn [combine map fst snd fold_right]. f_equal; field.
  Qed.

  Lemma com_single_dlog : forall (h : G) (gs : list G) (γ : list F) (v t : F), length γ = length gs -> (1 <= length gs)%nat ->
    (forall j, (j < length gs)%nat -> nth j gs gid = h ^ (nth j γ zero)) ->
    com h gs [v] t = h ^ (t + nth 0 γ zero * v).
  Proof.
    intros * hl hn hγ. rewrite (com_dlog h gs γ [v] t hl hγ). f_equal.
    destruct γ as [| γ0 γ]; [cbn in hl; lia |]. unfold dot; cbn [combine map fst snd fold_right nth].
    assert (e : combine γ ([] : list F) = []) by (destruct γ; reflexivity). rewrite e; cbn [map fold_right]. field.
  Qed.

  Lemma gop_solve : forall u v w : G, gop u v = w -> u = gop w (ginv v).
  Proof. intros u v w h. rewrite <-h, <-gassoc, ginv_r, gid_r; reflexivity. Qed.

