(** * Special honest-verifier zero knowledge of the Bayer–Groth arguments

    This file proves that the Bayer–Groth shuffle argument (Bayer and Groth,
    _Efficient Zero-Knowledge Argument for Correctness of a Shuffle_,
    EUROCRYPT 2012) and its sub-arguments, as formalised in
    [Sigma.BayerGroth], are _perfect special honest-verifier zero
    knowledge_ in the finite-distribution model of [Probability.Distr].
    The protocols and verifiers live in [BayerGroth.v]; soundness and
    witness extraction are in [BayerGrothSound.v]. The algorithm numbers
    quoted below are those of the Swiss Post verifiable-mixnet
    specification, which follows Bayer–Groth.

    For each argument the statement is: for every fixed choice of the
    verifier challenges, the distribution of the honest transcript (all
    announcements and responses, the challenges themselves left out) is
    identical to the distribution produced by a simulator that knows only
    the public statement and the challenges. Concretely, each section
    defines

    - [*real l] (for example [zreal]): the honest prover of [BayerGroth.v]
      run on the witness, with the list of scalars [l] supplying all of its
      random coins;
    - [*sim l]: the simulator, which reads responses and free announcements
      from [l] and solves the verification equations for the remaining
      announcements;
    - [*Phi] and [*Psi]: mutually inverse maps on coin lists of the right
      length, with [real l = sim (Phi l)] for every coin list [l];
    - [*real_eq_*sim]: that equation, proved under the hypothesis that the
      honest transcript is accepted by the verifier on an arbitrary
      statement (so that the composite arguments can reuse it on the
      statements derived by the outer verifier);
    - [*_shvzk]: the main theorem, a [Permutation] between the real and
      simulated distributions, both obtained by drawing the coin list
      uniformly from [F^k] with [rand].

    Since a [dist] is a list of weighted outcomes, a [Permutation] between
    the two lists means the two distributions are identical: this is
    _perfect_ (not statistical or computational) zero knowledge. The
    reduction from a bijection of coin lists to equality of distributions
    is [zk_of_bijection], built on [Distr.repeat_uniform_bijection_perm].

    Arguments covered, each with a theorem in this file:

    - zero argument: [zero_shvzk];
    - single-value product argument (Alg. 9.9/9.10): [svp_shvzk];
    - Hadamard product argument (Alg. 9.20/9.21), simulated through the
      zero-argument simulator: [hadamard_shvzk];
    - product argument (Alg. 9.18/9.19), composed of the Hadamard and
      single-value product simulators: [product_shvzk];
    - multi-exponentiation argument (Alg. 9.15/9.16) for single-message
      ElGamal ciphertexts ([l = 1], ciphertexts in [G × G]):
      [multiexp_shvzk];
    - shuffle argument (Alg. 9.11/9.12) for single-message ElGamal, composed
      of the product and multi-exponentiation simulators: [shuffle_shvzk].

    Common hypotheses. The scalar field [F] is finite and enumerated by a
    duplicate-free list [lf] ([NoDup lf] and [∀ v, In v lf]); coins are
    drawn uniformly from [lf]. The Pedersen commitment key [gs] lies in the
    group generated by [h]: [nth j gs gid = h ^ nth j γ zero] for a vector
    [γ] of discrete logarithms. This hypothesis is only used in the proof
    (a fresh commitment [com h gs v t = h ^ (t + ⟨γ, v⟩)] is uniform when
    [t] is), the simulators never use [γ]. Each theorem also assumes the
    witness relation of its argument (for example [hrel] for the zero
    argument) and the length side conditions on vectors and matrices. The
    Hadamard argument needs [x ≠ 0] and [y ≠ 0]; the product and shuffle
    arguments need the Hadamard challenges non-zero when [m > 1].

    Restrictions. The multi-exponentiation and shuffle results fix
    [l = 1] and additionally assume a function [dl] with [g ^ dl v = v] for
    every [v : G], that is, [g] generates the whole group and [dl] is a
    (non-computational) discrete logarithm. This is what makes a fresh
    single-message ElGamal ciphertext a uniformly random pair of group
    elements, so the simulator can replace the prover's ciphertexts
    [E_k] by random pairs. For [l > 1] (or under a mere DDH assumption) the
    argument is only computationally zero knowledge, which this
    finite-distribution framework does not express. Only special
    honest-verifier zero knowledge of the interactive protocols is proved;
    nothing is claimed here about the Fiat–Shamir transformed verifiers.
    All results are fully proved; nothing is admitted or axiomatised. *)
