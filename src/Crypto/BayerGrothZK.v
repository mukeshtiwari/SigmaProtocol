  Local Notation product_verify := (product_verify (zero := zero) (one := one) (add := add)
    (mul := mul) (sub := sub) (opp := opp) (Fdec := Fdec) (gid := gid) (gop := gop) (gpow := gpow)
    (Gdec := Gdec)).
  Local Notation product_prove := (product_prove (zero := zero) (one := one) (add := add)
    (mul := mul) (sub := sub) (opp := opp) (gid := gid) (gop := gop) (gpow := gpow)).
  Local Notation product_argument := (@product_argument F G).
  Local Notation mk_prod := (@mk_prod F G).

  Section ProductZK.

    Variables (h : G) (gs : list G) (γ : list F).
    Variables (A : list (list F)) (r : list F) (xh yh xz xs : F) (m : nat).
    Local Notation n := (length gs).
    Local Notation cA := (com_list h gs A r).
    Local Notation bvec := (hprefix A (length A - 1)).
    Local Notation b := (fold_right mul one bvec).

    Hypothesis hAm : length A = m.
    Hypothesis hm : (1 <= m)%nat.
    Hypothesis hn : (2 <= n)%nat.
    Hypothesis hr : length r = m.
    Hypothesis hAn : Forall (fun v => length v = n) A.
    Hypothesis hγl : length γ = n.
    Hypothesis hγ : forall j, (j < n)%nat -> nth j gs gid = h ^ (nth j γ zero).

    Lemma hbl : length bvec = n.
    Proof. apply (hprefix_length n A _ hAn); lia. Qed.
    Lemma ha0 : length (nth 0 A []) = n.
    Proof. rewrite Forall_forall in hAn; apply hAn, nth_In; lia. Qed.

    (* the prover's randomness: s, the Hadamard argument's, the single value product argument's *)
    Definition pR : nat := (1 + hR gs m + sR n)%nat.

    Definition preal (l : list F) : product_argument :=
      let s := nth 0 l zero in
      let lh := slice l 1 (hR gs m) in
      let lz := skipn (m - 2) lh in
      let ls := skipn (1 + hR gs m) l in
      product_prove h gs n A r s (slice lh 0 (m - 2)) (slice lz 0 n) (slice lz n n) (nth (2 * n) lz zero) (nth (2 * n + 1) lz zero)
        (slice lz (2 * n + 2) (S m)) (slice lz (2 * n + 3 + m) (m - 1))
        (slice ls 0 n) (nth n ls zero) (slice ls (n + 1) (n - 2)) (nth (2 * n - 1) ls zero) (nth (2 * n) ls zero) xh yh xz xs.

    (* the simulator: for m ≥ 2 a random commitment c_b = h^u and the two simulated
       sub-arguments; for m = 1 only the simulated single value product argument *)
    Definition psim (cA' : list G) (b' : F) (l : list F) : product_argument :=
      let u := nth 0 l zero in
      let lh := slice l 1 (hR gs m) in
      let ls := skipn (1 + hR gs m) l in
      if 1 <? length cA' then
        mk_prod (h ^ u) (Some (hsim h gs xh yh xz m cA' (h ^ u) lh)) (ssim h gs xs n (h ^ u) b' ls)
      else mk_prod gid None (ssim h gs xs n (nth 0 cA' gid) b' ls).

    Definition product_real_distribution (lf : list F) (Hlfn : lf <> []) : dist product_argument :=
      Bind (rand lf Hlfn pR) (fun l => Ret (preal l)).
    Definition product_sim_distribution (lf : list F) (Hlfn : lf <> []) (cA' : list G) (b' : F) : dist product_argument :=
      Bind (rand lf Hlfn pR) (fun l => Ret (psim cA' b' l)).

    Definition pPhi (l : list F) : list F :=
      let s := nth 0 l zero in
      let lh := slice l 1 (hR gs m) in
      let ls := skipn (1 + hR gs m) l in
      if 1 <? length A then (s + dot γ bvec) :: hPhi gs γ A r s xh yh xz m lh ++ sPhi γ bvec s xs n ls
      else s :: lh ++ sPhi γ (nth 0 A []) (nth 0 r zero) xs n ls.
    Definition pPsi (l : list F) : list F :=
      let u := nth 0 l zero in
      let lh := slice l 1 (hR gs m) in
      let ls := skipn (1 + hR gs m) l in
      if 1 <? length A then
        let s := u - dot γ bvec in
        s :: hPsi gs γ A r s xh yh xz m lh ++ sPsi γ bvec s xs n ls
      else u :: lh ++ sPsi γ (nth 0 A []) (nth 0 r zero) xs n ls.

    Lemma pslices : forall (a : F) (X Y : list F), length X = hR gs m ->
      nth 0 (a :: X ++ Y) zero = a /\ slice (a :: X ++ Y) 1 (hR gs m) = X /\ skipn (1 + hR gs m) (a :: X ++ Y) = Y.
    Proof.
      intros a X Y hX. repeat split.
      + unfold slice; cbn [skipn]. exact (slice_app0 X Y _ hX).
      + cbn [skipn Nat.add]. exact (skipn_app_exact X Y _ hX).
    Qed.

    Lemma precompose : forall l, length l = pR -> l = nth 0 l zero :: slice l 1 (hR gs m) ++ skipn (1 + hR gs m) l.
    Proof.
      intros l hl. unfold pR in hl. destruct l as [| a l0]; [cbn in hl; lia |].
      cbn [nth]. unfold slice. cbn [skipn Nat.add]. f_equal. symmetry; apply firstn_skipn.
    Qed.

    Lemma preal_eq_psim : forall l (cA' : list G) (b' : F), length l = pR -> length cA' = m ->
      product_verify h gs n cA' b' xh yh xz xs (preal l) = true -> preal l = psim cA' b' (pPhi l).
    Proof.
      intros l cA' b' hl hcA hv. unfold pR in hl.
      unfold preal, psim, pPhi in *; cbv zeta in *.
      set (s := nth 0 l zero) in *. set (lh := slice l 1 (hR gs m)) in *. set (ls := skipn (1 + hR gs m) l) in *.
      assert (hlh : length lh = hR gs m) by (apply length_slice; lia).
      assert (hls : length ls = sR n) by (unfold ls; rewrite length_skipn; lia).
      assert (hlt' : (1 <? m) = (1 <? length A)) by (rewrite hAm; reflexivity).
      rewrite hcA, hlt' in *.
      unfold BayerGroth.product_prove in hv |- *; cbv zeta in hv |- *.
      destruct (1 <? length A) eqn:hlt.
      + (* m ≥ 2 *)
        assert (hm2 : (2 <= m)%nat) by (pose proof (proj1 (Nat.ltb_lt _ _) hlt); lia).
        apply product_verify_true in hv; [| lia].
        destruct hv as [(_ & hvh & hvs) | (h1 & _)]; [| lia].
        set (X := hPhi gs γ A r s xh yh xz m lh). set (Y := sPhi γ bvec s xs n ls).
        assert (hX : length X = hR gs m) by apply (hPhi_length gs γ A r s xh yh xz m hAm hm2 (ltac:(lia)) hr hAn hγl lh hlh).
        destruct (pslices (s + dot γ bvec) X Y hX) as (P0 & P1 & P2). rewrite P0, P1, P2.
        rewrite <-(com_dlog h gs γ bvec s hγl hγ).
        f_equal.
        - f_equal. exact (hreal_eq_hsim h gs γ A r s xh yh xz m hAm hm2 (ltac:(lia)) hr hAn hγl hγ lh cA' _ hlh hvh).
        - exact (sreal_eq_ssim h gs γ bvec s xs n hbl hn hγl hγ ls _ b' hls hvs).
      + (* m = 1 *)
        unfold BayerGroth.product_verify in hv; cbv zeta in hv. rewrite hcA, hlt' in hv. cbn [pa_svp] in hv.
        destruct (pslices s lh (sPhi γ (nth 0 A []) (nth 0 r zero) xs n ls) hlh) as (P0 & P1 & P2). rewrite P2.
        f_equal.
        exact (sreal_eq_ssim h gs γ (nth 0 A []) (nth 0 r zero) xs n ha0 hn hγl hγ ls _ b' hls hv).
    Qed.

    Lemma pPhi_length : forall l, length l = pR -> length (pPhi l) = pR.
    Proof.
      intros l hl. unfold pR in *. unfold pPhi; cbv zeta.
      assert (hlh : length (slice l 1 (hR gs m)) = hR gs m) by (apply length_slice; lia).
      assert (hls : length (skipn (1 + hR gs m) l) = sR n) by (rewrite length_skipn; lia).
      destruct (1 <? length A) eqn:hlt; cbn [length]; rewrite length_app.
      + assert (hm2 : (2 <= m)%nat) by (pose proof (proj1 (Nat.ltb_lt _ _) hlt); lia).
        rewrite (hPhi_length gs γ A r _ xh yh xz m hAm hm2 (ltac:(lia)) hr hAn hγl _ hlh).
        rewrite (sPhi_length gs γ bvec _ xs n hbl hn hγl _ hls). lia.
      + rewrite hlh, (sPhi_length gs γ (nth 0 A []) _ xs n ha0 hn hγl _ hls). lia.
    Qed.

