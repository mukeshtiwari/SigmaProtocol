  (** ** Uniform coins and the bijection principle

      The prover's and the simulator's randomness is one list of [k]
      scalars drawn uniformly and independently from [lf]. The key result
      of this part, [zk_of_bijection], says that two functions of the coins
      that differ by a bijection of [F^k] induce the same distribution. *)

  (** [rand lf Hlfn k] is the uniform distribution on lists of length [k]
      over [lf] (with replacement), obtained from the vector distribution
      [repeat_dist_ntimes_vector] by forgetting the length index. *)
  Definition rand (lf : list F) (Hlfn : lf <> []) (k : nat) : dist (list F) :=
    List.map (fun '(v, p) => (Vector.to_list v, p)) (repeat_dist_ntimes_vector (uniform_with_replacement lf Hlfn) k).

  (** [of_list_n k l] converts a list to a vector of length [k], truncating
      or padding with [zero]. It is the inverse of [Vector.to_list] on lists
      of length [k] and is used to transport bijections on lists to
      bijections on vectors. *)
  Fixpoint of_list_n (k : nat) (l : list F) : Vector.t F k :=
    match k with 0 => Vector.nil F | S k' => Vector.cons F (hd zero l) k' (of_list_n k' (tl l)) end.

  (** [of_list_n] followed by [Vector.to_list] is the identity on lists of
      length [k]. *)
  Lemma to_list_of_list_n : forall k (l : list F), length l = k -> Vector.to_list (of_list_n k l) = l.
  Proof.
    induction k as [| k ih]; intros l hl; destruct l as [| a l]; try discriminate; [reflexivity |].
    cbn [of_list_n hd tl]. change (Vector.to_list (Vector.cons F a k (of_list_n k l))) with (a :: Vector.to_list (of_list_n k l)).
    f_equal. apply ih. cbn in hl; lia.
  Qed.

  (** [Vector.to_list] followed by [of_list_n] is the identity on vectors. *)
  Lemma of_list_n_to_list : forall k (v : Vector.t F k), of_list_n k (Vector.to_list v) = v.
  Proof.
    intros k v; induction v as [| a k v ih]; [reflexivity |].
    change (Vector.to_list (Vector.cons F a k v)) with (a :: Vector.to_list v). cbn [of_list_n hd tl]. rewrite ih; reflexivity.
  Qed.

  (** Every outcome in the support of [rand lf Hlfn k] has length [k]. *)
  Lemma in_rand_length : forall lf Hlfn k (l : list F) p, In (l, p) (rand lf Hlfn k) -> length l = k.
  Proof.
    intros lf Hlfn k l p hin. unfold rand in hin. apply in_map_iff in hin.
    destruct hin as ((v & q) & e & _). injection e as <- _. apply length_to_list.
  Qed.

  (** Mapping the value component of a weighted list twice is mapping the
      composition once. *)
  Lemma map_pair_compose : forall {A B C P : Type} (f : A -> B) (k : B -> C) (l : list (A * P)),
    List.map (fun '(v, p) => (k (f v), p)) l = List.map (fun '(v, p) => (k v, p)) (List.map (fun '(v, p) => (f v, p)) l).
  Proof. intros; induction l as [| (v & p) l ih]; [reflexivity | cbn; rewrite ih; reflexivity]. Qed.

  (** If [Phi] and [Psi] are mutually inverse length-preserving maps on
      lists of length [k], then applying [Phi] to the outcomes of
      [rand lf Hlfn k] permutes the weighted list: the uniform distribution
      on [F^k] is invariant under bijections. The hypotheses [NoDup lf] and
      [∀ x, In x lf] say that [lf] enumerates [F] exactly once. The proof
      lifts [Phi] and [Psi] to vectors and applies
      [repeat_uniform_bijection_perm]. *)
  Lemma rand_bijection_perm : forall (lf : list F) (Hlfn : lf <> []) (k : nat) (Phi Psi : list F -> list F),
    NoDup lf -> (forall x, In x lf) ->
    (forall l, length l = k -> length (Phi l) = k) -> (forall l, length l = k -> length (Psi l) = k) ->
    (forall l, length l = k -> Psi (Phi l) = l) -> (forall l, length l = k -> Phi (Psi l) = l) ->
    Permutation (List.map (fun '(l, p) => (Phi l, p)) (rand lf Hlfn k)) (rand lf Hlfn k).
  Proof.
    intros lf Hlfn k Phi Psi hnd hall hlP hlQ hPsi hPhi.
    set (PhiV := fun v : Vector.t F k => of_list_n k (Phi (Vector.to_list v))).
    set (PsiV := fun v : Vector.t F k => of_list_n k (Psi (Vector.to_list v))).
    unfold rand. rewrite <-map_pair_compose.
    rewrite (List.map_ext (fun '(v, p) => (Phi (Vector.to_list v), p)) (fun '(v, p) => (Vector.to_list (PhiV v), p))).
    2: { intros (v & p). unfold PhiV. rewrite to_list_of_list_n by (apply hlP, length_to_list). reflexivity. }
    rewrite map_pair_compose. apply Permutation_map.
    apply (repeat_uniform_bijection_perm lf Hlfn k PhiV PsiV hnd hall).
    + intro v. unfold PsiV, PhiV. rewrite to_list_of_list_n by (apply hlP, length_to_list).
      rewrite hPsi by apply length_to_list. apply of_list_n_to_list.
    + intro v. unfold PsiV, PhiV. rewrite to_list_of_list_n by (apply hlQ, length_to_list).
      rewrite hPhi by apply length_to_list. apply of_list_n_to_list.
  Qed.

  (** The generic zero-knowledge reduction. If [real l = sim (Phi l)] for
      every coin list [l] of length [k], where [Phi] is a bijection on such
      lists with inverse [Psi], then the distributions
      [Bind (rand lf Hlfn k) (fun l => Ret (real l))] and
      [Bind (rand lf Hlfn k) (fun l => Ret (sim l))] are permutations of
      each other, that is, identical. Every [*_shvzk] theorem below is an
      instance of this lemma. *)
  Theorem zk_of_bijection : forall {T : Type} (lf : list F) (Hlfn : lf <> []) (k : nat)
    (real sim : list F -> T) (Phi Psi : list F -> list F),
    NoDup lf -> (forall x, In x lf) ->
    (forall l, length l = k -> length (Phi l) = k) -> (forall l, length l = k -> length (Psi l) = k) ->
    (forall l, length l = k -> Psi (Phi l) = l) -> (forall l, length l = k -> Phi (Psi l) = l) ->
    (forall l, length l = k -> real l = sim (Phi l)) ->
    Permutation (Bind (rand lf Hlfn k) (fun l => Ret (real l))) (Bind (rand lf Hlfn k) (fun l => Ret (sim l))).
  Proof.
    intros * hnd hall hlP hlQ hPsi hPhi heq.
    apply (bind_ret_perm (rand lf Hlfn k) Phi real sim).
    + apply (rand_bijection_perm lf Hlfn k Phi Psi); assumption.
    + intros l p hin. apply heq. exact (in_rand_length lf Hlfn k l p hin).
  Qed.

  (** ** List slicing and arithmetic helpers

      The coin list of each argument is cut into consecutive blocks. This
      part provides [slice] and lemmas computing slices and [nth] of
      concatenations, pointwise subtraction [psub] (inverse of [padd]) and
      the inner product [dot]. *)

  (** [slice l off len] is the sublist of [l] of length [len] starting at
      position [off]. *)
  Definition slice (l : list F) (off len : nat) : list F := firstn len (skipn off l).

  (** A slice that lies inside the list has the requested length. *)
  Lemma length_slice : forall l off len, (off + len <= length l)%nat -> length (slice l off len) = len.
  Proof. intros; unfold slice; rewrite length_firstn, length_skipn; lia. Qed.

  (** The initial slice of length [length a] of [a ++ r] is [a]. *)
  Lemma slice_app0 : forall (a r : list F) len, length a = len -> slice (a ++ r) 0 len = a.
  Proof. intros a r len hl; unfold slice; cbn [skipn]; rewrite firstn_app, firstn_all2, hl, Nat.sub_diag by lia; cbn; apply app_nil_r. Qed.

  (** Dropping exactly [length a] elements of [a ++ r] leaves [r]. *)
  Lemma skipn_app_exact : forall (a r : list F) off, length a = off -> skipn off (a ++ r) = r.
  Proof. intros a r off hl; rewrite skipn_app, skipn_all2, hl, Nat.sub_diag by lia; reflexivity. Qed.

  (** A slice starting right after [a] in [a ++ r] is a prefix slice of [r]. *)
  Lemma slice_app : forall (a r : list F) off len, length a = off -> slice (a ++ r) off len = slice r 0 len.
  Proof. intros; unfold slice; rewrite skipn_app_exact by assumption; reflexivity. Qed.

  (** Shifting the offset of a slice is slicing a suffix. Not used in this
      file. *)
  Lemma slice_skip : forall (l : list F) off1 off2 len, slice l (off1 + off2) len = slice (skipn off1 l) off2 len.
  Proof. intros; unfold slice; rewrite skipn_skipn, Nat.add_comm; reflexivity. Qed.

  (** Indexing [a ++ r] past [a] is indexing [r]. *)
  Lemma nth_app_exact : forall (a r : list F) off i d, length a = off -> nth (off + i) (a ++ r) d = nth i r d.
  Proof. intros a r off i d hl; rewrite app_nth2 by lia; rewrite hl; replace (off + i - off)%nat with i by lia; reflexivity. Qed.

  (** The element of [a ++ rest] at position [length a] is the head of
      [rest]. *)
  Lemma nth_app_len : forall (a rest : list F) k d, length a = k -> nth k (a ++ rest) d = nth 0 rest d.
  Proof. intros a rest k d hl; rewrite app_nth2 by lia; rewrite hl, Nat.sub_diag; reflexivity. Qed.

  (** A list of length at least 2 starts with its elements 0 and 1. Not
      used in this file. *)
  Lemma firstn2 : forall (l : list F), (2 <= length l)%nat -> firstn 2 l = [nth 0 l zero; nth 1 l zero].
  Proof. intros l hl; destruct l as [| a [| b l]]; cbn in hl; try lia; reflexivity. Qed.

  (** [psub a b] is the pointwise difference [a - b] (truncated to the
      shorter list). It inverts [padd] and is used by the inverse maps
      [*Psi] to recover the prover's coins from the responses. *)
  Definition psub (a b : list F) : list F := map (fun p => fst p - snd p) (combine a b).

  (** [(a - b) + b = a] for lists of equal length. *)
  Lemma psub_padd : forall a b, length a = length b -> padd (psub a b) b = a.
  Proof.
    induction a as [| a0 a ih]; intros b hl; destruct b as [| b0 b]; try discriminate; [reflexivity |].
    unfold psub in *; cbn [combine map fst snd SigmaK.padd]. rewrite ih by (cbn in hl; lia). f_equal; field.
  Qed.

  (** [(a + b) - b = a] for lists of equal length. *)
  Lemma padd_psub : forall a b, length a = length b -> psub (padd a b) b = a.
  Proof.
    induction a as [| a0 a ih]; intros b hl; destruct b as [| b0 b]; try discriminate; [reflexivity |].
    unfold psub in *; cbn [combine map fst snd SigmaK.padd]. rewrite ih by (cbn in hl; lia). f_equal; field.
  Qed.

  (** [psub a b] has the length of [a] when the lengths agree. *)
  Lemma psub_length : forall a b, length a = length b -> length (psub a b) = length a.
  Proof. intros; unfold psub; rewrite length_map, length_combine; lia. Qed.

  (** *** Commitments as powers of [h]

      Under the hypothesis [g_j = h ^ γ_j] on the commitment key, a
      Pedersen commitment is a single power of [h]. This is what makes a
      fresh commitment uniformly distributed and lets the simulator replace
      commitments by random powers [h ^ u]. *)

  (** [dot γ v] is the inner product [⟨γ, v⟩ = Σ γ_j · v_j] (truncated to
      the shorter list). *)
  Definition dot (γ v : list F) : F := fold_right add zero (map (fun p => fst p * snd p) (combine γ v)).

  (** If the key [gs] satisfies [gs_j = h ^ γ_j] for all [j], then
      [com h gs v t = h ^ (t + ⟨γ, v⟩)] for every vector [v] and
      randomness [t]. Proof by induction on [gs]. *)
  Lemma com_dlog : forall (h : G) (gs : list G) (γ v : list F) (t : F), length γ = length gs ->
    (forall j, (j < length gs)%nat -> nth j gs gid = h ^ (nth j γ zero)) ->
    com h gs v t = h ^ (t + dot γ v).
  Proof.
    intros h gs; induction gs as [| g gs ih]; intros γ v t hl hγ.
    + unfold BayerGroth.com. rewrite lmexp_nil_l. destruct γ; [| discriminate]. unfold dot; cbn.
      rewrite gid_r. f_equal; field.
    + destruct γ as [| γ0 γ]; [discriminate |]. destruct v as [| v0 v].
      - unfold BayerGroth.com. rewrite lmexp_nil_r, gid_r. unfold dot; cbn. f_equal; field.
      - unfold BayerGroth.com. rewrite lmexp_cons. pose proof (hγ 0%nat ltac:(cbn; lia)) as h0; cbn [nth] in h0. rewrite h0.
        rewrite <-gpow_mul, gassoc, <-gpow_add.
        assert (hrec : gop (h ^ (t + γ0 * v0)) (gmexp gs v) = com h gs v (t + γ0 * v0)) by reflexivity.
        rewrite hrec, (ih γ v) by (cbn in hl; lia || (intros j hj; exact (hγ (S j) ltac:(cbn; lia)))).
        unfold dot; cbn [combine map fst snd fold_right]. f_equal; field.
  Qed.

  (** Special case of [com_dlog] for a single committed scalar:
      [com h gs [v] t = h ^ (t + γ_0 · v)]. *)
  Lemma com_single_dlog : forall (h : G) (gs : list G) (γ : list F) (v t : F), length γ = length gs -> (1 <= length gs)%nat ->
    (forall j, (j < length gs)%nat -> nth j gs gid = h ^ (nth j γ zero)) ->
    com h gs [v] t = h ^ (t + nth 0 γ zero * v).
  Proof.
    intros * hl hn hγ. rewrite (com_dlog h gs γ [v] t hl hγ). f_equal.
    destruct γ as [| γ0 γ]; [cbn in hl; lia |]. unfold dot; cbn [combine map fst snd fold_right nth].
    assert (e : combine γ ([] : list F) = []) by (destruct γ; reflexivity). rewrite e; cbn [map fold_right]. field.
  Qed.

  (** Solving a group equation for the left factor:
      [u · v = w] implies [u = w · v⁻¹]. Used to show that the announcement
      solved by the simulator equals the honest one. *)
  Lemma gop_solve : forall u v w : G, gop u v = w -> u = gop w (ginv v).
  Proof. intros u v w h. rewrite <-h, <-gassoc, ginv_r, gid_r; reflexivity. Qed.

  (** A slice of [a ++ rest] at offset [length a + off] is a slice of
      [rest] at offset [off]. *)
  Lemma slice_app_gen : forall (a rest : list F) k off len, length a = k -> slice (a ++ rest) (k + off) len = slice rest off len.
  Proof. intros a rest k off len hl; unfold slice; rewrite skipn_app, skipn_all2, hl by lia; replace (k + off - k)%nat with off by lia; reflexivity. Qed.

  (** The [i]-th element of [map f (seq st len)] is [f (st + i)] for
      [i < len]. *)
  Lemma nth_map_seq_gen : forall {X : Type} (f : nat -> X) (st len i : nat) (d : X), (i < len)%nat ->
    nth i (map f (seq st len)) d = f (st + i)%nat.
  Proof.
    intros X f st len i d hi. rewrite (nth_indep _ d (f 0%nat)) by (rewrite length_map, length_seq; exact hi).
    rewrite map_nth, seq_nth by exact hi. reflexivity.
  Qed.

  (** A non-empty list of group elements is its head consed onto its tail. *)
  Lemma list_hd_tl : forall (l : list G) (d : G), l <> [] -> l = nth 0 l d :: tl l.
  Proof. intros l d hl; destruct l; [contradiction | reflexivity]. Qed.

  (** Solving a group equation for the right factor:
      [u · v = w] implies [v = w · u⁻¹]. *)
  Lemma gop_solve_r : forall u v w : G, gop u v = w -> v = gop w (ginv u).
  Proof. intros u v w e. apply gop_solve. rewrite gcomm. exact e. Qed.

  (** [firstn (k + k') l] is [firstn k l] followed by the first [k']
      elements after position [k]. *)
  Lemma firstn_add_skipn : forall (l : list F) k k', firstn (Nat.add k k') l = firstn k l ++ firstn k' (skipn k l).
  Proof.
    intros l k; revert l; induction k as [| k ih]; intros l k'; [reflexivity |].
    destruct l as [| a l]; [cbn [firstn skipn app]; rewrite !firstn_nil; reflexivity |].
    cbn [Nat.add firstn skipn app]. rewrite ih. reflexivity.
  Qed.

  (** A slice of length [len + len'] splits into two adjacent slices. *)
  Lemma slice_split : forall (l : list F) off len len', slice l off (len + len')%nat = slice l off len ++ slice l (off + len)%nat len'.
  Proof. intros; unfold slice. rewrite firstn_add_skipn, skipn_skipn, (Nat.add_comm len off). reflexivity. Qed.

  (** A slice of length 1 inside the list is the singleton of [nth]. *)
  Lemma slice_one : forall (l : list F) off, (off < length l)%nat -> slice l off 1 = [nth off l zero].
  Proof.
    intros l off hoff. unfold slice.
    assert (hne : skipn off l <> []) by (intro e; apply (f_equal (@length F)) in e; rewrite length_skipn in e; cbn in e; lia).
    destruct (skipn off l) as [| a t] eqn:e; [contradiction |]. cbn [firstn]. f_equal.
    transitivity (nth 0 (skipn off l) zero); [rewrite e; reflexivity | rewrite nth_skipn_add, Nat.add_0_r; reflexivity].
  Qed.

  (** The slice from 0 of the full length is the whole list. *)
  Lemma slice_all : forall (l : list F) k, length l = k -> slice l 0 k = l.
  Proof. intros l k hk; unfold slice; cbn [skipn]; apply firstn_all2; lia. Qed.

  (** Re-reading a list of length [k] element by element gives it back:
      [map (fun i => nth i l zero) (seq 0 k) = l]. *)
  Lemma map_nth_seq_id : forall (l : list F) k, length l = k -> map (fun i => nth i l zero) (seq 0 k) = l.
  Proof.
    intros l k hk. apply (nth_ext _ _ zero zero).
    + rewrite length_map, length_seq; symmetry; exact hk.
    + intros i hi; rewrite length_map, length_seq in hi. rewrite nth_map_seq_gen by exact hi. reflexivity.
  Qed.

  (** ** The zero argument

      Statement: commitments [cA = com_list h gs A r] and
      [cB = com_list h gs B s] to [m] column vectors each, and a challenge
      [y], with witness relation [Σ_i A_i ⋆_y B_i = 0], where [⋆_y] is the
      bilinear map [star y]. The prover ([zero_prove]) commits to fresh
      vectors [a_0] and [b_m] and to the [2m + 1] coefficients [d_k] of the
      polynomial [Σ_{i,j} (a_i ⋆ b_j) X^k], with commitment
      [c_{D,m+1}] forced to [com(0; 0)]; after the challenge [x] it opens
      the evaluations [a = Σ x^i a_i], [b], [r], [s] and [t].

      The simulator [zsim] picks the responses [a], [b], [r], [s], [t] and
      the free commitments [c_{D,k}] ([k ≠ 0, m+1]) at random, and solves
      the three verification equations for [c_{A0}], [c_{Bm}] and
      [c_{D0}]. The theorem [zero_shvzk] shows that its output distribution
      equals the honest one, for every [x] and [y]. *)
  Section ZeroZK.

    (** The commitment key [h], [gs] with discrete logarithms [γ]; the
        witness matrices [A], [B] (lists of [m] columns of length [n]) with
        commitment randomness [r], [s]; the challenges [y] (for [⋆_y]) and
        [x]. *)
    Variables (h : G) (gs : list G) (γ : list F).
    Variables (A B : list (list F)) (r s : list F) (y x : F) (m : nat).
    (** [n] is the length of the commitment key, hence of every column. *)
    Local Notation n := (length gs).
    (** [A] has [m] columns. This hypothesis is stated early because the
        bijection [zPhi] depends on it. *)
    Hypothesis hAm : length A = m.
    (** The honest statement: the commitments to [A] and [B]. *)
    Local Notation cA := (com_list h gs A r).
    Local Notation cB := (com_list h gs B s).

    (** The number of prover coins: [a_0] and [b_m] in [F^n], [r_0], [s_m],
        and the [2m] free randomisers [t_0 .. t_m, t_{m+2} .. t_{2m}] of the
        [c_{D,k}] ([t_{m+1}] is fixed to 0). In total [2n + 2m + 2]. *)
    Definition zR : nat := (2 * n + 2 * m + 2)%nat.

    (** The honest transcript as a function of the coin list [l]: the
        prover [zero_prove] with [a_0] the first [n] coins, [b_m] the next [n],
        [r_0] and [s_m] the coins at positions [2n] and [2n + 1], [t_0 .. t_m] and
        [t_{m+2} .. t_{2m}] read from the remaining slices. *)
    Definition zreal (l : list F) : zero_argument :=
      zero_prove h gs A B r s y (slice l 0 n) (slice l n n) (nth (2 * n) l zero) (nth (2 * n + 1) l zero)
        (slice l (2 * n + 2) (S m)) (slice l (2 * n + 3 + m) (m - 1)) x.

    (** The simulator on statement [cA'], [cB'] (and the fixed challenges
        [x], [y]). From [l] it reads responses [ã], [b̃] in [F^n], [r̃], [s̃],
        [t̃] and [2m - 1] exponents [u_k]; it sets
        [c_{D,k} = h ^ u_k] for [k = 1 .. 2m], [k ≠ m+1], and
        [c_{D,m+1} = 1], and then solves the verification equations:
        [c_{A0} = com(ã; r̃) · (Π cA'_i ^ x^i)^(-x)], similarly
        [c_{Bm}] from [rev cB'] and [c_{D0}] from [com(ã ⋆ b̃; t̃)]. The
        simulator does not use [γ]. *)
    Definition zsim (cA' cB' : list G) (l : list F) : zero_argument :=
      let at_ := slice l 0 n in
      let bt := slice l n n in
      let rt := nth (2 * n) l zero in
      let st := nth (2 * n + 1) l zero in
      let tt := nth (2 * n + 2) l zero in
      let us := slice l (2 * n + 3) (2 * m - 1) in
      let cdt := map (fun k => if Nat.eqb k (S m) then gid else h ^ (nth (if Nat.leb k m then k - 1 else k - 2) us zero)) (seq 1 (2 * m)) in
      mk_zero (gop (com h gs at_ rt) (ginv ((geval cA' x) ^ x))) (gop (com h gs bt st) (ginv ((geval (rev cB') x) ^ x)))
        (gop (com h gs [star y at_ bt] tt) (ginv ((geval cdt x) ^ x)) :: cdt) at_ bt rt st tt.

    (** The real and simulated transcript distributions: push the uniform
        coin distribution [rand lf Hlfn zR] through [zreal] and through
        [zsim cA' cB'] respectively. *)
    Definition zero_real_distribution (lf : list F) (Hlfn : lf <> []) : dist zero_argument :=
      Bind (rand lf Hlfn zR) (fun l => Ret (zreal l)).
    Definition zero_sim_distribution (lf : list F) (Hlfn : lf <> []) (cA' cB' : list G) : dist zero_argument :=
      Bind (rand lf Hlfn zR) (fun l => Ret (zsim cA' cB' l)).

    (** The bijection from prover coins to simulator coins: it computes the
        honest responses [a = Σ x^i a_i] (with [a_0] prepended), [b], [r],
        [s], [t], followed by the discrete logarithms
        [t_k + γ_0 · d_k] of the honest commitments [c_{D,k}] for
        [k ∈ 1..m] and [k ∈ m+2..2m]. Each response is an affine bijection
        of a fresh coin ([a_0], [b_m], [r_0], [s_m], [t_0] respectively),
        and each [u_k] is a translate of [t_k]. *)
    Definition zPhi (l : list F) : list F :=
      let a0 := slice l 0 n in
      let bm := slice l n n in
      let r0 := nth (2 * n) l zero in
      let sm := nth (2 * n + 1) l zero in
      let t1 := slice l (2 * n + 2) (S m) in
      let t2 := slice l (2 * n + 3 + m) (m - 1) in
      let tz := t1 ++ zero :: t2 in
      let d := fpmul (star y) (a0 :: A) (bm :: rev B) in
      lveval (a0 :: A) x ++ lveval (bm :: rev B) x ++
      [feval (r0 :: r) x; feval (sm :: rev s) x; feval tz x] ++
      map (fun k => nth k tz zero + nth 0 γ zero * nth k d zero) (seq 1 m ++ seq (m + 2) (m - 1)).

    (** The inverse of [zPhi]: recover [a_0 = ã - x · Σ x^i a_{i+1}] (with
        [psub]), [b_m], [r_0], [s_m], then [d] from [a_0] and [b_m], then
        [t_k = u_k - γ_0 · d_k] and finally [t_0 = t̃ - x · t(x)]. The
        argument relies on the honest witness [A], [B], [r], [s] only
        through the shifts, which do not depend on the coins being
        inverted (except [d], which is recomputed from the already
        recovered [a_0] and [b_m]). *)
    Definition zPsi (l : list F) : list F :=
      let at_ := slice l 0 n in
      let bt := slice l n n in
      let rt := nth (2 * n) l zero in
      let st := nth (2 * n + 1) l zero in
      let tt := nth (2 * n + 2) l zero in
      let us := slice l (2 * n + 3) (2 * m - 1) in
      let a0 := psub at_ (lscale x (lveval A x)) in
      let bm := psub bt (lscale x (lveval (rev B) x)) in
      let r0 := rt - x * feval r x in
      let sm := st - x * feval (rev s) x in
      let d := fpmul (star y) (a0 :: A) (bm :: rev B) in
      let ttl := map (fun k => nth (k - 1) us zero - nth 0 γ zero * nth k d zero) (seq 1 m) ++
                 zero :: map (fun k => nth (k - 2) us zero - nth 0 γ zero * nth k d zero) (seq (m + 2) (m - 1)) in
      let t0 := tt - x * feval ttl x in
      a0 ++ bm ++ [r0; sm] ++ (t0 :: firstn m ttl) ++ skipn (m + 1) ttl.

    (** Side conditions: [n ≥ 1] and [m ≥ 1]; [B], [r], [s] have length
        [m]; all columns have length [n]; [γ] are the discrete logarithms
        of the commitment key to base [h]. *)
    Hypothesis hn : (1 <= n)%nat.
    Hypothesis hm : (1 <= m)%nat.
    Hypothesis hB : length B = m.
    Hypothesis hr : length r = m.
    Hypothesis hs : length s = m.
    Hypothesis hAn : Forall (fun v => length v = n) A.
    Hypothesis hBn : Forall (fun v => length v = n) B.
    Hypothesis hγl : length γ = n.
    Hypothesis hγ : forall j, (j < n)%nat -> nth j gs gid = h ^ (nth j γ zero).

    (** The slices read by [zreal] fit in a coin list of length [zR]. *)
    Lemma zR_ge : (2 * n + 3 + m + (m - 1) <= zR)%nat.
    Proof. unfold zR; lia. Qed.

    (** Key equation. For any coin list [l] of length [zR] and any
        statement [cA'], [cB'] on which the verifier accepts the honest
        transcript [zreal l], that transcript equals the simulator output
        [zsim cA' cB' (zPhi l)]. The responses coincide by construction;
        the commitments [c_{D,k}] for [k ≠ 0] coincide by [com_single_dlog]
        and the verifier's check [c_{D,m+1} = 1]; the three solved
        commitments coincide because they satisfy the same verification
        equations ([gop_solve]). Stating it for arbitrary [cA'], [cB'] lets
        the Hadamard argument reuse it on the statement it derives. *)
    Lemma zreal_eq_zsim : forall l (cA' cB' : list G), length l = zR ->
      zero_verify h gs cA' cB' y x (zreal l) = true -> zreal l = zsim cA' cB' (zPhi l).
    Proof.
      intros l cA' cB' hl hv. pose proof zR_ge as hR.
      set (a0 := slice l 0 n). set (bm := slice l n n). set (r0 := nth (2 * n) l zero). set (sm := nth (2 * n + 1) l zero).
      set (t1 := slice l (2 * n + 2) (S m)). set (t2 := slice l (2 * n + 3 + m) (m - 1)).
      assert (ha0 : length a0 = n) by (unfold a0; apply length_slice; lia).
      assert (hbm : length bm = n) by (unfold bm; apply length_slice; lia).
      assert (ht1 : length t1 = S m) by (unfold t1; apply length_slice; lia).
      assert (ht2 : length t2 = (m - 1)%nat) by (unfold t2; apply length_slice; lia).
      set (As := a0 :: A). set (Bs := bm :: rev B). set (tz := t1 ++ zero :: t2).
      set (d := fpmul (star y) As Bs). set (RC := com_list h gs (map (fun dk => [dk]) d) tz).
      assert (hd : length d = (2 * m + 1)%nat).
      { unfold d; rewrite (pmul_length (vid := zero) (vadd := add)) by discriminate. unfold As, Bs; cbn [length]; rewrite length_rev, hB; lia. }
      assert (htz : length tz = (2 * m + 1)%nat) by (unfold tz; rewrite length_app; cbn [length]; lia).
      unfold zreal, BayerGroth.zero_prove in hv; cbv zeta in hv. fold a0 bm r0 sm t1 t2 As Bs tz d RC in hv.
      (* Unpack the verifier's acceptance into the length checks, the
         check that c_{D,m+1} is the identity and the three equations. *)
      apply zero_verify_true in hv. destruct hv as (_ & _ & hRCl & hmid & E1 & E2 & E3).
      assert (hcA'l : length cA' = m).
      { unfold RC in hRCl; rewrite com_list_length, length_map, hd, htz, Nat.min_id in hRCl; lia. }
      rewrite hcA'l in hmid.
      assert (hRCl' : length RC = (2 * m + 1)%nat) by (unfold RC; rewrite com_list_length, length_map, hd, htz, Nat.min_id; reflexivity).
      assert (hlAs : length (lveval As x) = n) by (apply lveval_length; [discriminate |]; intros v [<- | hv]; [exact ha0 | rewrite Forall_forall in hAn; apply hAn; exact hv]).
      assert (hlBs : length (lveval Bs x) = n) by (apply lveval_length; [discriminate |]; intros v [<- | hv]; [exact hbm | rewrite Forall_forall in hBn; apply hBn, in_rev; exact hv]).
      set (P4 := map (fun k => nth k tz zero + nth 0 γ zero * nth k d zero) (seq 1 m ++ seq (m + 2) (m - 1))).
      assert (hP4 : length P4 = (2 * m - 1)%nat) by (unfold P4; rewrite length_map, length_app, !length_seq; lia).
      unfold zreal, BayerGroth.zero_prove; cbv zeta. fold a0 bm r0 sm t1 t2 As Bs tz d RC.
      unfold zsim, zPhi; cbv zeta. fold a0 bm r0 sm t1 t2 As Bs tz d P4.
      rewrite (slice_app0 (lveval As x)) by exact hlAs.
      rewrite (slice_app (lveval As x) _ n n hlAs), (slice_app0 (lveval Bs x)) by exact hlBs.
      replace (2 * n)%nat with (n + n)%nat by lia. rewrite (nth_app_exact (lveval As x) _ n n zero hlAs).
      replace (n + n + 1)%nat with (n + (n + 1))%nat by lia. rewrite (nth_app_exact (lveval As x) _ n (n + 1) zero hlAs).
      replace (n + n + 2)%nat with (n + (n + 2))%nat by lia. rewrite (nth_app_exact (lveval As x) _ n (n + 2) zero hlAs).
      rewrite (nth_app_len (lveval Bs x) _ n zero hlBs), (nth_app_exact (lveval Bs x) _ n 1 zero hlBs), (nth_app_exact (lveval Bs x) _ n 2 zero hlBs).
      replace (n + n + 3)%nat with (n + (n + (3 + 0)))%nat by lia.
      rewrite (slice_app_gen (lveval As x) _ n _ _ hlAs), (slice_app_gen (lveval Bs x) _ n _ _ hlBs).
      rewrite (slice_app_gen [feval (r0 :: r) x; feval (sm :: rev s) x; feval tz x] _ 3 0 _ eq_refl).
      unfold slice; cbn [skipn]; rewrite firstn_all2 by (rewrite hP4; lia).
      cbn [app nth].
      set (cdt := map (fun k => if Nat.eqb k (S m) then gid else h ^ (nth (if Nat.leb k m then k - 1 else k - 2) P4 zero)) (seq 1 (2 * m))).
      (* The free commitments: c_{D,k} = h ^ (t_k + γ_0 d_k) by
         com_single_dlog, except the forced identity at position m+1. *)
      assert (hcdt : cdt = tl RC).
      { apply (nth_ext _ _ gid gid).
        + unfold cdt; rewrite length_map, length_seq, tl_len, hRCl'; lia.
        + intros i hi. unfold cdt in hi; rewrite length_map, length_seq in hi.
          unfold cdt; rewrite nth_map_seq_gen by exact hi.
          rewrite nth_tl by (destruct RC; [cbn in hRCl'; lia | discriminate]).
          destruct (Nat.eqb (1 + i) (S m)) eqn:e.
          - apply Nat.eqb_eq in e. replace (S i) with (S m) by lia. exact (eq_sym hmid).
          - apply Nat.eqb_neq in e.
            unfold RC. rewrite (nth_com_list (zero := zero)) by (rewrite ?length_map, ?hd, ?htz; lia).
            rewrite (nth_indep _ [] ((fun dk => [dk]) zero)) by (rewrite length_map, hd; lia).
            rewrite (map_nth (fun dk => [dk])). rewrite (com_single_dlog h gs γ) by (assumption || lia). f_equal.
            unfold P4. rewrite map_app. destruct (Nat.leb (1 + i) m) eqn:e2.
            * apply Nat.leb_le in e2. rewrite app_nth1 by (rewrite length_map, length_seq; lia).
              rewrite nth_map_seq_gen by lia. replace (1 + (1 + i - 1))%nat with (S i) by lia. reflexivity.
            * apply Nat.leb_gt in e2. rewrite app_nth2 by (rewrite length_map, length_seq; lia).
              rewrite length_map, length_seq, nth_map_seq_gen by lia. replace (m + 2 + (1 + i - 2 - m))%nat with (S i) by lia. reflexivity. }
      f_equal.
      (* The three solved announcements: each verification equation is
         solved for its leading factor. *)
      + rewrite (veval_cons (HV := Hvec)) in E1. exact (gop_solve _ _ _ E1).
      + rewrite (veval_cons (HV := Hvec)) in E2. exact (gop_solve _ _ _ E2).
      + rewrite (list_hd_tl RC gid) in E3 by (destruct RC; [cbn in hRCl'; lia | discriminate]).
        rewrite (veval_cons (HV := Hvec)) in E3. rewrite hcdt. rewrite <-(gop_solve _ _ _ E3).
        apply list_hd_tl. destruct RC; [cbn in hRCl'; lia | discriminate].
    Qed.

    (** Reading back the fields of a simulator coin list assembled as
        [ã ++ b̃ ++ [r̃; s̃; t̃] ++ us]. *)
    Lemma sim_slices : forall (x1 x2 x4 : list F) (a b c : F), length x1 = n -> length x2 = n -> length x4 = (2 * m - 1)%nat ->
      slice (x1 ++ x2 ++ [a; b; c] ++ x4) 0 n = x1 /\ slice (x1 ++ x2 ++ [a; b; c] ++ x4) n n = x2 /\
      nth (2 * n) (x1 ++ x2 ++ [a; b; c] ++ x4) zero = a /\ nth (2 * n + 1) (x1 ++ x2 ++ [a; b; c] ++ x4) zero = b /\
      nth (2 * n + 2) (x1 ++ x2 ++ [a; b; c] ++ x4) zero = c /\ slice (x1 ++ x2 ++ [a; b; c] ++ x4) (2 * n + 3) (2 * m - 1) = x4.
    Proof.
      intros * h1 h2 h4.
      rewrite (slice_app0 x1) by exact h1. rewrite (slice_app x1 _ n n h1), (slice_app0 x2) by exact h2.
      replace (2 * n)%nat with (n + n)%nat by lia. rewrite (nth_app_exact x1 _ n n zero h1).
      replace (n + n + 1)%nat with (n + (n + 1))%nat by lia. rewrite (nth_app_exact x1 _ n (n + 1) zero h1).
      replace (n + n + 2)%nat with (n + (n + 2))%nat by lia. rewrite (nth_app_exact x1 _ n (n + 2) zero h1).
      rewrite (nth_app_len x2 _ n zero h2), (nth_app_exact x2 _ n 1 zero h2), (nth_app_exact x2 _ n 2 zero h2).
      replace (n + n + 3)%nat with (n + (n + (3 + 0)))%nat by lia.
      rewrite (slice_app_gen x1 _ n _ _ h1), (slice_app_gen x2 _ n _ _ h2), (slice_app_gen [a; b; c] _ 3 0 _ eq_refl).
      unfold slice; cbn [skipn]; rewrite firstn_all2 by (rewrite h4; lia). cbn [app nth].
      repeat split; reflexivity.
    Qed.

    (** Reading back the fields of a prover coin list assembled as
        [a_0 ++ b_m ++ [r_0; s_m] ++ t1 ++ t2]. *)
    Lemma real_slices : forall (x1 x2 x4 x5 : list F) (a b : F), length x1 = n -> length x2 = n -> length x4 = S m -> length x5 = (m - 1)%nat ->
      slice (x1 ++ x2 ++ [a; b] ++ x4 ++ x5) 0 n = x1 /\ slice (x1 ++ x2 ++ [a; b] ++ x4 ++ x5) n n = x2 /\
      nth (2 * n) (x1 ++ x2 ++ [a; b] ++ x4 ++ x5) zero = a /\ nth (2 * n + 1) (x1 ++ x2 ++ [a; b] ++ x4 ++ x5) zero = b /\
      slice (x1 ++ x2 ++ [a; b] ++ x4 ++ x5) (2 * n + 2) (S m) = x4 /\ slice (x1 ++ x2 ++ [a; b] ++ x4 ++ x5) (2 * n + 3 + m) (m - 1) = x5.
    Proof.
      intros * h1 h2 h4 h5.
      rewrite (slice_app0 x1) by exact h1. rewrite (slice_app x1 _ n n h1), (slice_app0 x2) by exact h2.
      replace (2 * n)%nat with (n + n)%nat by lia. rewrite (nth_app_exact x1 _ n n zero h1).
      replace (n + n + 1)%nat with (n + (n + 1))%nat by lia. rewrite (nth_app_exact x1 _ n (n + 1) zero h1).
      rewrite (nth_app_len x2 _ n zero h2), (nth_app_exact x2 _ n 1 zero h2).
      replace (n + n + 2)%nat with (n + (n + (2 + 0)))%nat by lia.
      rewrite (slice_app_gen x1 _ n _ _ h1), (slice_app_gen x2 _ n _ _ h2), (slice_app_gen [a; b] _ 2 0 _ eq_refl).
      replace (n + n + 3 + m)%nat with (n + (n + (2 + (S m + 0))))%nat by lia.
      rewrite (slice_app_gen x1 _ n _ _ h1), (slice_app_gen x2 _ n _ _ h2), (slice_app_gen [a; b] _ 2 _ _ eq_refl),
        (slice_app_gen x4 _ (S m) 0 _ h4).
      rewrite (slice_app0 x4 x5 (S m) h4).
      unfold slice; cbn [skipn]; rewrite (firstn_all2 x5) by (rewrite h5; lia).
      cbn [app nth]. repeat split; reflexivity.
    Qed.

    (** Every list of length [zR] is the assembly of its simulator fields. *)
    Lemma recompose_sim : forall l, length l = zR ->
      l = slice l 0 n ++ slice l n n ++ [nth (2 * n) l zero; nth (2 * n + 1) l zero; nth (2 * n + 2) l zero] ++ slice l (2 * n + 3) (2 * m - 1).
    Proof.
      intros l hl. unfold slice, zR in *. cbn [skipn].
      rewrite <-(firstn_skipn n l) at 1. f_equal.
      rewrite <-(firstn_skipn n (skipn n l)) at 1. f_equal.
      rewrite skipn_skipn. replace (n + n)%nat with (2 * n)%nat by lia.
      rewrite <-(firstn_skipn 3 (skipn (2 * n) l)) at 1. f_equal.
      + assert (h3 : (3 <= length (skipn (2 * n) l))%nat) by (rewrite length_skipn; lia).
        assert (h0 : nth (2 * n) l zero = nth 0 (skipn (2 * n) l) zero) by (rewrite nth_skipn_add, Nat.add_0_r; reflexivity).
        assert (h1 : nth (2 * n + 1) l zero = nth 1 (skipn (2 * n) l) zero) by (rewrite nth_skipn_add; reflexivity).
        assert (h2 : nth (2 * n + 2) l zero = nth 2 (skipn (2 * n) l) zero) by (rewrite nth_skipn_add; reflexivity).
        rewrite h0, h1, h2. destruct (skipn (2 * n) l) as [| a [| b [| c l']]]; cbn in h3; try lia. reflexivity.
      + rewrite skipn_skipn. replace (3 + 2 * n)%nat with (2 * n + 3)%nat by lia. rewrite firstn_all2; [reflexivity | rewrite length_skipn; lia].
    Qed.

    (** Every list of length [zR] is the assembly of its prover fields. *)
    Lemma recompose_real : forall l, length l = zR ->
      l = slice l 0 n ++ slice l n n ++ [nth (2 * n) l zero; nth (2 * n + 1) l zero] ++ slice l (2 * n + 2) (S m) ++ slice l (2 * n + 3 + m) (m - 1).
    Proof.
      intros l hl. unfold slice, zR in *. cbn [skipn].
      rewrite <-(firstn_skipn n l) at 1. f_equal.
      rewrite <-(firstn_skipn n (skipn n l)) at 1. f_equal.
      rewrite skipn_skipn. replace (n + n)%nat with (2 * n)%nat by lia.
      rewrite <-(firstn_skipn 2 (skipn (2 * n) l)) at 1. f_equal.
      + assert (h2 : (2 <= length (skipn (2 * n) l))%nat) by (rewrite length_skipn; lia).
        assert (h0 : nth (2 * n) l zero = nth 0 (skipn (2 * n) l) zero) by (rewrite nth_skipn_add, Nat.add_0_r; reflexivity).
        assert (h1 : nth (2 * n + 1) l zero = nth 1 (skipn (2 * n) l) zero) by (rewrite nth_skipn_add; reflexivity).
        rewrite h0, h1. destruct (skipn (2 * n) l) as [| a [| b l']]; cbn in h2; try lia. reflexivity.
      + rewrite skipn_skipn. replace (2 + 2 * n)%nat with (2 * n + 2)%nat by lia.
        rewrite <-(firstn_skipn (S m) (skipn (2 * n + 2) l)) at 1. f_equal.
        rewrite skipn_skipn. replace (S m + (2 * n + 2))%nat with (2 * n + 3 + m)%nat by lia.
        rewrite firstn_all2; [reflexivity | rewrite length_skipn; lia].
    Qed.

    (** Entries [1 .. m] of [t = t1 ++ 0 :: t2] are the tail of [t1]. *)
    Lemma map_nth_tz1 : forall (t1 t2 : list F), length t1 = S m ->
      map (fun k => nth k (t1 ++ zero :: t2) zero) (seq 1 m) = tl t1.
    Proof.
      intros t1 t2 h1. apply (nth_ext _ _ zero zero); [rewrite length_map, length_seq, tl_len; lia |].
      intros i hi. rewrite length_map, length_seq in hi. rewrite nth_map_seq_gen by exact hi.
      rewrite app_nth1 by lia. rewrite nth_tl by (destruct t1; [discriminate | discriminate]). f_equal; lia.
    Qed.

    (** Entries [m+2 .. 2m] of [t = t1 ++ 0 :: t2] are [t2]. *)
    Lemma map_nth_tz2 : forall (t1 t2 : list F), length t1 = S m -> length t2 = (m - 1)%nat ->
      map (fun k => nth k (t1 ++ zero :: t2) zero) (seq (m + 2) (m - 1)) = t2.
    Proof.
      intros t1 t2 h1 h2. apply (nth_ext _ _ zero zero); [rewrite length_map, length_seq; lia |].
      intros i hi. rewrite length_map, length_seq in hi. rewrite nth_map_seq_gen by exact hi.
      rewrite app_nth2 by lia. rewrite h1. replace (m + 2 + i - S m)%nat with (S i) by lia. reflexivity.
    Qed.

    (** The tail of [l1 ++ l2] for non-empty [l1]. *)
    Lemma tl_app : forall (l1 l2 : list F), l1 <> [] -> tl (l1 ++ l2) = tl l1 ++ l2.
    Proof. intros l1 l2 hne; destruct l1; [contradiction | reflexivity]. Qed.

    (** Horner step: [l(x) = l_0 + x · (tl l)(x)] for non-empty [l]. *)
    Lemma feval_hd_tl : forall (l : list F) (x0 : F), l <> [] -> feval l x0 = nth 0 l zero + x0 * feval (tl l) x0.
    Proof. intros l x0 hne; destruct l; [contradiction | cbn [nth tl]; apply feval_cons]. Qed.

    (** A non-empty list of scalars is its head consed onto its tail. *)
    Lemma tl_cons_eq : forall (t1 : list F) (d : F), t1 <> [] -> t1 = nth 0 t1 d :: tl t1.
    Proof. intros t1 d hne; destruct t1; [contradiction | reflexivity]. Qed.

    (** [A] is non-empty, and the evaluations [Σ x^i A_i] and
        [Σ x^i (rev B)_i] have length [n] ([hAne], [hlvA], [hlvB]). *)
    Lemma hAne : A <> [].
    Proof. destruct A; [cbn in hAm; lia | discriminate]. Qed.

    Lemma hlvA : length (lveval A x) = n.
    Proof. apply lveval_length; [exact hAne | rewrite Forall_forall in hAn; exact hAn]. Qed.

    Lemma hlvB : length (lveval (rev B) x) = n.
    Proof.
      apply lveval_length.
      + intro e; apply (f_equal (@length (list F))) in e; rewrite length_rev, hB in e; cbn in e; lia.
      + intros v hv; rewrite Forall_forall in hBn; apply hBn, in_rev; exact hv.
    Qed.

    (** [zPhi] preserves length [zR]. *)
    Lemma zPhi_length : forall l, length l = zR -> length (zPhi l) = zR.
    Proof.
      intros l hl. pose proof zR_ge as hR. unfold zPhi; cbv zeta.
      rewrite !length_app, length_map, length_app, !length_seq; cbn [length].
      rewrite (lveval_length _ _ n) by (discriminate || (intros v [<- | hv]; [apply length_slice; lia | rewrite Forall_forall in hAn; apply hAn; exact hv])).
      rewrite (lveval_length _ _ n) by (discriminate || (intros v [<- | hv]; [apply length_slice; lia | rewrite Forall_forall in hBn; apply hBn, in_rev; exact hv])).
      unfold zR; lia.
    Qed.

    (** [zPsi] preserves length [zR]. *)
    Lemma zPsi_length : forall l, length l = zR -> length (zPsi l) = zR.
    Proof.
      intros l hl. pose proof zR_ge as hR. unfold zPsi; cbv zeta.
      assert (e1 : length (psub (slice l 0 n) (lscale x (lveval A x))) = n).
      { rewrite psub_length; [| unfold SigmaK.lscale; rewrite length_map, hlvA]; apply length_slice; lia. }
      assert (e2 : length (psub (slice l n n) (lscale x (lveval (rev B) x))) = n).
      { rewrite psub_length; [| unfold SigmaK.lscale; rewrite length_map, hlvB]; apply length_slice; lia. }
      rewrite !length_app; cbn [length]. rewrite length_firstn, length_skipn, !length_app; cbn [length].
      rewrite !length_map, !length_seq, e1, e2. unfold zR; lia.
    Qed.

    (** [zPsi] is a left inverse of [zPhi] on lists of length [zR]. *)
    Lemma zPsi_zPhi : forall l, length l = zR -> zPsi (zPhi l) = l.
    Proof.
      intros l hl. pose proof zR_ge as hR.
      set (a0 := slice l 0 n). set (bm := slice l n n). set (r0 := nth (2 * n) l zero). set (sm := nth (2 * n + 1) l zero).
      set (t1 := slice l (2 * n + 2) (S m)). set (t2 := slice l (2 * n + 3 + m) (m - 1)).
      assert (ha0 : length a0 = n) by (unfold a0; apply length_slice; lia).
      assert (hbm : length bm = n) by (unfold bm; apply length_slice; lia).
      assert (ht1 : length t1 = S m) by (unfold t1; apply length_slice; lia).
      assert (ht2 : length t2 = (m - 1)%nat) by (unfold t2; apply length_slice; lia).
      set (As := a0 :: A). set (Bs := bm :: rev B). set (tz := t1 ++ zero :: t2). set (d := fpmul (star y) As Bs).
      set (P4 := map (fun k => nth k tz zero + nth 0 γ zero * nth k d zero) (seq 1 m ++ seq (m + 2) (m - 1))).
      assert (hP4 : length P4 = (2 * m - 1)%nat) by (unfold P4; rewrite length_map, length_app, !length_seq; lia).
      assert (hlAs : length (lveval As x) = n) by (apply lveval_length; [discriminate |]; intros v [<- | hv]; [exact ha0 | rewrite Forall_forall in hAn; apply hAn; exact hv]).
      assert (hlBs : length (lveval Bs x) = n) by (apply lveval_length; [discriminate |]; intros v [<- | hv]; [exact hbm | rewrite Forall_forall in hBn; apply hBn, in_rev; exact hv]).
      unfold zPhi; cbv zeta. fold a0 bm r0 sm t1 t2 As Bs tz d P4.
      unfold zPsi; cbv zeta.
      (* Read the fields of zPhi l, then undo each affine shift. *)
      destruct (sim_slices (lveval As x) (lveval Bs x) P4 (feval (r0 :: r) x) (feval (sm :: rev s) x) (feval tz x) hlAs hlBs hP4)
        as (e1 & e2 & e3 & e4 & e5 & e6).
      rewrite e1, e2, e3, e4, e5, e6.
      assert (ea0 : psub (lveval As x) (lscale x (lveval A x)) = a0).
      { unfold As; rewrite lveval_cons. apply padd_psub. unfold SigmaK.lscale; rewrite length_map, hlvA; exact ha0. }
      assert (ebm : psub (lveval Bs x) (lscale x (lveval (rev B) x)) = bm).
      { unfold Bs; rewrite lveval_cons. apply padd_psub. unfold SigmaK.lscale; rewrite length_map, hlvB; exact hbm. }
      assert (er0 : feval (r0 :: r) x - x * feval r x = r0) by (rewrite feval_cons; field).
      assert (esm : feval (sm :: rev s) x - x * feval (rev s) x = sm) by (rewrite feval_cons; field).
      rewrite ea0, ebm, er0, esm. fold As Bs d.
      (* The recovered randomisers t_1 .. t_{2m} are the original ones,
         with the forced zero at position m+1. *)
      assert (ettl : map (fun k => nth (k - 1) P4 zero - nth 0 γ zero * nth k d zero) (seq 1 m) ++
          zero :: map (fun k => nth (k - 2) P4 zero - nth 0 γ zero * nth k d zero) (seq (m + 2) (m - 1)) = tl tz).
      { transitivity (map (fun k => nth k tz zero) (seq 1 m) ++ zero :: map (fun k => nth k tz zero) (seq (m + 2) (m - 1))).
        + f_equal; [| f_equal]; apply map_ext_in; intros k hk; apply in_seq in hk; unfold P4; rewrite map_app.
          - rewrite app_nth1 by (rewrite length_map, length_seq; lia). rewrite nth_map_seq_gen by lia.
            replace (1 + (k - 1))%nat with k by lia. field.
          - rewrite app_nth2 by (rewrite length_map, length_seq; lia). rewrite length_map, length_seq, nth_map_seq_gen by lia.
            replace (m + 2 + (k - 2 - m))%nat with k by lia. field.
        + unfold tz. rewrite map_nth_tz1, map_nth_tz2 by assumption. rewrite tl_app by (destruct t1; discriminate). reflexivity. }
      rewrite ettl.
      assert (ht1ne : t1 <> []) by (destruct t1; [discriminate ht1 | discriminate]).
      assert (et0 : feval tz x - x * feval (tl tz) x = nth 0 tz zero).
      { rewrite (feval_hd_tl tz x) by (unfold tz; destruct t1; discriminate). field. }
      rewrite et0.
      assert (etz : nth 0 tz zero :: firstn m (tl tz) = t1).
      { unfold tz. rewrite app_nth1 by (destruct t1; [contradiction | cbn; lia]). rewrite tl_app by exact ht1ne.
        rewrite firstn_app, firstn_all2, tl_len, ht1 by (rewrite tl_len; lia). replace (m - (S m - 1))%nat with 0%nat by lia.
        rewrite firstn_O, app_nil_r. symmetry; apply tl_cons_eq; exact ht1ne. }
      assert (etz2 : skipn (m + 1) (tl tz) = t2).
      { unfold tz. rewrite tl_app by exact ht1ne.
        rewrite skipn_app, skipn_all2, tl_len, ht1 by (rewrite tl_len; lia). replace (m + 1 - (S m - 1))%nat with 1%nat by lia. reflexivity. }
      rewrite etz, etz2.
      symmetry. apply recompose_real. exact hl.
    Qed.

    (** [zPsi] is a right inverse of [zPhi] on lists of length [zR]. *)
    Lemma zPhi_zPsi : forall l, length l = zR -> zPhi (zPsi l) = l.
    Proof.
      intros l hl. pose proof zR_ge as hR.
      set (at_ := slice l 0 n). set (bt := slice l n n). set (rt := nth (2 * n) l zero). set (st := nth (2 * n + 1) l zero).
      set (tt := nth (2 * n + 2) l zero). set (us := slice l (2 * n + 3) (2 * m - 1)).
      assert (hat : length at_ = n) by (unfold at_; apply length_slice; lia).
      assert (hbt : length bt = n) by (unfold bt; apply length_slice; lia).
      assert (hus : length us = (2 * m - 1)%nat) by (unfold us; apply length_slice; lia).
      set (a0 := psub at_ (lscale x (lveval A x))). set (bm := psub bt (lscale x (lveval (rev B) x))).
      set (r0 := rt - x * feval r x). set (sm := st - x * feval (rev s) x).
      set (d := fpmul (star y) (a0 :: A) (bm :: rev B)).
      set (L1 := map (fun k => nth (k - 1) us zero - nth 0 γ zero * nth k d zero) (seq 1 m)).
      set (L2 := map (fun k => nth (k - 2) us zero - nth 0 γ zero * nth k d zero) (seq (m + 2) (m - 1))).
      set (ttl := L1 ++ zero :: L2). set (t0 := tt - x * feval ttl x).
      assert (hL1 : length L1 = m) by (unfold L1; rewrite length_map, length_seq; reflexivity).
      assert (hL2 : length L2 = (m - 1)%nat) by (unfold L2; rewrite length_map, length_seq; reflexivity).
      assert (ha0 : length a0 = n) by (unfold a0; rewrite psub_length; [exact hat | unfold SigmaK.lscale; rewrite length_map, hlvA; exact hat]).
      assert (hbm : length bm = n) by (unfold bm; rewrite psub_length; [exact hbt | unfold SigmaK.lscale; rewrite length_map, hlvB; exact hbt]).
      unfold zPsi; cbv zeta. fold at_ bt rt st tt us a0 bm r0 sm d L1 L2 ttl t0.
      assert (hfirst : firstn m ttl = L1) by (unfold ttl; rewrite firstn_app, firstn_all2, hL1, Nat.sub_diag by lia; cbn; apply app_nil_r).
      assert (hskip : skipn (m + 1) ttl = L2) by (unfold ttl; rewrite skipn_app, skipn_all2, hL1 by lia; replace (m + 1 - m)%nat with 1%nat by lia; reflexivity).
      rewrite hfirst, hskip.
      unfold zPhi; cbv zeta.
      (* Read the fields of zPsi l, then show each response and each
         exponent u_k is recomputed exactly. *)
      destruct (real_slices a0 bm (t0 :: L1) L2 r0 sm ha0 hbm ltac:(cbn; lia) hL2) as (e1 & e2 & e3 & e4 & e5 & e6).
      rewrite e1, e2, e3, e4, e5, e6.
      change ((t0 :: L1) ++ zero :: L2) with (t0 :: ttl). fold d.
      assert (eat : lveval (a0 :: A) x = at_) by (rewrite lveval_cons; unfold a0; apply psub_padd; unfold SigmaK.lscale; rewrite length_map, hlvA; exact hat).
      assert (ebt : lveval (bm :: rev B) x = bt) by (rewrite lveval_cons; unfold bm; apply psub_padd; unfold SigmaK.lscale; rewrite length_map, hlvB; exact hbt).
      assert (ert : feval (r0 :: r) x = rt) by (rewrite feval_cons; unfold r0; field).
      assert (est : feval (sm :: rev s) x = st) by (rewrite feval_cons; unfold sm; field).
      assert (ett : feval (t0 :: ttl) x = tt) by (rewrite feval_cons; unfold t0; field).
      rewrite eat, ebt, ert, est, ett.
      assert (eus : map (fun k => nth k (t0 :: ttl) zero + nth 0 γ zero * nth k d zero) (seq 1 m ++ seq (m + 2) (m - 1)) = us).
      { apply (nth_ext _ _ zero zero); [rewrite length_map, length_app, !length_seq; lia |].
        intros i hi. rewrite length_map, length_app, !length_seq in hi. rewrite map_app.
        destruct (Nat.lt_ge_cases i m) as [him | him].
        + rewrite app_nth1 by (rewrite length_map, length_seq; lia). rewrite nth_map_seq_gen by lia.
          assert (ei : (1 + i)%nat = S i) by lia. rewrite ei. cbn [nth]. unfold ttl. rewrite app_nth1 by lia.
          unfold L1. rewrite nth_map_seq_gen by lia. rewrite ei. replace (S i - 1)%nat with i by lia. field.
        + rewrite app_nth2 by (rewrite length_map, length_seq; lia). rewrite length_map, length_seq, nth_map_seq_gen by lia.
          assert (ei : (m + 2 + (i - m))%nat = S (i + 1)) by lia. rewrite ei. cbn [nth]. unfold ttl. rewrite app_nth2 by lia. rewrite hL1.
          replace (i + 1 - m)%nat with (S (i - m)) by lia. cbn [nth]. unfold L2. rewrite nth_map_seq_gen by lia. rewrite ei.
          replace (S (i + 1) - 2)%nat with i by lia. field. }
      rewrite eus. symmetry. apply recompose_sim. exact hl.
    Qed.

    (** The witness relation of the zero argument:
        [Σ_i A_i ⋆_y B_i = 0]. *)
    Hypothesis hrel : fold_right add zero (map (fun p => star y (fst p) (snd p)) (combine A B)) = zero.

    (** On the honest statement [cA], [cB], the transcript equals the
        simulation of the transformed coins; the verifier's acceptance is
        discharged by [zero_completeness]. *)
    Lemma zreal_eq_zsim_honest : forall l, length l = zR -> zreal l = zsim cA cB (zPhi l).
    Proof.
      intros l hl. pose proof zR_ge as hR. apply zreal_eq_zsim; [exact hl |].
      unfold zreal. apply (zero_completeness (Hvec := Hvec) (Gdec := Gdec)); try assumption;
        rewrite ?hAm; try assumption; try (apply length_slice; lia);
        (constructor; [apply length_slice; lia | assumption]).
    Qed.

    (** Perfect special HVZK of the zero argument. For every pair of
        challenges [x], [y], if [lf] enumerates [F] without duplicates, the
        honest transcript distribution on the witness [A], [B], [r], [s] is
        a permutation of (hence equal to) the simulator's distribution on
        the statement [cA], [cB]. Hypotheses: those of the section
        ([n ≥ 1], [m ≥ 1], the length conditions, [gs_j = h ^ γ_j]) and the
        relation [hrel]. Proof: [zk_of_bijection] with [zPhi] and
        [zPsi]. *)
    Theorem zero_shvzk : forall (lf : list F) (Hlfn : lf <> []),
      NoDup lf -> (forall v : F, In v lf) ->
      Permutation (zero_real_distribution lf Hlfn) (zero_sim_distribution lf Hlfn cA cB).
    Proof.
      intros lf Hlfn hnd hall. unfold zero_real_distribution, zero_sim_distribution.
      apply (zk_of_bijection lf Hlfn zR zreal (zsim cA cB) zPhi zPsi hnd hall zPhi_length zPsi_length zPsi_zPhi zPhi_zPsi).
      intros l hl. apply zreal_eq_zsim_honest. exact hl.
    Qed.

  End ZeroZK.

  (** ** The single-value product argument (Alg. 9.9 / 9.10)

      Statement: a commitment [ca = com h gs a r] and a scalar [b]; witness
      relation [b = Π_i a_i]. The prover commits to a random vector [d],
      to [δ] (with [δ_0 = d_0] and [δ_{n-1} = 0]) and to the vector [Δ] of
      cross terms, and after the challenge [x] answers [ã = x a + d],
      [b̃_k = x · Π_{j ≤ k} a_j + δ_k], [r̃] and [s̃].

      The simulator [ssim] draws [ã], [r̃], [s̃], the middle entries of
      [b̃] and a random [c_Δ = h ^ u], fixes [b̃_0 = ã_0] and
      [b̃_{n-1} = x · b] as the verifier requires, and solves for [c_d] and
      [c_δ]. Theorem: [svp_shvzk]. *)
  Local Notation svp_verify := (svp_verify (zero := zero) (mul := mul) (sub := sub) (Fdec := Fdec)
    (gid := gid) (gop := gop) (gpow := gpow) (Gdec := Gdec)).
  Local Notation svp_prove := (svp_prove (zero := zero) (one := one) (add := add) (mul := mul)
    (sub := sub) (opp := opp) (gid := gid) (gop := gop) (gpow := gpow)).
  Local Notation svp_argument := (@svp_argument F G).
  Local Notation mk_svp := (@mk_svp F G).
  Local Notation prefix_prod := (prefix_prod (one := one) (mul := mul)).

  (** Section for the single-value product argument. *)
  Section SvpZK.

    (** The commitment key [h], [gs] with discrete logarithms [γ]. The
        witness [a] of length [n] with commitment randomness [r], the
        challenge [x]; [ca] is the commitment and [b] the claimed product. *)
    Variables (h : G) (gs : list G) (γ : list F).
    Variables (a : list F) (r x : F) (n : nat).
    Local Notation ca := (com h gs a r).
    Local Notation b := (fold_right mul one a).

    (** Side conditions: [length a = n ≥ 2], and [γ] are the discrete
        logarithms of the commitment key. *)
    Hypothesis ha : length a = n.
    Hypothesis hn : (2 <= n)%nat.
    Hypothesis hγl : length γ = length gs.
    Hypothesis hγ : forall j, (j < length gs)%nat -> nth j gs gid = h ^ (nth j γ zero).

    (** Number of prover coins: [d ∈ F^n], [r_d], the [n - 2] middle
        entries of [δ], and the commitment randomisers [s_0], [s_x];
        [2n + 1] in total. *)
    Definition sR : nat := (2 * n + 1)%nat.

    (** The honest transcript: [svp_prove] with its coins read from [l]. *)
    Definition sreal (l : list F) : svp_argument :=
      svp_prove h gs a r (slice l 0 n) (nth n l zero) (slice l (n + 1) (n - 2)) (nth (2 * n - 1) l zero) (nth (2 * n) l zero) x.

    (** The simulator on statement [ca'], [b']. From [l] it reads [ã], [r̃],
        [s̃], the middle entries [bmid] of [b̃] and an exponent [u]; it sets
        [b̃ = ã_0 :: bmid ++ [x · b']], [c_Δ = h ^ u], and solves the two
        verification equations for [c_d = com(ã; r̃) · ca'^(-x)] and
        [c_δ = com(e; s̃) · c_Δ^(-x)], where
        [e_i = x b̃_{i+1} - b̃_i ã_{i+1}]. *)
    Definition ssim (ca' : G) (b' : F) (l : list F) : svp_argument :=
      let ta := slice l 0 n in let rt := nth n l zero in let st := nth (n + 1) l zero in
      let bmid := slice l (n + 2) (n - 2) in let u := nth (2 * n) l zero in
      let tb := nth 0 ta zero :: bmid ++ [x * b'] in
      let e := map (fun i => x * nth (S i) tb zero - nth i tb zero * nth (S i) ta zero) (seq 0 (n - 1)) in
      mk_svp (gop (com h gs ta rt) (ginv (ca' ^ x))) (gop (com h gs e st) (ginv ((h ^ u) ^ x))) (h ^ u) ta tb rt st.

    (** The real and simulated distributions over uniform coins. *)
    Definition svp_real_distribution (lf : list F) (Hlfn : lf <> []) : dist svp_argument :=
      Bind (rand lf Hlfn sR) (fun l => Ret (sreal l)).
    Definition svp_sim_distribution (lf : list F) (Hlfn : lf <> []) (ca' : G) (b' : F) : dist svp_argument :=
      Bind (rand lf Hlfn sR) (fun l => Ret (ssim ca' b' l)).

    (** The vector [Δ] committed by the honest prover, as a function of its
        coins [d] and [δ_1 .. δ_{n-2}]:
        [Δ_k = δ_{k+1} - a_{k+1} δ_k - (Π_{j ≤ k} a_j) d_{k+1}]. *)
    Definition DeltaOf (d dmid : list F) : list F :=
      let bf := prefix_prod a in
      let af := fun i => nth i a zero in
      let df := fun i => nth i d zero in
      let delta := fun i => nth i (df 0 :: dmid ++ [zero]) zero in
      map (fun k => delta (S k) - af (S k) * delta k - bf k * df (S k)) (seq 0 (n - 1)).

    (** The bijection from prover coins to simulator coins:
        [ã = x a + d], [r̃ = x r + r_d], [s̃ = x s_x + s_0], the middle of
        [b̃], and [u = s_x + ⟨γ, Δ⟩], the discrete logarithm of [c_Δ]. *)
    Definition sPhi (l : list F) : list F :=
      let d := slice l 0 n in let rd := nth n l zero in let dmid := slice l (n + 1) (n - 2) in
      let s0 := nth (2 * n - 1) l zero in let sx := nth (2 * n) l zero in
      map (fun k => x * nth k a zero + nth k d zero) (seq 0 n) ++ [x * r + rd; x * sx + s0]
        ++ map (fun k => x * prefix_prod a (S k) + nth k dmid zero) (seq 0 (n - 2)) ++ [sx + dot γ (DeltaOf d dmid)].

    (** The inverse of [sPhi]: recover [d], [δ], then [s_x = u - ⟨γ, Δ⟩]
        (with [Δ] recomputed from the recovered [d], [δ]), [r_d] and
        [s_0]. *)
    Definition sPsi (l : list F) : list F :=
      let ta := slice l 0 n in let rt := nth n l zero in let st := nth (n + 1) l zero in
      let bmid := slice l (n + 2) (n - 2) in let u := nth (2 * n) l zero in
      let d := map (fun k => nth k ta zero - x * nth k a zero) (seq 0 n) in
      let dmid := map (fun k => nth k bmid zero - x * prefix_prod a (S k)) (seq 0 (n - 2)) in
      let sx := u - dot γ (DeltaOf d dmid) in
      d ++ [rt - x * r] ++ dmid ++ [st - x * sx; sx].

    (** Reading back the fields of a simulator coin list. *)
    Lemma ssim_slices : forall (ta bmid : list F) (rt st u : F), length ta = n -> length bmid = (n - 2)%nat ->
      let l := ta ++ [rt; st] ++ bmid ++ [u] in
      slice l 0 n = ta /\ nth n l zero = rt /\ nth (n + 1) l zero = st /\ slice l (n + 2) (n - 2) = bmid /\ nth (2 * n) l zero = u.
    Proof.
      intros ta bmid rt st u hta hb. cbv zeta. repeat split.
      + apply slice_app0; exact hta.
      + rewrite (nth_app_len ta _ n zero hta); reflexivity.
      + rewrite (nth_app_exact ta _ n 1 zero hta); reflexivity.
      + rewrite (slice_app_gen ta _ n 2 (n - 2) hta), (slice_app [rt; st] _ 2 (n - 2) eq_refl). apply slice_app0; exact hb.
      + replace (2 * n)%nat with (n + (2 + (n - 2)))%nat by lia.
        rewrite (nth_app_exact ta _ n _ zero hta), (nth_app_exact [rt; st] _ 2 _ zero eq_refl), (nth_app_len bmid _ _ zero hb). reflexivity.
    Qed.

    (** Reading back the fields of a prover coin list. *)
    Lemma sreal_slices : forall (d dmid : list F) (rd s0 sx : F), length d = n -> length dmid = (n - 2)%nat ->
      let l := d ++ [rd] ++ dmid ++ [s0; sx] in
      slice l 0 n = d /\ nth n l zero = rd /\ slice l (n + 1) (n - 2) = dmid /\ nth (2 * n - 1) l zero = s0 /\ nth (2 * n) l zero = sx.
    Proof.
      intros d dmid rd s0 sx hd hm. cbv zeta. repeat split.
      + apply slice_app0; exact hd.
      + rewrite (nth_app_len d _ n zero hd); reflexivity.
      + rewrite (slice_app_gen d _ n 1 (n - 2) hd), (slice_app [rd] _ 1 (n - 2) eq_refl). apply slice_app0; exact hm.
      + replace (2 * n - 1)%nat with (n + (1 + (n - 2)))%nat by lia.
        rewrite (nth_app_exact d _ n _ zero hd), (nth_app_exact [rd] _ 1 _ zero eq_refl), (nth_app_len dmid _ _ zero hm). reflexivity.
      + replace (2 * n)%nat with (n + (1 + ((n - 2) + 1)))%nat by lia.
        rewrite (nth_app_exact d _ n _ zero hd), (nth_app_exact [rd] _ 1 _ zero eq_refl), (nth_app_exact dmid _ _ 1 zero hm). reflexivity.
    Qed.

    (** Every list of length [sR] is the assembly of its prover fields. *)
    Lemma srecompose_real : forall l, length l = sR ->
      l = slice l 0 n ++ [nth n l zero] ++ slice l (n + 1) (n - 2) ++ [nth (2 * n - 1) l zero; nth (2 * n) l zero].
    Proof.
      intros l hl. unfold sR in hl.
      transitivity (slice l 0 (n + (1 + ((n - 2) + (1 + 1))))); [symmetry; apply slice_all; lia |].
      rewrite !slice_split, !slice_one by lia.
      replace (0 + n)%nat with n by lia. replace (n + 1 + (n - 2))%nat with (2 * n - 1)%nat by lia.
      replace (2 * n - 1 + 1)%nat with (2 * n)%nat by lia. reflexivity.
    Qed.

    (** Every list of length [sR] is the assembly of its simulator fields. *)
    Lemma srecompose_sim : forall l, length l = sR ->
      l = slice l 0 n ++ [nth n l zero; nth (n + 1) l zero] ++ slice l (n + 2) (n - 2) ++ [nth (2 * n) l zero].
    Proof.
      intros l hl. unfold sR in hl.
      transitivity (slice l 0 (n + (1 + (1 + ((n - 2) + 1))))); [symmetry; apply slice_all; lia |].
      rewrite !slice_split, !slice_one by lia.
      replace (0 + n)%nat with n by lia. replace (n + 1 + 1)%nat with (n + 2)%nat by lia.
      replace (n + 2 + (n - 2))%nat with (2 * n)%nat by lia. reflexivity.
    Qed.

    (** [sPhi] and [sPsi] preserve length [sR]. *)
    Lemma sPhi_length : forall l, length l = sR -> length (sPhi l) = sR.
    Proof. intros l hl. unfold sPhi, sR in *; cbv zeta. rewrite !length_app, !length_map, !length_seq. cbn [length]. lia. Qed.

    Lemma sPsi_length : forall l, length l = sR -> length (sPsi l) = sR.
    Proof. intros l hl. unfold sPsi, sR in *; cbv zeta. rewrite !length_app, !length_map, !length_seq. cbn [length]. lia. Qed.

    (** Core equation, stated directly on the prover's coin arguments: if
        the verifier accepts [svp_prove] on statement [ca'], [b'], then the
        transcript equals [ssim ca' b'] on the transformed coins. *)
    Lemma svp_prove_eq_ssim : forall (d dmid : list F) (rd s0 sx : F) (ca' : G) (b' : F),
      length d = n -> length dmid = (n - 2)%nat ->
      svp_verify h gs ca' b' x (svp_prove h gs a r d rd dmid s0 sx x) = true ->
      svp_prove h gs a r d rd dmid s0 sx x =
      ssim ca' b' (map (fun k => x * nth k a zero + nth k d zero) (seq 0 n) ++ [x * r + rd; x * sx + s0]
        ++ map (fun k => x * prefix_prod a (S k) + nth k dmid zero) (seq 0 (n - 2)) ++ [sx + dot γ (DeltaOf d dmid)]).
    Proof.
      intros d dmid rd s0 sx ca' b' hd hdmid hv.
      set (ta := map (fun k => x * nth k a zero + nth k d zero) (seq 0 n)).
      set (bmid := map (fun k => x * prefix_prod a (S k) + nth k dmid zero) (seq 0 (n - 2))).
      set (u := sx + dot γ (DeltaOf d dmid)).
      assert (hta : length ta = n) by (unfold ta; rewrite length_map, length_seq; reflexivity).
      assert (hbmid : length bmid = (n - 2)%nat) by (unfold bmid; rewrite length_map, length_seq; reflexivity).
      destruct (ssim_slices ta bmid (x * r + rd) (x * sx + s0) u hta hbmid) as (S1 & S2 & S3 & S4 & S5).
      unfold ssim; cbv zeta. rewrite S1, S2, S3, S4, S5.
      unfold BayerGroth.svp_prove in hv |- *; cbv beta zeta in hv |- *. rewrite ha in hv |- *. fold ta in hv |- *.
      (* The verifier's checks give the shape of b̃ (first entry ã_0, last
         entry x b') and the two equations defining c_d and c_δ. *)
      apply svp_verify_true in hv. destruct hv as (_ & htb & E1 & E2 & E3 & E4).
      rewrite hta in htb, E2, E4.
      set (tb := map (fun k => x * prefix_prod a k + nth k (nth 0 d zero :: dmid ++ [zero]) zero) (seq 0 n)) in *.
      assert (hb : tb = nth 0 ta zero :: bmid ++ [x * b']).
      { apply (nth_ext _ _ zero zero).
        + rewrite htb; cbn [length]; rewrite length_app, hbmid; cbn [length]; lia.
        + intros i hi. rewrite htb in hi. destruct i as [| i].
          - cbn [nth]. exact E3.
          - cbn [nth]. destruct (Nat.eq_dec (S i) (n - 1)) as [e | e].
            * replace i with (n - 2)%nat by lia. rewrite (nth_app_len bmid _ _ zero hbmid). cbn [nth].
              replace (S (n - 2)) with (n - 1)%nat by lia. exact E4.
            * rewrite app_nth1 by (rewrite hbmid; lia).
              unfold tb, bmid; rewrite !nth_map_seq_gen by lia. cbn [Nat.add nth].
              rewrite app_nth1 by (rewrite hdmid; lia). reflexivity. }
      (* c_Δ = com(Δ; s_x) = h ^ (s_x + ⟨γ, Δ⟩); the other two
         commitments are the solutions of the verification equations. *)
      rewrite <-hb. unfold u. rewrite <-(com_dlog h gs γ (DeltaOf d dmid) sx hγl hγ). unfold DeltaOf; cbv beta zeta.
      f_equal; solve [exact (gop_solve_r _ _ _ E1) | exact (gop_solve_r _ _ _ E2) | reflexivity].
    Qed.

    (** [sreal l = ssim ca' b' (sPhi l)] whenever the verifier accepts
        [sreal l] on statement [ca'], [b']. *)
    Lemma sreal_eq_ssim : forall l (ca' : G) (b' : F), length l = sR ->
      svp_verify h gs ca' b' x (sreal l) = true -> sreal l = ssim ca' b' (sPhi l).
    Proof.
      intros l ca' b' hl hv. unfold sR in hl. unfold sreal in *. unfold sPhi; cbv zeta.
      apply svp_prove_eq_ssim; [apply length_slice; lia | apply length_slice; lia | exact hv].
    Qed.

    (** [sPsi] is a left inverse of [sPhi] on lists of length [sR]. *)
    Lemma sPsi_sPhi : forall l, length l = sR -> sPsi (sPhi l) = l.
    Proof.
      intros l hl. pose proof hl as hl'. unfold sR in hl'.
      unfold sPhi; cbv zeta.
      set (d := slice l 0 n). set (rd := nth n l zero). set (dmid := slice l (n + 1) (n - 2)).
      set (s0 := nth (2 * n - 1) l zero). set (sx := nth (2 * n) l zero).
      assert (hd : length d = n) by (apply length_slice; lia).
      assert (hdm : length dmid = (n - 2)%nat) by (apply length_slice; lia).
      set (ta := map (fun k => x * nth k a zero + nth k d zero) (seq 0 n)).
      set (bmid := map (fun k => x * prefix_prod a (S k) + nth k dmid zero) (seq 0 (n - 2))).
      assert (hta : length ta = n) by (unfold ta; rewrite length_map, length_seq; reflexivity).
      assert (hbmid : length bmid = (n - 2)%nat) by (unfold bmid; rewrite length_map, length_seq; reflexivity).
      destruct (ssim_slices ta bmid (x * r + rd) (x * sx + s0) (sx + dot γ (DeltaOf d dmid)) hta hbmid) as (S1 & S2 & S3 & S4 & S5).
      unfold sPsi; cbv zeta. rewrite S1, S2, S3, S4, S5.
      assert (hd' : map (fun k => nth k ta zero - x * nth k a zero) (seq 0 n) = d).
      { transitivity (map (fun k => nth k d zero) (seq 0 n)); [| apply map_nth_seq_id; exact hd].
        apply map_ext_in. intros k hk. apply in_seq in hk. unfold ta; rewrite nth_map_seq_gen by lia. cbn [Nat.add]. field. }
      assert (hdm' : map (fun k => nth k bmid zero - x * prefix_prod a (S k)) (seq 0 (n - 2)) = dmid).
      { transitivity (map (fun k => nth k dmid zero) (seq 0 (n - 2))); [| apply map_nth_seq_id; exact hdm].
        apply map_ext_in. intros k hk. apply in_seq in hk. unfold bmid; rewrite nth_map_seq_gen by lia. cbn [Nat.add]. field. }
      rewrite hd', hdm'.
      replace (sx + dot γ (DeltaOf d dmid) - dot γ (DeltaOf d dmid)) with sx by field.
      replace (x * r + rd - x * r) with rd by field.
      replace (x * sx + s0 - x * sx) with s0 by field.
      symmetry. apply srecompose_real. exact hl.
    Qed.

    (** [sPsi] is a right inverse of [sPhi] on lists of length [sR]. *)
    Lemma sPhi_sPsi : forall l, length l = sR -> sPhi (sPsi l) = l.
    Proof.
      intros l hl. pose proof hl as hl'. unfold sR in hl'.
      unfold sPsi; cbv zeta.
      set (ta := slice l 0 n). set (rt := nth n l zero). set (st := nth (n + 1) l zero).
      set (bmid := slice l (n + 2) (n - 2)). set (u := nth (2 * n) l zero).
      assert (hta : length ta = n) by (apply length_slice; lia).
      assert (hbmid : length bmid = (n - 2)%nat) by (apply length_slice; lia).
      set (d := map (fun k => nth k ta zero - x * nth k a zero) (seq 0 n)).
      set (dmid := map (fun k => nth k bmid zero - x * prefix_prod a (S k)) (seq 0 (n - 2))).
      set (sx := u - dot γ (DeltaOf d dmid)).
      assert (hd : length d = n) by (unfold d; rewrite length_map, length_seq; reflexivity).
      assert (hdm : length dmid = (n - 2)%nat) by (unfold dmid; rewrite length_map, length_seq; reflexivity).
      destruct (sreal_slices d dmid (rt - x * r) (st - x * sx) sx hd hdm) as (S1 & S2 & S3 & S4 & S5).
      unfold sPhi; cbv zeta. rewrite S1, S2, S3, S4, S5.
      assert (hta' : map (fun k => x * nth k a zero + nth k d zero) (seq 0 n) = ta).
      { transitivity (map (fun k => nth k ta zero) (seq 0 n)); [| apply map_nth_seq_id; exact hta].
        apply map_ext_in. intros k hk. apply in_seq in hk. unfold d; rewrite nth_map_seq_gen by lia. cbn [Nat.add]. field. }
      assert (hbmid' : map (fun k => x * prefix_prod a (S k) + nth k dmid zero) (seq 0 (n - 2)) = bmid).
      { transitivity (map (fun k => nth k bmid zero) (seq 0 (n - 2))); [| apply map_nth_seq_id; exact hbmid].
        apply map_ext_in. intros k hk. apply in_seq in hk. unfold dmid; rewrite nth_map_seq_gen by lia. cbn [Nat.add]. field. }
      rewrite hta', hbmid'.
      replace (x * r + (rt - x * r)) with rt by field.
      replace (x * sx + (st - x * sx)) with st by field.
      replace (sx + dot γ (DeltaOf d dmid)) with u by (unfold sx; field).
      symmetry. apply srecompose_sim. exact hl.
    Qed.

    (** The commitment key has the length of the committed vector. *)
    Hypothesis hgs : length gs = n.

    (** On the honest statement [ca], [b = Π a_i], the acceptance needed by
        [sreal_eq_ssim] is given by [svp_completeness]. *)
    Lemma sreal_eq_ssim_honest : forall l, length l = sR -> sreal l = ssim ca b (sPhi l).
    Proof.
      intros l hl. apply sreal_eq_ssim; [exact hl |]. unfold sR in hl. unfold sreal.
      apply svp_completeness; rewrite ?ha; [exact hn | apply length_slice; lia | apply length_slice; lia | symmetry; exact hgs].
    Qed.

    (** Perfect special HVZK of the single-value product argument: for every
        challenge [x], the honest transcript distribution equals the
        simulator's distribution on [ca], [b]. Hypotheses: [lf] enumerates
        [F], [length a = n ≥ 2], [length gs = n] and [gs_j = h ^ γ_j]. The
        relation [b = Π a_i] holds by definition of [b]. *)
    Theorem svp_shvzk : forall (lf : list F) (Hlfn : lf <> []),
      NoDup lf -> (forall v : F, In v lf) ->
      Permutation (svp_real_distribution lf Hlfn) (svp_sim_distribution lf Hlfn ca b).
    Proof.
      intros lf Hlfn hnd hall. unfold svp_real_distribution, svp_sim_distribution.
      apply (zk_of_bijection lf Hlfn sR sreal (ssim ca b) sPhi sPsi hnd hall sPhi_length sPsi_length sPsi_sPhi sPhi_sPsi).
      intros l hl. apply sreal_eq_ssim_honest. exact hl.
    Qed.

  End SvpZK.

  (** ** The Hadamard product argument (Alg. 9.20 / 9.21)

      Statement: commitments [cA] to the [m] columns of [A] and a
      commitment [cb] to their Hadamard product [b = A_0 ∘ … ∘ A_{m-1}].
      The prover commits to the prefix products [B_i = A_0 ∘ … ∘ A_i] (the
      first commitment equals [c_{A0}], the last equals [cb]) and then runs
      the zero argument on a derived statement, with challenges [x], [y]
      for the Hadamard part and [xz] for the zero argument.

      The simulator [hsim] picks the [m - 2] middle commitments [c_{Bi}] at
      random as [h ^ u_i], computes the derived zero-argument statement
      [hadamard_zero_stmt] from them, and runs [zsim] on it. Theorem:
      [hadamard_shvzk], for [m ≥ 2] and [x], [y] non-zero. *)
  Local Notation hadamard_zero_stmt := (hadamard_zero_stmt (zero := zero) (one := one) (mul := mul)
    (opp := opp) (gid := gid) (gop := gop) (gpow := gpow)).
  Local Notation hadamard_verify := (hadamard_verify (zero := zero) (one := one) (add := add)
    (mul := mul) (opp := opp) (Fdec := Fdec) (gid := gid) (gop := gop) (gpow := gpow) (Gdec := Gdec)).
  Local Notation hadamard_prove := (hadamard_prove (zero := zero) (one := one) (add := add)
    (mul := mul) (opp := opp) (gid := gid) (gop := gop) (gpow := gpow)).
  Local Notation hadamard_argument := (@hadamard_argument F G).
  Local Notation mk_had := (@mk_had F G).
  Local Notation hprefix := (hprefix (mul := mul)).

  (** Section for the Hadamard argument. *)
  Section HadamardZK.

    (** The commitment key [h], [gs] with discrete logarithms [γ]. The
        witness: [m] columns [A] with randomness [r], the randomness
        [s] of the commitment [cb] to the Hadamard product; the challenges
        [x], [y] and the zero-argument challenge [xz]. *)
    Variables (h : G) (gs : list G) (γ : list F).
    Variables (A : list (list F)) (r : list F) (s : F) (x y xz : F) (m : nat).
    (** [n] is the column length, [cA] and [cb] form the honest statement. *)
    Local Notation n := (length gs).
    Local Notation cA := (com_list h gs A r).
    Local Notation cb := (com h gs (hprefix A (length A - 1)) s).

    (** Side conditions: [m ≥ 2], [n ≥ 1], the lengths of [A] and [r],
        columns of length [n], and [gs_j = h ^ γ_j]. *)
    Hypothesis hAm : length A = m.
    Hypothesis hm : (2 <= m)%nat.
    Hypothesis hn : (1 <= n)%nat.
    Hypothesis hr : length r = m.
    Hypothesis hAn : Forall (fun v => length v = n) A.
    Hypothesis hγl : length γ = n.
    Hypothesis hγ : forall j, (j < n)%nat -> nth j gs gid = h ^ (nth j γ zero).

    (** The prefix Hadamard products [B_i = A_0 ∘ … ∘ A_i], [i < m]. *)
    Definition hBs : list (list F) := map (hprefix A) (seq 0 (length A)).
    (** The randomness of the commitments to [hBs]: [r_0] (so that
        [c_{B0} = c_{A0}]), the [m - 2] fresh coins [smid], and [s] (so
        that [c_{B,m-1} = cb]). *)
    Definition hss (smid : list F) : list F := nth 0 r zero :: smid ++ [s].
    (** The derived zero-argument witness, as [hadamard_prove] builds it:
        [hA'] are the columns [A_1 .. A_{m-1}] followed by [-1];
        [hB'] are the scaled prefix products [x^(i+1) B_i] followed by
        [x · Σ x^i B_{i+1}]; [hr'] and [hs'] are the matching
        randomness. *)
    Definition hA' : list (list F) := tl A ++ [repeat (opp one) n].
    Definition hB' : list (list F) :=
      map (fun i => lscale (fpow x (S i)) (hprefix A i)) (seq 0 (length A - 1)) ++ [lscale x (lveval (tl hBs) x)].
    Definition hr' : list F := tl r ++ [zero].
    Definition hs' (smid : list F) : list F :=
      map (fun i => fpow x (S i) * nth i (hss smid) zero) (seq 0 (length A - 1)) ++ [x * feval (tl (hss smid)) x].

    (** Number of coins: the [m - 2] middle randomisers followed by the
        [zR] coins of the inner zero argument. *)
    Definition hR : nat := (m - 2 + zR gs m)%nat.

    (** The honest transcript: [hadamard_prove] with [smid] the first [m - 2] coins and
        the zero-argument coins read from the rest of [l]. *)
    Definition hreal (l : list F) : hadamard_argument :=
      let l' := skipn (m - 2) l in
      hadamard_prove h gs n A r s (slice l 0 (m - 2)) x y (slice l' 0 n) (slice l' n n) (nth (2 * n) l' zero)
        (nth (2 * n + 1) l' zero) (slice l' (2 * n + 2) (S m)) (slice l' (2 * n + 3 + m) (m - 1)) xz.

    (** The simulator on statement [cA'], [cb']: [c_B] is
        [cA'_0 :: map (h ^ ·) u ++ cb' :: nil] with [u] the first [m - 2] coins, and the
        zero argument is simulated by [zsim] on the statement
        [hadamard_zero_stmt h gs n cA' c_B x] with the rest of [l]. *)
    Definition hsim (cA' : list G) (cb' : G) (l : list F) : hadamard_argument :=
      let cB := nth 0 cA' gid :: map (fun u => h ^ u) (slice l 0 (m - 2)) ++ [cb'] in
      let st := hadamard_zero_stmt h gs n cA' cB x in
      mk_had cB (zsim h gs y xz m (fst st) (snd st) (skipn (m - 2) l)).

    (** The real and simulated distributions over uniform coins. *)
    Definition hadamard_real_distribution (lf : list F) (Hlfn : lf <> []) : dist hadamard_argument :=
      Bind (rand lf Hlfn hR) (fun l => Ret (hreal l)).
    Definition hadamard_sim_distribution (lf : list F) (Hlfn : lf <> []) (cA' : list G) (cb' : G) : dist hadamard_argument :=
      Bind (rand lf Hlfn hR) (fun l => Ret (hsim cA' cb' l)).

    (** The bijection on the middle randomisers, [u_i = s_i + ⟨γ, B_{i+1}⟩]
        (the discrete logarithm of [c_{B,i+1}]), and its inverse. *)
    Definition hsmid_to_u (smid : list F) : list F := map (fun i => nth i smid zero + dot γ (hprefix A (S i))) (seq 0 (m - 2)).
    Definition hu_to_smid (us : list F) : list F := map (fun i => nth i us zero - dot γ (hprefix A (S i))) (seq 0 (m - 2)).

    (** The bijection on all coins: [hsmid_to_u] on the first [m - 2]
        coins and [zPhi] (for the derived witness) on the rest. *)
    Definition hPhi (l : list F) : list F :=
      let smid := slice l 0 (m - 2) in
      hsmid_to_u smid ++ zPhi gs γ hA' hB' hr' (hs' smid) y xz m (skipn (m - 2) l).
    (** The inverse of [hPhi]. The inner [zPsi] is taken for the derived
        witness built from the recovered [smid]. *)
    Definition hPsi (l : list F) : list F :=
      let smid := hu_to_smid (slice l 0 (m - 2)) in
      smid ++ zPsi gs γ hA' hB' hr' (hs' smid) y xz m (skipn (m - 2) l).

    (** Lengths of the derived lists: [hBs], [hss smid], [hA'], [hB'],
        [hr'] and [hs' smid] all have length [m]. *)
    Lemma hBs_length : length hBs = m.
    Proof. unfold hBs; rewrite length_map, length_seq; exact hAm. Qed.
    Lemma hss_length : forall smid, length smid = (m - 2)%nat -> length (hss smid) = m.
    Proof. intros smid hsm; unfold hss; cbn [length]; rewrite length_app, hsm; cbn [length]; lia. Qed.
    Lemma hA'_length : length hA' = m.
    Proof. unfold hA'; rewrite length_app, tl_len, hAm; cbn [length]; lia. Qed.
    Lemma hB'_length : length hB' = m.
    Proof. unfold hB'; rewrite length_app, length_map, length_seq, hAm; cbn [length]; lia. Qed.
    Lemma hr'_length : length hr' = m.
    Proof. unfold hr'; rewrite length_app, tl_len, hr; cbn [length]; lia. Qed.
    Lemma hs'_length : forall smid, length (hs' smid) = m.
    Proof. intros smid; unfold hs'; rewrite length_app, length_map, length_seq, hAm; cbn [length]; lia. Qed.
    (** All columns of [hA'], [hBs] and [hB'] have length [n], and
        [tl hBs] is non-empty ([hA'_rows], [hBs_rows], [tl_hBs_ne],
        [hB'_rows]). *)
    Lemma hA'_rows : Forall (fun v => length v = n) hA'.
    Proof.
      unfold hA'; apply Forall_app; split.
      + destruct A as [| a0 A0]; [constructor | inversion hAn; assumption].
      + constructor; [apply repeat_length | constructor].
    Qed.
    Lemma hBs_rows : forall v, In v hBs -> length v = n.
    Proof.
      intros v hv; unfold hBs in hv; apply in_map_iff in hv; destruct hv as (i & <- & hi); apply in_seq in hi.
      apply (hprefix_length n A i hAn); lia.
    Qed.
    Lemma tl_hBs_ne : tl hBs <> [].
    Proof. intro e; apply (f_equal (@length (list F))) in e; rewrite tl_len, hBs_length in e; cbn in e; lia. Qed.
    Lemma hB'_rows : Forall (fun v => length v = n) hB'.
    Proof.
      unfold hB'; apply Forall_app; split.
      + rewrite Forall_forall; intros v hv; apply in_map_iff in hv; destruct hv as (i & <- & hi); apply in_seq in hi.
        unfold SigmaK.lscale; rewrite length_map. apply (hprefix_length n A i hAn); lia.
      + constructor; [| constructor]. unfold SigmaK.lscale; rewrite length_map.
        apply lveval_length; [exact tl_hBs_ne |]. intros v hv; apply hBs_rows, in_tl; exact hv.
    Qed.
    (** [hsmid_to_u] and [hu_to_smid] produce lists of length [m - 2]. *)
    Lemma hsmid_to_u_length : forall smid, length (hsmid_to_u smid) = (m - 2)%nat.
    Proof. intros; unfold hsmid_to_u; rewrite length_map, length_seq; reflexivity. Qed.
    Lemma hu_to_smid_length : forall us, length (hu_to_smid us) = (m - 2)%nat.
    Proof. intros; unfold hu_to_smid; rewrite length_map, length_seq; reflexivity. Qed.
    (** [hsmid_to_u] and [hu_to_smid] are mutually inverse on lists of
        length [m - 2] ([hu_smid], [hsmid_u]). *)
    Lemma hu_smid : forall smid, length smid = (m - 2)%nat -> hu_to_smid (hsmid_to_u smid) = smid.
    Proof.
      intros smid hsm. unfold hu_to_smid.
      transitivity (map (fun i => nth i smid zero) (seq 0 (m - 2))); [| apply map_nth_seq_id; exact hsm].
      apply map_ext_in; intros i hi; apply in_seq in hi. unfold hsmid_to_u; rewrite nth_map_seq_gen by lia; cbn [Nat.add]; field.
    Qed.
    Lemma hsmid_u : forall us, length us = (m - 2)%nat -> hsmid_to_u (hu_to_smid us) = us.
    Proof.
      intros us hus. unfold hsmid_to_u.
      transitivity (map (fun i => nth i us zero) (seq 0 (m - 2))); [| apply map_nth_seq_id; exact hus].
      apply map_ext_in; intros i hi; apply in_seq in hi. unfold hu_to_smid; rewrite nth_map_seq_gen by lia; cbn [Nat.add]; field.
    Qed.

    (** Unfolding of [hreal]: the commitments to the prefix products and
        the zero-argument transcript [zreal] for the derived witness. *)
    Lemma hreal_unfold : forall l, hreal l = mk_had (com_list h gs hBs (hss (slice l 0 (m - 2))))
      (zreal h gs hA' hB' hr' (hs' (slice l 0 (m - 2))) y xz m (skipn (m - 2) l)).
    Proof. intros l; reflexivity. Qed.

    (** Key equation. If the Hadamard verifier accepts [hreal l] on
        statement [cA'], [cb'], then [hreal l = hsim cA' cb' (hPhi l)]. The
        verifier forces [c_{B0} = cA'_0] and [c_{B,m-1} = cb']; the middle
        commitments are [h ^ u_i] by [com_dlog]; and the inner zero
        argument is handled by [zreal_eq_zsim] on the derived statement. *)
    Lemma hreal_eq_hsim : forall l (cA' : list G) (cb' : G), length l = hR ->
      hadamard_verify h gs n cA' cb' x y xz (hreal l) = true -> hreal l = hsim cA' cb' (hPhi l).
    Proof.
      intros l cA' cb' hl hv. unfold hR in hl.
      rewrite hreal_unfold in hv |- *.
      set (smid := slice l 0 (m - 2)) in *. set (l' := skipn (m - 2) l) in *.
      assert (hsm : length smid = (m - 2)%nat) by (apply length_slice; lia).
      assert (hl' : length l' = zR gs m) by (unfold l'; rewrite length_skipn; lia).
      set (cB := com_list h gs hBs (hss smid)) in *.
      assert (hcBl : length cB = m) by (unfold cB; rewrite com_list_length, hBs_length, (hss_length smid hsm), Nat.min_id; reflexivity).
      (* The verifier's checks: lengths, c_{B0} = cA'_0, c_{B,m-1} = cb'
         and acceptance of the inner zero argument. *)
      apply hadamard_verify_true in hv. destruct hv as (hcA2 & hcBA & E0 & Em & hz).
      assert (hcAl : length cA' = m) by lia.
      set (us := hsmid_to_u smid).
      assert (hus : length us = (m - 2)%nat) by apply hsmid_to_u_length.
      assert (hcB : cB = nth 0 cA' gid :: map (fun u => h ^ u) us ++ [cb']).
      { apply (nth_ext _ _ gid gid).
        + rewrite hcBl; cbn [length]; rewrite length_app, length_map, hus; cbn [length]; lia.
        + intros i hi. rewrite hcBl in hi. destruct i as [| i]; [cbn [nth]; exact E0 |].
          cbn [nth]. destruct (Nat.eq_dec (S i) (m - 1)) as [e | e].
          - rewrite app_nth2 by (rewrite length_map, hus; lia). rewrite length_map, hus.
            replace (i - (m - 2))%nat with 0%nat by lia. cbn [nth].
            rewrite <-Em, hcAl, <-e. reflexivity.
          - rewrite app_nth1 by (rewrite length_map, hus; lia).
            rewrite (nth_indep (map (fun u => h ^ u) us) gid (h ^ zero)) by (rewrite length_map, hus; lia).
            rewrite (map_nth (fun u => h ^ u)). unfold us, hsmid_to_u. rewrite nth_map_seq_gen by lia. cbn [Nat.add].
            unfold cB. rewrite (nth_com_list (zero := zero)) by (rewrite ?hBs_length, ?(hss_length smid hsm); lia).
            unfold hBs; rewrite nth_map_seq_gen by lia. cbn [Nat.add].
            unfold hss; cbn [nth]. rewrite app_nth1 by lia.
            apply (com_dlog h gs γ (hprefix A (S i)) (nth i smid zero) hγl hγ). }
      unfold hsim, hPhi; cbv zeta. fold smid l' us.
      set (Z := zPhi gs γ hA' hB' hr' (hs' smid) y xz m l').
      rewrite (slice_app0 us Z (m - 2) hus), (skipn_app_exact us Z (m - 2) hus).
      rewrite <-hcB. f_equal.
      (* The inner zero argument, simulated on the derived statement. *)
      apply (zreal_eq_zsim h gs γ hA' hB' hr' (hs' smid) y xz m hA'_length hn (ltac:(lia)) hB'_length hr'_length
        (hs'_length smid) hA'_rows hB'_rows hγl hγ l' _ _ hl').
      unfold hadamard_zero_stmt; cbv zeta; cbn [fst snd]. exact hz.
    Qed.

    (** [hPhi] preserves length [hR]. *)
    Lemma hPhi_length : forall l, length l = hR -> length (hPhi l) = hR.
    Proof.
      intros l hl. unfold hR in *. unfold hPhi; cbv zeta. rewrite length_app, hsmid_to_u_length. f_equal.
      apply (zPhi_length gs γ hA' hB' hr' _ y xz m hA'_length hn (ltac:(lia)) hB'_length hr'_length (hs'_length _) hA'_rows hB'_rows hγl).
      rewrite length_skipn; lia.
    Qed.

    (** [hPsi] preserves length [hR]. *)
    Lemma hPsi_length : forall l, length l = hR -> length (hPsi l) = hR.
    Proof.
      intros l hl. unfold hR in *. unfold hPsi; cbv zeta. rewrite length_app, hu_to_smid_length. f_equal.
      apply (zPsi_length gs γ hA' hB' hr' _ y xz m hA'_length hn (ltac:(lia)) hB'_length hr'_length (hs'_length _) hA'_rows hB'_rows hγl).
      rewrite length_skipn; lia.
    Qed.

    (** [hPsi] is a left inverse of [hPhi] on lists of length [hR]. *)
    Lemma hPsi_hPhi : forall l, length l = hR -> hPsi (hPhi l) = l.
    Proof.
      intros l hl. unfold hR in hl.
      unfold hPhi; cbv zeta. set (smid := slice l 0 (m - 2)). set (l' := skipn (m - 2) l).
      assert (hsm : length smid = (m - 2)%nat) by (apply length_slice; lia).
      assert (hl' : length l' = zR gs m) by (unfold l'; rewrite length_skipn; lia).
      set (us := hsmid_to_u smid). set (Z := zPhi gs γ hA' hB' hr' (hs' smid) y xz m l').
      assert (hus : length us = (m - 2)%nat) by apply hsmid_to_u_length.
      unfold hPsi; cbv zeta. rewrite (slice_app0 us Z (m - 2) hus), (skipn_app_exact us Z (m - 2) hus).
      unfold us; rewrite (hu_smid smid hsm). unfold Z.
      rewrite (zPsi_zPhi gs γ hA' hB' hr' (hs' smid) y xz m hA'_length hn (ltac:(lia)) hB'_length hr'_length
        (hs'_length smid) hA'_rows hB'_rows hγl l' hl').
      unfold smid, l', slice; cbn [skipn]. apply firstn_skipn.
    Qed.

    (** [hPsi] is a right inverse of [hPhi] on lists of length [hR]. *)
    Lemma hPhi_hPsi : forall l, length l = hR -> hPhi (hPsi l) = l.
    Proof.
      intros l hl. unfold hR in hl.
      unfold hPsi; cbv zeta. set (us := slice l 0 (m - 2)). set (l' := skipn (m - 2) l).
      assert (hus : length us = (m - 2)%nat) by (apply length_slice; lia).
      assert (hl' : length l' = zR gs m) by (unfold l'; rewrite length_skipn; lia).
      set (smid := hu_to_smid us). set (Z := zPsi gs γ hA' hB' hr' (hs' smid) y xz m l').
      assert (hsm : length smid = (m - 2)%nat) by apply hu_to_smid_length.
      unfold hPhi; cbv zeta. rewrite (slice_app0 smid Z (m - 2) hsm), (skipn_app_exact smid Z (m - 2) hsm).
      unfold Z. rewrite (zPhi_zPsi gs γ hA' hB' hr' (hs' smid) y xz m hA'_length hn (ltac:(lia)) hB'_length hr'_length
        (hs'_length smid) hA'_rows hB'_rows hγl l' hl').
      unfold smid; rewrite (hsmid_u us hus).
      unfold us, l', slice; cbn [skipn]. apply firstn_skipn.
    Qed.

    (** The Hadamard challenges are non-zero, as [hadamard_completeness]
        (and the verifier) require. *)
    Hypothesis hx0 : x <> zero.
    Hypothesis hy0 : y <> zero.

    (** On the honest statement, acceptance follows from
        [hadamard_completeness]. *)
    Lemma hreal_eq_hsim_honest : forall l, length l = hR -> hreal l = hsim cA cb (hPhi l).
    Proof.
      intros l hl. apply hreal_eq_hsim; [exact hl |]. unfold hR, zR in hl. unfold hreal; cbv zeta.
      apply hadamard_completeness; rewrite ?hAm; try assumption; try reflexivity; apply length_slice; rewrite ?length_skipn; lia.
    Qed.

    (** Perfect special HVZK of the Hadamard argument: for all challenges
        [x ≠ 0], [y ≠ 0] and [xz], the honest transcript distribution on
        the witness [A], [r], [s] equals the simulator's distribution on
        [cA], [cb]. Hypotheses: [lf] enumerates [F], [m ≥ 2], [n ≥ 1], the
        length conditions and [gs_j = h ^ γ_j]. The relation
        (that [cb] commits to the Hadamard product) holds by definition of
        [cb]. *)
    Theorem hadamard_shvzk : forall (lf : list F) (Hlfn : lf <> []),
      NoDup lf -> (forall v : F, In v lf) ->
      Permutation (hadamard_real_distribution lf Hlfn) (hadamard_sim_distribution lf Hlfn cA cb).
    Proof.
      intros lf Hlfn hnd hall. unfold hadamard_real_distribution, hadamard_sim_distribution.
      apply (zk_of_bijection lf Hlfn hR hreal (hsim cA cb) hPhi hPsi hnd hall hPhi_length hPsi_length hPsi_hPhi hPhi_hPsi).
      intros l hl. apply hreal_eq_hsim_honest. exact hl.
    Qed.

  End HadamardZK.

  (** ** The product argument (Alg. 9.18 / 9.19)

      Statement: commitments [cA] to the columns of an [n × m] matrix [A]
      and a scalar [b] equal to the product of all its entries. For
      [m ≥ 2] the prover commits to the Hadamard product [bvec] of the
      columns, runs the Hadamard argument and the single-value product
      argument on [bvec]; for [m = 1] only the single-value product
      argument on the single column is run.

      The simulator [psim] draws a random commitment [c_b = h ^ u] (for
      [m ≥ 2]) and composes [hsim] and [ssim]. Theorem:
      [product_shvzk]. *)
  Local Notation product_verify := (product_verify (zero := zero) (one := one) (add := add)
    (mul := mul) (sub := sub) (opp := opp) (Fdec := Fdec) (gid := gid) (gop := gop) (gpow := gpow)
    (Gdec := Gdec)).
  Local Notation product_prove := (product_prove (zero := zero) (one := one) (add := add)
    (mul := mul) (sub := sub) (opp := opp) (gid := gid) (gop := gop) (gpow := gpow)).
  Local Notation product_argument := (@product_argument F G).
  Local Notation mk_prod := (@mk_prod F G).

  (** Section for the product argument. *)
  Section ProductZK.

    (** The commitment key [h], [gs] with discrete logarithms [γ]. The
        witness [A] with randomness [r]; challenges [xh], [yh] of the
        Hadamard argument, [xz] of its inner zero argument and [xs] of the
        single-value product argument. *)
    Variables (h : G) (gs : list G) (γ : list F).
    Variables (A : list (list F)) (r : list F) (xh yh xz xs : F) (m : nat).
    (** [bvec] is the Hadamard product of the columns, [b] the product of
        its entries (the claimed value). *)
    Local Notation n := (length gs).
    Local Notation cA := (com_list h gs A r).
    Local Notation bvec := (hprefix A (length A - 1)).
    Local Notation b := (fold_right mul one bvec).

    (** Side conditions: [m ≥ 1], [n ≥ 2], lengths of [A] and [r], columns
        of length [n], and [gs_j = h ^ γ_j]. *)
    Hypothesis hAm : length A = m.
    Hypothesis hm : (1 <= m)%nat.
    Hypothesis hn : (2 <= n)%nat.
    Hypothesis hr : length r = m.
    Hypothesis hAn : Forall (fun v => length v = n) A.
    Hypothesis hγl : length γ = n.
    Hypothesis hγ : forall j, (j < n)%nat -> nth j gs gid = h ^ (nth j γ zero).

    (** [bvec] has length [n]. *)
    Lemma hbl : length bvec = n.
    Proof. apply (hprefix_length n A _ hAn); lia. Qed.
    (** The first column has length [n]. *)
    Lemma ha0 : length (nth 0 A []) = n.
    Proof. rewrite Forall_forall in hAn; apply hAn, nth_In; lia. Qed.

    (** Number of coins: the randomness [s] of [c_b], the [hR] Hadamard
        coins and the [sR] single-value product coins. For [m = 1] the
        Hadamard coins are drawn but unused. *)
    Definition pR : nat := (1 + hR gs m + sR n)%nat.

    (** The honest transcript: [product_prove] with its coins read from
        [l]. *)
    Definition preal (l : list F) : product_argument :=
      let s := nth 0 l zero in
      let lh := slice l 1 (hR gs m) in
      let lz := skipn (m - 2) lh in
      let ls := skipn (1 + hR gs m) l in
      product_prove h gs n A r s (slice lh 0 (m - 2)) (slice lz 0 n) (slice lz n n) (nth (2 * n) lz zero) (nth (2 * n + 1) lz zero)
        (slice lz (2 * n + 2) (S m)) (slice lz (2 * n + 3 + m) (m - 1))
        (slice ls 0 n) (nth n ls zero) (slice ls (n + 1) (n - 2)) (nth (2 * n - 1) ls zero) (nth (2 * n) ls zero) xh yh xz xs.

    (** The simulator on statement [cA'], [b']. If [cA'] has more than one
        element it sets [c_b = h ^ u] with [u = l_0], simulates the
        Hadamard argument on [cA'], [c_b] and the single-value product
        argument on [c_b], [b']; otherwise it has no Hadamard part and
        simulates the single-value product argument on [cA'_0], [b']. *)
    Definition psim (cA' : list G) (b' : F) (l : list F) : product_argument :=
      let u := nth 0 l zero in
      let lh := slice l 1 (hR gs m) in
      let ls := skipn (1 + hR gs m) l in
      if 1 <? length cA' then
        mk_prod (h ^ u) (Some (hsim h gs xh yh xz m cA' (h ^ u) lh)) (ssim h gs xs n (h ^ u) b' ls)
      else mk_prod gid None (ssim h gs xs n (nth 0 cA' gid) b' ls).

    (** The real and simulated distributions over uniform coins. *)
    Definition product_real_distribution (lf : list F) (Hlfn : lf <> []) : dist product_argument :=
      Bind (rand lf Hlfn pR) (fun l => Ret (preal l)).
    Definition product_sim_distribution (lf : list F) (Hlfn : lf <> []) (cA' : list G) (b' : F) : dist product_argument :=
      Bind (rand lf Hlfn pR) (fun l => Ret (psim cA' b' l)).

    (** The bijection: for [m ≥ 2], [u = s + ⟨γ, bvec⟩] followed by [hPhi]
        and [sPhi]; for [m = 1], the identity on the first [1 + hR] coins
        followed by [sPhi]. *)
    Definition pPhi (l : list F) : list F :=
      let s := nth 0 l zero in
      let lh := slice l 1 (hR gs m) in
      let ls := skipn (1 + hR gs m) l in
      if 1 <? length A then (s + dot γ bvec) :: hPhi gs γ A r s xh yh xz m lh ++ sPhi γ bvec s xs n ls
      else s :: lh ++ sPhi γ (nth 0 A []) (nth 0 r zero) xs n ls.
    (** The inverse of [pPhi], case by case. *)
    Definition pPsi (l : list F) : list F :=
      let u := nth 0 l zero in
      let lh := slice l 1 (hR gs m) in
      let ls := skipn (1 + hR gs m) l in
      if 1 <? length A then
        let s := u - dot γ bvec in
        s :: hPsi gs γ A r s xh yh xz m lh ++ sPsi γ bvec s xs n ls
      else u :: lh ++ sPsi γ (nth 0 A []) (nth 0 r zero) xs n ls.

    (** Reading back the three fields of [a :: X ++ Y]. *)
    Lemma pslices : forall (a : F) (X Y : list F), length X = hR gs m ->
      nth 0 (a :: X ++ Y) zero = a /\ slice (a :: X ++ Y) 1 (hR gs m) = X /\ skipn (1 + hR gs m) (a :: X ++ Y) = Y.
    Proof.
      intros a X Y hX. repeat split.
      + unfold slice; cbn [skipn]. exact (slice_app0 X Y _ hX).
      + cbn [skipn Nat.add]. exact (skipn_app_exact X Y _ hX).
    Qed.

    (** Every list of length [pR] is the assembly of its three fields. *)
    Lemma precompose : forall l, length l = pR -> l = nth 0 l zero :: slice l 1 (hR gs m) ++ skipn (1 + hR gs m) l.
    Proof.
      intros l hl. unfold pR in hl. destruct l as [| a l0]; [cbn in hl; lia |].
      cbn [nth]. unfold slice. cbn [skipn Nat.add]. f_equal. symmetry; apply firstn_skipn.
    Qed.

    (** Key equation: if the product verifier accepts [preal l] on
        statement [cA'] (of length [m]) and [b'], then
        [preal l = psim cA' b' (pPhi l)]. Proof by cases on [m]: for
        [m ≥ 2], [c_b = h ^ (s + ⟨γ, bvec⟩)] by [com_dlog] and the two
        sub-arguments by [hreal_eq_hsim] and [sreal_eq_ssim]; for [m = 1]
        only [sreal_eq_ssim]. *)
    Lemma preal_eq_psim : forall l (cA' : list G) (b' : F), length l = pR -> length cA' = m ->
      product_verify h gs n cA' b' xh yh xz xs (preal l) = true -> preal l = psim cA' b' (pPhi l).
    Proof.
      intros l cA' b' hl hcA hv. unfold pR in hl.
      unfold preal, psim, pPhi in *; cbv zeta in *.
      set (s := nth 0 l zero) in *. set (lh := slice l 1 (hR gs m)) in *. set (ls := skipn (1 + hR gs m) l) in *.
      assert (hlh : length lh = hR gs m) by (apply length_slice; lia).
      assert (hls : length ls = sR n) by (unfold ls; rewrite length_skipn; lia).
      assert (hlt' : (1 <? m) = (1 <? length A)) by (rewrite hAm; reflexivity).
      rewrite hcA, hlt' in *.
      unfold BayerGroth.product_prove in hv |- *; cbv zeta in hv |- *.
      destruct (1 <? length A) eqn:hlt.
      +
        assert (hm2 : (2 <= m)%nat) by (pose proof (proj1 (Nat.ltb_lt _ _) hlt); lia).
        (* Case m ≥ 2: acceptance of both sub-arguments. *)
        apply product_verify_true in hv; [| lia].
        destruct hv as [(_ & hvh & hvs) | (h1 & _)]; [| lia].
        set (X := hPhi gs γ A r s xh yh xz m lh). set (Y := sPhi γ bvec s xs n ls).
        assert (hX : length X = hR gs m) by apply (hPhi_length gs γ A r s xh yh xz m hAm hm2 (ltac:(lia)) hr hAn hγl lh hlh).
        destruct (pslices (s + dot γ bvec) X Y hX) as (P0 & P1 & P2). rewrite P0, P1, P2.
        rewrite <-(com_dlog h gs γ bvec s hγl hγ).
        f_equal.
        - f_equal. exact (hreal_eq_hsim h gs γ A r s xh yh xz m hAm hm2 (ltac:(lia)) hr hAn hγl hγ lh cA' _ hlh hvh).
        - exact (sreal_eq_ssim h gs γ bvec s xs n hbl hn hγl hγ ls _ b' hls hvs).
      +
        (* Case m = 1: only the single-value product argument. *)
        unfold BayerGroth.product_verify in hv; cbv zeta in hv. rewrite hcA, hlt' in hv. cbn [pa_svp] in hv.
        destruct (pslices s lh (sPhi γ (nth 0 A []) (nth 0 r zero) xs n ls) hlh) as (P0 & P1 & P2). rewrite P2.
        f_equal.
        exact (sreal_eq_ssim h gs γ (nth 0 A []) (nth 0 r zero) xs n ha0 hn hγl hγ ls _ b' hls hv).
    Qed.

    (** [pPhi] preserves length [pR]. *)
    Lemma pPhi_length : forall l, length l = pR -> length (pPhi l) = pR.
    Proof.
      intros l hl. unfold pR in *. unfold pPhi; cbv zeta.
      assert (hlh : length (slice l 1 (hR gs m)) = hR gs m) by (apply length_slice; lia).
      assert (hls : length (skipn (1 + hR gs m) l) = sR n) by (rewrite length_skipn; lia).
      destruct (1 <? length A) eqn:hlt; cbn [length]; rewrite length_app.
      + assert (hm2 : (2 <= m)%nat) by (pose proof (proj1 (Nat.ltb_lt _ _) hlt); lia).
        rewrite (hPhi_length gs γ A r _ xh yh xz m hAm hm2 (ltac:(lia)) hr hAn hγl _ hlh).
