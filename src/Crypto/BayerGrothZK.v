  Definition rand (lf : list F) (Hlfn : lf <> []) (k : nat) : dist (list F) :=
    List.map (fun '(v, p) => (Vector.to_list v, p)) (repeat_dist_ntimes_vector (uniform_with_replacement lf Hlfn) k).

  Fixpoint of_list_n (k : nat) (l : list F) : Vector.t F k :=
    match k with 0 => Vector.nil F | S k' => Vector.cons F (hd zero l) k' (of_list_n k' (tl l)) end.

  Lemma to_list_of_list_n : forall k (l : list F), length l = k -> Vector.to_list (of_list_n k l) = l.
  Proof.
    induction k as [| k ih]; intros l hl; destruct l as [| a l]; try discriminate; [reflexivity |].
    cbn [of_list_n hd tl]. change (Vector.to_list (Vector.cons F a k (of_list_n k l))) with (a :: Vector.to_list (of_list_n k l)).
    f_equal. apply ih. cbn in hl; lia.
  Qed.

  Lemma of_list_n_to_list : forall k (v : Vector.t F k), of_list_n k (Vector.to_list v) = v.
  Proof.
    intros k v; induction v as [| a k v ih]; [reflexivity |].
    change (Vector.to_list (Vector.cons F a k v)) with (a :: Vector.to_list v). cbn [of_list_n hd tl]. rewrite ih; reflexivity.
  Qed.

  Lemma in_rand_length : forall lf Hlfn k (l : list F) p, In (l, p) (rand lf Hlfn k) -> length l = k.
  Proof.
    intros lf Hlfn k l p hin. unfold rand in hin. apply in_map_iff in hin.
    destruct hin as ((v & q) & e & _). injection e as <- _. apply length_to_list.
  Qed.

  Lemma map_pair_compose : forall {A B C P : Type} (f : A -> B) (k : B -> C) (l : list (A * P)),
    List.map (fun '(v, p) => (k (f v), p)) l = List.map (fun '(v, p) => (k v, p)) (List.map (fun '(v, p) => (f v, p)) l).
  Proof. intros; induction l as [| (v & p) l ih]; [reflexivity | cbn; rewrite ih; reflexivity]. Qed.

  Lemma rand_bijection_perm : forall (lf : list F) (Hlfn : lf <> []) (k : nat) (Phi Psi : list F -> list F),
    NoDup lf -> (forall x, In x lf) ->
    (forall l, length l = k -> length (Phi l) = k) -> (forall l, length l = k -> length (Psi l) = k) ->
    (forall l, length l = k -> Psi (Phi l) = l) -> (forall l, length l = k -> Phi (Psi l) = l) ->
    Permutation (List.map (fun '(l, p) => (Phi l, p)) (rand lf Hlfn k)) (rand lf Hlfn k).
  Proof.
    intros lf Hlfn k Phi Psi hnd hall hlP hlQ hPsi hPhi.
    set (PhiV := fun v : Vector.t F k => of_list_n k (Phi (Vector.to_list v))).
    set (PsiV := fun v : Vector.t F k => of_list_n k (Psi (Vector.to_list v))).
    unfold rand. rewrite <-map_pair_compose.
    rewrite (List.map_ext (fun '(v, p) => (Phi (Vector.to_list v), p)) (fun '(v, p) => (Vector.to_list (PhiV v), p))).
    2: { intros (v & p). unfold PhiV. rewrite to_list_of_list_n by (apply hlP, length_to_list). reflexivity. }
    rewrite map_pair_compose. apply Permutation_map.
    apply (repeat_uniform_bijection_perm lf Hlfn k PhiV PsiV hnd hall).
    + intro v. unfold PsiV, PhiV. rewrite to_list_of_list_n by (apply hlP, length_to_list).
      rewrite hPsi by apply length_to_list. apply of_list_n_to_list.
    + intro v. unfold PsiV, PhiV. rewrite to_list_of_list_n by (apply hlQ, length_to_list).
      rewrite hPhi by apply length_to_list. apply of_list_n_to_list.
  Qed.

  (* two maps of the randomness that differ by a bijection give the same distribution *)
  Theorem zk_of_bijection : forall {T : Type} (lf : list F) (Hlfn : lf <> []) (k : nat)
    (real sim : list F -> T) (Phi Psi : list F -> list F),
    NoDup lf -> (forall x, In x lf) ->
    (forall l, length l = k -> length (Phi l) = k) -> (forall l, length l = k -> length (Psi l) = k) ->
    (forall l, length l = k -> Psi (Phi l) = l) -> (forall l, length l = k -> Phi (Psi l) = l) ->
    (forall l, length l = k -> real l = sim (Phi l)) ->
    Permutation (Bind (rand lf Hlfn k) (fun l => Ret (real l))) (Bind (rand lf Hlfn k) (fun l => Ret (sim l))).
  Proof.
    intros * hnd hall hlP hlQ hPsi hPhi heq.
    apply (bind_ret_perm (rand lf Hlfn k) Phi real sim).
    + apply (rand_bijection_perm lf Hlfn k Phi Psi); assumption.
    + intros l p hin. apply heq. exact (in_rand_length lf Hlfn k l p hin).
  Qed.

