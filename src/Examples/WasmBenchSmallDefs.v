(* Reduced-parameter WebAssembly benchmarks: the same fixed 7-candidate
   approval ballot as WasmBenchDefs.v, but over small Schnorr groups
   (64-, 128-, and 256-bit p), to locate the point at which the
   CertiRocq WebAssembly backend's 2 GB linear-memory limit binds.

   The primality proofs are Admitted: they are erased during
   compilation (the same reasoning as the quick-compilation trick in
   the top-level README), so the generated WebAssembly is identical to
   what fully proven parameters would produce. The parameters were
   generated by bench/wasm/gen_small_params.py: p = k*q + 1 with p, q
   prime, g of order q, and h = g^x for a random secret x. *)

Module Small64.

  (* 32-bit prime q, 64-bit prime p *)
  Definition q : Z := 3199286161%Z.
  Lemma prime_q : Znumtheory.prime q. Admitted.
  Definition p : Z := 10690002613329673913%Z.
  Lemma prime_p : Znumtheory.prime p. Admitted.

  Definition k : Z := Z.div p q.
  Theorem safe_prime : p = (k * q + 1)%Z.
  Proof. vm_cast_no_check (eq_refl p). Qed.

  Definition gval : Z := 1124220994599102764%Z.
  Definition g : @Schnorr_group p q.
  Proof.
    refine
      {| Schnorr.v := gval;
        Ha := conj eq_refl eq_refl : (0 < gval < p)%Z;
        Hb := _ |}.
    vm_cast_no_check (eq_refl (Zpow_facts.Zpow_mod gval q p)).
  Defined.

  Definition hval : Z := 2011698458059402266%Z.
  Definition h : @Schnorr_group p q.
  Proof.
    refine
      {| Schnorr.v := hval;
        Ha := conj eq_refl eq_refl : (0 < hval < p)%Z;
        Hb := _ |}.
    vm_cast_no_check (eq_refl (Zpow_facts.Zpow_mod hval q p)).
  Defined.

  Lemma q_neq_zero : q <> 0%Z.
  Proof. discriminate. Qed.

  Definition mkzp (z : Z) : @Zp q :=
    mk_zp (Z.modulo z q) (Z.mod_mod z q q_neq_zero).

  Definition small_encrypt_ballot_and_generate_enc_proof {n : nat}
    (rs ms : Vector.t (@Zp q) n)
    (uscs : Vector.t (Vector.t (@Zp q) 3) n)
    (c : Vector.t (@Zp q) n) :
    Vector.t ((@Schnorr_group p q) * (@Schnorr_group p q) *
      @Sigma.sigma_proto (@Zp q) (@Schnorr_group p q * @Schnorr_group p q) 2 3 2) n.
  Proof.
    refine(@encrypt_ballot_and_generate_enc_proof (@Zp q)
      Zpfield.zero Zpfield.one zp_add zp_mul zp_sub
      zp_opp zp_dec (@Schnorr_group p q)
      (@inv_schnorr_group k p q safe_prime prime_p prime_q)
      (@mul_schnorr_group p q prime_p prime_q)
      (@pow k p q safe_prime prime_p prime_q) _
      g h rs ms uscs c).
    all: (try eapply prime_q).
    all: (try eapply prime_p).
    all: (try eapply safe_prime).
  Defined.

  Definition small_verify_encryption_ballot_proof {n : nat}
    (proof : Vector.t ((@Schnorr_group p q) * (@Schnorr_group p q) *
    @Sigma.sigma_proto (@Zp q)
    (@Schnorr_group p q * @Schnorr_group p q) 2 3 2) n) : bool.
  Proof.
    refine(@verify_encryption_ballot_proof (@Zp q)
      Zpfield.zero Zpfield.one zp_add zp_dec
      (@Schnorr_group p q)
      (@inv_schnorr_group k p q safe_prime prime_p prime_q)
      (@mul_schnorr_group p q prime_p prime_q)
      (@pow k p q safe_prime prime_p prime_q)
      Schnorr.dec_zpstar _ g h proof).
    all: (try eapply prime_q).
    all: (try eapply prime_p).
    all: (try eapply safe_prime).
  Defined.

  Definition bench_rs : Vector.t (@Zp q) 7 :=
    [mkzp 1452066460; mkzp 90341466; mkzp 2526766691; mkzp 2379074820;
     mkzp 988335252; mkzp 2527331059; mkzp 945826487].

  Definition bench_ms : Vector.t (@Zp q) 7 :=
    [mkzp 1; mkzp 0; mkzp 1; mkzp 0; mkzp 1; mkzp 1; mkzp 0].

  Definition bench_uscs : Vector.t (Vector.t (@Zp q) 3) 7 :=
    [[mkzp 134917628; mkzp 1419179581; mkzp 304330004];
     [mkzp 2208283729; mkzp 1022222126; mkzp 1196050748];
     [mkzp 2873237672; mkzp 2084839400; mkzp 920140091];
     [mkzp 2315992116; mkzp 568275056; mkzp 3106775596];
     [mkzp 2452611419; mkzp 2474810180; mkzp 2030106618];
     [mkzp 1043665193; mkzp 2031403297; mkzp 1748309235];
     [mkzp 817804384; mkzp 405126229; mkzp 416314668]].

  Definition bench_cs : Vector.t (@Zp q) 7 :=
    [mkzp 30884439; mkzp 304912983; mkzp 3040153711; mkzp 2710566583;
     mkzp 252860897; mkzp 983297493; mkzp 289482183].

  Definition ballot_bench :=
    small_encrypt_ballot_and_generate_enc_proof bench_rs bench_ms bench_uscs bench_cs.

  Definition ballot_verify_bench : bool :=
    small_verify_encryption_ballot_proof ballot_bench.

End Small64.


