(** * Approval voting: the voter side over a toy Schnorr group

    This file instantiates the approval-voting front end of
    [Frontend/Approval.v] over a small Schnorr group. A ballot is a vector
    of ElGamal encryptions [Enc(g^m_i)] of approvals [m_i ∈ {0, 1}], one per
    candidate. Each comes with a disjunctive encryption proof ([EncProof],
    two branches, for messages [g^0] and [g^1]) that it encrypts 0 or 1.
    Optionally an _overall proof_ shows that the product of the
    ciphertexts encrypts a total between [0] and [n + 1]. The functions are
    the voter's computations (encryption and proof generation) and the
    public verifier. They are extracted by
    [src/Extraction/Approvallib/Extraction.v] and driven by
    [src/Executable/Approvalcode].

    The group is the order-[q] subgroup of [Z_p^*] with [q = 2963] and the
    safe prime [p = 2q + 1 = 5927], generated by [g = 4], with public key
    [h = 3210]. The secret key ([x = 1234], with [h = g^x]) is not used
    here, because everything in this file runs on the voter's machine. The
    decryption side is in [Examples/TallyIns.v]. The same group is reused by
    [Examples/SchulzeIns.v]. These parameters are for testing only.

    The challenges of the interactive functions are explicit arguments. The
    non-interactive ([nizk_]) functions take the hash function as a
    parameter, which the extracted program instantiates. Most definitions
    are written in proof mode and close the primality side conditions with
    [prime_q], [prime_p] and [safe_prime]. *)
Section Ins.

  (** *** The group *)

  (** The prime order [q = 2963] of the subgroup. *)
  Definition q : Z := 2963.

  (** The safe prime [p = 2q + 1]. *)
  Definition p : Z := 2 * q + 1.

  (** Primality of [q] and [p] by trial division up to the square root, and
      the safe-prime equation. *)
  Theorem prime_q : Znumtheory.prime q : Prop : Type.
  Proof.
    eapply is_prime_sqrt_correct.
    compute; reflexivity.
  Qed.

  Theorem prime_p : Znumtheory.prime p : Prop : Type.
  Proof.
    eapply is_prime_sqrt_correct.
    compute; reflexivity.
  Qed.

  Theorem safe_prime : p = (2 * q + 1)%Z.
  Proof. compute. exact eq_refl. Qed.

  (** The generator [g = 4]. Its membership in the subgroup ([4^q mod p = 1])
      is checked by [vm_compute]. *)
  Definition g : @Schnorr_group p q.
  Proof.
    refine
    {| Schnorr.v := 4;
    Ha := conj eq_refl eq_refl : (0 < 4 < p)%Z;
    Hb := _ |}.
    vm_cast_no_check (eq_refl (Zpow_facts.Zpow_mod 4 q p)).
  Defined.

  (** The election public key [h = 3210]. *)
  Definition h : @Schnorr_group p q.
  Proof.
    refine
    {| Schnorr.v := 3210;
    Ha := conj eq_refl eq_refl : (0 < 3210 < p)%Z;
    Hb := _ |}.
    vm_cast_no_check (eq_refl (Zpow_facts.Zpow_mod 3210 q p)).
  Defined.

  (** *** A single approval *)

  (** [Enc(g^m; r) = (g^r, g^m · h^r)]. *)
  Definition encrypt_vote_ins (r m : (@Zp q)) :
    (@Schnorr_group p q * @Schnorr_group p q).
  Proof.
    refine(@encrypt_vote (@Zp q) (@Schnorr_group p q)
      (@mul_schnorr_group p q prime_p prime_q)
      (@pow 2 p q safe_prime prime_p prime_q)
      g h r m).
  Defined.

  (** The announcement (commitment) of the 0-or-1 encryption proof for
      [Enc(g^m; r)], with commitment randomness and simulated challenge
      [uscs]. It is [Approval.generate_enc_proof_commitment], which, like
      the prover [generate_enc_proof], puts the real Chaum–Pedersen
      commitment on branch 0 when [m = 0] and on branch 1 otherwise, and
      simulates the other branch. The real branch therefore always sits where
      the prover puts it, and the result is exactly the announcement of the
      proof ([generate_vote_commitment_ins_announcement]), as Fiat–Shamir
      hashing requires. *)
  Definition generate_vote_commitment_ins
    (r m : (@Zp q)) (uscs : Vector.t (@Zp q) 3) :
    Vector.t (@Schnorr_group p q * @Schnorr_group p q) 2.
  Proof.
    refine(@generate_enc_proof_commitment (@Zp q) Zpfield.zero Zpfield.one
      zp_opp zp_dec (@Schnorr_group p q)
      (@inv_schnorr_group 2 p q safe_prime prime_p prime_q)
      (@mul_schnorr_group p q prime_p prime_q)
      pow g h m uscs (encrypt_vote_ins r m)).
    all:(try (eapply prime_q)).
    all:(try (eapply prime_p)).
    all:(try (eapply safe_prime)).
  Defined.

  (** The 0-or-1 encryption proof for the ciphertext [cp] with challenge
      [c]. *)
  Definition generate_vote_enc_proof_ins (r m : (@Zp q))
    (uscs : Vector.t (@Zp q) 3)
    (cp : (@Schnorr_group p q * @Schnorr_group p q)) (c : (@Zp q)) :
    @Sigma.sigma_proto (@Zp q) (@Schnorr_group p q * @Schnorr_group p q)
    2 3 2.
  Proof.
    refine(@generate_enc_proof (@Zp q)
     Zpfield.zero Zpfield.one zp_add zp_mul zp_sub zp_opp zp_dec
     (@Schnorr_group p q)
     (@inv_schnorr_group 2 p q safe_prime prime_p prime_q)
     (@mul_schnorr_group p q prime_p prime_q) pow g h r m uscs cp c).
    all:(try (eapply prime_q)).
    all:(try (eapply prime_p)).
    all:(try (eapply safe_prime)).
  Defined.

  (** Fiat–Shamir binding for a single vote: the commitments returned by
      [generate_vote_commitment_ins] are exactly the announcement of the
      proof that [generate_vote_enc_proof_ins] produces for the same vote,
      randomness and [uscs], whatever the challenge [c] and whether
      [m = 0] or not. A challenge derived by hashing these commitments
      therefore binds the published announcement. Instance of
      [Approval.generate_enc_proof_commitment_announcement]. *)
  Lemma generate_vote_commitment_ins_announcement :
    ∀ (r m c : @Zp q) (uscs : Vector.t (@Zp q) 3),
    generate_vote_commitment_ins r m uscs =
    Sigma.announcement (generate_vote_enc_proof_ins r m uscs (encrypt_vote_ins r m) c).
  Proof.
    intros r m c uscs.
    unfold generate_vote_commitment_ins, generate_vote_enc_proof_ins.
    symmetry.
    apply generate_enc_proof_commitment_announcement.
  Qed.

  (** Encryption together with its 0-or-1 proof. *)
  Definition encrypt_vote_and_generate_enc_proof_ins
    (r m : (@Zp q)) (uscs : Vector.t (@Zp q) 3) (c : (@Zp q)) :
    @Schnorr_group p q * @Schnorr_group p q *
    @Sigma.sigma_proto (@Zp q) (@Schnorr_group p q * @Schnorr_group p q)
    2 3 2.
  Proof.
    refine(@encrypt_vote_and_generate_enc_proof (@Zp q)
     Zpfield.zero Zpfield.one zp_add zp_mul zp_sub zp_opp zp_dec
     (@Schnorr_group p q)
     (@inv_schnorr_group 2 p q safe_prime prime_p prime_q)
     (@mul_schnorr_group p q prime_p prime_q) pow
     g h r m uscs c).
    all: (try eapply prime_q).
    exact safe_prime.
    eapply prime_p.
  Defined.

  (** Verification of a single encrypted approval and its proof. *)
  Definition verify_encryption_vote_proof_ins
    (proof : @Schnorr_group p q * @Schnorr_group p q *
    @Sigma.sigma_proto (@Zp q) (@Schnorr_group p q * @Schnorr_group p q)
    2 3 2) : bool.
  Proof.
    refine(@verify_encryption_vote_proof (@Zp q)
      Zpfield.zero Zpfield.one zp_add zp_dec
      (@Schnorr_group p q)
      (@inv_schnorr_group 2 p q safe_prime prime_p prime_q)
      (@mul_schnorr_group p q prime_p prime_q) pow
      Schnorr.dec_zpstar g h proof).
    all: (try eapply prime_q).
    exact safe_prime.
    eapply prime_p.
  Defined.

  (** *** A ballot of [n] approvals *)

  (** Entrywise encryption of the approval vector [ms] with randomness
      [rs]. *)
  Definition encrypt_ballot_ins {n : nat}
    (rs ms : Vector.t (@Zp q) n) :
    Vector.t (@Schnorr_group p q * @Schnorr_group p q) n.
  Proof.
    refine(@encrypt_ballot (@Zp q) (@Schnorr_group p q)
      (@mul_schnorr_group p q prime_p prime_q)
      (@pow 2 p q safe_prime prime_p prime_q)
      _ g h rs ms).
  Defined.

  (** The announcements of all the 0-or-1 proofs of a ballot. A
      non-interactive ballot derives its challenges from them.
      [Approval.ballot_commitment_announcement] shows that they are exactly
      the announcements of the proofs produced by
      [encrypt_ballot_and_generate_enc_proof_ins]. *)
  Definition generate_ballot_commitment_ins
    {n : nat} (rs ms : Vector.t (@Zp q) n)
    (uscs : Vector.t (Vector.t (@Zp q) 3) n) :
    Vector.t (Vector.t (@Schnorr_group p q * @Schnorr_group p q) 2) n.
  Proof.
    refine(@generate_ballot_commitment (@Zp q) Zpfield.zero Zpfield.one
      zp_opp zp_dec (@Schnorr_group p q)
      (@inv_schnorr_group 2 p q safe_prime prime_p prime_q)
      (@mul_schnorr_group p q prime_p prime_q)
      pow n g h rs ms uscs).
    all: (try eapply prime_q).
    all: (try eapply prime_p).
    all: (try eapply safe_prime).
  Defined.

  (** The 0-or-1 proofs for a vector of ciphertexts, one challenge each. *)
  Definition generate_ballot_enc_proof_ins {n : nat}
    (rs : Vector.t (@Zp q) n) (ms : Vector.t (@Zp q) n)
    (uscs : Vector.t (Vector.t (@Zp q) 3) n)
    (cp : Vector.t (@Schnorr_group p q * @Schnorr_group p q) n)
    (c : Vector.t (@Zp q) n) :
    Vector.t (@Sigma.sigma_proto (@Zp q) (@Schnorr_group p q * @Schnorr_group p q)
    2 3 2) n.
  Proof.
    refine(@generate_enc_proof_ballot (@Zp q)
     Zpfield.zero Zpfield.one zp_add zp_mul zp_sub zp_opp zp_dec
     (@Schnorr_group p q)
     (@inv_schnorr_group 2 p q safe_prime prime_p prime_q)
     (@mul_schnorr_group p q prime_p prime_q) pow n
     g h rs ms uscs cp c).
    all: (try eapply prime_q).
    all: (try eapply prime_p).
    all: (try eapply safe_prime).
  Defined.

  (** Encryption of a ballot together with its 0-or-1 proofs. *)
  Definition encrypt_ballot_and_generate_enc_proof_ins {n : nat}
    (rs : Vector.t (@Zp q) n) (ms : Vector.t (@Zp q) n)
    (uscs : Vector.t (Vector.t (@Zp q) 3) n) (c : Vector.t (@Zp q) n) :
    Vector.t ((@Schnorr_group p q) * (@Schnorr_group p q) *
      @Sigma.sigma_proto (@Zp q) (@Schnorr_group p q * @Schnorr_group p q) 2 3 2) n.
  Proof.
    refine(@encrypt_ballot_and_generate_enc_proof (@Zp q)
      Zpfield.zero Zpfield.one zp_add zp_mul zp_sub
      zp_opp zp_dec (@Schnorr_group p q)
      (@inv_schnorr_group 2 p q safe_prime prime_p prime_q)
      (@mul_schnorr_group p q prime_p prime_q) pow _
      g h rs ms uscs c).
    all: (try eapply prime_q).
    exact safe_prime.
    eapply prime_p.
  Defined.

  (** Flattens [n] announcements (two pairs each) into [4n] group elements
      for hashing. *)
  Definition vector_unfold : ∀ {n : nat}, Vector.t (Vector.t (@Schnorr_group p q * @Schnorr_group p q) 2) n ->
    Vector.t (@Schnorr_group p q) (4 * n).
  Proof.
    refine
    (fix fn {n : nat} (v : Vector.t (Vector.t (@Schnorr_group p q * @Schnorr_group p q) 2) n) :
      Vector.t (@Schnorr_group p q) (4 * n) :=
      match v as v' in Vector.t _ n' return
        Vector.t ((@Schnorr_group p q)) (4 * n')
      with
      | [] =>  []
      | @Vector.cons _ vh nt vt =>
         let ret := fn vt in _
      end).
    assert (ha : 4 * S nt = 4 + 4 * nt). nia.
    rewrite ha; clear ha.
    destruct (vector_inv_S vh) as ((vha, vhb) & vht & _).
    destruct (vector_inv_S vht) as ((vhta, vhtb) & _ & _).
    exact (vha :: vhb :: vhta :: vhtb :: ret).
  Defined.

  (** The non-interactive ballot. The [n] challenges are [fn] applied to
      [(p, q, g, h)] followed by all announcements. *)
  Definition nizk_encrypt_ballot_and_generate_enc_proof_ins {n : nat}
    (fn : ∀ {m : nat}, Vector.t (Z + (@Schnorr_group p q)) m -> Vector.t (@Zp q) n)
    (rs : Vector.t (@Zp q) n) (ms : Vector.t (@Zp q) n)
    (uscs : Vector.t (Vector.t (@Zp q) 3) n) :
    Vector.t ((@Schnorr_group p q) * (@Schnorr_group p q) *
      @Sigma.sigma_proto (@Zp q) (@Schnorr_group p q * @Schnorr_group p q) 2 3 2) n.
  Proof.
    set (comm := generate_ballot_commitment_ins rs ms uscs).
    set (c := fn _ ([inl p; inl q; inr g; inr h] ++
      Vector.map inr (vector_unfold comm))).
    exact(encrypt_ballot_and_generate_enc_proof_ins rs ms uscs c).
  Defined.

  (** Verification of a ballot's 0-or-1 proofs. *)
  Definition verify_encryption_ballot_proof_ins {n : nat}
    (proof : Vector.t ((@Schnorr_group p q) * (@Schnorr_group p q) *
    @Sigma.sigma_proto (@Zp q)
    (@Schnorr_group p q * @Schnorr_group p q) 2 3 2) n) : bool.
  Proof.
    refine(@verify_encryption_ballot_proof (@Zp q)
      Zpfield.zero Zpfield.one zp_add zp_dec
      (@Schnorr_group p q)
      (@inv_schnorr_group 2 p q safe_prime prime_p prime_q)
      (@mul_schnorr_group p q prime_p prime_q) pow
      Schnorr.dec_zpstar _ g h proof).
    all: (try eapply prime_q).
    exact safe_prime.
    eapply prime_p.
  Defined.

  (** *** The overall proof

      The overall proof is a disjunction with [n + 2] branches showing that
      the product of the [n + 1] ciphertexts encrypts a total in
      [{0, ..., n + 1}]. *)

  (** The overall proof with challenge [c]. *)
  Definition generate_overall_proof_ins {n : nat}
    (rs ms : Vector.t (@Zp q) (S n))
    (uscs : Vector.t (@Zp q) ((2 + n) + (1 + n))) (c : @Zp q) :
    @Sigma.sigma_proto (@Zp q) (@Schnorr_group p q * @Schnorr_group p q)
      (2 + n) (1 + (2 + n)) (2 + n).
  Proof.
    refine(@generate_overall_proof (@Zp q) Zpfield.zero Zpfield.one
      zp_add zp_mul zp_sub zp_opp zp_dec (@Schnorr_group p q)
      (@Schnorr.one p q prime_p prime_q)
      (@inv_schnorr_group 2 p q safe_prime prime_p prime_q)
      (@mul_schnorr_group p q prime_p prime_q) pow n g h rs ms uscs c).
    all: (try eapply prime_q).
    all: (try eapply prime_p).
    all: (try eapply safe_prime).
  Defined.

  (** Verification of an overall proof against the ciphertexts. *)
  Definition verify_overall_proof_ins {n : nat}
    (cps : Vector.t (@Schnorr_group p q * @Schnorr_group p q) n)
    (pf : @Sigma.sigma_proto (@Zp q) (@Schnorr_group p q * @Schnorr_group p q)
      (S n) (S (S n)) (S n)) : bool.
  Proof.
    refine(@verify_overall_proof (@Zp q) Zpfield.zero zp_add zp_dec
      (@Schnorr_group p q) (@Schnorr.one p q prime_p prime_q)
      (@inv_schnorr_group 2 p q safe_prime prime_p prime_q)
      (@mul_schnorr_group p q prime_p prime_q) pow Schnorr.dec_zpstar
      n g h cps pf).
    all: (try eapply prime_q).
    all: (try eapply prime_p).
    all: (try eapply safe_prime).
  Defined.

  (** Verification of a full ballot: the 0-or-1 proofs and the overall
      proof. *)
  Definition verify_ballot_ins {n : nat}
    (b : Vector.t (@Schnorr_group p q * @Schnorr_group p q *
        @Sigma.sigma_proto (@Zp q) (@Schnorr_group p q * @Schnorr_group p q) 2 3 2) n *
        @Sigma.sigma_proto (@Zp q) (@Schnorr_group p q * @Schnorr_group p q)
        (S n) (S (S n)) (S n)) : bool.
  Proof.
    refine(@verify_ballot (@Zp q) Zpfield.zero Zpfield.one zp_add zp_dec
      (@Schnorr_group p q) (@Schnorr.one p q prime_p prime_q)
      (@inv_schnorr_group 2 p q safe_prime prime_p prime_q)
      (@mul_schnorr_group p q prime_p prime_q) pow Schnorr.dec_zpstar
      n g h b).
    all: (try eapply prime_q).
    all: (try eapply prime_p).
    all: (try eapply safe_prime).
  Defined.

  (** An announcement flattened for hashing. *)
  Definition announcement_to_list {k : nat}
    (a : Vector.t (@Schnorr_group p q * @Schnorr_group p q) k) :
    list (Z + @Schnorr_group p q) :=
    Vector.fold_right (fun '(u, v) acc => (inr u :: inr v :: acc)%list) a List.nil.

  (** The non-interactive ballot with overall proof. The individual
      challenges come from [fn], as in
      [nizk_encrypt_ballot_and_generate_enc_proof_ins]. The challenge of the
      overall proof is [fo] applied to the public parameters and the proof's
      announcement. Since that announcement does not depend on the challenge,
      it is first computed with challenge zero, and the proof is then
      regenerated with the hashed challenge from the same randomness. *)
  Definition nizk_encrypt_ballot_with_overall_proof_ins {n : nat}
    (fn : ∀ {m : nat}, Vector.t (Z + (@Schnorr_group p q)) m -> Vector.t (@Zp q) (S n))
    (fo : ∀ {m : nat}, Vector.t (Z + (@Schnorr_group p q)) m -> @Zp q)
    (rs ms : Vector.t (@Zp q) (S n))
    (uscs : Vector.t (Vector.t (@Zp q) 3) (S n))
    (uscs' : Vector.t (@Zp q) ((2 + n) + (1 + n))) :
    Vector.t ((@Schnorr_group p q) * (@Schnorr_group p q) *
      @Sigma.sigma_proto (@Zp q) (@Schnorr_group p q * @Schnorr_group p q) 2 3 2) (S n) *
    @Sigma.sigma_proto (@Zp q) (@Schnorr_group p q * @Schnorr_group p q)
      (2 + n) (1 + (2 + n)) (2 + n).
  Proof.
    set (b := nizk_encrypt_ballot_and_generate_enc_proof_ins (@fn) rs ms uscs).
    set (pf0 := generate_overall_proof_ins rs ms uscs' (@Zpfield.zero q prime_q)).
    set (c := fo _ (Vector.of_list
      ((inl p :: inl q :: inr g :: inr h ::
        announcement_to_list (Sigma.announcement pf0))%list))).
    exact (b, generate_overall_proof_ins rs ms uscs' c).
  Defined.

End Ins.
