(** * Swiss Post zero-knowledge proofs at the [Post_E2E_DEV] group *)

(** The verifiers of the zero-knowledge proofs of the Swiss Post
crypto-primitives library (specification 1.6.0, section 10: Schnorr,
decryption, exponentiation and plaintext-equality proofs) at
the group of [BayerGrothE2EIns.v] (the 3072-bit encryption group of
the Swiss Post synthetic election [Post_E2E_DEV], [g = 2]), whose
[prime_q] is an axiom, not a certificate.

Each proof is a Maurer-style proof of a preimage for a group homomorphism
[φ : Z_q^K → G^m] whose components are multi-exponentiations,
[φ(w)ᵢ = ∏ⱼ B_(i,j)^wⱼ], for a public statement [y ∈ G^m]. The proof is
published in compact form [(e, z)]: the verifier reconstructs the
announcement [c'ᵢ = yᵢ^(-e) · ∏ⱼ B_(i,j)^zⱼ] and checks [e = H(c')], where
[H] is the specification's RecursiveHash with the public values (the
statement and auxiliary data) fixed. This is [verify_rows] of
[Backend/BBSSharpVerifier.v], whose reconstruction ([ext_reconstruct],
[Crypto/OkamotoRows.v]) uses the same sign convention [y^(-e)].

The matrix of bases [B] for each proof is built by the OCaml driver
[Executable/Swisspostzkp] (and is trusted):

- Schnorr: [K = 1], [m = 1], row [[g]], statement [y].
- Exponentiation: [K = 1], [m = n], rows [[gᵢ]], statements [yᵢ].
- Plaintext equality: [K = 2], [m = 3], rows [[g, 1]], [[1, g]],
  [[h, h'⁻¹]], statement [(c₀, c'₀, c₁/c'₁)].
- Decryption: [K = ℓ], [m = 2ℓ], rows [g·eᵢ] and [γ·eᵢ] (with [eᵢ] the
  [i]-th unit vector), statements [pkᵢ] and [φᵢ/mᵢ].

The generalised Okamoto protocol of [Crypto/Okamoto.v] needs at least two
bases per row, so [verify_rows_accepting] is stated for [K ≥ 2]. To cover
[K = 1] as well, [verify_zkp_ins] appends a column of base [1] with
response [0]; this changes neither [φ] nor the reconstruction, and every
proof gets the accepting-transcript theorem [verify_zkp_ins_accepting].

This file is generated by [bench/swisspost-e2e/certified/mkins.py] from
[SwissPostZkpIns.v] and should not be edited by hand; it differs only in
the imported group. It is extracted by [src/Extraction/SwissPostE2Elib]. *)
From Stdlib Require Import Utf8 Vector.
From Algebra Require Import Hierarchy Vector_space.
From Sigma Require Import Sigma OkamotoRows.
From Backend Require Import BBSSharpVerifier.
From Utility Require Import Zpstar Util.
From Examples Require Import BayerGrothE2EIns.
Import VectorNotations.

Section SwissPostZkpE2EIns.

  (** [VG m] is a vector of [m] group elements. *)
  Local Notation VG m := (Vector.t G m).

  (** Appends a base [1] (the group identity) to every row of [Bs], turning
      [K] columns into [K + 1]. *)
  Definition pad_rows {K m : nat} (Bs : Vector.t (VG K) m) : Vector.t (VG (S K)) m :=
    Vector.map (fun row => Vector.shiftin Gone row) Bs.
  (** Appends the response [0] for the padding column. *)
  Definition pad_resp {K : nat} (rs : Vector.t F K) : Vector.t F (S K) := Vector.shiftin Fzero rs.

  (** The reconstructed announcement [yᵢ^(-e)·∏ⱼ B_(i,j)^rⱼ], exported so that
      the driver can compute the hash input. *)
  Definition reconstruct_ins {K m : nat} (e : F) (Bs : Vector.t (VG K) m) (Ts : VG m) (rs : Vector.t F K) : VG m :=
    ext_reconstruct (opp := Fopp) (gid := Gone) (gop := Gmul) (gpow := Gpow) e Bs Ts rs.

  (** The certified verifier: reconstructs the announcement for the padded
      rows and checks [e = H(announcement)]. [H] is the RecursiveHash computed
      by the driver. *)
  Definition verify_zkp_ins {K m : nat} (H : VG m -> F) (Bs : Vector.t (VG K) m) (Ts : VG m) (e : F)
    (rs : Vector.t F K) : bool :=
    verify_rows (Fdec := Fdec) (opp := Fopp) (gid := Gone) (gop := Gmul) (gpow := Gpow)
      H (pad_rows Bs) Ts e (pad_resp rs).

  (** If [verify_zkp_ins] accepts a proof with [K = n + 1 ≥ 1] columns, then
      for the reconstructed announcement [A] the challenge is its hash,
      [e = H A], and [([A], [e], padded responses)] is an accepting transcript
      of the generalised Okamoto protocol for the padded rows ([ext_verify]).
      This connects the verifier to the special soundness of that protocol;
      the random-oracle argument for [H] itself is not formalised. It is
      [verify_rows_accepting] at [bg_vspace]. *)
  Theorem verify_zkp_ins_accepting : forall (n m : nat) (H : VG m -> F) (Bs : Vector.t (VG (S n)) m)
    (Ts : VG m) (e : F) (rs : Vector.t F (S n)),
    verify_zkp_ins H Bs Ts e rs = true ->
    let A := ext_reconstruct (opp := Fopp) (gid := Gone) (gop := Gmul) (gpow := Gpow) e (pad_rows Bs) Ts (pad_resp rs) in
    e = H A /\
    ext_verify (gid := Gone) (gop := Gmul) (gpow := Gpow) (Gdec := Gdec) (pad_rows Bs) Ts
      (mk_sigma _ _ _ [A] [e] (pad_resp rs)) = true.
  Proof.
    intros * hv; cbv zeta.
    exact (verify_rows_accepting (Hvec := bg_vspace) n m H (pad_rows Bs) Ts e (pad_resp rs) hv).
  Qed.

End SwissPostZkpE2EIns.
