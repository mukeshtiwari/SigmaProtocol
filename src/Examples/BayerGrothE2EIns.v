(* How the Swiss Post shuffle argument works, and what this verifier checks.

   The Swiss Post voting system proves the correctness of its mix-net with
   the argument of Bayer and Groth. The claim is that of any proof of a
   shuffle: the output ciphertexts C'_i are the input ciphertexts C_i,
   re-encrypted and permuted by a secret π,

     C'_i = Enc(1; ρ_i) · C_{π(i)}.

   Ingredients. Pedersen commitments to vectors of Z_q,

     com(a; r) = h^r · ∏ g_i^{a_i},

   and ElGamal ciphertexts of the multi-recipient form
   (g^r, pk_1^r · m_1, …, pk_ℓ^r · m_ℓ).

   The argument.
   1. The prover commits to the permutation, c_A = com(π(1), …, π(N)).
   2. The verifier sends x.
   3. The prover commits to the permuted powers,
      c_B = com(x^{π(1)}, …, x^{π(N)}).
   4. The verifier sends y and z.
   5. Product argument: the prover shows

        ∏_i (y·π(i) + x^{π(i)} − z) = ∏_i (y·i + x^i − z).

   6. Multi-exponentiation argument: the prover shows

        ∏_i C_i^{x^i} = Enc(1; ρ) · ∏_i C'_i^{x^{π(i)}}.

   Why step 5 gives a permutation. Both sides are polynomials in z, with
   roots y·a_i + b_i for the committed values on the left and y·i + x^i on
   the right. If they agree at a random z they are equal, so the committed
   pairs (a_i, b_i) are a rearrangement of the pairs (i, x^i); the random
   y ties every index to its own power.

   Why step 6 gives the shuffle. If C'_i = Enc(1; ρ_i) · C_{π(i)} then

        ∏_i C'_i^{x^{π(i)}} = Enc(1; Σ_i ρ_i·x^{π(i)}) · ∏_j C_j^{x^j},

   so the equation holds with ρ = −Σ_i ρ_i·x^{π(i)}, and because x is
   random it cannot hold for another relation between C and C'.

   The five sub-arguments underneath (specification 1.6.0, Section 9):

     single value product   ∏ a_i = b for a committed vector a
     zero                   Σ_i a_i ⋆ b_{i−1} = 0 for committed matrices
     Hadamard               b = a_0 ∘ ⋯ ∘ a_{m−1} for committed columns
     product                ∏_{i,j} a_{i,j} = b for a committed matrix
     multi-exponentiation   C = Enc(1; ρ) · ∏_i C_i^{a_i} for committed a

   What is proved. Crypto/BayerGroth.v has the verifier of every argument
   and its completeness. The argument has more than three moves, so its
   soundness is k-special soundness: Crypto/BayerGrothSound.v proves it for
   every sub-argument and composes them into shuffle_soundness, and
   Crypto/BayerGrothZK.v gives the honest-verifier zero-knowledge
   simulators for single-message ElGamal. Backend/BayerGrothVerifier.v is
   the Fiat–Shamir verifier (shuffle_fs_soundness). What is trusted: the
   parser of the fixtures and the RecursiveHash challenges computed by
   the driver. *)

