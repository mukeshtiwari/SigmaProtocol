  (** ** Completeness at this group

      [shuffle_fs_completeness_ins]: for every oracle record whose challenge
      functions [o_xh] and [o_yh] never return zero, if [Cs'] really is a
      re-encryption of [Cs] under the permutation [perm] with randomness [ρs]
      (that is, [C'ᵢ = Enc(1; ρᵢ)·C_perm(i)]), [1 ≤ m], [2 ≤ n], [n] equals the
      number of commitment generators, and all the random inputs have the
      lengths the prover expects, then the honest prover's argument passes
      the verifier. It is [shuffle_fs_completeness] of
      [Backend/BayerGrothVerifier.v] at [bg_vspace]. *)
  Theorem shuffle_fs_completeness_ins : forall (l : nat) (O : oracles l) (h : G) (gs : list G) (g : G)
    (pk : Vector.t G l) (m n : nat) (Cs Cs' : list (ciphertext l)) (perm : list nat) (ρs : list F) (r s : list F)
    (sp : F) (smid : list F) (a0z bmz : list F) (r0z smz : F) (t1 t2 : list F)
    (d : list F) (rd : F) (dmid : list F) (s0 sx : F) (a0 : list F) (r0 : F) (bs ss τs : list F),
    (1 <= m)%nat -> (2 <= n)%nat -> length Cs = (m * n)%nat -> length Cs' = (m * n)%nat ->
    Permutation.Permutation perm (seq 0 (m * n)) -> length ρs = (m * n)%nat ->
    (forall i, (i < m * n)%nat ->
      nth i Cs' (vec_id (vid := Gone) (S l)) = reenc_ins g pk (nth i ρs Fzero) (nth (nth i perm 0%nat) Cs (vec_id (vid := Gone) (S l)))) ->
    length r = m -> length s = m -> length smid = (m - 2)%nat -> length t1 = S m -> length t2 = (m - 1)%nat ->
    length d = n -> length dmid = (n - 2)%nat ->
    length bs = (2 * m)%nat -> length ss = (2 * m)%nat -> length τs = (2 * m)%nat ->
    n = length gs -> length a0z = n -> length bmz = n -> length a0 = n ->
    (forall cA cb cB, o_xh O cA cb cB <> Fzero) -> (forall cA cb cB, o_yh O cA cb cB <> Fzero) ->
    shuffle_verify_fs_ins O h gs g pk m n Cs Cs'
      (shuffle_prove_fs_ins O h gs g pk m n Cs Cs' perm ρs r s sp smid a0z bmz r0z smz t1 t2 d rd dmid s0 sx a0 r0 bs ss τs) = true.
  Proof.
    intros; unfold shuffle_verify_fs_ins, shuffle_prove_fs_ins.
    apply (shuffle_fs_completeness (Hvec := bg_vspace)); assumption.
  Qed.

