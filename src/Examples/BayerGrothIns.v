(** * The Bayer–Groth shuffle argument at the Swiss Post 3072-bit group *)

(** This file instantiates the Bayer–Groth shuffle argument (Bayer and Groth,
EUROCRYPT 2012), in the variant used by the mix-net of the Swiss Post
e-voting system ([Crypto/BayerGroth.v], [Backend/BayerGrothVerifier.v]), at
the group of the Swiss Post crypto-primitives test vectors: the 3072-bit
safe prime [p = 2q + 1] of
[crypto-primitives/src/test/resources/mixnet/verify-*.json] (the
‘3072-bits’ group of the crypto-primitives specification, section 3.1),
with generator [g = 2]. The scalar field is [Z_q] and the group is the
order-[q] subgroup of [Z_p^*].

Everything here is fully certified: [q] is prime by the ECPP certificate of
[primeQSP.v] (generated by PARI/GP's [primecert] and converted by
[bench/ecpp2coq.py]), and [p] is then prime by Pocklington's criterion
since [p - 1 = 2q]; [p = 2q + 1] and the order of [g] are checked by
computation.

The file is extracted to OCaml by [src/Extraction/BayerGrothlib]. The
driver [Executable/Bgverifier] parses the JSON test vectors, computes the
RecursiveHash challenges and passes them in through the [oracles] record,
and runs [shuffle_verify_fs_ins]; the provers are exported too, so the
driver can also produce and check honest arguments. The parser and the
hash computations are trusted. The same file, with only the group
replaced, is the template from which [BayerGrothE2EIns.v],
[BayerGrothIvxvIns.v] and [BayerGrothIvxvGoIns.v] are generated.
*)

(** ** The argument

The claim is that of any proof of a shuffle: the output ciphertexts [C'ᵢ]
are the input ciphertexts [Cᵢ], re-encrypted and permuted by a secret [π],

[[
C'ᵢ = Enc(1; ρᵢ) · C_π(i).
]]

The ingredients are Pedersen commitments to vectors of [Z_q],
[com(a; r) = h^r · ∏ gᵢ^aᵢ], and multi-recipient ElGamal ciphertexts
[(g^r, pk₁^r·m₁, …, pk_ℓ^r·m_ℓ)] with [ℓ] message components. The
[N = m·n] ciphertexts are arranged as an [m × n] matrix.

- The prover commits to the permutation, [c_A = com(π(1), …, π(N))].
- The verifier sends [x]; the prover commits to the permuted powers
  [c_B = com(x^π(1), …, x^π(N))].
- The verifier sends [y] and [z]. A product argument shows
  [∏ᵢ (y·aᵢ + bᵢ - z) = ∏ᵢ (y·i + x^i - z)] for the committed [a], [b]:
  as polynomials in [z] both sides must coincide, so the committed pairs
  [(aᵢ, bᵢ)] are a rearrangement of the pairs [(i, x^i)].
- A multi-exponentiation argument shows
  [∏ᵢ Cᵢ^(x^i) = Enc(1; ρ) · ∏ᵢ C'ᵢ^(x^π(i))], which holds for an honest
  shuffle with [ρ = -Σᵢ ρᵢ·x^π(i)] and, [x] being random, for no other
  relation between the [C] and [C'].

Underneath are five sub-arguments (Swiss Post specification 1.6.0,
section 9): single value product ([∏ aᵢ = b] for a committed vector),
zero ([Σ aᵢ ⋆ b_(i-1) = 0] for committed matrices), Hadamard (a committed
vector is the entrywise product of committed columns), product
([∏ a_(i,j) = b] for a committed matrix) and multi-exponentiation.

[Crypto/BayerGroth.v] defines the interactive verifiers and proves their
completeness; [Crypto/BayerGrothSound.v] proves k-special soundness of every
sub-argument and composes them ([shuffle_soundness]);
[Crypto/BayerGrothZK.v] gives honest-verifier zero-knowledge simulators for
single-message ElGamal. [Backend/BayerGrothVerifier.v] is the Fiat–Shamir
layer: an [oracles] record supplies each challenge as a function of the
transcript so far, and [shuffle_fs_soundness] / [shuffle_fs_completeness]
hold for every oracle. This file only instantiates those definitions; the
one theorem stated here is completeness at this group. *)
