  (** The generator [g = 2] (as an integer). *)
  Definition gval : Z := 2.

  (** [q] is prime, by the ECPP certificate [primeQSP.prime_q_sp]. *)
  Theorem prime_q : prime q.
  Proof. exact primeQSP.prime_q_sp. Qed.

  (** [p = 2q + 1], checked by computation. *)
  Theorem cofactor : p = 2 * q + 1.
  Proof. vm_cast_no_check (eq_refl p). Qed.

  (** [2^q mod p = 1], so [g = 2] is a quadratic residue and lies in the
      subgroup of order [q]. The modular power is evaluated with the [BigN]
      implementation of [BigNPow], which is proved equal to [Zpow_mod]. *)
  Theorem g_order : Zpow_mod gval q p = 1.
  Proof.
    unfold q; rewrite BigNPow.bpow_mod_spec by (vm_compute; discriminate).
    vm_cast_no_check (eq_refl 1).
  Qed.

  (** [p] is prime, by Pocklington's criterion ([PocklingtonCorollary1]) with
      the fully factored part [q] of [p - 1 = 2q]: since [q > √p], it suffices
      that the witness [2] satisfies [2^(p-1) ≡ 1] and
      [gcd(2^((p-1)/q) - 1, p) = gcd(3, p) = 1]. *)
  Theorem prime_p : prime p.
  Proof.
    assert (hq0 : 0 < q) by (vm_cast_no_check (eq_refl Lt)).
    assert (hp0 : p <> 0) by (unfold p; discriminate).
    assert (e : p - 1 = q * 2) by (rewrite cofactor; ring).
    apply (PocklingtonCorollary1 p q 2).
    - vm_cast_no_check (eq_refl Lt).
    - lia.
    - exact e.
    - vm_cast_no_check (eq_refl Lt).
    (* The only prime divisor of q is q itself; use the witness 2. *)
    - intros π hπ hdiv.
      pose proof (prime_ge_2 π hπ) as hπ2.
      destruct (prime_divisors q prime_q π hdiv) as [eπ | [eπ | [eπ | eπ]]]; try lia.
      subst π. exists 2. split; [lia |]. split.
      (* 2^(p-1) = (2^q)^2 ≡ 1, from g_order. *)
      +
        rewrite e, Z.pow_mul_r by lia. rewrite Zpower_mod by lia.
        rewrite <-(Zpow_mod_correct 2 q p hp0).
        pose proof g_order as hg; unfold gval in hg; rewrite hg.
        vm_cast_no_check (eq_refl 1).
      (* (p-1)/q = 2 and gcd(2^2 - 1, p) = 1. *)
      +
        replace ((p - 1) / q) with 2 by (rewrite e, Z.mul_comm, Z.div_mul; lia).
        vm_cast_no_check (eq_refl 1).
  Qed.

  (** The scalar field [Z_q]. *)
  Definition F : Type := @Zp q.
  (** The group: the order-[q] subgroup of [Z_p^*] ([Utility/Zpstar.v]). *)
  Definition G : Type := @Schnorr_group p q.

  (** [g = 2] as a group element, with the membership proof [g_order]. *)
  Definition generator : G.
  Proof.
    refine {| Schnorr.v := gval; Ha := conj eq_refl eq_refl : (0 < gval < p); Hb := g_order |}.
  Defined.

  (** The field operations of [Z_q] at this [q]: [Fzero], [Fone], [Fadd],
      [Fmul], [Fsub], [Fdiv], [Fopp], [Finv] and the decidable equality
      [Fdec]. *)
  Definition Fzero : F := @Zpfield.zero q prime_q.
  Definition Fone : F := @Zpfield.one q prime_q.
  Definition Fadd : F -> F -> F := @zp_add q.
  Definition Fmul : F -> F -> F := @zp_mul q.
  Definition Fsub : F -> F -> F := @zp_sub q.
  Definition Fdiv : F -> F -> F := @zp_div q.
  Definition Fopp : F -> F := @zp_opp q prime_q.
  Definition Finv : F -> F := @zp_inv q.
  Definition Fdec : forall x y : F, {x = y} + {x <> y} := @zp_dec q.
  (** The group operations at this [(p, q)]: identity [Gone], inverse [Ginv],
      product [Gmul], exponentiation [Gpow] by a scalar and decidable equality
      [Gdec]. *)
  Definition Gone : G := @Schnorr.one p q prime_p prime_q.
  Definition Ginv : G -> G := @inv_schnorr_group p q prime_p prime_q.
  Definition Gmul : G -> G -> G := @mul_schnorr_group p q prime_p prime_q.
  Definition Gpow : G -> F -> G := @pow 2 p q cofactor prime_p prime_q.
  Definition Gdec : forall x y : G, {x = y} + {x <> y} := @Schnorr.dec_zpstar p q.

  (** The vector-space structure of [G] over [Z_q], needed to apply the
      generic theorems of [Crypto/BayerGroth.v] and
      [Backend/BayerGrothVerifier.v] at this group. *)
  Definition bg_vspace :
    @vector_space F (@eq F) Fzero Fone Fadd Fmul Fsub Fdiv Fopp Finv G (@eq G) Gone Ginv Gmul Gpow :=
    @pow_vspace 2 p q cofactor prime_p prime_q.

  (** ** Conversions and types for the driver

      The OCaml driver works with integers. [of_Z] reduces an integer modulo
      [q] into [Z_q]; [to_Z] and [elem_to_Z] return the integer
      representative of a scalar or group element. Group elements are built
      by the driver, which checks membership ([0 < v < p] and [v^q = 1])
      first. *)
  Definition of_Z (z : Z) : F.
  Proof. refine (Zpfield.mk_zp (Z.modulo z q) _). apply Z.mod_mod. vm_compute; discriminate. Defined.
  Definition to_Z (x : F) : Z := Zpfield.v x.
  Definition elem_to_Z (x : G) : Z := Schnorr.v x.

  (** A multi-recipient ElGamal ciphertext with [l] message components:
      the vector [(γ, φ₁, …, φ_l)] of [l + 1] group elements. *)
  Definition ciphertext (l : nat) : Type := Vector.t G (S l).

  (** The argument records of [Crypto/BayerGroth.v] and the oracle record of
      [Backend/BayerGrothVerifier.v] at this group, each with its
      constructor: single value product ([svp_argument], [mk_svp]), zero
      ([zero_argument], [mk_zero]), Hadamard ([hadamard_argument], [mk_had]),
