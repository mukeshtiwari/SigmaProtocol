  (** Product argument: the matrix committed in [cA] has product [b]. *)
  Definition product_verify_fs_ins {l : nat} (O : oracles l) (h : G) (gs : list G) (n : nat) (cA : list G) (b : F)
    (arg : product_argument) : bool :=
    product_verify_fs (zero := Fzero) (one := Fone) (add := Fadd) (mul := Fmul) (sub := Fsub) (opp := Fopp)
      (Fdec := Fdec) (gid := Gone) (gop := Gmul) (gpow := Gpow) (Gdec := Gdec) O h gs n cA b arg.
  (** The shuffle verifier: [Cs'] is a re-encryption and permutation of
      [Cs] ([m·n] ciphertexts) under the commitment key [(h, gs)] and the
