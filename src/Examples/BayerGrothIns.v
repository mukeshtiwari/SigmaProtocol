  (** ** Encryption, commitments and honest statements

      Helpers used by the driver to build honest test statements.

      [enc_ins g pk ms r = (g^r, pk₁^r·m₁, …, pk_l^r·m_l)]. *)
  Definition enc_ins {l : nat} (g : G) (pk : Vector.t G l) (ms : Vector.t G l) (r : F) : ciphertext l :=
    enc (gop := Gmul) (gpow := Gpow) g pk ms r.
  (** Re-encryption [Enc(1; ρ)·c]: multiplies [c] componentwise by an
      encryption of the identity with randomness [ρ]. *)
  Definition reenc_ins {l : nat} (g : G) (pk : Vector.t G l) (ρ : F) (c : ciphertext l) : ciphertext l :=
    vec_add (vadd := Gmul) (encg (gop := Gmul) (gpow := Gpow) g pk Fzero ρ) c.
  (** The Pedersen vector commitment [com(a; r) = h^r·∏ gsᵢ^aᵢ]. *)
  Definition com_ins (h : G) (gs : list G) (a : list F) (r : F) : G :=
    com (gid := Gone) (gop := Gmul) (gpow := Gpow) h gs a r.
  (** Commitments to the rows of a matrix [A] with randomness [r], one per
      row. *)
  Definition com_list_ins (h : G) (gs : list G) (A : list (list F)) (r : list F) : list G :=
    com_list (gid := Gone) (gop := Gmul) (gpow := Gpow) h gs A r.
  (** The Hadamard (entrywise) product of the first [j + 1] vectors of [A];
      used to form the intermediate statements of the Hadamard argument. *)
  Definition hprefix_ins (A : list (list F)) (j : nat) : list F := hprefix (mul := Fmul) A j.
  (** The multi-exponentiation statement [Enc(1; ρ)·∏ᵢ ∏ⱼ Cᵢⱼ^(Aᵢⱼ)]
      for ciphertext rows [Cs] and exponent rows [A]. *)
  Definition multiexp_C_ins {l : nat} (g : G) (pk : Vector.t G l) (Cs : list (list (ciphertext l)))
    (A : list (list F)) (ρ : F) : ciphertext l :=
    multiexp_C (gid := Gone) (gop := Gmul) (gpow := Gpow) g pk Cs A ρ.

