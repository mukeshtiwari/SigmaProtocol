(** Arithmetic modulo the order [l = 2^252 + 27742317777372353535851937790883648493]
    of the Ed25519 base point, as bedrock2 functions generated by
    fiat-crypto's word-by-word Montgomery pipeline (64-bit words, 4 limbs),
    with fiat-crypto's correctness theorems against the specifications of
    [Crypto.Bedrock.Specs.Field].

    Two representations of a residue by four 64-bit limbs [w] are used, both
    with [w] fully reduced ([WordByWordMontgomery.valid]: [eval w < l]):
    - [frepL] (Montgomery form): [w] represents [eval w * R^-1 mod l],
      [R = 2^256]; the arithmetic ([fl_mul], [fl_square], [fl_add],
      [fl_sub], [fl_opp]) and the conversions [fl_to_mont], [fl_from_mont]
      are specified against it;
    - [frepL_raw] (plain form): [w] represents [eval w mod l]; the byte
      conversions [fl_from_bytes], [fl_to_bytes] (32 little-endian bytes)
      are specified against it.
    [ExecFieldL.v] relates the two and states the operations on SigmaProtocol's
    [Zl.F = Zmod l]. *)

